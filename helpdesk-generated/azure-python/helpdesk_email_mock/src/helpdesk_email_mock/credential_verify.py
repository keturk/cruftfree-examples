"""Gateway credential verification endpoint.

Auto-generated by cruftfree-codegen-python. Do not edit manually.

Used by the gateway's ``auth_request`` to decide whether a request may be
forwarded: it answers 200 for a valid bearer JWT, or for a request carrying no
``Authorization`` header and exactly one admitted API-key header whose value is
within the presented-key bounds. The gateway forwards only the key headers the
requested route admits, so a key reaches this check only on such a route. The
edge checks a key's presence, never its validity: the service's own credential
chain verifies the key on the next hop, so a key costs one owner round trip,
not two.

A WebSocket upgrade's bearer is read in the order the service's own handshake
reads it: the ``Authorization`` header, else a ``cruftfree.bearer.<token>``
``Sec-WebSocket-Protocol`` offer (the only header a browser can set), else, on the
path of a route that opted in with ``queryToken(...)``, that query parameter. A
present but malformed value, or two bearer offers, is refused, never skipped. No
token, offer or query value is ever logged.

A bearer is verified by the gateway's JWT model: the service's own auth chain
when verification is delegated to this service, and only a token of a provider
the application declares passes (a provider a platform injects for its own test
runs trusts a published key, so it never passes this edge); otherwise the
asymmetric key the secrets resolver returns for ``jwt_public_key``.
"""

