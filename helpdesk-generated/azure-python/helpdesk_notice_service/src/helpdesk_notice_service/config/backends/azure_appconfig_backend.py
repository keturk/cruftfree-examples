"""Azure App Configuration backend for the runtime config-store client.

Auto-generated by cruftfree-codegen-python. Do not edit manually.

Reads config-store profiles from an Azure App Configuration store via the
``azure-appconfiguration`` SDK, authenticating with the no-env
``_credentials.azure_credential()`` (managed identity in cloud,
mounted-credential-file locally). The store endpoint and the deployment
environment are baked into ``config/_bootstrap`` at generation time — no
environment variable reads at runtime.

Each profile is read in two passes that the App Configuration data model keeps
distinct:

- Freeform key-values are stored under the ``<profile>:<key>`` key convention
  and selected by the ``<profile>:*`` key filter; their JSON-encoded scalar
  values are decoded into the ``key -> scalar`` mapping the client expects.
- Feature flags are stored under App Configuration's reserved
  ``.appconfig.featureflag/`` prefix with the feature-management content type;
  each flag's ``enabled`` state is mapped onto its Boolean config key.

Key Vault reference values (secret content type) are never returned: the client
exposes those keys' non-sensitive ``secretRef`` metadata separately, so this
backend skips them rather than dereferencing the secret. The client validates
and merges the returned scalars over the generated defaults.
"""

from __future__ import annotations

import json
import logging

from azure.appconfiguration import AzureAppConfigurationClient, ConfigurationSetting
from azure.core.exceptions import AzureError

logger = logging.getLogger(__name__)

_APPLICATION_NAME = "lanternpost"
_DEFAULT_ENVIRONMENT = "local"

#: Separator between the profile and the bare key name in a freeform key.
_PROFILE_KEY_SEPARATOR = ":"

#: Reserved prefix App Configuration assigns to feature-flag key-values.
_FEATURE_FLAG_PREFIX = ".appconfig.featureflag/"

#: Content type marking a feature-flag key-value (feature-management schema).
_FEATURE_FLAG_CONTENT_TYPE = "application/vnd.microsoft.appconfig.ff+json"

#: Content type marking a Key Vault reference; such values are secret and are
#: never dereferenced here (their metadata is exposed via ``get_secret_ref``).
_KEY_VAULT_REF_CONTENT_TYPE = "application/vnd.microsoft.appconfig.keyvaultref+json"

#: Feature-management envelope field holding the flag's enabled state.
_FEATURE_FLAG_ENABLED_KEY = "enabled"

#: Content-type prefix marking a freeform value whose stored text is a JSON scalar
#: (``application/json;type=integer|number|boolean;...``). The deploy-time seeder
#: tags numbers and booleans this way and stores String values as ``text/plain``,
#: so a value whose content type lacks this prefix is returned verbatim as a
#: string rather than JSON-parsed. (Feature-flag and Key Vault reference content
#: types are ``application/vnd.microsoft.*`` and are filtered out before decode.)
_FREEFORM_JSON_CONTENT_TYPE_PREFIX = "application/json"

PROFILE_NAMES: tuple[str, ...] = ("settings",)


class AzureAppConfigError(RuntimeError):
    """Raised when App Configuration cannot be reached or returns malformed data."""


class AzureAppConfigBackend:
    """Read config-store profiles from an Azure App Configuration store."""

    def __init__(self) -> None:
        from helpdesk_notice_service.config import _bootstrap, _credentials  # noqa: PLC0415

        endpoint = (_bootstrap.CONFIG_STORE_ENDPOINT or "").rstrip("/")
        if not endpoint:
            raise AzureAppConfigError(
                "Azure App Configuration endpoint is not configured. "
                "CONFIG_STORE_ENDPOINT is not set in config/_bootstrap.py. "
                "Regenerate the service with a deployment profile that sets "
                "the App Configuration store URL (for example "
                "'https://my-store.azconfig.io')."
            )
        self._environment: str = _bootstrap.ENVIRONMENT or _DEFAULT_ENVIRONMENT
        self._endpoint = endpoint
        # The synchronous AzureAppConfigurationClient calls credential.get_token()
        # directly and reads .expires_on off the result, so it requires the
        # SYNCHRONOUS managed-identity credential. Passing the async credential
        # (azure.identity.aio) returns an un-awaited coroutine and crashes startup
        # with "'coroutine' object has no attribute 'expires_on'".
        self._client = AzureAppConfigurationClient(
            base_url=endpoint,
            credential=_credentials.azure_credential_sync(),
        )

    def describe_source(self) -> str:
        """Name the App Configuration store this backend reads, for a
        fail-closed lookup's error message. The endpoint URL and environment
        label are a location; the credential is held by the managed-identity
        credential object and is never named here."""
        return f"Azure App Configuration {self._endpoint!r} label {self._environment!r}"

    def fetch_profile(self, profile: str) -> dict[str, object]:
        """Return decoded scalar values for one profile keyed by config key name.

        Reads the profile's freeform key-values (``<profile>:*``) and its feature
        flags, normalizing both into one ``key -> scalar`` mapping. Returns an
        empty mapping when the profile has no key-values; the client falls back
        to generated defaults for absent keys.
        """
        values: dict[str, object] = {}
        values.update(self._fetch_freeform(profile))
        values.update(self._fetch_feature_flags(profile))
        return values

    def fetch_key(self, profile: str, key: str) -> object:
        """Fetch exactly one config key for a targeted per-key TTL re-read.

        App Configuration stores freeform key-values and feature flags under
        distinct key conventions, so this re-reads the profile and selects *key*
        rather than guessing the convention for a bare key. A missing key raises
        :class:`AzureAppConfigError` so the client applies its ``fail_open`` policy.

        Raises:
            AzureAppConfigError: When App Configuration is unreachable/malformed
                (via :meth:`fetch_profile`) or *key* is absent from *profile*.
        """
        profile_values = self.fetch_profile(profile)
        if key not in profile_values:
            raise AzureAppConfigError(
                f"Config key {profile}/{key} is not present in App Configuration "
                f"for profile {profile!r}. Add the key to the store, or remove its "
                "ttlSeconds."
            )
        return profile_values[key]

    def _fetch_freeform(self, profile: str) -> dict[str, object]:
        key_filter = f"{profile}{_PROFILE_KEY_SEPARATOR}*"
        values: dict[str, object] = {}
        for setting in self._list_settings(profile, key_filter):
            if _is_feature_flag(setting):
                # Feature flags are listed under their reserved prefix, not here.
                continue
            if _is_key_vault_ref(setting):
                # Secret reference: the client exposes its metadata separately.
                logger.debug(
                    "azure_appconfig_secret_ref_skipped profile=%s key=%s",
                    profile,
                    setting.key,
                )
                continue
            key_name = _strip_profile_prefix(profile, setting.key)
            if key_name is None:
                continue
            values[key_name] = _decode_freeform_value(
                profile, key_name, setting.value, setting.content_type or ""
            )
        return values

    def _fetch_feature_flags(self, profile: str) -> dict[str, object]:
        key_filter = f"{_FEATURE_FLAG_PREFIX}{profile}{_PROFILE_KEY_SEPARATOR}*"
        values: dict[str, object] = {}
        for setting in self._list_settings(profile, key_filter):
            if not _is_feature_flag(setting):
                continue
            flag_key = _strip_feature_flag_key(profile, setting.key)
            if flag_key is None:
                continue
            values[flag_key] = _decode_feature_flag(profile, flag_key, setting.value)
        return values

    def _list_settings(
        self,
        profile: str,
        key_filter: str,
    ) -> list[ConfigurationSetting]:
        try:
            return list(
                self._client.list_configuration_settings(
                    key_filter=key_filter,
                    label_filter=self._environment,
                )
            )
        except AzureError as exc:
            raise AzureAppConfigError(
                f"Failed to read App Configuration for profile {profile!r} "
                f"(application {_APPLICATION_NAME!r}, environment "
                f"{self._environment!r}, key filter {key_filter!r}): {exc}. Verify "
                "the CONFIG_STORE_ENDPOINT in config/_bootstrap.py and that the "
                "runtime managed identity has the App Configuration Data Reader role."
            ) from exc


def _is_feature_flag(setting: ConfigurationSetting) -> bool:
    content_type = setting.content_type or ""
    by_content_type = content_type.startswith(_FEATURE_FLAG_CONTENT_TYPE)
    by_key_prefix = setting.key.startswith(_FEATURE_FLAG_PREFIX)
    return by_content_type or by_key_prefix


def _is_key_vault_ref(setting: ConfigurationSetting) -> bool:
    content_type = setting.content_type or ""
    return content_type.startswith(_KEY_VAULT_REF_CONTENT_TYPE)


def _strip_profile_prefix(profile: str, key: str) -> str | None:
    prefix = f"{profile}{_PROFILE_KEY_SEPARATOR}"
    if not key.startswith(prefix):
        return None
    key_name = key[len(prefix) :]
    if not key_name:
        return None
    return key_name


def _strip_feature_flag_key(profile: str, key: str) -> str | None:
    if not key.startswith(_FEATURE_FLAG_PREFIX):
        return None
    return _strip_profile_prefix(profile, key[len(_FEATURE_FLAG_PREFIX) :])


def _decode_freeform_value(
    profile: str, key_name: str, raw: str | None, content_type: str
) -> object:
    """Decode one freeform value using its App Configuration content type.

    App Configuration tags each value with a content type that signals its scalar
    type: numbers and booleans are stored as JSON with an
    ``application/json;type=*`` content type, while String values are stored as
    their raw text with a ``text/plain`` content type. A value whose content type
    is not JSON is therefore returned verbatim as a string (a bare host/URL is
    valid config, not malformed JSON); only JSON-typed values are ``json.loads``-
    parsed into their native ``int``/``float``/``bool``.
    """
    if raw is None:
        raise AzureAppConfigError(
            f"App Configuration key {profile}/{key_name} has no value. Store the "
            "value with a content type that matches its type (text/plain for a "
            "string, application/json for a number/boolean)."
        )
    if not content_type.startswith(_FREEFORM_JSON_CONTENT_TYPE_PREFIX):
        # text/plain (or untyped): the stored text is the string value itself.
        return raw
    try:
        return json.loads(raw)
    except json.JSONDecodeError as exc:
        raise AzureAppConfigError(
            f"App Configuration value for {profile}/{key_name} is tagged "
            f"{content_type!r} (JSON) but is not valid JSON: {exc}. Store a "
            "number/boolean as its JSON form, or tag a string as text/plain."
        ) from exc


def _decode_feature_flag(profile: str, flag_key: str, raw: str | None) -> bool:
    if raw is None:
        raise AzureAppConfigError(
            f"App Configuration feature flag {profile}/{flag_key} has no value. "
            "Feature flags must use the feature-management JSON schema."
        )
    try:
        payload = json.loads(raw)
    except json.JSONDecodeError as exc:
        raise AzureAppConfigError(
            f"App Configuration feature flag {profile}/{flag_key} is not valid "
            f"JSON: {exc}. Feature flags must use the feature-management schema."
        ) from exc
    if not isinstance(payload, dict):
        raise AzureAppConfigError(
            f"App Configuration feature flag {profile}/{flag_key} is not a JSON "
            f"object; got {type(payload).__name__}."
        )
    if _FEATURE_FLAG_ENABLED_KEY not in payload:
        raise AzureAppConfigError(
            f"App Configuration feature flag {profile}/{flag_key} is missing the "
            f"'{_FEATURE_FLAG_ENABLED_KEY}' field. Feature-flag profiles map each "
            "flag's enabled state onto its Boolean config key."
        )
    enabled = payload[_FEATURE_FLAG_ENABLED_KEY]
    if not isinstance(enabled, bool):
        raise AzureAppConfigError(
            f"App Configuration feature flag {profile}/{flag_key} has a non-boolean "
            f"'{_FEATURE_FLAG_ENABLED_KEY}' value of type {type(enabled).__name__}; "
            "expected a boolean."
        )
    return enabled
