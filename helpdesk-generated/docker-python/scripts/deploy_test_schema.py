#!/usr/bin/env python3
"""Expand every RDBMS block of the deploy test's own project, before its release starts.

The deploy test starts its stack with compose alone, and compose creates no table: a deploy's
schema converge does. This script runs that converge's expand, through the deploy script's own
schema client, so the owner login stays with that client and neither the test runner nor a test
process reads it. It expands every block whatever the profile's ``schemaConvergence`` says,
because a test needs its tables either way, and it refuses any project but the deploy test's,
because on a real stack that would override the profile.

Auto-generated by CruftFree. Do not edit manually.
"""

from __future__ import annotations

import os
import sys

import deploy as deploy

#: The compose project the deploy test starts, and the only one this script changes.
DEPLOY_TEST_PROJECT = "helpdesk_system_test"


def _announce_release() -> None:
    """Leave the release to the deploy test, which starts it once this script exits."""
    print("Every block is expanded: the deploy test starts the release.")


def main() -> int:
    """Expand every block; 0 when each holds its declared schema, otherwise non-zero."""
    project = os.environ.get("COMPOSE_PROJECT_NAME", "").strip()
    if project != DEPLOY_TEST_PROJECT:
        print(
            f"This script changes only the deploy test's project {DEPLOY_TEST_PROJECT!r}; "
            f"COMPOSE_PROJECT_NAME names {project!r}.",
            file=sys.stderr,
        )
        return 2
    try:
        deploy.resolve_docker()
        deploy.require_compose()
        deploy.require_env_file()
        deploy.expand_schema_blocks(
            deploy.SCHEMA_BLOCKS,
            False,
            bring_up_data=deploy.compose_up_databases,
            start_release=_announce_release,
            concurrent_runs=deploy.serial_schema_runs,
            schema_tool=deploy.run_project_schema_tool,
            channel=deploy.compose_schema_channel(deploy.STEP_CONVERGE),
            failure=deploy.DeployError,
        )
    except deploy.DeployError as error:
        print(str(error), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
