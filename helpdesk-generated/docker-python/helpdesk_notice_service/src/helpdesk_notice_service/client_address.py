"""The caller's address behind the proxies this service's platform declares.

Auto-generated by cruftfree-codegen-python. Do not edit manually.

A header (``X-Forwarded-For``, or the framework header ``X-CruftFree-Client-Address``
that the system gateway overwrites) is read only when a declared, vendor-documented
proxy wrote it and the request provably came through that proxy; every other case, and
every failure, uses the connection peer, which the caller cannot choose. The server's
own proxy-header handling is off, so ``request.client`` is always that peer.

A serverless endpoint hosted off the container runtime resolves under its host's own
policy (``serverless_client_address``), with the address the host reports as the peer:
the gateway header the listener's policy may trust is never written on a serverless
invocation.

The body below is inlined verbatim from
cruftfree_codegen_python/runtime/client_address.py. It is a real module so the
resolution is unit tested by calling it, rather than by executing this rendered
file.
"""

from __future__ import annotations

import ipaddress
import logging
from collections.abc import Sequence
from dataclasses import dataclass
from functools import lru_cache

from starlette.requests import HTTPConnection

logger = logging.getLogger(__name__)

KIND_TRANSPORT_PEER = "transport_peer"
KIND_FORWARDED_FOR = "forwarded_for"
KIND_GATEWAY_ASSERTED = "gateway_asserted"

FORWARDED_FOR_HEADER = "x-forwarded-for"
UNKNOWN_CLIENT_KEY = "ip:unknown"


@dataclass(frozen=True, slots=True)
class ClientAddressPolicy:
    """The baked facts one service's client-address resolution reads."""

    kind: str
    trusted_hops: int
    trusted_peer_networks: tuple[str, ...]
    peer_is_platform_front_end: bool
    asserted_header: str
    requires_trusted_caller: bool
    ipv6_rate_limit_prefix_length: int
    reason_forwarded_short: str
    reason_forwarded_invalid: str
    reason_assertion_invalid: str


def canonicalize_address(value: str) -> str | None:
    """Return *value* in canonical form, or ``None`` when it is not a bare address.

    Brackets, ports and zones are invalid; an IPv4-mapped IPv6 address becomes its
    IPv4 address; IPv6 is written lowercase and compressed.
    """
    try:
        address = ipaddress.ip_address(value.strip())
    except ValueError:
        return None
    if isinstance(address, ipaddress.IPv6Address):
        if address.scope_id is not None:
            return None
        if address.ipv4_mapped is not None:
            return str(address.ipv4_mapped)
    return str(address)


@lru_cache(maxsize=32)
def _parsed_networks(
    networks: tuple[str, ...],
) -> tuple[ipaddress.IPv4Network | ipaddress.IPv6Network, ...]:
    return tuple(ipaddress.ip_network(network, strict=True) for network in networks)


def _peer_in_trusted_networks(peer: str, networks: tuple[str, ...]) -> bool:
    address = ipaddress.ip_address(peer)
    return any(address in network for network in _parsed_networks(networks))


def _header_values(headers: Sequence[tuple[str, str]], name: str) -> list[str]:
    lowered = name.lower()
    return [value for header_name, value in headers if header_name.lower() == lowered]


def _log_fallback(reason: str, policy: ClientAddressPolicy, level: int) -> None:
    logger.log(level, "client_address_fallback reason=%s kind=%s", reason, policy.kind)


def forwarded_entry_address(entry: str) -> str | None:
    """The canonical address of one ``X-Forwarded-For`` entry, or ``None`` when invalid.

    A proxy may append the peer it saw with its port (``203.0.113.7:51234``,
    ``[2001:db8::1]:51234``); the port is dropped before the address is
    canonicalized. Anything else follows :func:`canonicalize_address`.
    """
    text = entry.strip()
    if text.startswith("["):
        host, bracket, port = text[1:].partition("]")
        if not bracket or (port and not (port.startswith(":") and port[1:].isdigit())):
            return None
        return canonicalize_address(host)
    host, colon, port = text.partition(":")
    if colon and ":" not in port:
        return canonicalize_address(host) if port.isdigit() else None
    return canonicalize_address(text)


def _from_forwarded_for(
    peer: str | None, headers: Sequence[tuple[str, str]], policy: ClientAddressPolicy
) -> str | None:
    # With the platform front end as the only ingress the header is the front end's
    # whatever the peer, so a host that hands over no connection peer still reads it.
    if peer is None and not policy.peer_is_platform_front_end:
        return None
    if (
        peer is not None
        and policy.trusted_peer_networks
        and not _peer_in_trusted_networks(peer, policy.trusted_peer_networks)
    ):
        return peer
    entries = [
        entry.strip()
        for value in _header_values(headers, FORWARDED_FOR_HEADER)
        for entry in value.split(",")
    ]
    if len(entries) < policy.trusted_hops:
        # A request through the declared peer with no entry is a platform probe or a
        # direct call: informational, never a security event.
        _log_fallback(policy.reason_forwarded_short, policy, logging.INFO)
        return peer
    forwarded = forwarded_entry_address(entries[-policy.trusted_hops])
    if forwarded is None:
        _log_fallback(policy.reason_forwarded_invalid, policy, logging.WARNING)
        return peer
    return forwarded


def _from_assertion(
    peer: str | None,
    headers: Sequence[tuple[str, str]],
    policy: ClientAddressPolicy,
    trusted_caller_verified: bool,
) -> str | None:
    if policy.requires_trusted_caller and not trusted_caller_verified:
        return peer
    values = _header_values(headers, policy.asserted_header)
    if not values:
        return peer
    if len(values) > 1:
        _log_fallback(policy.reason_assertion_invalid, policy, logging.WARNING)
        return peer
    asserted = canonicalize_address(values[0])
    if asserted is None:
        _log_fallback(policy.reason_assertion_invalid, policy, logging.WARNING)
        return peer
    return asserted


def resolve_client_address(
    peer: str | None,
    headers: Sequence[tuple[str, str]],
    policy: ClientAddressPolicy,
    *,
    trusted_caller_verified: bool,
) -> str | None:
    """Return the caller's canonical address under *policy*, or ``None`` with no peer.

    Args:
        peer: The connection's remote address as the server reports it.
        headers: Every request header as ``(name, value)`` pairs, duplicates kept.
        policy: The service's baked policy.
        trusted_caller_verified: Whether the trusted-caller stage verified this request.
    """
    canonical_peer = None if peer is None else canonicalize_address(peer)
    if policy.kind == KIND_TRANSPORT_PEER:
        return canonical_peer
    if policy.kind == KIND_FORWARDED_FOR:
        return _from_forwarded_for(canonical_peer, headers, policy)
    if policy.kind == KIND_GATEWAY_ASSERTED:
        return _from_assertion(canonical_peer, headers, policy, trusted_caller_verified)
    raise ValueError(
        f"Unknown client address kind {policy.kind!r}. Valid kinds: "
        f"{KIND_TRANSPORT_PEER!r}, {KIND_FORWARDED_FOR!r}, {KIND_GATEWAY_ASSERTED!r}."
    )


def client_rate_limit_key(address: str | None, prefix_length: int) -> str:
    """The anonymous rate-limit key: ``ip:<IPv4>``, ``ip:<IPv6 network>`` or ``ip:unknown``.

    An IPv6 caller is keyed by its network of *prefix_length* bits, so one holder of
    a /64 cannot rotate buckets across it.
    """
    if address is None:
        return UNKNOWN_CLIENT_KEY
    parsed = ipaddress.ip_address(address)
    if isinstance(parsed, ipaddress.IPv6Address):
        network = ipaddress.ip_network((parsed, prefix_length), strict=False)
        return f"ip:{network}"
    return f"ip:{parsed}"


CLIENT_ADDRESS_POLICY = ClientAddressPolicy(
    kind="gateway_asserted",
    trusted_hops=0,
    trusted_peer_networks=(),
    peer_is_platform_front_end=False,
    asserted_header="X-CruftFree-Client-Address",
    requires_trusted_caller=False,
    ipv6_rate_limit_prefix_length=64,
    reason_forwarded_short="client_address_forwarded_short",
    reason_forwarded_invalid="client_address_forwarded_invalid",
    reason_assertion_invalid="client_address_assertion_invalid",
)


def client_address(request: HTTPConnection) -> str | None:
    """The caller's canonical address for *request*, or ``None`` with no connection peer."""
    peer = request.client.host if request.client is not None else None
    return resolve_client_address(
        peer,
        request.headers.items(),
        CLIENT_ADDRESS_POLICY,
        trusted_caller_verified=bool(
            getattr(request.state, "verified_trusted_caller", False)
        ),
    )


def anonymous_rate_limit_key(request: HTTPConnection) -> str:
    """The rate-limit key of a request that authenticates nobody: its caller's address."""
    return client_rate_limit_key(
        client_address(request), CLIENT_ADDRESS_POLICY.ipv6_rate_limit_prefix_length
    )
