async def _run_probe(probe: _DependencyProbe) -> dict[str, object]:
    """Run one probe; a raising probe is recorded as down and logged, never propagated."""
    up = False
    try:
        up = await probe.run()
    except Exception as exc:  # noqa: BLE001 -- a failed probe is recorded as down
        logger.error("health_probe_failed dependency=%s error=%s", probe.key, exc)
    if not up:
        logger.warning("health_probe_down dependency=%s", probe.key)
    check: dict[str, object] = {
        "status": _STATUS_UP if up else _STATUS_DOWN,
        "required": probe.required,
    }
    if probe.health is not None:
        check["health"] = probe.health
    return check


@health_router.get("/live")
async def liveness_check() -> dict[str, str]:
    """Process liveness. Returns 200 whenever the process is serving requests.

    Performs no dependency checks -- a live process that cannot reach its
    dependencies is still live (use ``/ready`` to gate traffic).
    """
    return {"status": _STATUS_UP, "service": _SERVICE_NAME}


@health_router.get("/ready")
async def readiness_check(request: Request, response: Response) -> dict[str, object]:
    """Readiness gate. Returns 503 when any readiness-blocking dependency is down.

    A ``required`` dependency, or a ``degraded`` dependency declared
    ``readyOnDegraded = false``, blocks readiness when its probe is down. An
    ``optional`` dependency never blocks readiness.

    A stopped event consumer hosted in this process also blocks readiness.
    Probing only the datastores let a service whose receive loop had died report
    healthy indefinitely while consuming nothing and its subscription backlog
    grew -- the failure mode health checks exist to catch.
    """
    blockers: dict[str, str] = {}
    if getattr(request.app.state, "consumer_failed", False):
        blockers[_CONSUMERS_BLOCKER] = _STATUS_DOWN
    for probe in _PROBES:
        if not probe.blocks_readiness:
            continue
        check = await _run_probe(probe)
        if check["status"] != _STATUS_UP:
            blockers[probe.key] = str(check["status"])
    if blockers:
        response.status_code = 503
        logger.warning(
            "readiness_not_ready service=%s blockers=%s", _SERVICE_NAME, blockers
        )
        return {"status": _STATUS_DOWN, "service": _SERVICE_NAME, "blockers": blockers}
    return {"status": _STATUS_UP, "service": _SERVICE_NAME, "blockers": {}}


@health_router.get("/health")
async def health_check(response: Response) -> dict[str, object]:
    """Detailed health report with a per-dependency ``checks`` map.

    Overall status is ``down`` when a required dependency is down, ``degraded``
    when a non-required dependency is down, else ``up``. Returns 503 only when a
    required dependency is down.
    """
    checks: dict[str, dict[str, object]] = {}
    required_down = False
    degraded = False
    for probe in _PROBES:
        check = await _run_probe(probe)
        checks[probe.key] = check
        if check["status"] == _STATUS_UP:
            continue
        if probe.required:
            required_down = True
        else:
            degraded = True

    if required_down:
        overall = _STATUS_DOWN
        response.status_code = 503
    elif degraded:
        overall = _STATUS_DEGRADED
    else:
        overall = _STATUS_UP

    return {
        "status": overall,
        "service": _SERVICE_NAME,
        "checks": checks,
    }


