"""Health, readiness, and liveness endpoints.

Three distinct contracts:

* ``/live``   -- process liveness; 200 whenever the process is up. No checks.
* ``/ready``  -- readiness; 503 when any readiness-blocking dependency (a required
                 one, or a degraded one declared ``readyOnDegraded = false``) is
                 down, or an in-process event consumer is stopped.
* ``/health`` -- detailed per-dependency report (status / required / health),
                 keyed by dependency identity (``<kind>.<block>``).

The routes are unauthenticated, so a failed probe's exception is logged here and
never returned: its text routinely names a dependency's internal host and port.

Auto-generated by cruftfree-codegen-python. Do not edit manually.
"""

