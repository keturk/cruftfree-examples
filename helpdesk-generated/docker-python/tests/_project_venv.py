"""The project's own virtual environment, shared by the host-side test runners.

Auto-generated by cruftfree-codegen-python. Do not edit manually.

``tests/unit_tests.py`` and ``tests/deploy_test.py`` run every service's tests in
``<project>/.venv``, never in the interpreter that launched them: that could be a
developer's system Python, or another tool's environment. This module is the one
owner of that venv: it creates it on first use from the base installation of the
launching interpreter, reuses it while it was built from that installation, and
rebuilds it when it was built from another, so a change of interpreter reaches
the project however the runner was launched. Every pip run is checked, so a
requirements file pip cannot install stops the runner with pip's own output
instead of surfacing later as an ImportError inside a test.

Standard library only: this module runs before any dependency is installed.
"""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

PROJECT_VENV_DIR = ".venv"
_PYVENV_CFG = "pyvenv.cfg"
#: The pyvenv.cfg key ``venv`` writes the directory of the base installation into.
_PYVENV_HOME_KEY = "home"


class ProjectEnvironmentError(RuntimeError):
    """The project venv could not be prepared, or pip could not install into it."""


def _venv_interpreter(venv_dir: Path) -> Path:
    """The python executable inside the virtual environment at *venv_dir*."""
    if os.name == "nt":
        return venv_dir / "Scripts" / "python.exe"
    return venv_dir / "bin" / "python"


def _process_output(result: subprocess.CompletedProcess[str]) -> str:
    """A finished process's stderr, then its stdout, or a marker when both are empty."""
    output = "\n".join(
        part.strip() for part in (result.stderr, result.stdout) if part.strip()
    )
    return output or "(no output)"


def _same_directory(left: str, right: str) -> bool:
    """Whether two directory paths name the same directory on this host."""
    return os.path.normcase(os.path.realpath(left)) == os.path.normcase(
        os.path.realpath(right)
    )


def base_installation_dir() -> str:
    """The directory of the base installation a venv built now would run on.

    ``venv`` builds from ``sys._base_executable`` whether it is launched by a base
    interpreter or by any virtual environment of one (this project's own venv
    included) and records that executable's directory as ``home``; this is the
    same value, so the launcher a runner is started with never decides a rebuild.
    """
    return os.path.dirname(os.path.abspath(sys._base_executable))


def _built_from_base(venv_dir: Path) -> bool:
    """Whether *venv_dir*'s pyvenv.cfg records the base installation as its ``home``."""
    for line in (venv_dir / _PYVENV_CFG).read_text(encoding="utf-8").splitlines():
        key, separator, value = line.partition("=")
        if separator and key.strip().lower() == _PYVENV_HOME_KEY:
            return _same_directory(value.strip(), base_installation_dir())
    return False


def _is_current(venv_dir: Path) -> bool:
    """Whether *venv_dir* carries its interpreter and was built from the base installation."""
    return _venv_interpreter(venv_dir).is_file() and _built_from_base(venv_dir)


def _build_venv(venv_dir: Path) -> None:
    """Create (or, with ``--clear``, rebuild) the virtual environment at *venv_dir*.

    Raises:
        ProjectEnvironmentError: When ``venv`` exits non-zero.
    """
    print(
        "Preparing project environment %s from %s"
        % (venv_dir, base_installation_dir()),
        flush=True,
    )
    result = subprocess.run(
        [sys.executable, "-m", "venv", "--clear", str(venv_dir)],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        check=False,
    )
    if result.returncode != 0:
        raise ProjectEnvironmentError(
            "Creating the project environment %s from %s failed (exit code %d):\n%s\n"
            "Fix: confirm the interpreter runs, ships the venv module and can write to "
            "the project directory, then rerun."
            % (venv_dir, sys.executable, result.returncode, _process_output(result))
        )


def project_venv_python(project_root: Path) -> Path:
    """The interpreter of ``<project_root>/.venv``, built from the launching interpreter's base.

    The venv is created when absent, reused while its ``pyvenv.cfg`` records the
    base installation of the interpreter running this file (see
    :func:`base_installation_dir`), and rebuilt with ``venv --clear`` when it
    records another, or when its interpreter is missing. A directory at that path
    that is not a virtual environment (no ``pyvenv.cfg``) is refused and left intact.

    Raises:
        ProjectEnvironmentError: When the directory exists but is not a virtual
            environment, when ``venv`` exits non-zero, or when the venv carries
            no interpreter afterwards.
    """
    venv_dir = project_root / PROJECT_VENV_DIR
    if venv_dir.exists() and not (venv_dir / _PYVENV_CFG).is_file():
        raise ProjectEnvironmentError(
            "%s exists but is not a virtual environment (no %s). Expected the project's "
            "own test environment there. Fix: move or delete that directory, then rerun."
            % (venv_dir, _PYVENV_CFG)
        )
    if not venv_dir.exists() or not _is_current(venv_dir):
        _build_venv(venv_dir)
    python = _venv_interpreter(venv_dir)
    if not python.is_file():
        raise ProjectEnvironmentError(
            "The project environment %s has no interpreter at %s. Expected the venv's own "
            "python there. Fix: delete %s so it is recreated, then rerun."
            % (venv_dir, python, venv_dir)
        )
    return python


def install_requirements(python: Path, requirements: Path) -> None:
    """Install the packages *requirements* lists into the environment of *python*.

    Installs only from the file named, from pip's configured index with pip's
    default TLS verification.

    Raises:
        ProjectEnvironmentError: When pip exits non-zero. The message names the
            requirements file, the interpreter, pip's exit code and pip's own
            output (stderr, then stdout).
    """
    result = subprocess.run(
        [str(python), "-m", "pip", "install", "-r", str(requirements)],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        check=False,
    )
    if result.returncode != 0:
        raise ProjectEnvironmentError(
            "pip could not install %s into %s (exit code %d). Expected every listed package "
            "to install. pip reported:\n%s\n"
            "Fix: correct the failing requirement, or run the tests with an interpreter "
            "whose platform has a build of every listed package."
            % (requirements, python, result.returncode, _process_output(result))
        )
