@asynccontextmanager
async def _block_lock(conn: AsyncConnection) -> AsyncIterator[None]:
    """Hold the block's session lock on *conn* for the body of the ``with``.

    Bounded, non-blocking acquisition. A NULL answer is not "not acquired": the
    engine did not say whether the lock was obtained, so nothing is written.
    """
    acquired = False
    for _attempt in range(_BLOCK_LOCK_MAX_ATTEMPTS):
        answer = (await conn.execute(text(_BLOCK_LOCK_TRY_ACQUIRE))).scalar()
        if answer is None:
            raise RuntimeError(
                "the database returned NULL for the block lock of component "
                "ticket_db; it did not say whether the lock was obtained, "
                "so nothing was seeded."
            )
        if answer == _BLOCK_LOCK_ACQUIRED:
            acquired = True
            break
        await asyncio.sleep(_BLOCK_LOCK_RETRY_SECONDS)
    if not acquired:
        raise RuntimeError(
            "could not acquire the block lock for component ticket_db "
            f"after {_BLOCK_LOCK_MAX_ATTEMPTS} attempts; another session may be stuck "
            "holding it. Retry."
        )
    try:
        yield
    finally:
        # Cleanup must never mask the primary failure; the session ending frees the lock.
        try:
            await conn.execute(text(_BLOCK_LOCK_RELEASE))
        except Exception:  # noqa: BLE001 -- logged; the connection closing releases the lock
            logger.warning(
                "seed_block_unlock_failed component=ticket_db", exc_info=True
            )


