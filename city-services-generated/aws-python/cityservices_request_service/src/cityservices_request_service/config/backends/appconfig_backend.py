"""AWS AppConfig backend for the runtime config-store client.

Auto-generated by cruftfree-codegen-python. Do not edit manually.

Reads config-store profiles from AWS AppConfig via the AppConfig Data API
(``StartConfigurationSession`` / ``GetLatestConfiguration``). The AppConfig
application, configuration-profile names, and the deployment environment are
baked into ``config/_bootstrap`` at generation time — no environment variable
reads at runtime.

Each profile maps to one AppConfig configuration profile resolved by name. A
session is started per profile on first fetch and reused so subsequent polls
send the returned ``NextPollConfigurationToken``; AppConfig returns an empty
configuration body when nothing changed, in which case the last decoded values
are returned. Feature-flag content (``AWS.AppConfig.FeatureFlags``) and freeform
JSON are normalized into the same ``key -> scalar`` mapping the client expects;
the client validates and merges those over the generated defaults.
"""

