    def fetch_profile(self, profile: str) -> dict[str, object]:
        """Return decoded scalar values for one profile keyed by config key name.

        Starts (or resumes) the AppConfig configuration session for *profile* and
        returns the normalized ``key -> scalar`` mapping. When AppConfig reports
        no change since the last poll it returns the previously decoded values.
        """
        token = self._poll_token(profile)
        try:
            response = self._client.get_latest_configuration(ConfigurationToken=token)
        except Exception as exc:  # boto3 raises ClientError/BotoCoreError subclasses
            # Drop the session token so the next poll starts a fresh session.
            self._poll_tokens.pop(profile, None)
            raise AppConfigError(
                f"Failed to fetch AppConfig configuration for profile {profile!r} "
                f"(application {_APPLICATION_NAME!r}, environment "
                f"{self._environment!r}): {exc}. Verify the AppConfig application, "
                "environment, and configuration profile exist and the runtime IAM "
                "role grants appconfig:GetLatestConfiguration."
            ) from exc

        self._poll_tokens[profile] = str(response["NextPollConfigurationToken"])
        raw = response["Configuration"].read()
        if not raw:
            # Empty body: configuration is unchanged since the previous poll.
            return dict(self._last_values.get(profile, {}))

        values = self._decode_configuration(profile, raw)
        self._last_values[profile] = values
        return dict(values)

    def fetch_key(self, profile: str, key: str) -> object:
        """Fetch exactly one config key for a targeted per-key TTL re-read.

        AWS AppConfig exposes no single-key read; the Data API returns a whole
        configuration body per session. This re-reads the profile (resuming the
        session) and selects *key*. A missing key raises :class:`AppConfigError`
        so the client applies its ``fail_open`` policy.

        Raises:
            AppConfigError: When AppConfig is unreachable/malformed (via
                :meth:`fetch_profile`) or *key* is absent from *profile*.
        """
        profile_values = self.fetch_profile(profile)
        if key not in profile_values:
            raise AppConfigError(
                f"Config key {profile}/{key} is not present in the AppConfig "
                f"configuration for profile {profile!r}. Add the key to the "
                "AppConfig profile, or remove its ttlSeconds."
            )
        return profile_values[key]

    def _poll_token(self, profile: str) -> str:
        existing = self._poll_tokens.get(profile)
        if existing is not None:
            return existing
        try:
            session = self._client.start_configuration_session(
                ApplicationIdentifier=_APPLICATION_NAME,
                EnvironmentIdentifier=self._environment,
                ConfigurationProfileIdentifier=profile,
                RequiredMinimumPollIntervalInSeconds=_REQUIRED_MINIMUM_POLL_SECONDS,
            )
        except Exception as exc:  # boto3 raises ClientError/BotoCoreError subclasses
            raise AppConfigError(
                f"Failed to start AppConfig session for profile {profile!r} "
                f"(application {_APPLICATION_NAME!r}, environment "
                f"{self._environment!r}): {exc}. Verify the AppConfig application, "
                "environment, and configuration profile names match the resolved "
                "configStore declaration and that AWS credentials are available."
            ) from exc
        token = str(session["InitialConfigurationToken"])
        self._poll_tokens[profile] = token
        return token

    @staticmethod
    def _decode_configuration(profile: str, raw: bytes) -> dict[str, object]:
        try:
            payload = json.loads(raw.decode("utf-8"))
        except (UnicodeDecodeError, json.JSONDecodeError) as exc:
            raise AppConfigError(
                f"AppConfig configuration for profile {profile!r} is not valid "
                f"UTF-8 JSON: {exc}. Store freeform profiles as a JSON object of "
                "key -> scalar and feature-flag profiles in AppConfig feature-flag "
                "format."
            ) from exc
        if not isinstance(payload, dict):
            raise AppConfigError(
                f"AppConfig configuration for profile {profile!r} must be a JSON "
                f"object; got {type(payload).__name__}."
            )
        if AppConfigBackend._is_feature_flag_payload(payload):
            return AppConfigBackend._decode_feature_flags(profile, payload)
        return AppConfigBackend._decode_freeform(profile, payload)

    @staticmethod
    def _is_feature_flag_payload(payload: dict[str, object]) -> bool:
        # AppConfig feature-flag content wraps flags in a versioned envelope:
        # {"version": "1", "flags": {"<name>": {"enabled": <bool>, ...}}}.
        return _FEATURE_FLAG_VERSION_KEY in payload and isinstance(
            payload.get(_FEATURE_FLAG_FLAGS_KEY), dict
        )

    @staticmethod
    def _decode_feature_flags(
        profile: str,
        payload: dict[str, object],
    ) -> dict[str, object]:
        flags = payload[_FEATURE_FLAG_FLAGS_KEY]
        if not isinstance(flags, dict):
            raise AppConfigError(
                f"AppConfig feature-flag content for profile {profile!r} has a "
                f"'{_FEATURE_FLAG_FLAGS_KEY}' field that is not an object; got "
                f"{type(flags).__name__}."
            )
        values: dict[str, object] = {}
        raw_values = payload.get(_FEATURE_FLAG_VALUES_KEY, {})
        values_by_flag = raw_values if isinstance(raw_values, dict) else {}
        for flag_name, flag_body in flags.items():
            if not isinstance(flag_body, dict):
                raise AppConfigError(
                    f"AppConfig feature flag {profile}/{flag_name} is not an "
                    f"object; got {type(flag_body).__name__}."
                )
            value_body = values_by_flag.get(flag_name)
            if isinstance(value_body, dict) and _FEATURE_FLAG_ENABLED_KEY in value_body:
                enabled = value_body[_FEATURE_FLAG_ENABLED_KEY]
            elif _FEATURE_FLAG_ENABLED_KEY in flag_body:
                enabled = flag_body[_FEATURE_FLAG_ENABLED_KEY]
            else:
                raise AppConfigError(
                    f"AppConfig feature flag {profile}/{flag_name} is missing the "
                    f"'{_FEATURE_FLAG_ENABLED_KEY}' field. Feature-flag profiles "
                    "map each flag's enabled state onto its Boolean config key."
                )
            if not isinstance(enabled, bool):
                raise AppConfigError(
                    f"AppConfig feature flag {profile}/{flag_name} has a non-boolean "
                    f"'{_FEATURE_FLAG_ENABLED_KEY}' value of type "
                    f"{type(enabled).__name__}; expected a boolean."
                )
            values[str(flag_name)] = enabled
        return values

    @staticmethod
    def _decode_freeform(
        profile: str,
        payload: dict[str, object],
    ) -> dict[str, object]:
        # Freeform JSON is already key -> scalar; the client validates each
        # value's type against the declared default and merges accordingly.
        return {str(key): value for key, value in payload.items()}
