def current_client_ip() -> str:
    """Caller address of the active request under its hosting path's platform policy.

    Resolved by the binding's resolver, never read from a header here; empty when
    the request has no caller address (no connection peer, no forwarded entry).

    Raises:
        RuntimeError: Outside a request; and on a request of a service that serves
            no HTTP request surface its platform names a caller address for.
    """
    binding = _active_binding()
    if binding.client_address is None:
        raise RuntimeError(
            "Request.ip() was evaluated in a service that declares no HTTP request "
            "surface (no rest_api, graphql_api, websocket_api or serverless endpoint "
            "behind an exposed ingress), so its platform names no caller address for "
            "it. Declare an HTTP surface on the service, or stop reading the caller "
            "address here."
        )
    return binding.client_address(binding.request) or ""


