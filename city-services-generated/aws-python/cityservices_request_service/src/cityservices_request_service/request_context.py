def require_request_tenant(request: Request) -> uuid.UUID:
    """Tenant the tenant binding resolved for *request*; refuses a request with none.

    ``Request.tenantId()`` is declared non-null, yet under ``relaxed`` enforcement
    a request may reach a handler with no tenant bound. The accessor fails closed
    rather than hand the body an absent tenant: the request is answered 401, as
    every target answers it.

    Raises:
        HTTPException: 401 when *request* carries no resolved tenant.
    """
    tenant_id = getattr(request.state, "tenant_id", None)
    if tenant_id is None:
        raise missing_tenant_refusal()
    return tenant_id


class MissingTenantRefusal(HTTPException):
    """A request refused 401 for want of a resolved tenant.

    The one class every refusal for a missing tenant raises -- the tenant binding
    (``strict`` enforcement), the route guard and a ``Request.tenantId()`` read -- so
    the service's problem responder answers all of them as the registered
    ``missing-tenant`` family rather than the generic ``unauthorized`` one, and a
    client tells "valid credential, no tenant" from "bad credential" by ``type``.
    """

    def __init__(self) -> None:
        super().__init__(
            status_code=_UNAUTHORIZED,
            detail=_MISSING_TENANT_DETAIL,
            headers={"WWW-Authenticate": "Bearer"},
        )


def missing_tenant_refusal() -> MissingTenantRefusal:
    """The 401 a ``Request.tenantId()`` read answers when no tenant is bound."""
    return MissingTenantRefusal()


def request_has_tenant(request: Request) -> bool:
    """Whether the tenant binding resolved a tenant for *request*; never refuses.

    ``False`` exactly when :func:`require_request_tenant` would refuse *request*,
    including a request no binding ran for. Reads no row and returns no tenant.
    """
    return getattr(request.state, "tenant_id", None) is not None


