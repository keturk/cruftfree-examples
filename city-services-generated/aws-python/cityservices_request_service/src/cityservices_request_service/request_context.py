@contextmanager
def bound_request(
    request: Request, client_address: ClientAddressResolver | None
) -> Iterator[Request]:
    """Bind *request* as the active request for the body of the ``with`` block.

    Args:
        request: The request being served.
        client_address: The resolver of its caller's address on this hosting path;
            ``None`` where the service serves no HTTP request surface its platform
            names a caller address for.
    """
    token = _current_request.set(_BoundRequest(request, client_address))
    try:
        yield request
    finally:
        _current_request.reset(token)


class RequestContextMiddleware:
    """Bind the active HTTP request to the request-context variable."""

    def __init__(
        self, app: ASGIApp, client_address: ClientAddressResolver | None
    ) -> None:
        self._app = app
        self._client_address = client_address

    async def __call__(self, scope: Scope, receive: Receive, send: Send) -> None:
        if scope["type"] != "http":
            await self._app(scope, receive, send)
            return
        with bound_request(Request(scope), self._client_address):
            await self._app(scope, receive, send)


def http_invocation_request(
    *,
    method: str,
    path: str,
    query_string: str,
    headers: Iterable[tuple[str, str]],
    host_reported_peer: str | None,
) -> Request:
    """A ``Request`` for one serverless HTTP invocation, built from what its host handed over.

    Args:
        method: The invocation's HTTP method.
        path: The route's declared path.
        query_string: The raw (still percent-encoded) query string, without ``?``.
        headers: Every header as ``(name, value)``, duplicates kept; names in any case.
        host_reported_peer: The caller address the serverless host reports for the
            invocation, or ``None`` when it reports none (the request then has no
            connection peer).
    """
    scope: Scope = {
        "type": "http",
        "method": method.upper(),
        "path": path,
        "query_string": query_string.encode(_HEADER_ENCODING),
        "headers": [
            (name.lower().encode(_HEADER_ENCODING), value.encode(_HEADER_ENCODING))
            for name, value in headers
        ],
        "client": None if host_reported_peer is None else (host_reported_peer, 0),
    }
    return Request(scope)


