class PageWindow(Protocol):
    """What a page query reads of a request: the row window to cut."""

    offset: int
    limit: int


def page_of_items(
    items: Sequence[T], request: PageWindow, *, max_limit: int
) -> Page[T]:
    """One window of an array a route already computed, with the array's length as the total.

    The elements are those from ``request.offset`` for ``request.limit`` (none once the offset
    passes the end); ``total`` counts every element, so a client numbers its pages exactly as it
    does for a page cut from a query.

    Args:
        items: The whole array, in the order the page lists it.
        request: The window to cut.
        max_limit: The largest page size the deployment profile accepts, reported as the
            envelope's ``maxLimit``.
    """
    return Page(
        items=list(items[request.offset : request.offset + request.limit]),
        total=len(items),
        offset=request.offset,
        limit=request.limit,
        max_limit=max_limit,
    )
