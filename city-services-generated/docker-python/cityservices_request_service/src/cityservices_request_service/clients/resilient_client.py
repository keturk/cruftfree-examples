def _json_default(value: object) -> object:
    """Encode JSON-incompatible DSL values for inter-service request bodies.

    DSL values forwarded into a service-to-service ``json=`` body carry native
    Python objects (``UUID``, ``Decimal``, ``datetime``/``date``/``time``,
    ``Enum``, Pydantic models) that the stdlib JSON encoder rejects. Mirrors the
    framework's route-response encoder so a forwarded ``tenant_id`` (UUID) or any
    temporal/Decimal field serializes instead of raising ``Object of type UUID is
    not JSON serializable``.
    """
