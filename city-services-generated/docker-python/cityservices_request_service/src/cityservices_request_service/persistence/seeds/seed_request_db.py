async def _seed_table(
    conn: AsyncConnection,
    entity_name: str,
    strategy: str,
    statement: str,
    rows: list[dict[str, object]],
) -> None:
    """Write one seed table's rows through its named-placeholder statement.

    Each row's ``@lookup()`` sentinels are resolved first, then the row is
    executed as bound parameters -- no row value is ever formatted into SQL.
    The statement already carries the write strategy's conflict handling
    (upsert for reference data, insert-if-not-exists for baseline/volume).
    """
    for row in rows:
        bound_row = await _resolve_seed_lookups(conn, row)
        await conn.execute(text(statement), bound_row)
    logger.debug(
        "seed_entity_completed entity=%s row_count=%d strategy=%s",
        entity_name,
        len(rows),
        strategy,
    )
