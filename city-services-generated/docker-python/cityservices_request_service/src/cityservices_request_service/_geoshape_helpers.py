def _geoshape_canonical_number(value: float) -> str:
    """*value* in the shortest round-trip form JavaScript's ``String(number)`` gives.

    The bounding-box text is evidence compared across targets, so its numbers
    are spelled one way: integers without a fraction (``1``, not ``1.0``),
    plain decimals from 1e-6 up to 1e21, exponent form outside that range.
    """
    if value == 0:
        return "0"
    sign = "-" if value < 0 else ""
    digits_tuple, exponent = Decimal(repr(abs(value))).normalize().as_tuple()[1:]
    digits = "".join(str(digit) for digit in digits_tuple)
    point = len(digits) + int(exponent)  # position of the decimal point within digits
    if len(digits) <= point <= 21:
        return sign + digits + "0" * (point - len(digits))
    if 0 < point <= 21:
        return sign + digits[:point] + "." + digits[point:]
    if -6 < point <= 0:
        return sign + "0." + "0" * (-point) + digits
    mantissa = digits[0] + ("." + digits[1:] if len(digits) > 1 else "")
    power = point - 1
    return f"{sign}{mantissa}e{'+' if power > 0 else '-'}{abs(power)}"


