def status_problem_response(
    status: int,
    *,
    instance: str,
    detail: str,
    headers: Mapping[str, str] | None = None,
) -> JSONResponse:
    """The answer to a bare HTTP status (an `HTTPException` raised by a guard,
    the rate limiter, a thrown builtin `ValidationError`, a client): the
    registered generic family for *status*, or the composed `http-<status>` type
    for a status the registry does not hold. A family with a fixed detail never
    carries the raiser's text; a family naming a status-detail member carries
    the detail there too, as its one entry."""
    family = GENERIC_PROBLEM_FAMILY_BY_STATUS.get(status)
    if family is None:
        return _write_problem(
            urn=f"{PROBLEM_TYPE_URN_PREFIX}http-{status}",
            family=f"http-{status}",
            title=f"HTTP {status}",
            status=status,
            detail=detail,
            instance=instance,
            headers=headers,
        )
    problem = _registered(family)
    if problem.fixed_detail is not None:
        return problem_response(family, instance=instance, headers=headers)
    member = problem.status_detail_member
    if member is None:
        return problem_response(
            family, instance=instance, detail=detail, headers=headers
        )
    if member == _VIOLATIONS_MEMBER:
        return problem_response(
            family,
            instance=instance,
            detail=detail,
            violations=[detail],
            headers=headers,
        )
    return problem_response(
        family,
        instance=instance,
        detail=detail,
        extensions={member: [detail]},
        headers=headers,
    )


# Inlined from cruftfree_codegen_python/runtime/field_error_path.py. Maps a
# pydantic-style loc tuple to the one wire field-error path every realized
# request-validation problem's errors[].field follows -- unit tested by
# calling it directly, never by executing this rendered module.
_BODY_ROOT_SEGMENT = "body"


def format_field_error_path(loc: Sequence[str | int]) -> str:
    """Map a pydantic-style ``loc`` tuple to the one wire field-error path.

    Args:
        loc: E.g. ``("body", "shippingAddress", "postalCode")`` or
            ``("body", "items", 0, "sku")``. A ``loc`` not starting with
            ``"body"`` is passed through unchanged from its first element --
            a query/path-param validation error carries no body prefix.

    Returns:
        ``"shippingAddress.postalCode"`` / ``"items[0].sku"``.

    Raises:
        ValueError: ``loc`` is empty, or its only element is the body-root
            segment itself (no field to name).
    """
    segments = list(loc)
    if segments and segments[0] == _BODY_ROOT_SEGMENT:
        segments = segments[1:]
    if not segments:
        raise ValueError(
            f"format_field_error_path() received an empty field path "
            f"(loc={list(loc)!r}). Expected: at least one segment naming a "
            f"field beyond the body root."
        )
    parts: list[str] = []
    for segment in segments:
        if isinstance(segment, int):
            parts.append(f"[{segment}]")
        elif parts:
            parts.append(f".{segment}")
        else:
            parts.append(str(segment))
    return "".join(parts)


