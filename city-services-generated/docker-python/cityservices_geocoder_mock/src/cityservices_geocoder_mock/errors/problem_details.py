@dataclass(frozen=True, slots=True)
class RequestRefusal:
    """How a request was refused.

    Attributes:
        unreadable_body: True when the body bytes are not JSON, are absent, or
            their top level is not the declared kind: the host answers
            ``bad-request`` and ``errors`` is empty.
        errors: Otherwise the non-empty field errors, one per
            ``(location, field)``.
    """

    unreadable_body: bool
    errors: tuple[FieldRefusal, ...]


def _code_for(error_type: str) -> str:
    if error_type.startswith(_TYPE_MISSING_PREFIX):
        return _CODE_REQUIRED
    if error_type == _TYPE_EXTRA_FORBIDDEN or error_type.startswith(
        _TYPE_UNEXPECTED_PREFIX
    ):
        return _CODE_UNKNOWN_FIELD
    if error_type == REPEATED_ERROR_TYPE:
        return _CODE_REPEATED
    return _CODE_INVALID


def _is_unreadable_body(error: Mapping[str, object]) -> bool:
    loc = error["loc"]
    if not isinstance(loc, Sequence) or isinstance(loc, str):
        raise ValueError(
            f"A validation error's loc must be a sequence of segments, got {loc!r}. "
            f"Expected a pydantic-style loc tuple such as ('query', 'limit')."
        )
    return error["type"] == _TYPE_JSON_INVALID or (
        len(loc) == _BODY_ROOT_LOC_LENGTH and loc[0] == _BODY_ROOT_SEGMENT
    )


def _field_for(
    location: str,
    loc: Sequence[str | int],
    path_field_names: Mapping[str, str],
    format_body_path: BodyPathFormatter,
) -> str:
    if location == _LOCATION_BODY:
        return format_body_path(loc)
    name = str(loc[1])
    if location == _LOCATION_QUERY:
        return name
    if name not in path_field_names:
        raise ValueError(
            f"A path-parameter validation error names {name!r}, which the service's "
            f"routes do not declare (declared: {sorted(path_field_names)}). Expected "
            f"every path parameter the routes bind to appear in the generated "
            f"path-field table."
        )
    return path_field_names[name]


def classify_request_validation(
    errors: Sequence[Mapping[str, object]],
    *,
    path_field_names: Mapping[str, str],
    format_body_path: BodyPathFormatter,
) -> RequestRefusal:
    """Classify the ``errors()`` of one ``RequestValidationError``.

    Args:
        errors: ``RequestValidationError.errors()`` -- dicts carrying ``loc``
            and ``type``. Messages and inputs are never read: a pydantic message
            embeds fragments of the received value.
        path_field_names: ``{path parameter wire name: DSL placeholder name}``;
            the wire name is what pydantic reports in ``loc``.
        format_body_path: Maps a body ``loc`` to the one wire field-error path
            (``format_field_error_path``).

    Returns:
        ``RequestRefusal(unreadable_body=True, ...)`` when any error is a
        ``json_invalid`` or sits at the body root; otherwise the deduplicated
        field errors in first-seen order.

    Raises:
        ValueError: ``errors`` is empty, a ``loc`` names a location outside
            path / query / body, or a path parameter is not in
            ``path_field_names``.
    """
    if not errors:
        raise ValueError(
            "classify_request_validation() received no errors. Expected the non-empty "
            "errors() of a RequestValidationError."
        )
    if any(_is_unreadable_body(error) for error in errors):
        return RequestRefusal(unreadable_body=True, errors=())
    chosen: dict[tuple[str, str], str] = {}
    for error in errors:
        loc = error["loc"]
        location = str(loc[0])
        if location not in _LOCATIONS:
            raise ValueError(
                f"A validation error names location {location!r}. Expected one of "
                f"{list(_LOCATIONS)}: a generated route binds only path, query and body "
                f"values."
            )
        field = _field_for(location, loc, path_field_names, format_body_path)
        code = _code_for(str(error["type"]))
        key = (location, field)
        held = chosen.get(key)
        if held is None or _CODE_PRECEDENCE.index(code) < _CODE_PRECEDENCE.index(held):
            chosen[key] = code
    return RequestRefusal(
        unreadable_body=False,
        errors=tuple(
            FieldRefusal(location=location, field=field, code=code)
            for (location, field), code in chosen.items()
        ),
    )


def repeated_query_keys_guard(
    keys: Sequence[str],
) -> Callable[[Request], Awaitable[None]]:
    """Build the dependency that refuses a scalar query key sent more than once.

    A scalar query parameter delivered twice (``?limit=1&limit=2``) is HTTP
    parameter pollution: FastAPI silently keeps the last value, so a proxy or
    filter that inspected the first one and the handler that acts on the last
    disagree. The dependency answers it as a ``request-validation`` problem
    (code ``repeated``) before the handler runs.

    Args:
        keys: The scalar query keys the route declares, as the client sends
            them (the wire spelling, never the Python identifier).

    Returns:
        An async dependency over the request that raises
        ``RequestValidationError`` naming every repeated declared key.
    """
    declared = tuple(keys)

    async def reject_repeated_query_keys(request: Request) -> None:
        repeated = [
            key for key in declared if len(request.query_params.getlist(key)) > 1
        ]
        if repeated:
            raise RequestValidationError(
                [
                    {
                        "type": REPEATED_ERROR_TYPE,
                        "loc": (_LOCATION_QUERY, key),
                        "msg": "A scalar query parameter was given more than once.",
                        "input": None,
                    }
                    for key in repeated
                ]
            )

    return reject_repeated_query_keys
