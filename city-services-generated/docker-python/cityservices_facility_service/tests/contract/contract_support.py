class ContractFailure(AssertionError):
    """A route answered other than its declared contract."""


def _is_text(value: object) -> bool:
    return isinstance(value, str)


def _is_integer(value: object) -> bool:
    return isinstance(value, int) and not isinstance(value, bool)


def _is_number(value: object) -> bool:
    return isinstance(value, int | float) and not isinstance(value, bool)


def _is_boolean(value: object) -> bool:
    return isinstance(value, bool)


def _is_finite(value: object) -> bool:
    return _is_number(value) and math.isfinite(value)


def _parses(parse: Callable[[str], object], value: object) -> bool:
    if not isinstance(value, str):
        return False
    try:
        parse(value)
    except ValueError:
        return False
    return True


def _is_uuid(value: object) -> bool:
    return _parses(uuid.UUID, value)


def _is_date_time(value: object) -> bool:
    return _parses(_dt.datetime.fromisoformat, value)


def _is_date(value: object) -> bool:
    return _parses(_dt.date.fromisoformat, value)


def _is_time(value: object) -> bool:
    return _parses(_dt.time.fromisoformat, value)


def _is_duration(value: object) -> bool:
    return isinstance(value, str) and _DURATION_PATTERN.fullmatch(value) is not None


def _is_decimal(value: object) -> bool:
    if _is_number(value):
        return True
    if not isinstance(value, str):
        return False
    try:
        return Decimal(value).is_finite()
    except InvalidOperation:
        return False


def _is_base64(value: object) -> bool:
    return isinstance(value, str) and (
        value == "" or _BYTES_JSON_PATTERN.fullmatch(value) is not None
    )


def _is_any(value: object) -> bool:
    return True


def _is_present(value: object) -> bool:
    return value is not None


