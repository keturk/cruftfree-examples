def _instant(value: str) -> _dt.datetime:
    """A timestamp, a naive one read as UTC."""
    parsed = _dt.datetime.fromisoformat(value)
    return (
        parsed if parsed.tzinfo is not None else parsed.replace(tzinfo=_dt.timezone.utc)
    )


def _same_parsed(
    parse: Callable[[str], object], sent: object, answered: object
) -> bool:
    return (
        _parses(parse, sent)
        and _parses(parse, answered)
        and parse(sent) == parse(answered)
    )


def _same(sent: object, answered: object) -> bool:
    return sent == answered


def _same_uuid(sent: object, answered: object) -> bool:
    return _same_parsed(uuid.UUID, sent, answered)


def _same_date_time(sent: object, answered: object) -> bool:
    return _same_parsed(_instant, sent, answered)


def _same_date(sent: object, answered: object) -> bool:
    return _same_parsed(_dt.date.fromisoformat, sent, answered)


def _same_time(sent: object, answered: object) -> bool:
    return _same_parsed(_dt.time.fromisoformat, sent, answered)


def _same_number(sent: object, answered: object) -> bool:
    return _is_number(sent) and _is_number(answered) and float(sent) == float(answered)


def _same_decimal(sent: object, answered: object) -> bool:
    return (
        _is_decimal(sent)
        and _is_decimal(answered)
        and Decimal(str(sent)) == Decimal(str(answered))
    )


def _answered(sent: object, answered: object) -> bool:
    """A kind whose text form a backend may normalize: answered at all."""
    return answered is not None


#: How a member sent as one scalar kind is recognized in the answer.
_ECHO_SCALARS: dict[str, Callable[[object, object], bool]] = {
    "string": _same,
    "uuid": _same_uuid,
    "date-time": _same_date_time,
    "date": _same_date,
    "time": _same_time,
    "duration": _answered,
    "integer": _same,
    "number": _same_number,
    "decimal": _same_decimal,
    "boolean": _same,
    "base64": _same,
    "any": _answered,
    "present": _answered,
}

#: The comparison operators a computed member's ``compare`` rule names.
_COMPARISONS: dict[str, Callable[[object, object], bool]] = {
    "<": operator.lt,
    "<=": operator.le,
    ">": operator.gt,
    ">=": operator.ge,
}


def _computed_equals(argument: JsonValue, value: Mapping[str, object]) -> object:
    return value[argument["member"]] == argument["value"]


def _computed_compare(argument: JsonValue, value: Mapping[str, object]) -> object:
    if argument["operator"] not in _COMPARISONS:
        raise ContractFailure(
            f"contract.json names the unknown comparison {argument['operator']!r}."
        )
    return _COMPARISONS[argument["operator"]](
        value[argument["member"]], argument["threshold"]
    )


def _computed_interpolate(argument: JsonValue, value: Mapping[str, object]) -> object:
    return "".join(
        part["text"] if "text" in part else _text_form(value[part["member"]])
        for part in argument
    )


#: What a computed member equals, per rule kind a contract names, over the answer's own members.
_COMPUTED_CHECKS: dict[str, Callable[[JsonValue, Mapping[str, object]], object]] = {
    "equals": _computed_equals,
    "compare": _computed_compare,
    "interpolate": _computed_interpolate,
}


def _describe(value: object) -> str:
    """A value's JSON type, never the value itself."""
    if value is None:
        return "null"
    return type(value).__name__


class ShapeChecker:
    """Checks a decoded JSON value against a contract shape."""

    def __init__(
        self,
        objects: Mapping[str, JsonValue],
        page: Mapping[str, JsonValue],
        geojson: Mapping[str, JsonValue],
    ) -> None:
        self._objects = objects
        self._page = page
        self._geojson = geojson

    def check(self, shape: JsonValue, value: object, where: str) -> None:
        if not isinstance(shape, dict) or len(shape) != 1:
            raise ContractFailure(
                f"{where}: contract.json holds a malformed shape {shape!r}."
            )
        [(kind, argument)] = shape.items()
        if kind not in _SHAPE_CHECKS:
            raise ContractFailure(
                f"{where}: contract.json names the unknown shape kind {kind!r}."
            )
        _SHAPE_CHECKS[kind](self, argument, value, where)

    def scalar(self, kind: JsonValue, value: object, where: str) -> None:
        if not isinstance(kind, str) or kind not in _SCALAR_CHECKS:
            raise ContractFailure(
                f"{where}: contract.json names the unknown scalar kind {kind!r}."
            )
        if not _SCALAR_CHECKS[kind](value):
            raise ContractFailure(
                f"{where}: expected a {kind} value, got {_describe(value)}."
            )

    def enum(self, members: JsonValue, value: object, where: str) -> None:
        if not isinstance(members, list) or value not in members:
            raise ContractFailure(
                f"{where}: expected one of {members!r}, got {_describe(value)}."
            )

    def object_shape(self, shape_id: JsonValue, value: object, where: str) -> None:
        if not isinstance(shape_id, str) or shape_id not in self._objects:
            raise ContractFailure(
                f"{where}: contract.json names the unknown object {shape_id!r}."
            )
        declared = self._objects[shape_id]
        fields = declared["fields"] if isinstance(declared, dict) else None
        if not isinstance(fields, dict):
            raise ContractFailure(
                f"{where}: contract.json holds a malformed object {shape_id!r}."
            )
        if not isinstance(value, dict):
            raise ContractFailure(
                f"{where}: expected an object, got {_describe(value)}."
            )
        unknown = sorted(set(value) - set(fields))
        if unknown:
            raise ContractFailure(
                f"{where}: undeclared members {unknown} (declared: {sorted(fields)})."
            )
        for name, member in fields.items():
            self._member(name, member, value, f"{where}.{name}")
        computed = declared["computed"] if "computed" in declared else {}
        for name, rule in computed.items():
            if name in value:
                self._computed(rule, value, name, f"{where}.{name}")

    def _computed(
        self, rule: JsonValue, value: dict[str, object], name: str, where: str
    ) -> None:
        if not isinstance(rule, dict) or len(rule) != 1:
            raise ContractFailure(
                f"{where}: contract.json holds a malformed computed rule."
            )
        [(kind, argument)] = rule.items()
        if kind not in _COMPUTED_CHECKS:
            raise ContractFailure(
                f"{where}: contract.json names the unknown computed rule {kind!r}."
            )
        if value[name] != _COMPUTED_CHECKS[kind](argument, value):
            raise ContractFailure(
                f"{where}: the computed member disagrees with its declared {kind!r} rule over the answer's own members."
            )

    def fields_of(self, shape: JsonValue, where: str) -> Mapping[str, JsonValue]:
        """The declared members of the object shape *shape*."""
        if (
            not isinstance(shape, dict)
            or "object" not in shape
            or shape["object"] not in self._objects
        ):
            raise ContractFailure(
                f"{where}: contract.json compares members of a non-object answer {shape!r}."
            )
        return self._objects[shape["object"]]["fields"]

    # -- a sent value, recognized in the answer ------------------------------

    def same(self, shape: JsonValue, sent: object, answered: object) -> bool:
        """Whether *answered* is the value *sent*, read by the answer's declared *shape*."""
        [(kind, argument)] = shape.items()
        if kind not in _ECHO_SHAPES:
            raise ContractFailure(
                f"contract.json names the unknown shape kind {kind!r}."
            )
        return _ECHO_SHAPES[kind](self, argument, sent, answered)

    def _same_scalar(self, kind: JsonValue, sent: object, answered: object) -> bool:
        return _ECHO_SCALARS[kind](sent, answered)

    def _same_member(self, members: JsonValue, sent: object, answered: object) -> bool:
        return sent == answered

    def _same_object(self, shape_id: JsonValue, sent: object, answered: object) -> bool:
        fields = self._objects[shape_id]["fields"]
        if not isinstance(sent, dict) or not isinstance(answered, dict):
            return False
        return all(
            name in fields
            and name in answered
            and self.same(fields[name]["shape"], member, answered[name])
            for name, member in sent.items()
        )

    def _same_array(self, element: JsonValue, sent: object, answered: object) -> bool:
        if (
            not isinstance(sent, list)
            or not isinstance(answered, list)
            or len(sent) != len(answered)
        ):
            return False
        return all(self.same(element, one, other) for one, other in zip(sent, answered))

    def _same_map(self, element: JsonValue, sent: object, answered: object) -> bool:
        if (
            not isinstance(sent, dict)
            or not isinstance(answered, dict)
            or set(sent) != set(answered)
        ):
            return False
        return all(
            self.same(element, member, answered[key]) for key, member in sent.items()
        )

    def _same_nullable(self, inner: JsonValue, sent: object, answered: object) -> bool:
        if sent is None:
            return answered is None
        return answered is not None and self.same(inner, sent, answered)

    def _answered_shape(
        self, argument: JsonValue, sent: object, answered: object
    ) -> bool:
        """A page, a union or a GeoJSON value: answered at all."""
        return answered is not None

    def _member(
        self, name: str, member: JsonValue, value: dict[str, object], where: str
    ) -> None:
        if not isinstance(member, dict):
            raise ContractFailure(f"{where}: contract.json holds a malformed member.")
        if name in value:
            self.check(member["shape"], value[name], where)
        elif member["required"]:
            raise ContractFailure(f"{where}: required member is missing.")

    def array(self, element: JsonValue, value: object, where: str) -> None:
        if not isinstance(value, list):
            raise ContractFailure(
                f"{where}: expected an array, got {_describe(value)}."
            )
        for index, item in enumerate(value):
            self.check(element, item, f"{where}[{index}]")

    def map_shape(self, element: JsonValue, value: object, where: str) -> None:
        if not isinstance(value, dict):
            raise ContractFailure(
                f"{where}: expected an object map, got {_describe(value)}."
            )
        for key, item in value.items():
            self.check(element, item, f"{where}[{key!r}]")

    def page(self, element: JsonValue, value: object, where: str) -> None:
        items_member = self._page["items"]
        counts = self._page["counts"]
        if not isinstance(items_member, str) or not isinstance(counts, list):
            raise ContractFailure(
                f"{where}: contract.json holds a malformed page envelope."
            )
        if not isinstance(value, dict):
            raise ContractFailure(
                f"{where}: expected a page object, got {_describe(value)}."
            )
        declared = {items_member, *counts}
        if set(value) != declared:
            raise ContractFailure(
                f"{where}: page members {sorted(value)}, expected {sorted(declared)}."
            )
        for count in counts:
            self.scalar("integer", value[count], f"{where}.{count}")
        self.array(element, value[items_member], f"{where}.{items_member}")
        total_member = self._page["members"]["total"]
        if value[total_member] < len(value[items_member]):
            raise ContractFailure(
                f"{where}.{total_member}: below the {len(value[items_member])} items answered."
            )

    def nullable(self, inner: JsonValue, value: object, where: str) -> None:
        if value is not None:
            self.check(inner, value, where)

    def any_of(self, members: JsonValue, value: object, where: str) -> None:
        if not isinstance(members, list):
            raise ContractFailure(f"{where}: contract.json holds a malformed union.")
        reasons: list[str] = []
        for member in members:
            try:
                self.check(member, value, where)
            except ContractFailure as failure:
                reasons.append(str(failure))
            else:
                return
        raise ContractFailure(f"{where}: matches no union member: {reasons}")

    # -- GeoJSON (RFC 7946), by the rules contract.json states ---------------

    def geojson(self, argument: JsonValue, value: object, where: str) -> None:
        if (
            not isinstance(argument, dict)
            or argument.get("kind") not in _GEOJSON_CHECKS
        ):
            raise ContractFailure(
                f"{where}: contract.json holds a malformed GeoJSON shape {argument!r}."
            )
        _GEOJSON_CHECKS[argument["kind"]](self, argument["properties"], value, where)

    def _member_name(self, role: str) -> str:
        return self._geojson["members"][role]

    def _typed_object(
        self, value: object, where: str, types: set[str]
    ) -> dict[str, object]:
        if not isinstance(value, dict):
            raise ContractFailure(
                f"{where}: expected a GeoJSON object, got {_describe(value)}."
            )
        type_member = self._member_name("type")
        if type_member not in value or value[type_member] not in types:
            raise ContractFailure(
                f"{where}.{type_member}: expected one of {sorted(types)}."
            )
        bbox_member = self._member_name("bbox")
        if bbox_member in value:
            self._bbox(value[bbox_member], f"{where}.{bbox_member}")
        return value

    def _required(self, value: dict[str, object], role: str, where: str) -> object:
        member = self._member_name(role)
        if member not in value:
            raise ContractFailure(f"{where}.{member}: required member is missing.")
        return value[member]

    def _bbox(self, value: object, where: str) -> None:
        lengths = self._geojson["bboxLengths"]
        if (
            not isinstance(value, list)
            or len(value) not in lengths
            or not all(map(_is_finite, value))
        ):
            raise ContractFailure(f"{where}: expected {lengths} finite numbers.")

    def _position(self, value: object, where: str) -> None:
        shortest, longest = self._geojson["positionLengths"]
        if not isinstance(value, list) or not shortest <= len(value) <= longest:
            raise ContractFailure(
                f"{where}: expected a position of {shortest} to {longest} numbers."
            )
        if not all(map(_is_finite, value)):
            raise ContractFailure(f"{where}: a position holds finite numbers only.")
        if (
            abs(value[0]) > self._geojson["longitudeBound"]
            or abs(value[1]) > self._geojson["latitudeBound"]
        ):
            raise ContractFailure(
                f"{where}: the position lies outside WGS 84 longitude/latitude bounds."
            )

    def _each(
        self, value: object, where: str, check: Callable[[object, str], None]
    ) -> None:
        if not isinstance(value, list):
            raise ContractFailure(
                f"{where}: expected an array, got {_describe(value)}."
            )
        for index, item in enumerate(value):
            check(item, f"{where}[{index}]")

    def _positions(self, value: object, where: str, minimum: int = 0) -> None:
        self._each(value, where, self._position)
        if len(value) < minimum:
            raise ContractFailure(f"{where}: expected at least {minimum} positions.")

    def _line(self, value: object, where: str) -> None:
        self._positions(value, where, self._geojson["lineMinPositions"])

    def _ring(self, value: object, where: str) -> None:
        self._positions(value, where, self._geojson["ringMinPositions"])
        if value[0] != value[-1]:
            raise ContractFailure(
                f"{where}: a linear ring must end at its first position."
            )

    def _lines(self, value: object, where: str) -> None:
        self._each(value, where, self._line)

    def _polygon(self, value: object, where: str) -> None:
        self._each(value, where, self._ring)

    def _polygons(self, value: object, where: str) -> None:
        self._each(value, where, self._polygon)

    def _geometry(
        self, value: object, where: str, nested_collection: bool = True
    ) -> None:
        held_by_type = self._geojson["coordinates"]
        collection_type = self._geojson["geometryCollection"]
        types = set(held_by_type) | ({collection_type} if nested_collection else set())
        geometry = self._typed_object(value, where, types)
        declared = geometry[self._member_name("type")]
        if declared == collection_type:
            members = self._required(geometry, "geometries", where)
            self._each(
                members,
                f"{where}.{self._member_name('geometries')}",
                self._simple_geometry,
            )
            return
        coordinates = self._required(geometry, "coordinates", where)
        _COORDINATE_CHECKS[held_by_type[declared]](
            self, coordinates, f"{where}.{self._member_name('coordinates')}"
        )

    def _simple_geometry(self, value: object, where: str) -> None:
        self._geometry(value, where, nested_collection=False)

    def _feature(self, properties: JsonValue, value: object, where: str) -> None:
        feature = self._typed_object(value, where, {self._geojson["feature"]})
        geometry = self._required(feature, "geometry", where)
        if geometry is not None:
            self._geometry(geometry, f"{where}.{self._member_name('geometry')}")
        members = self._required(feature, "properties", where)
        if members is not None:
            self.check(
                properties, members, f"{where}.{self._member_name('properties')}"
            )
        id_member = self._member_name("id")
        if id_member in feature and not (
            _is_text(feature[id_member]) or _is_finite(feature[id_member])
        ):
            raise ContractFailure(
                f"{where}.{id_member}: expected a string or a number, got {_describe(feature[id_member])}."
            )

    def geojson_geometry(
        self, properties: JsonValue, value: object, where: str
    ) -> None:
        self._geometry(value, where)

    def geojson_feature(self, properties: JsonValue, value: object, where: str) -> None:
        self._feature(properties, value, where)

    def geojson_feature_collection(
        self, properties: JsonValue, value: object, where: str
    ) -> None:
        collection = self._typed_object(
            value, where, {self._geojson["featureCollection"]}
        )
        features = self._required(collection, "features", where)
        self._each(
            features,
            f"{where}.{self._member_name('features')}",
            lambda item, at: self._feature(properties, item, at),
        )


#: One check per GeoJSON shape a contract names.
_GEOJSON_CHECKS: dict[str, Callable[[ShapeChecker, JsonValue, object, str], None]] = {
    "GeoJsonGeometry": ShapeChecker.geojson_geometry,
    "GeoJsonFeature": ShapeChecker.geojson_feature,
    "GeoJsonFeatureCollection": ShapeChecker.geojson_feature_collection,
}

#: One check per kind of coordinates a geometry type holds.
