def _text_form(value: object) -> str:
    """A value's text as a query parameter, a path segment or a form field carries it."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, dict | list):
        return json.dumps(value, separators=(",", ":"))
    return str(value)


@dataclass(frozen=True)
class Principal:
    """One caller the credentials file supplies: who it is to the deployment and the
    token it presents. The token is opaque -- never decoded, verified, printed or logged."""

    name: str
    provider: str
    roles: frozenset[str]
    token: str = field(repr=False)
    tenant: str | None = None
    #: The file declares the principal belongs to no tenant (``"tenant": null``); a principal
    #: whose file states nothing about its tenant is a member of one the suite cannot name.
    tenantless: bool = False


def _principal_text(entry: Mapping[str, object], member: str, where: str) -> str:
    value = entry[member]
    if not isinstance(value, str) or not value:
        raise RuntimeError(f"{where}: {member!r} must be a non-empty text.")
    return value


def _principal_tenant(
    entry: Mapping[str, object], where: str
) -> tuple[str | None, bool]:
    """The tenant a principal names and whether it declares it has none: ``(None, False)``
    when the entry says nothing, ``(None, True)`` for ``"tenant": null``."""
    if "tenant" not in entry:
        return None, False
    tenant = entry["tenant"]
    if tenant is None:
        return None, True
    if not isinstance(tenant, str) or not tenant:
        raise RuntimeError(
            f"{where}: 'tenant' must be a non-empty text, or null for a principal that belongs to no tenant."
        )
    return tenant, False


def _principal_roles(entry: Mapping[str, object], where: str) -> frozenset[str]:
    roles = entry["roles"]
    if not isinstance(roles, list) or not all(
        isinstance(role, str) and role for role in roles
    ):
        raise RuntimeError(
            f"{where}: 'roles' must be a list of non-empty texts (an empty list holds no role)."
        )
    return frozenset(roles)


def _principal(entry: object, position: int) -> Principal:
    """One principal of the credentials file, validated; a message names the entry, never its token."""
    where = f"{CREDENTIALS_ENV} principal #{position}"
    if not isinstance(entry, dict):
        raise RuntimeError(f"{where} is not an object.")
    unknown = sorted(set(entry) - PRINCIPAL_MEMBERS)
    missing = [member for member in PRINCIPAL_REQUIRED_MEMBERS if member not in entry]
    if unknown or missing:
        raise RuntimeError(
            f"{where}: unknown members {unknown}, missing members {missing}; "
            f"a principal holds {sorted(PRINCIPAL_MEMBERS)} (tenant is optional; null declares none)."
        )
    token = _principal_text(entry, "token", where)
    if _TOKEN_PATTERN.fullmatch(token) is None:
        raise RuntimeError(
            f"{where}: 'token' must be the bearer token alone, one run of visible characters."
        )
    tenant, tenantless = _principal_tenant(entry, where)
    return Principal(
        name=_principal_text(entry, "name", where),
        provider=_principal_text(entry, "provider", where),
        roles=_principal_roles(entry, where),
        token=token,
        tenant=tenant,
        tenantless=tenantless,
    )


def load_principals(path: Path) -> tuple[Principal, ...]:
    """The principals of the credentials file at *path*.

    Raises:
        RuntimeError: the file cannot be read, is not the documented JSON document, or
            holds a malformed or duplicate principal. A message never carries a token.
    """
    try:
        document = json.loads(path.read_text(encoding="utf-8"))
    except OSError as error:
        raise RuntimeError(
            f"{CREDENTIALS_ENV} names {str(path)!r}, which cannot be read ({error.strerror})."
        ) from None
    except ValueError as error:
        raise RuntimeError(
            f"{CREDENTIALS_ENV} file {str(path)!r} is not a JSON document ({type(error).__name__})."
        ) from None
    entries = (
        document.get("principals")
        if isinstance(document, dict) and set(document) == CREDENTIALS_MEMBERS
        else None
    )
    if not isinstance(entries, list) or not entries:
        raise RuntimeError(
            f"{CREDENTIALS_ENV} file {str(path)!r} must be "
            '{"principals": [...]} with at least one principal.'
        )
    principals = tuple(
        _principal(entry, position) for position, entry in enumerate(entries, start=1)
    )
    names = [principal.name for principal in principals]
    duplicates = sorted({name for name in names if names.count(name) > 1})
    if duplicates:
        raise RuntimeError(
            f"{CREDENTIALS_ENV} file {str(path)!r} names the principals {duplicates} more than once."
        )
    return principals


class ContractSuite:
    """One deployed service, called route by route against contract.json."""

    def __init__(
        self,
        contract: Mapping[str, JsonValue],
        client: httpx.Client,
        principals: Sequence[Principal] = (),
    ) -> None:
        self._contract = contract
        self._client = client
        self._principals = tuple(principals)
        self._caller: Principal | None = None
        self._routes = contract["routes"]
        self._resources = contract["resources"]
        self._identity = contract["identity"]
        self._tenant = contract["tenant"]
        self._run_tenant = str(uuid.uuid4())
        self._tenant_id = self._run_tenant
        self._problem = contract["problem"]
        self._page = contract["page"]
        self._shapes = ShapeChecker(
            contract["shapes"], contract["page"], contract["geojson"]
        )
        self._foreign_key: object | None = None

    @classmethod
    def open(cls) -> ContractSuite:
        """The suite over contract.json, calling the origin ``BASE_URL`` names.

        With ``CONTRACT_CREDENTIALS`` naming a credentials file, every positive call
        presents a token that file supplies; without it, one signed with the test identity.
        """
        base_url = os.environ.get(BASE_URL_ENV, "").strip()
        if not base_url:
            raise RuntimeError(
                f"{BASE_URL_ENV} is not set. Set it to the deployed service's origin "
                "(for example https://orders.example.test) and run the suite again."
            )
        credentials = os.environ.get(CREDENTIALS_ENV, "").strip()
        principals = load_principals(Path(credentials)) if credentials else ()
        contract = json.loads(CONTRACT_FILE.read_text(encoding="utf-8"))
        client = httpx.Client(
            base_url=base_url, timeout=REQUEST_TIMEOUT_SECONDS, follow_redirects=False
        )
        return cls(contract, client, principals)

    def close(self) -> None:
        self._client.close()

    # -- tokens ------------------------------------------------------------

    def _claims(self, roles: list[str], tenant_claim: bool) -> dict[str, object]:
        identity = self._identity
        issued_at = int(time.time())
        claims: dict[str, object] = {
            "sub": str(uuid.uuid4()),
            "iss": identity["issuer"],
            "iat": issued_at,
            "exp": issued_at + identity["tokenLifetimeSeconds"],
            identity["rolesClaim"]: roles,
        }
        if tenant_claim:
            claims[self._tenant["name"]] = self._tenant_id
        return claims

    def _token(self, roles: list[str], tenant_claim: bool) -> str:
        identity = self._identity
        return jwt.encode(
            self._claims(roles, tenant_claim),
            identity["privateKey"],
            algorithm=identity["algorithm"],
            headers={"kid": identity["keyId"]},
        )

    def _foreign_token(self, roles: list[str]) -> str:
        """A well-formed token naming the test identity's issuer and key id, signed
        by a key this run generated, which no deployment trusts."""
        identity = self._identity
        algorithm = identity["algorithm"]
        if algorithm not in _FOREIGN_KEYS:
            raise ContractFailure(
                f"No foreign signing key for the test identity's algorithm {algorithm!r} "
                f"(known: {sorted(_FOREIGN_KEYS)})."
            )
        if self._foreign_key is None:
            self._foreign_key = _FOREIGN_KEYS[algorithm]()
        return jwt.encode(
            self._claims(roles, False),
            self._foreign_key,
            algorithm=algorithm,
            headers={"kid": identity["keyId"]},
        )

    def _anonymous_headers(self) -> dict[str, str]:
        """The headers of a call without a credential: a header-sourced tenant rides every call."""
        headers = {"Accept": JSON_MEDIA_TYPE}
        if self._tenant is not None and self._tenant["source"] == TENANT_FROM_HEADER:
            headers[self._tenant["name"]] = self._tenant_id
        return headers

    def _bearer_headers(self, token: str) -> dict[str, str]:
        return {**self._anonymous_headers(), "Authorization": f"Bearer {token}"}

    def _headers(
        self, route: Mapping[str, JsonValue], roles: list[str] | None = None
    ) -> dict[str, str]:
        """The headers of a positive call: with supplied principals, the token of the one
        presenting this route; without, a token signed with the test identity, holding the
        route's roles or *roles*."""
        if route["auth"] == AUTH_PUBLIC:
            return self._anonymous_headers()
        if self._principals:
            return self._bearer_headers(self._presenter(route).token)
        held = route["roles"] if roles is None else roles
        return self._bearer_headers(self._token(held, route["tenantClaim"]))

    # -- supplied principals -----------------------------------------------

    @staticmethod
    def _admits(
        route: Mapping[str, JsonValue], principal: Principal, *, wrong_role: bool
    ) -> bool:
        """Whether *principal* is of a provider the route admits and holds one of the route's
        roles (any principal of the provider when the route declares none) -- or, for a
        wrong-role call, holds none of them."""
        if principal.provider not in route["providers"]:
            return False
        holds = bool(principal.roles & set(route["roles"]))
        return not holds if wrong_role else holds or not route["roles"]

    def _admits_tenancy(
        self, route: Mapping[str, JsonValue], principal: Principal
    ) -> bool:
        """Whether *principal*'s tenant standing suits *route*: an ``@onboarding`` route, which
        refuses a caller that already belongs to a tenant, admits only a principal declared
        tenantless; any other route of a tenant-scoped service needs a tenant, so admits none."""
        if route.get(ONBOARDING_MEMBER):
            return principal.tenantless
        return not (principal.tenantless and self._tenant is not None)

    def _in_caller_tenant(self, principal: Principal) -> bool:
        """Whether *principal* shares the tenant of the principal calling the route under test,
        so a record one call creates is one the next call reads. A caller declared tenantless
        has no tenant to share with another principal; it alone is in its own standing."""
        if self._tenant is None or self._caller is None:
            return True
        if self._caller.tenantless:
            return principal is self._caller
        return principal.tenant == self._caller.tenant

    def _select(
        self, route: Mapping[str, JsonValue], *, wrong_role: bool = False
    ) -> Principal | None:
        """The first supplied principal that presents (or, for *wrong_role*, is refused by) *route*."""
        return next(
            (
                principal
                for principal in self._principals
                if self._admits(route, principal, wrong_role=wrong_role)
                and self._admits_tenancy(route, principal)
                and self._in_caller_tenant(principal)
            ),
            None,
        )

    def _no_principal(
        self, route: Mapping[str, JsonValue], *, wrong_role: bool = False
    ) -> NoReturn:
        """Skip the test: no supplied principal fits the route. Never a pass, never a failure."""
        providers = ", ".join(route["providers"])
        roles = ", ".join(route["roles"]) or "none declared"
        holding = "holding none of roles" if wrong_role else "roles"
        scope = (
            " in the tenant of the calling principal"
            if self._tenant is not None and self._caller is not None
            else ""
        )
        standing = " without a tenant" if route.get(ONBOARDING_MEMBER) else ""
        pytest.skip(
            f"no supplied principal{standing} for providers [{providers}], {holding} [{roles}]{scope}"
        )

    def _presenter(self, route: Mapping[str, JsonValue]) -> Principal:
        """The supplied principal that presents a positive call to *route*."""
        principal = self._select(route)
        if principal is None:
            self._no_principal(route)
        return principal

    def _use(self, principal: Principal) -> None:
        """Make *principal* the test's caller; a tenant the service reads from the request is its own."""
        self._caller = principal
        if self._tenant is None or self._tenant["source"] == TENANT_FROM_JWT:
            return
        if principal.tenant is None:
            pytest.skip(
                f"supplied principal {principal.name!r} holds no tenant, "
                f"which the service reads from the request's {self._tenant['source']}"
            )
        self._tenant_id = principal.tenant

    def _begin(
        self,
        route: Mapping[str, JsonValue],
        *,
        presents: bool,
        wrong_role: bool = False,
    ) -> None:
        """Start a test with no caller in the run's tenant; when its calls present a supplied
        principal, choose that principal first, so a test no principal fits is skipped before
        it creates anything."""
        self._caller = None
        self._tenant_id = self._run_tenant
        if not self._principals or not presents or route["auth"] == AUTH_PUBLIC:
            return
        principal = self._select(route, wrong_role=wrong_role)
        if principal is None:
            self._no_principal(route, wrong_role=wrong_role)
        self._use(principal)

    # -- values ------------------------------------------------------------

    def value(self, spec: JsonValue) -> object:
        """The JSON value a value spec stands for, creating referenced resources first."""
        if not isinstance(spec, dict) or len(spec) != 1:
            raise ContractFailure(f"contract.json holds a malformed value {spec!r}.")
        [(kind, argument)] = spec.items()
        if kind not in _VALUE_BUILDERS:
            raise ContractFailure(
                f"contract.json names the unknown value kind {kind!r}."
            )
        return _VALUE_BUILDERS[kind](self, argument)

    def literal(self, argument: JsonValue) -> object:
        return argument

    def unique(self, argument: JsonValue) -> object:
        token = secrets.token_hex(argument["hexLength"])[: argument["hexLength"]]
        if argument["uppercase"]:
            token = token.upper()
        return f"{argument['prefix']}{token}{argument['suffix']}"

    def uuid4(self, argument: JsonValue) -> object:
        return str(uuid.uuid4())

    def object_value(self, argument: JsonValue) -> object:
        return {name: self.value(member) for name, member in argument.items()}

    def array_value(self, argument: JsonValue) -> object:
        return [self.value(element) for element in argument]

    def map_value(self, argument: JsonValue) -> object:
        return {_text_form(self.value(argument["key"])): self.value(argument["value"])}

    def reference(self, argument: JsonValue) -> object:
        """The key of a fresh instance of the entity *argument* names, made through its create route."""
        return self._create(argument, {})[self._resources[argument]["key"]]

    def _create(
        self, qualified_name: str, overrides: Mapping[str, object]
    ) -> dict[str, object]:
        """A fresh instance of the entity *qualified_name* names, made through its
        create route with *overrides* replacing members of its planned input."""
        resource = self._resources[qualified_name]
        route_id = resource["create"]
        route = self._routes[route_id]
        response = self._send(
            route_id,
            route,
            body={"json": {**self._json_body(route_id, route), **overrides}},
        )
        if response.status_code != route["success"]["status"]:
            raise ContractFailure(
                f"Creating a {qualified_name} through {route_id} answered {response.status_code}, "
                f"expected {route['success']['status']}{self._problem_summary(response)}."
            )
        created = response.json()
        key = resource["key"]
        if not isinstance(created, dict) or key not in created:
            raise ContractFailure(
                f"Creating a {qualified_name} through {route_id} answered no {key!r} member."
            )
        return created

    def upload(self, argument: JsonValue) -> object:
        return (UPLOAD_FILE_NAME, UPLOAD_FILE_BYTES, UPLOAD_MEDIA_TYPE)

    def tenant(self, argument: JsonValue) -> object:
        return self._tenant_id

    # -- calls -------------------------------------------------------------

    def _path_values(self, params: Mapping[str, JsonValue]) -> dict[str, object]:
        return {name: self.value(spec) for name, spec in params.items()}

    def _path(
        self, route: Mapping[str, JsonValue], values: Mapping[str, object]
    ) -> str:
        texts = {
            name: quote(_text_form(value), safe="") for name, value in values.items()
        }
        missing = sorted(set(_PATH_PARAMETER.findall(route["path"])) - set(texts))
        if missing:
            raise ContractFailure(
                f"contract.json gives no value for the path parameters {missing}."
            )
        return _PATH_PARAMETER.sub(lambda match: texts[match.group(1)], route["path"])

    def _query(self, route: Mapping[str, JsonValue]) -> dict[str, str]:
        return {
            name: _text_form(self.value(spec)) for name, spec in route["query"].items()
        }

    def _body(self, route_id: str, body: JsonValue) -> dict[str, object]:
        """The request arguments carrying the value of the body spec *body*."""
        if body is None:
            return {}
        if body["encoding"] == BODY_JSON:
            return {"json": self.value(body["value"])}
        if body["encoding"] != BODY_MULTIPART:
            raise ContractFailure(
                f"{route_id}: contract.json names the unknown body encoding {body['encoding']!r}."
            )
        parts = {name: self.value(spec) for name, spec in body["parts"].items()}
        return {
            "files": {
                name: part for name, part in parts.items() if isinstance(part, tuple)
            },
            "data": {
                name: _text_form(part)
                for name, part in parts.items()
                if not isinstance(part, tuple)
            },
        }

    def _json_body(
        self, route_id: str, route: Mapping[str, JsonValue]
    ) -> dict[str, object]:
        """The planned JSON object input of *route*."""
        body = self._body(route_id, route["body"])
        if "json" not in body or not isinstance(body["json"], dict):
            raise ContractFailure(
                f"{route_id}: contract.json gives the route no JSON object input to vary."
            )
        return body["json"]

    def _send(
        self,
        route_id: str,
        route: Mapping[str, JsonValue],
        *,
        path_values: Mapping[str, object] | None = None,
        query: Mapping[str, str] | None = None,
        body: Mapping[str, object] | None = None,
        headers: Mapping[str, str] | None = None,
    ) -> httpx.Response:
        """Call *route*, each part of the request planned by contract.json unless given."""
        values = (
            self._path_values(route["pathParams"])
            if path_values is None
            else path_values
        )
        request: dict[str, object] = {
            "params": self._query(route) if query is None else query,
            "headers": self._headers(route) if headers is None else headers,
            **(self._body(route_id, route["body"]) if body is None else body),
        }
        return self._client.request(
            route["method"], self._path(route, values), **request
        )

    def _problem_summary(self, response: httpx.Response) -> str:
        """The problem type and title of an error answer, never its detail or body."""
        if not response.headers.get("content-type", "").startswith(
            self._problem["mediaType"]
        ):
            return ""
        try:
            problem = response.json()
        except ValueError:
            return ""
        if not isinstance(problem, dict):
            return ""
        return f" ({problem.get('type')!s}: {problem.get('title')!s})"

    def _check_success(
        self, route_id: str, route: Mapping[str, JsonValue], response: httpx.Response
    ) -> object:
        """Check a success answer's media type or shape; its decoded JSON body, or ``None``."""
        success = route["success"]
        media_type = success["mediaType"]
        if media_type is not None:
            content_type = response.headers.get("content-type", "")
            if not content_type.startswith(media_type):
                raise ContractFailure(
                    f"{route_id}: answered {content_type!r}, expected {media_type!r}."
                )
            return None
        if success["shape"] is None or response.status_code == NO_CONTENT:
            return None
        try:
            body = response.json()
        except ValueError as error:
            raise ContractFailure(
                f"{route_id}: the success answer is not JSON."
            ) from error
        self._shapes.check(success["shape"], body, f"{route_id} response")
        return body

    def _check_answer(
        self, label: str, route: Mapping[str, JsonValue], response: httpx.Response
    ) -> object:
        """Check *response* against the route's positive expectation; the decoded success body, or ``None``."""
        expected = route["success"]["status"]
        if response.status_code == expected:
            return self._check_success(label, route, response)
        refused = str(response.status_code) in self._problem["refusals"]
        client_error = CLIENT_ERROR_MIN <= response.status_code <= CLIENT_ERROR_MAX
        if route["expect"] == EXPECT_EXACT or refused or not client_error:
            raise ContractFailure(
                f"{label}: answered {response.status_code}, expected {expected}"
                f"{self._problem_summary(response)}."
            )
        self._check_problem(label, response, None)
        return None

    def _check_echo(
        self,
        label: str,
        route: Mapping[str, JsonValue],
        answer: object,
        body: Mapping[str, object],
        path_values: Mapping[str, object],
    ) -> None:
        """Each member the call sent, and each key it asked for, comes back as sent."""
        success = route["success"]
        sent = (
            {member: body["json"][member] for member in success["echo"]}
            if "echo" in success
            else {}
        )
        if "echoPath" in success:
            sent.update(
                {
                    member: path_values[param]
                    for member, param in success["echoPath"].items()
                }
            )
        if not sent:
            return
        fields = self._shapes.fields_of(success["shape"], label)
        for member, value in sent.items():
            if not isinstance(answer, dict) or member not in answer:
                raise ContractFailure(
                    f"{label} response.{member}: the member sent is not answered."
                )
            if not self._shapes.same(fields[member]["shape"], value, answer[member]):
                raise ContractFailure(
                    f"{label} response.{member}: answered other than the value sent."
                )

    def _call(
        self,
        label: str,
        route_id: str,
        route: Mapping[str, JsonValue],
        headers: Mapping[str, str] | None,
    ) -> None:
        """Call *route* as planned (under *headers* when given) and check its positive answer."""
        values = self._path_values(route["pathParams"])
        body = self._body(route_id, route["body"])
        response = self._send(
            route_id, route, path_values=values, body=body, headers=headers
        )
        answer = self._check_answer(label, route, response)
        if answer is not None:
            self._check_echo(label, route, answer, body, values)

    def _check_problem(
        self,
        route_id: str,
        response: httpx.Response,
        expected: Mapping[str, JsonValue] | None,
    ) -> dict[str, object]:
        content_type = response.headers.get("content-type", "")
        if not content_type.startswith(self._problem["mediaType"]):
            raise ContractFailure(
                f"{route_id}: the {response.status_code} answer is {content_type!r}, "
                f"expected {self._problem['mediaType']!r}."
            )
        try:
            problem = response.json()
        except ValueError as error:
            raise ContractFailure(
                f"{route_id}: the {response.status_code} answer is not JSON."
            ) from error
        if not isinstance(problem, dict) or any(
            member not in problem for member in PROBLEM_MEMBERS
        ):
            raise ContractFailure(
                f"{route_id}: the {response.status_code} answer lacks {list(PROBLEM_MEMBERS)}."
            )
        if problem["status"] != response.status_code:
            raise ContractFailure(
                f"{route_id}: problem status {problem['status']!r} != HTTP {response.status_code}."
            )
        if expected is not None and (problem["type"], problem["title"]) != (
            expected["type"],
            expected["title"],
        ):
            raise ContractFailure(
                f"{route_id}: problem {problem['type']!r} / {problem['title']!r}, "
                f"expected {expected['type']!r} / {expected['title']!r}."
            )
        return problem

    def _expect_problem(
        self, label: str, response: httpx.Response, expected: list[JsonValue]
    ) -> dict[str, object]:
        """*response* is a problem of one of the *expected* framework problem types."""
        statuses = sorted({entry["status"] for entry in expected})
        if response.status_code not in statuses:
            raise ContractFailure(
                f"{label}: answered {response.status_code}, expected {statuses}{self._problem_summary(response)}."
            )
        problem = self._check_problem(label, response, None)
        declared = [
            (entry["type"], entry["title"])
            for entry in expected
            if entry["status"] == response.status_code
        ]
        if (problem["type"], problem["title"]) not in declared:
            raise ContractFailure(
                f"{label}: problem {problem['type']!r} / {problem['title']!r}, expected one of {declared}."
            )
        return problem

    def _expect_refusal(
        self, label: str, response: httpx.Response, status: str
    ) -> None:
        if str(response.status_code) != status:
            raise ContractFailure(
                f"{label}: answered {response.status_code}, expected {status}."
            )
        self._check_problem(label, response, self._problem["refusals"][status])

    def _field_errors(
        self, label: str, problem: Mapping[str, object]
    ) -> list[tuple[object, ...]]:
        """``(location, field, code)`` of each field error a request-validation problem names."""
        member = self._problem["fieldErrors"]["member"]
        errors = problem[member] if member in problem else None
        well_formed = isinstance(errors, list) and all(
            isinstance(entry, dict)
            and all(name in entry for name in FIELD_ERROR_MEMBERS)
            for entry in errors
        )
        if not well_formed:
            raise ContractFailure(
                f"{label}: the problem's {member!r} member is not a list of {list(FIELD_ERROR_MEMBERS)} entries."
            )
        return [tuple(entry[name] for name in FIELD_ERROR_MEMBERS) for entry in errors]

    def _expect_field_error(
        self, label: str, response: httpx.Response, location: str, field: str
    ) -> None:
        """*response* refuses the request with exactly one ``invalid`` error at (*location*, *field*)."""
        vocabulary = self._problem["fieldErrors"]
        problem = self._expect_problem(
            label, response, self._problem["requestValidation"]
        )
        errors = self._field_errors(label, problem)
        expected = [(vocabulary[location], field, vocabulary["invalid"])]
        if errors != expected:
            raise ContractFailure(
                f"{label}: field errors {errors}, expected {expected}."
            )

    def check_route(self, route_id: str) -> None:
        """Call *route_id* as its declaration allows and check the answer."""
        route = self._routes[route_id]
        self._begin(route, presents=True)
        self._call(route_id, route_id, route, None)

    def check_refusal(self, route_id: str) -> None:
        """Call *route_id* with no credential, query or body: it must answer an unauthorized problem."""
        route = self._routes[route_id]
        self._begin(route, presents=False)
        path = self._path(route, self._path_values(route["refusalPathParams"]))
        response = self._client.request(
            route["method"], path, headers=self._anonymous_headers()
        )
        self._expect_refusal(f"{route_id} without a credential", response, UNAUTHORIZED)

    def check_case(self, route_id: str, case_id: str) -> None:
        """Make the further call the route case *case_id* names and check its answer."""
        route = self._routes[route_id]
        cases = route["cases"]
        if case_id not in cases:
            raise ContractFailure(
                f"{route_id}: contract.json holds no case {case_id!r} (cases: {sorted(cases)})."
            )
        case = cases[case_id]
        kind = case["kind"]
        if kind not in _CASE_CHECKS:
            raise ContractFailure(
                f"{route_id}: contract.json names the unknown case kind {kind!r}."
            )
        self._begin(
            route,
            presents=kind not in UNPRESENTED_CASES,
            wrong_role=kind == CASE_WRONG_ROLE,
        )
        _CASE_CHECKS[kind](self, f"{route_id} [{case_id}]", route_id, route, case)

    # -- cases -------------------------------------------------------------

    def invalid_body(
        self, label: str, route_id: str, route: Mapping[str, JsonValue], case: JsonValue
    ) -> None:
        """An empty input is refused, naming each field error in the declared vocabulary."""
        response = self._send(route_id, route, body={"json": {}})
        problem = self._expect_problem(
            label, response, self._problem["requestValidation"]
        )
        vocabulary = self._problem["fieldErrors"]
        errors = self._field_errors(label, problem)
        if not errors:
            raise ContractFailure(f"{label}: the refusal names no field error.")
        for location, field, code in errors:
            if (
                location not in vocabulary["locations"]
                or code not in vocabulary["codes"]
            ):
                raise ContractFailure(
                    f"{label}: field error ({location!r}, {code!r}) is outside "
                    f"{vocabulary['locations']} / {vocabulary['codes']}."
                )
            if not isinstance(field, str) or not field:
                raise ContractFailure(f"{label}: a field error names no field.")

    def invalid_enum(
        self, label: str, route_id: str, route: Mapping[str, JsonValue], case: JsonValue
    ) -> None:
        """A value no enum member spells is refused, naming exactly that member."""
        body = {
            "json": {**self._json_body(route_id, route), case["member"]: case["value"]}
        }
        response = self._send(route_id, route, body=body)
        self._expect_field_error(label, response, "body", case["member"])

    def valid_enum(
        self, label: str, route_id: str, route: Mapping[str, JsonValue], case: JsonValue
    ) -> None:
        """A declared enum member is accepted and answered back."""
        values = self._path_values(route["pathParams"])
        body = {
            "json": {**self._json_body(route_id, route), case["member"]: case["value"]}
        }
        response = self._send(route_id, route, path_values=values, body=body)
        answer = self._check_answer(label, route, response)
        self._check_echo(label, route, answer, body, values)

    def wrong_role(
        self, label: str, route_id: str, route: Mapping[str, JsonValue], case: JsonValue
    ) -> None:
        """A caller holding none of the route's roles is forbidden: a supplied principal of an
        admitted provider that holds none, else a token signed with the test identity holding
        only a role no route declares."""
        if self._principals:
            headers = self._bearer_headers(self._caller.token)
        else:
            headers = self._headers(route, roles=[case["role"]])
        response = self._send(
            route_id,
            route,
            path_values=self._path_values(case["pathParams"]),
            headers=headers,
        )
        self._expect_refusal(label, response, FORBIDDEN)

    def invalid_token(
        self, label: str, route_id: str, route: Mapping[str, JsonValue], case: JsonValue
    ) -> None:
        """A malformed token and a token signed by an untrusted key are both unauthorized."""
        path = self._path(route, self._path_values(route["refusalPathParams"]))
        for token in (MALFORMED_TOKEN, self._foreign_token(route["roles"])):
            response = self._client.request(
                route["method"], path, headers=self._bearer_headers(token)
            )
            self._expect_refusal(label, response, UNAUTHORIZED)

    def anonymous(
        self, label: str, route_id: str, route: Mapping[str, JsonValue], case: JsonValue
    ) -> None:
        """An optional-auth route answers a caller without a credential as it answers one with."""
        self._call(label, route_id, route, self._anonymous_headers())

    def not_found(
        self, label: str, route_id: str, route: Mapping[str, JsonValue], case: JsonValue
    ) -> None:
        """A key no instance has is a not-found problem."""
        response = self._send(
            route_id, route, path_values=self._path_values(case["pathParams"])
        )
        self._expect_problem(label, response, self._problem["notFound"])

    def delete_twice(
        self, label: str, route_id: str, route: Mapping[str, JsonValue], case: JsonValue
    ) -> None:
        """A deleted instance is gone: deleting it again is a not-found problem."""
        values = self._path_values(route["pathParams"])
        first = self._send(route_id, route, path_values=values)
        if first.status_code != route["success"]["status"]:
            raise ContractFailure(
                f"{label}: the first delete answered {first.status_code}, expected "
                f"{route['success']['status']}{self._problem_summary(first)}."
            )
        second = self._send(route_id, route, path_values=values)
        self._expect_problem(label, second, self._problem["notFound"])

    def restrict_delete(
        self, label: str, route_id: str, route: Mapping[str, JsonValue], case: JsonValue
    ) -> None:
        """An instance a child still references under ``onDelete(restrict)`` refuses deletion."""
        values = self._path_values(route["pathParams"])
        self._create(case["child"], {case["reference"]: values[case["param"]]})
        response = self._send(route_id, route, path_values=values)
        self._expect_problem(label, response, self._problem["conflict"])

    def _page_call(
        self, route_id: str, route: Mapping[str, JsonValue], extra: Mapping[str, object]
    ) -> httpx.Response:
        query = {
            **self._query(route),
            **{name: _text_form(value) for name, value in extra.items()},
        }
        return self._send(route_id, route, query=query)

    def _window(self, case: JsonValue) -> dict[str, object]:
        """The page query a window case sends, in the backend's own parameter names."""
        names = self._page["query"]
        return {
            names[role]: case[role] for role in ("position", "size") if role in case
        }

    def _check_page(
        self,
        label: str,
        route: Mapping[str, JsonValue],
        response: httpx.Response,
        expected: Mapping[str, object],
    ) -> dict[str, object]:
        if response.status_code != route["success"]["status"]:
            raise ContractFailure(
                f"{label}: answered {response.status_code}, expected "
                f"{route['success']['status']}{self._problem_summary(response)}."
            )
        page = self._check_success(label, route, response)
        members = self._page["members"]
        for role, value in expected.items():
            if page[members[role]] != value:
                raise ContractFailure(
                    f"{label}: page {members[role]} is {page[members[role]]!r}, expected {value!r}."
                )
        return page

    def page_window(
        self, label: str, route_id: str, route: Mapping[str, JsonValue], case: JsonValue
    ) -> None:
        """An explicit window is answered as asked, never longer, with the largest size accepted."""
        response = self._page_call(route_id, route, self._window(case))
        expected = {
            "position": case["position"],
            "size": case["size"],
            "maxSize": self._page["maxSize"],
        }
        page = self._check_page(label, route, response, expected)
        if len(page[self._page["items"]]) > case["size"]:
            raise ContractFailure(
                f"{label}: answered more than the {case['size']} items asked for."
            )

    def page_default_window(
        self, label: str, route_id: str, route: Mapping[str, JsonValue], case: JsonValue
    ) -> None:
        """No window asks for the first position and the application's default size."""
        response = self._page_call(route_id, route, {})
        self._check_page(
            label,
            route,
            response,
            {"position": case["position"], "size": self._page["defaultSize"]},
        )

    def page_oversize(
        self, label: str, route_id: str, route: Mapping[str, JsonValue], case: JsonValue
    ) -> None:
        """A size above the largest accepted is refused."""
        response = self._page_call(route_id, route, self._window(case))
        self._expect_problem(label, response, self._problem["requestValidation"])

    def page_negative_position(
        self, label: str, route_id: str, route: Mapping[str, JsonValue], case: JsonValue
    ) -> None:
        """A negative position is refused."""
        response = self._page_call(route_id, route, self._window(case))
        self._expect_problem(label, response, self._problem["requestValidation"])

    def sort_unknown(
        self, label: str, route_id: str, route: Mapping[str, JsonValue], case: JsonValue
    ) -> None:
        """A sort naming no sortable field is refused, naming exactly the sort key."""
        response = self._page_call(route_id, route, {case["key"]: case["value"]})
        self._expect_field_error(label, response, "query", case["key"])


def _rsa_key() -> object:
    return rsa.generate_private_key(
        public_exponent=RSA_PUBLIC_EXPONENT, key_size=RSA_KEY_BITS
    )


