    epilog = _lifecycle_epilog(
        verb_help,
        unrealized_verbs,
        schema_help,
        schema_blocks,
        extra_commands,
        schema_operands=schema_operands,
        deploy_verb=deploy_verb,
        deploy_step_help=deploy_step_help,
        client_step_help=client_step_help,
        unrealized_client_members=unrealized_client_members,
    )
