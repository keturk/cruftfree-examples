#: This profile's realized verbs, bound to their implementations. The keys are
#: exactly REALIZED_VERBS -- ``require_command_coverage`` proves it on every
#: run, so a verb the parser accepts can never reach a missing implementation.
#: ``deploy`` is dispatched by ``main`` with what its command line gave,
#: and so is ``down``, with its scope; such an entry here is for
#: coverage, and a call through it fails for want of that.
COMMANDS: dict[str, Callable[..., None]] = {
    VERB_DEPLOY: command_deploy,
    VERB_DOWN: command_down,
    VERB_RESET: command_reset,
}

#: This profile's schema verbs, bound to their implementations, each taking the
#: block it acts on and then its SCHEMA_VERB_OPERANDS. The keys are exactly
#: SCHEMA_VERBS, proved alongside.
SCHEMA_COMMANDS: dict[str, Callable[..., None]] = {
    VERB_SCHEMA_READ: command_schema_read,
    VERB_SCHEMA_APPLY: command_schema_apply,
}

#: Whether 'deploy' takes its schema flags to the plan below (``deploy --plan``):
#: exactly when the parser declares them, which ``require_command_coverage``
#: proves on every run, so a flag the parser accepts always reaches the plan.
DEPLOY_PLANS: bool = True

#: The blocks 'deploy --plan' plans, by their block keys: every block, or none
#: when this profile's migrations are disabled, since a deploy then changes no
#: schema.
PLAN_BLOCKS: tuple[str, ...] = ("realestate-listing-service.listing-db", "realestate-viewing-service.viewing-db", "realestate-deal-service.deal-db", "realestate-mortgage-mock.mortgage-db", "realestate-signature-mock.signature-db", "realestate-email-mock.email-db", )


def require_command_coverage() -> None:
    """Fail loud unless every accepted verb, flag and block has an implementation, and vice versa.

    The parser's choice set and the dispatch tables are two sides of one seam:
    argparse decides what is accepted, ``COMMANDS`` and ``SCHEMA_COMMANDS``
    decide what happens, and ``SCHEMA_READ_CLIENTS`` how a block is reached. A
    verb or block in one and not the other is a KeyError at the worst possible
    moment -- after an operator confirmed a destructive command -- or one that
    quietly cannot be reached at all. The schema flags of 'deploy' the parser
    takes (SCHEMA_DEPLOY_FLAGS) are declared exactly when the deploy dispatch
    plans (DEPLOY_PLANS), and every block it plans has a client. Comparing the
    sets costs nothing and runs before any argument is parsed.

    Raises:
        DeployError: If the sets differ, naming what is on each side.
    """
    accepted = set(REALIZED_VERBS) | set(SCHEMA_VERBS)
    implemented = set(COMMANDS) | set(SCHEMA_COMMANDS)
    blocks = set(SCHEMA_BLOCKS)
    reached = set(SCHEMA_READ_CLIENTS)
    declared_flags = set(SCHEMA_DEPLOY_FLAGS)
    planned = set(PLAN_BLOCKS)
    if (
        accepted == implemented
        and blocks == reached
        and bool(declared_flags) == DEPLOY_PLANS
        and planned <= reached
    ):
        return
    raise DeployError(
        f"This script accepts {sorted(accepted)} but implements "
        f"{sorted(implemented)}. Accepted-but-missing: "
        f"{sorted(accepted - implemented)}; implemented-but-unreachable: "
        f"{sorted(implemented - accepted)}. Blocks accepted without a client: "
        f"{sorted(blocks - reached)}; clients of no accepted block: "
        f"{sorted(reached - blocks)}. Deploy flags accepted: "
        f"{sorted(declared_flags)}, while the deploy dispatch "
        f"{'plans' if DEPLOY_PLANS else 'plans nothing'}; blocks planned without "
        f"a client: {sorted(planned - reached)}. This is a generator defect, not "
        f"something to work around here -- regenerate the project."
    )


def main(argv: list[str] | None = None) -> int:
    """Entry point: dispatch the requested lifecycle or schema command.

    Every argument is a command or a flag this script declares. A verb it does
    not implement is rejected by name, with ``--help`` explaining what this
    profile has instead -- never answered by silently deploying, which is the
    most dangerous shape a fallback can take: the action performed is not the
    action requested, and the output looks like success.

    ``deploy --plan`` reads every block in PLAN_BLOCKS and prints the plan a
    deploy would apply to it, and does nothing else: no image is built, no
    container started, no schema changed. ``deploy`` converges every block in
    PLAN_BLOCKS around the release. Approval is the command line's
    ``--approved`` alone, handed to the deploy command directly; a call
    through ``COMMANDS`` never carries it.

    Args:
        argv: Arguments to parse; ``sys.argv[1:]`` when omitted.

    Returns:
        Process exit code -- 0 on success, 1 on any operator-actionable failure.
    """
    raw_arguments = list(sys.argv[1:] if argv is None else argv)
    try:
        require_command_coverage()
    except DeployError as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 1
    arguments = normalize_argv(raw_arguments)
    parser = build_lifecycle_parser(
        "Manage this application's Docker Compose deployment."
    )
    parsed = parser.parse_args(arguments)
    try:
        if parsed.plan:
            plan_schema_blocks(
                PLAN_BLOCKS,
                parsed.approved,
                concurrent_runs=serial_schema_runs,
                schema_tool=run_project_schema_tool,
                channel=compose_schema_channel(VERB_SCHEMA_READ),
                failure=DeployError,
            )
        elif parsed.command == VERB_DEPLOY:
            command_deploy(force_requested(parsed.force), parsed.approved, client_request(parsed))
        elif parsed.command == VERB_DOWN:
            command_down(force_requested(parsed.force), parsed.scope)
        elif parsed.command in SCHEMA_COMMANDS:
            SCHEMA_COMMANDS[parsed.command](
                parsed.block,
                *(getattr(parsed, operand) for operand in SCHEMA_VERB_OPERANDS[parsed.command]),
            )
        else:
            COMMANDS[parsed.command](force_requested(parsed.force))
    except DeployError as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 1
    except KeyboardInterrupt:
        print("\nInterrupted.", file=sys.stderr)
        return 130
    return 0


if __name__ == "__main__":
    sys.exit(main())
