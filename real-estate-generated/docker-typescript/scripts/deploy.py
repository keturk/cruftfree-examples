def compose_up() -> None:
    """Build and start the release, returning once each service passes its healthcheck.

    Raises:
        DeployError: If compose could not bring the services up healthy.
    """
    step("Building and starting services")
    compose_up_services(*RELEASE_SERVICES, build=True)


def compose_up_services(*services: str, build: bool) -> None:
    """Start *services*, building them first when *build*, returning once each runs and
    passes its healthcheck.

    Every compose file is loaded and only *services* are named, so the release
    starts no static site and a site's start touches nothing of the release.
    ``--wait`` makes compose itself wait: a long-running service until it runs
    and its healthcheck passes, a one-shot job a service awaits until it exits
    0. A service that never gets there fails the deploy here. A caller that built
    the images itself passes ``build=False``, so ``up`` starts exactly those.

    Raises:
        DeployError: If compose could not bring the services up healthy.
    """
    result = docker(
        "compose", *COMPOSE_FILE_ARGS, "up", "-d", "--build" if build else "--no-build", "--wait",
        *services,
        capture=False,
    )
    if not result.succeeded:
        failed = _report_failed_container_logs()
        if failed is None:
            detail = (
                " Compose's account of the containers could not be read, so no "
                "failed container could be named; review the output above."
            )
        elif failed:
            detail = (
                f" The failing container(s) were: {', '.join(failed)}; their logs are "
                f"above."
            )
        else:
            detail = (
                " No container reported a non-zero exit, so the failure is in "
                "the build, in compose itself, or a healthcheck that never passed; "
                "review the output above."
            )
        raise DeployError(
            f"'docker compose up --wait' failed (exit {result.returncode}).{detail}"
        )


def _service_states(result: CommandResult) -> list[dict[str, object]]:
    """Compose's account of each container, from ``docker compose ps --format json``.

    Compose prints one JSON object per line, or one JSON array, to stdout; what
    it writes to stderr (an interpolation warning, a deprecation notice) is no
    part of that document and is read only to explain a refusal.

    Raises:
        DeployError: If stdout is neither.
    """
    text = result.stdout
    stderr_note = f" Its stderr: {result.stderr[:200]!r}." if result.stderr else ""
    try:
        if text.startswith("["):
            entries = json.loads(text)
        else:
            entries = [json.loads(line) for line in text.splitlines() if line.strip()]
    except ValueError as error:
        raise DeployError(
            f"'docker compose ps --format json' printed output this script cannot read "
            f"({error}): {text[:200]!r}. Expected one JSON object per container."
            f"{stderr_note}"
        ) from error
    if not isinstance(entries, list) or not all(isinstance(entry, dict) for entry in entries):
        raise DeployError(
            f"'docker compose ps --format json' printed {text[:200]!r}, not one JSON "
            f"object per container.{stderr_note}"
        )
    return entries


def verify_services_healthy() -> None:
    """The deploy's health verification: every service runs healthy, every job exited 0.

    Reads compose's own account of every container of the project after
    ``up --wait`` returned, and prints the status table. A container that is not
    running with a passing (or no) healthcheck, and is not a job that exited 0,
    fails the deploy, named; so does a project with no container at all.

    Raises:
        DeployError: If the state could not be read, or any container is unhealthy.
    """
    step("Verifying the services")
    result = docker("compose", *COMPOSE_FILE_ARGS, "ps", "--all", "--format", "json")
    if not result.succeeded:
        raise DeployError(
            f"'docker compose ps' failed (exit {result.returncode}): "
            f"{result.output or 'no output'}. The services' health could not be verified."
        )
    states = _service_states(result)
    unhealthy: list[str] = []
    for entry in states:
        name = entry.get("Service") or entry.get("Name")
        state = entry.get("State")
        health = entry.get("Health") or ""
        finished = state == "exited" and entry.get("ExitCode") == 0
        if not finished and (state != "running" or health not in ("", "healthy")):
            unhealthy.append(f"{name} ({state}{', ' + str(health) if health else ''})")
    if not states or unhealthy:
        raise DeployError(
            f"The release is not healthy: {', '.join(unhealthy) or 'compose reports no container'}. "
            f"No schema change that needs the release healthy was applied; read the "
            f"logs with: {COMPOSE_COMMAND} logs <service>"
        )
    docker("compose", *COMPOSE_FILE_ARGS, "ps", capture=False)


#: The one-shot job that publishes the client contract, the contract's path inside
#: it, and where this script copies it (project-root-relative): the path the
#: clients step reads.
CLIENT_CONTRACT_JOB = "realestate-system-client-contract"
CLIENT_CONTRACT_JOB_FILE = "/client-contract/client-contract.test.json"
CLIENT_CONTRACT_HOST_FILE = "config/resolved/client-contract.test.json"
#: The compose profile the contract job carries: it keeps the job out of ``up``,
#: and this script starts it and awaits its exit.
CLIENT_CONTRACT_JOB_PROFILE = "deploy-run"


def export_client_contract() -> None:
    """Copy the client contract out of the finished contract job.

    The job runs as root and writes into its own container filesystem, so
    nothing it makes lands in this tree as root: ``docker cp`` creates the copy
    as the user running this script. Only the contract is copied and only it is
    replaced: its directory also holds the runtime configs the clients step
    composed, which the running sites mount, so a backend-only deploy leaves
    them as they are. The copy lands beside the contract and replaces it in one
    rename, so a reader never sees half a file. The job is waited for first, and
    its exit read. Its profile keeps it out of ``up``, and it is started here:
    ``up --wait`` would read a job nothing awaits exiting as a failure.

    Raises:
        DeployError: If the job failed, or the contract cannot be copied or
            put in place.
    """
    step("Exporting the client contract")
    started = docker(
        "compose", *COMPOSE_FILE_ARGS, "--profile", CLIENT_CONTRACT_JOB_PROFILE, "up", "-d",
        CLIENT_CONTRACT_JOB, capture=False,
    )
    if not started.succeeded:
        raise DeployError(
            f"'docker compose up' could not start the client contract job "
            f"'{CLIENT_CONTRACT_JOB}' (exit {started.returncode}); review the output above."
        )
    waited = docker("wait", CLIENT_CONTRACT_JOB)
    if not waited.succeeded or waited.stdout != "0":
        raise DeployError(
            f"The client contract job '{CLIENT_CONTRACT_JOB}' did "
            f"not finish successfully (docker wait: {waited.output or 'no output'}). "
            f"Its log says why: docker logs {CLIENT_CONTRACT_JOB}"
        )
    target = PROJECT_ROOT / CLIENT_CONTRACT_HOST_FILE
    staged = target.with_name(f".{target.name}.copy")
    try:
        target.parent.mkdir(parents=True, exist_ok=True)
        staged.unlink(missing_ok=True)
    except OSError as error:
        raise DeployError(
            f"Cannot prepare '{CLIENT_CONTRACT_HOST_FILE}' for the contract ({error}). "
            f"If an earlier deploy left its directory owned by root, remove it once as "
            f"root, then deploy again."
        ) from error
    copied = docker("cp", f"{CLIENT_CONTRACT_JOB}:{CLIENT_CONTRACT_JOB_FILE}", str(staged))
    if not copied.succeeded:
        raise DeployError(
            f"'docker cp' could not copy the client contract out of "
            f"'{CLIENT_CONTRACT_JOB}': {copied.output or 'no output'}"
        )
    try:
        staged.replace(target)
    except OSError as error:
        raise DeployError(
            f"Cannot put the client contract in place at '{CLIENT_CONTRACT_HOST_FILE}' "
            f"({error}); the copy is at '{staged}'."
        ) from error


