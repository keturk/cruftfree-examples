# Runs once the contract exists: it proves the backend the contract names and the
# identity provider each signing-in app trusts, composes every runtime config, then
# starts each site and builds each native target.

#: The runtime config's identity block and its client-id member -- the same
#: names `client_runtime_config` declares.
RUNTIME_CONFIG_IDENTITY_KEY = "identity"
RUNTIME_CONFIG_CLIENT_ID_KEY = "clientId"
#: The other environment facts a deployed runtime config carries -- the same
#: names `client_runtime_config` declares.
RUNTIME_CONFIG_API_BASE_URL_KEY = "apiBaseUrl"
RUNTIME_CONFIG_WEB_ORIGIN_KEY = "webOrigin"
#: The members of a deployed config's identity block -- the same names as
#: `client_runtime_config.IDENTITY_CLIENT_KEYS`.
CLIENT_RECORD_KEYS = (
    "authority",
    RUNTIME_CONFIG_CLIENT_ID_KEY,
    "scopes",
    "redirectUris",
    "logoutUris",
    "flows",
    "rolesClaim",
    "roleMappings",
)
#: The identity provider's `iss`, which its OpenID configuration must state: a
#: release checks the provider against it. A contract's client record carries it;
#: a deployed identity block does not, since no client reads it.
CLIENT_CONTRACT_ISSUER_KEY = "issuer"
#: The members of a client record in the client contract.
CLIENT_CONTRACT_RECORD_KEYS = (*CLIENT_RECORD_KEYS, CLIENT_CONTRACT_ISSUER_KEY)

#: The client contract's own members.
CLIENT_CONTRACT_SYSTEM_KEY = "system"
CLIENT_CONTRACT_SYSTEM_NAME_KEY = "name"
CLIENT_CONTRACT_SYSTEM_VERSION_KEY = "version"
CLIENT_CONTRACT_BACKEND_KEY = "backend"
CLIENT_CONTRACT_REGISTRATIONS_KEY = "registrations"
CLIENT_CONTRACT_APP_ID_KEY = "appId"
CLIENT_CONTRACT_KINDS_KEY = "kinds"
CLIENT_CONTRACT_SERVICES_KEY = "services"
CLIENT_CONTRACT_CLIENTS_KEY = "clients"
#: In a contract plan only: a client record whose id the platform provisions
#: names the output it is published under here. The published contract never
#: carries it.
CLIENT_PLAN_ID_REF_KEY = "clientIdRef"
#: The backend's member holding the API it serves its clients: the consumed API
#: document (`client_api_document`) of the backend's own client contract, which a
#: release compares each app's consumed document against.
CLIENT_CONTRACT_BACKEND_API_KEY = "api"
#: An API document's list of services, each with the routes a client may call.
CLIENT_API_DOCUMENT_SERVICES_KEY = "services"

#: What a provisioned OAuth2 client id may look like before it is written into
#: a file a browser loads: a GUID, a Cognito app-client id, a Zitadel
#: `<digits>@<project>` id. Anything else -- whitespace, a quote, markup, an
#: empty value -- is refused rather than served.
_PROVISIONED_CLIENT_ID_SHAPE = re.compile(r"[A-Za-z0-9][A-Za-z0-9@._:-]{0,255}")

#: What an origin in a contract may look like: `https://<host>[:port]`, or a
#: loopback host over either scheme. The whole value is matched, so no userinfo,
#: path, query or fragment reaches a client. A pattern rather than `urllib`
#: because every host imports `re` and not every host imports `urllib.parse`.
CLIENT_ORIGIN_SHAPE = re.compile(
    r"(?:https://[A-Za-z0-9][A-Za-z0-9.-]*|https?://(?:localhost|127\.0\.0\.1|\[::1\]))"
    r"(?::[0-9]{1,5})?"
)

#: How to clear any defect in a contract a deploy reads.
_CONTRACT_FIX = (
    "Use the file the backend's deploy published, unchanged; if it is out of date, "
    "redeploy the backend."
)

#: A client contract, as the JSON object it is published as. Plain data, so a
#: host needs no import beyond this module's own.
ClientContractDocument = dict[str, object]


class ClientRuntimeResolutionError(RuntimeError):
    """A client contract or a runtime config could not be written, read or composed."""


def _read_generated_config(generated_path: Path) -> dict[str, object]:
    """The generated runtime config at *generated_path*, or fail naming it."""
    if not generated_path.is_file():
        raise ClientRuntimeResolutionError(
            f"Runtime config '{generated_path}' does not exist. It is produced by "
            "generation; regenerate the project before deploying."
        )
    try:
        config = json.loads(generated_path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise ClientRuntimeResolutionError(
            f"Runtime config '{generated_path}' is not valid JSON ({exc}). "
            "Regenerate the project; never edit the generated file by hand."
        ) from exc
    if not isinstance(config, dict):
        raise ClientRuntimeResolutionError(
            f"Runtime config '{generated_path}' is not a JSON object. Regenerate "
            "the project; never edit the generated file by hand."
        )
    return config


def _write_sorted_json(path: Path, document: dict[str, object]) -> None:
    """Write *document* to *path* as sorted JSON, parents created."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(document, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def _provisioned_client_id(
    reference: str,
    consumer: str,
    lookup_client_id: Callable[[str], str | None],
) -> str:
    """The well-formed id the platform published under *reference*, or fail naming it."""
    client_id = lookup_client_id(reference)
    if client_id is None or not _PROVISIONED_CLIENT_ID_SHAPE.fullmatch(client_id):
        found = "nothing" if client_id is None else "a malformed value"
        raise ClientRuntimeResolutionError(
            f"The platform published {found} under '{reference}', the client id "
            f"{consumer} signs users in with. The "
            "registration is provisioned by this deployment's infrastructure; "
            "deploy the infrastructure first, and check that it created the "
            "registration. No client is deployed without its provisioned id."
        )
    return client_id


def client_contract_from_plan(
    plan: dict[str, object],
    lookup_client_id: Callable[[str], str | None],
) -> ClientContractDocument:
    """The client contract of *plan*, every late-bound client id looked up.

    Args:
        plan: The generation-time contract: the published document, except that a
            client record the platform provisions holds
            ``CLIENT_PLAN_ID_REF_KEY`` in place of its client id.
        lookup_client_id: Returns the id the platform provisioned under the given
            reference, or ``None`` when it publishes none.

    Returns:
        The contract, ready for :func:`write_client_contract`.

    Raises:
        ClientRuntimeResolutionError: A client record carries both or neither of
            the client id and its reference, or the platform publishes no
            well-formed id under a reference.
    """
    registrations = _contract_object(plan, CLIENT_CONTRACT_REGISTRATIONS_KEY, "plan")
    return {
        **plan,
        CLIENT_CONTRACT_REGISTRATIONS_KEY: {
            name: _registration_with_client_ids(
                name, _contract_object(registrations, name, "plan"), lookup_client_id
            )
            for name in registrations
        },
    }


def _registration_with_client_ids(
    name: str,
    registration: dict[str, object],
    lookup_client_id: Callable[[str], str | None],
) -> dict[str, object]:
    """*registration* with each client record's id in place."""
    source = f"plan, registration '{name}'"
    clients = _contract_object(registration, CLIENT_CONTRACT_CLIENTS_KEY, source)
    return {
        **registration,
        CLIENT_CONTRACT_CLIENTS_KEY: {
            kind: _client_with_id(
                f"registration '{name}' ({kind})",
                _contract_object(clients, kind, source),
                lookup_client_id,
            )
            for kind in clients
        },
    }


def _client_with_id(
    consumer: str,
    record: dict[str, object],
    lookup_client_id: Callable[[str], str | None],
) -> dict[str, object]:
    """*record* holding its client id: its own, or the one published under its reference."""
    has_id = RUNTIME_CONFIG_CLIENT_ID_KEY in record
    has_ref = CLIENT_PLAN_ID_REF_KEY in record
    if has_id == has_ref:
        raise ClientRuntimeResolutionError(
            f"Client contract plan: {consumer} carries "
            f"{'both' if has_id else 'neither'} of '{RUNTIME_CONFIG_CLIENT_ID_KEY}' "
            f"and '{CLIENT_PLAN_ID_REF_KEY}'; exactly one is required. "
            "Regenerate the project."
        )
    if has_id:
        return record
    reference = _contract_text(record, CLIENT_PLAN_ID_REF_KEY, consumer)
    resolved = {key: value for key, value in record.items() if key != CLIENT_PLAN_ID_REF_KEY}
    resolved[RUNTIME_CONFIG_CLIENT_ID_KEY] = _provisioned_client_id(
        reference, consumer, lookup_client_id
    )
    return resolved


def write_client_contract(contract: ClientContractDocument, path: Path) -> None:
    """Publish *contract* at *path* as sorted JSON (parents created).

    Args:
        contract: The contract (:func:`client_contract_from_plan`).
        path: Where it is published (``client_runtime_paths.client_contract_path``).

    Raises:
        ClientRuntimeResolutionError: The contract is not well formed; nothing is
            written.
    """
    _require_valid_contract(contract, f"'{path}'")
    _write_sorted_json(path, contract)


def read_client_contract(path: Path) -> ClientContractDocument:
    """The published client contract at *path*, checked as the writer checks it.

    Args:
        path: The contract file. In a frontend run an operator places it, so
            nothing about its content is taken on trust.

    Returns:
        The contract.

    Raises:
        ClientRuntimeResolutionError: The file is absent, is not a JSON object, or
            is not a well-formed contract.
    """
    if not path.is_file():
        raise ClientRuntimeResolutionError(
            f"Client contract '{path}' does not exist or is not a file. The backend's "
            "deploy publishes it: deploy the backend, or place its published contract "
            "at this path."
        )
    try:
        contract = json.loads(path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, UnicodeDecodeError) as exc:
        raise ClientRuntimeResolutionError(
            f"Client contract '{path}' is not valid JSON ({exc}). {_CONTRACT_FIX}"
        ) from exc
    if not isinstance(contract, dict):
        raise ClientRuntimeResolutionError(
            f"Client contract '{path}' is not a JSON object. {_CONTRACT_FIX}"
        )
    _require_valid_contract(contract, f"'{path}'")
    return contract


def compose_client_runtime_config(
    generated_path: Path,
    contract: ClientContractDocument,
    registration_name: str,
    kind: str,
    resolved_path: Path,
    *,
    identity: bool,
    web_origin: bool,
) -> None:
    """Write *resolved_path*: the app facts of *generated_path* plus the contract's facts.

    The deployed copy always carries the API base URL. The contract is checked
    again here, because a frontend run's copy is one an operator placed.

    Args:
        generated_path: The generated runtime config.
        contract: The published client contract.
        registration_name: The registration the app composes from.
        kind: The client kind the target runs as.
        resolved_path: Where the deployed copy is written (parents created).
        identity: Whether the deployed copy carries the kind's client record,
            projected onto `CLIENT_RECORD_KEYS` (the record's `issuer` stays in
            the contract).
        web_origin: Whether the deployed copy carries the registration's web origin.

    Raises:
        ClientRuntimeResolutionError: The generated config or the contract is not
            well formed, the registration or kind is absent from the contract, or
            a wanted client record or web origin is; nothing is written.
    """
    source = f"read for '{generated_path}'"
    _require_valid_contract(contract, source)
    config = _read_generated_config(generated_path)
    registration = _contract_registration(contract, registration_name, kind, generated_path)
    backend = _contract_object(contract, CLIENT_CONTRACT_BACKEND_KEY, source)
    config[RUNTIME_CONFIG_API_BASE_URL_KEY] = backend[RUNTIME_CONFIG_API_BASE_URL_KEY]
    if identity:
        clients = _contract_object(registration, CLIENT_CONTRACT_CLIENTS_KEY, source)
        if kind not in clients:
            raise ClientRuntimeResolutionError(
                f"Runtime config '{generated_path}' signs users in, but registration "
                f"'{registration_name}' has no '{kind}' client in the client contract. "
                "Check that the backend declares a login provider for it, then "
                "redeploy the backend."
            )
        record = _contract_object(clients, kind, source)
        config[RUNTIME_CONFIG_IDENTITY_KEY] = {key: record[key] for key in CLIENT_RECORD_KEYS}
    if web_origin:
        if RUNTIME_CONFIG_WEB_ORIGIN_KEY not in registration:
            raise ClientRuntimeResolutionError(
                f"Runtime config '{generated_path}' needs a web origin, but registration "
                f"'{registration_name}' states none in the client contract. Declare the "
                "registration's web origin on the backend, then redeploy it."
            )
        config[RUNTIME_CONFIG_WEB_ORIGIN_KEY] = registration[RUNTIME_CONFIG_WEB_ORIGIN_KEY]
    _write_sorted_json(resolved_path, config)


def _contract_registration(
    contract: ClientContractDocument,
    registration_name: str,
    kind: str,
    generated_path: Path,
) -> dict[str, object]:
    """The contract's *registration_name* entry running as *kind*, or fail naming both."""
    source = f"read for '{generated_path}'"
    registrations = _contract_object(contract, CLIENT_CONTRACT_REGISTRATIONS_KEY, source)
    if registration_name not in registrations:
        raise ClientRuntimeResolutionError(
            f"Runtime config '{generated_path}' composes from registration "
            f"'{registration_name}', which the client contract does not hold. It holds "
            f"{sorted(registrations)}. Check the app's `appId` against the backend's "
            "registrations, then redeploy the backend."
        )
    registration = _contract_object(registrations, registration_name, source)
    kinds = _contract_text_list(registration, CLIENT_CONTRACT_KINDS_KEY, source)
    if kind not in kinds:
        raise ClientRuntimeResolutionError(
            f"Runtime config '{generated_path}' runs as client kind '{kind}', which "
            f"registration '{registration_name}' does not list in the client contract. "
            f"It lists {sorted(kinds)}. Add the kind to the registration on the "
            "backend, then redeploy it."
        )
    return registration


def _require_valid_contract(contract: ClientContractDocument, source: str) -> None:
    """Fail unless *contract* is one a client may be given; *source* names it in the message."""
    system = _contract_object(contract, CLIENT_CONTRACT_SYSTEM_KEY, source)
    _contract_text(system, CLIENT_CONTRACT_SYSTEM_NAME_KEY, source)
    _contract_text(system, CLIENT_CONTRACT_SYSTEM_VERSION_KEY, source)
    backend = _contract_object(contract, CLIENT_CONTRACT_BACKEND_KEY, source)
    _require_origin(backend, RUNTIME_CONFIG_API_BASE_URL_KEY, source)
    _require_served_api(backend, f"{source}, '{CLIENT_CONTRACT_BACKEND_KEY}'")
    registrations = _contract_object(contract, CLIENT_CONTRACT_REGISTRATIONS_KEY, source)
    for name in registrations:
        _require_valid_registration(
            _contract_object(registrations, name, source),
            f"{source}, registration '{name}'",
        )


def _require_served_api(backend: dict[str, object], source: str) -> None:
    """Fail unless *backend* states the API it serves: an object listing its services.

    Only the shape is checked here; the release verifier reads each service's routes
    and names any member it cannot read.
    """
    api = _contract_object(backend, CLIENT_CONTRACT_BACKEND_API_KEY, source)
    services = api.get(CLIENT_API_DOCUMENT_SERVICES_KEY)
    if not isinstance(services, list) or not all(isinstance(item, dict) for item in services):
        raise ClientRuntimeResolutionError(
            f"Client contract {source}, '{CLIENT_CONTRACT_BACKEND_API_KEY}': "
            f"'{CLIENT_API_DOCUMENT_SERVICES_KEY}' is not a list of JSON objects. {_CONTRACT_FIX}"
        )


def _require_valid_registration(registration: dict[str, object], source: str) -> None:
    """Fail unless *registration* holds what a contract entry must."""
    if CLIENT_CONTRACT_APP_ID_KEY not in registration:
        raise ClientRuntimeResolutionError(
            f"Client contract {source}: '{CLIENT_CONTRACT_APP_ID_KEY}' is missing; "
            f"expected a string, or null for a client that states none. {_CONTRACT_FIX}"
        )
    _contract_text_list(registration, CLIENT_CONTRACT_SERVICES_KEY, source)
    kinds = _contract_text_list(registration, CLIENT_CONTRACT_KINDS_KEY, source)
    if RUNTIME_CONFIG_WEB_ORIGIN_KEY in registration:
        _require_origin(registration, RUNTIME_CONFIG_WEB_ORIGIN_KEY, source)
    clients = _contract_object(registration, CLIENT_CONTRACT_CLIENTS_KEY, source)
    if not clients:
        return
    if set(clients) != set(kinds):
        raise ClientRuntimeResolutionError(
            f"Client contract {source}: its clients {sorted(clients)} are not its kinds "
            f"{sorted(kinds)}. A registration with a login provider has one client per "
            f"kind, and one without has none. {_CONTRACT_FIX}"
        )
    for kind in clients:
        _require_valid_client(_contract_object(clients, kind, source), f"{source} ({kind})")


def _require_valid_client(record: dict[str, object], source: str) -> None:
    """Fail unless client *record* is complete, its issuer stated and its client id well formed."""
    missing = [key for key in CLIENT_CONTRACT_RECORD_KEYS if key not in record]
    if missing:
        raise ClientRuntimeResolutionError(
            f"Client contract {source}: the client record lacks {missing}. {_CONTRACT_FIX}"
        )
    _contract_text(record, CLIENT_CONTRACT_ISSUER_KEY, source)
    client_id = record[RUNTIME_CONFIG_CLIENT_ID_KEY]
    if not isinstance(client_id, str) or not _PROVISIONED_CLIENT_ID_SHAPE.fullmatch(client_id):
        raise ClientRuntimeResolutionError(
            f"Client contract {source}: '{RUNTIME_CONFIG_CLIENT_ID_KEY}' is malformed. "
            f"Expected a provisioned OAuth2 client id. {_CONTRACT_FIX}"
        )


def _require_origin(parent: dict[str, object], key: str, source: str) -> None:
    """Fail unless *parent*'s *key* is an https origin, or a loopback one."""
    origin = _contract_text(parent, key, source)
    if not CLIENT_ORIGIN_SHAPE.fullmatch(origin):
        raise ClientRuntimeResolutionError(
            f"Client contract {source}: '{key}' {origin!r} is not an origin a client may "
            "call. Expected 'https://<host>[:port]', or a loopback host on a local "
            f"profile, with no path. {_CONTRACT_FIX}"
        )


def _contract_object(parent: dict[str, object], key: str, source: str) -> dict[str, object]:
    """*parent*'s *key* as a JSON object, or fail naming it."""
    value = parent.get(key)
    if not isinstance(value, dict):
        raise ClientRuntimeResolutionError(
            f"Client contract {source}: '{key}' is not a JSON object. {_CONTRACT_FIX}"
        )
    return value


def _contract_text(parent: dict[str, object], key: str, source: str) -> str:
    """*parent*'s *key* as a non-empty string, or fail naming it."""
    value = parent.get(key)
    if not isinstance(value, str) or not value:
        raise ClientRuntimeResolutionError(
            f"Client contract {source}: '{key}' is not a non-empty string. {_CONTRACT_FIX}"
        )
    return value


def _contract_text_list(parent: dict[str, object], key: str, source: str) -> list[str]:
    """*parent*'s *key* as a list of strings, or fail naming it."""
    value = parent.get(key)
    if not isinstance(value, list) or not all(isinstance(item, str) for item in value):
        raise ClientRuntimeResolutionError(
            f"Client contract {source}: '{key}' is not a list of strings. {_CONTRACT_FIX}"
        )
    return value


