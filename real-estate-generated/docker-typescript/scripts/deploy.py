#: This project declares no infrastructure outside compose, so a compose
#: teardown IS the whole teardown and there is nothing further to name.
EXTERNAL_TEARDOWN_SCRIPT = None


def compose_project_name() -> str:
    """Return the project name compose itself will use.

    Compose's own rule: ``COMPOSE_PROJECT_NAME`` when set, otherwise the base
    name of the project directory. Resolved the same way here so the name shown
    in a destructive confirmation is the name of the thing actually being
    removed, rather than a value baked at generation time that a later rename
    or an environment override would have silently invalidated.
    """
    return os.environ.get("COMPOSE_PROJECT_NAME", "").strip() or PROJECT_ROOT.name


def command_deploy(forced: bool, approved: bool, clients: ClientRequest) -> None:
    """Check the prerequisites, build what compose cannot, and converge every block around the release.

    The ``converge`` step: the databases start first, every block is read,
    planned and expanded, the release starts and is verified healthy, and only
    then is each block's contract applied and its schema verified.

    Args:
        forced: Unused -- ``deploy`` removes nothing and needs no confirmation.
            Accepted so every command shares one signature.
        approved: Whether the command line gave ``--approved``: the one source
            of approval for a change that needs it.
        clients: What the command line asked of the clients.
    """
    del forced
    contract = client_contract_file(clients)
    resolve_docker()
    require_engine_image_store()
    require_compose()
    require_env_file()
    require_env_keys()
    if clients.scope == SCOPE_CLIENTS:
        # Export the contract off the running backend again, so the clients are released
        # against the backend as it is deployed, also from a clean checkout.
        export_client_contract()
        run_clients_step(contract, clients.build_number)
        prune_superseded_build_state()
        print(f"Clients released. Follow logs with:  {COMPOSE_COMMAND} logs -f")
        return
    provision_owned_keypairs()
    require_secret_files()
    build_base_images()
    converge_schema_blocks(
        PLAN_BLOCKS,
        approved,
        bring_up_data=compose_up_databases,
        start_release=compose_up,
        verify_release=verify_services_healthy,
        concurrent_runs=serial_schema_runs,
        schema_tool=run_project_schema_tool,
        channel=compose_schema_channel(STEP_CONVERGE),
        failure=DeployError,
    )
    export_client_contract()
    if clients.scope != SCOPE_BACKEND:
        run_clients_step(contract, clients.build_number)
    prune_superseded_build_state()
    print(f"Deployment complete. Follow logs with:  {COMPOSE_COMMAND} logs -f")


def compose_remove_services(services: tuple[str, ...], what: str) -> None:
    """Stop and remove the containers of *services* alone, keeping every volume and image.

    Every compose file is loaded so compose knows each service, and only
    *services* are named, so nothing outside them is stopped.

    Raises:
        DeployError: If compose could not stop or remove them.
    """
    step(f"Stopping {what}")
    result = docker(
        "compose", *COMPOSE_FILE_ARGS, "--profile", CLIENT_CONTRACT_JOB_PROFILE, "rm",
        "--stop", "--force", *services, capture=False,
    )
    if not result.succeeded:
        raise DeployError(
            f"'docker compose rm --stop' of {what} failed (exit {result.returncode}). "
            f"They may be partially stopped; review the output above."
        )


def command_down(forced: bool, scope: str | None) -> None:
    """Stop and remove the containers, keeping every byte of data.

    Volumes, images and the environment file all survive, so ``deploy`` brings
    the same stack back with the same data. This is the reversible one.
    With a scope, one side alone stops: the backend scope the stack file's
    services, the clients scope the static sites; with none, both.

    Args:
        forced: Unused -- ``down`` destroys nothing and needs no confirmation.
        scope: The scope flag's value, or ``None`` for both scopes.

    Raises:
        DeployError: If compose could not stop the services.
    """
    del forced
    resolve_docker()
    require_compose()
    if scope == SCOPE_CLIENTS:
        if not CLIENT_SITE_SERVICES:
            print("This deployment runs no static site, so there is nothing of the clients to stop.")
            return
        compose_remove_services(tuple(CLIENT_SITE_SERVICES.values()), "the static sites")
        print(
            f"Static sites stopped; the backend runs on. "
            f"'{SCRIPT_NAME} {VERB_DEPLOY} {FLAG_SCOPE} {SCOPE_CLIENTS}' starts them again."
        )
        return
    if scope == SCOPE_BACKEND:
        compose_remove_services(BACKEND_SERVICES, "the backend")
        print(
            f"Backend stopped; the static sites run on. Volumes, images and '{ENV_FILE}' "
            f"are untouched -- '{SCRIPT_NAME} {VERB_DEPLOY} {FLAG_SCOPE} {SCOPE_BACKEND}' "
            f"brings the same data back."
        )
        return
    step("Stopping services")
    result = docker(
        "compose", *COMPOSE_FILE_ARGS, "--profile", CLIENT_CONTRACT_JOB_PROFILE, "down",
        "--remove-orphans", capture=False,
    )
    if not result.succeeded:
        raise DeployError(
            f"'docker compose down' failed (exit {result.returncode}). The "
            f"stack may be partially stopped; review the output above."
        )
    print(
        f"Stopped. Volumes, images and '{ENV_FILE}' are untouched -- "
        f"'{SCRIPT_NAME} {VERB_DEPLOY}' brings the same data back."
    )


def command_reset(forced: bool) -> None:
    """Remove the containers, their volumes and the images built for them.

    Irreversible: every named volume this project's compose files declare is
    deleted, and with it every database, cache and uploaded file living inside
    the stack; the static sites' containers and images go with it.

    ``.env`` is deliberately NOT removed. It holds operator-authored secrets
    that no regeneration can reproduce -- the generator writes '.env.example'
    and never overwrites '.env' for exactly that reason -- and it is
    configuration rather than provisioned state, so removing it would destroy
    something this command never created.

    Args:
        forced: Whether the operator waived the confirmation prompt.

    Raises:
        DeployError: If compose could not tear the stack down.
    """
    resolve_docker()
    require_compose()
    project = compose_project_name()
    lost = (
        f"Every named volume of compose project '{project}' is deleted, with "
        f"every database, cache and uploaded file inside the stack, plus the "
        f"images built for it."
    )
    if not confirm_destructive(VERB_RESET, lost, project, forced):
        raise DeployError(
            f"'{VERB_RESET}' was not confirmed. Nothing has been changed."
        )
    step("Removing containers, volumes and locally-built images")
    result = docker(
        "compose", *COMPOSE_FILE_ARGS, "--profile", CLIENT_CONTRACT_JOB_PROFILE, "down",
        "--volumes", "--remove-orphans", "--rmi", "local",
        capture=False,
    )
    if not result.succeeded:
        raise DeployError(
            f"'docker compose down --volumes' failed (exit "
            f"{result.returncode}). The stack may be partially removed; review "
            f"the output above and re-run once the cause is fixed."
        )
    print(f"Compose project '{project}' removed, volumes and images included.")
    print(f"Kept: '{ENV_FILE}' -- it holds values only you have.")
    if EXTERNAL_TEARDOWN_SCRIPT is not None:
        print(
            f"NOT removed: this project also provisions infrastructure outside "
            f"compose (host databases, their application role, object storage). "
            f"That half lives on the host carrying it and is removed there, by "
            f"the counterpart of the script that created it:\n"
            f"  {EXTERNAL_TEARDOWN_SCRIPT}"
        )


