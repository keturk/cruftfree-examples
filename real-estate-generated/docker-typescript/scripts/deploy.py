# Inlined from cruftfree_codegen_docker/deploy_runtime.py. Pure text parsing --
# no filesystem, no subprocess -- so the generator's own suite tests it by
# calling it. Reading the files and raising DeployError stays in this script.
#: A compose ``${VAR}`` / ``${VAR:?msg}`` reference. The optional group
#: captures the separator, which is what distinguishes a reference that NEEDS a
#: value from one carrying its own default:
#:   ${VAR}        -> required; unset expands to empty, silently
#:   ${VAR:?msg}   -> required; unset aborts interpolation
#:   ${VAR:-x}     -> NOT required; unset falls back to x
#:   ${VAR-x}      -> NOT required; same, for the unset-only form
#: ``$$`` is compose's escape for a literal ``$``, so ``$${VAR}`` is the text
#: ``${VAR}`` handed to the container's shell, not an interpolation: a reference
#: is a ``${`` after an even number of ``$`` (none included).
COMPOSE_VAR_REF = re.compile(r"(?<!\$)(?:\$\$)*\$\{([A-Za-z_][A-Za-z0-9_]*)(:?[-?+])?")

#: Reference forms that still require a value to be supplied.
REQUIRING_SEPARATORS = (None, ":?", "?")

#: The subset of requiring forms for which compose treats an EMPTY value as
#: unset and aborts. ``${VAR:?msg}`` is the documented one; ``${VAR?msg}`` is
#: the unset-only variant, which compose accepts empty -- so a blank assignment
#: satisfies it, and only the ``:?`` form is mandatory-non-empty.
MANDATORY_NON_EMPTY_SEPARATORS = (":?",)


def compose_required_variables(compose_text: str) -> list[str]:
    """Every variable the compose file needs a value for, in first-seen order.

    Reads the CONSUMER side of the seam directly instead of a documentation
    block, so a variable is covered whether or not anything remembered to
    document it -- which is the case that actually bit: a plain ``${VAR}`` for
    an extern service's token appeared in no ``# Required:`` block at all and
    expanded to a blank string with nothing but a warning.

    Args:
        compose_text: The compose file's text.

    Returns:
        Variable names, first-seen order preserved so the report reads in the
        order an operator would find them.
    """
    seen: dict[str, None] = {}
    for match in COMPOSE_VAR_REF.finditer(compose_text):
        if match.group(2) in REQUIRING_SEPARATORS:
            seen.setdefault(match.group(1), None)
    return list(seen)


#: The start of a compose interpolation: ``${`` after an even number of ``$``
#: (none included), the same escape rule :data:`COMPOSE_VAR_REF` applies.
_COMPOSE_INTERPOLATION_START = re.compile(r"(?<!\$)(?:\$\$)*\$\{")
_UNREADABLE_SNIPPET_LENGTH = 40


def compose_unreadable_references(compose_text: str) -> list[str]:
    """Every interpolation in the compose file that :data:`COMPOSE_VAR_REF` cannot read.

    The non-vacuity check of :func:`compose_required_variables`: a reference it
    cannot parse is a variable whose need nothing checks. Every reference it CAN
    read counts as understood whatever its form, so a file whose references all
    carry a default (``${PORT:-8080}``) is fully read and has no required variable.

    Args:
        compose_text: The compose file's text.

    Returns:
        The text from each unreadable ``${`` on (at most 40 characters, one line),
        in file order; empty when every interpolation is a readable reference.
    """
    readable = {match.start(1) - 2 for match in COMPOSE_VAR_REF.finditer(compose_text)}
    unreadable: list[str] = []
    for match in _COMPOSE_INTERPOLATION_START.finditer(compose_text):
        opening = match.end() - 2
        if opening not in readable:
            snippet = compose_text[opening : opening + _UNREADABLE_SNIPPET_LENGTH]
            unreadable.append(snippet.splitlines()[0])
    return unreadable


def compose_mandatory_variables(compose_text: str) -> list[str]:
    """Every variable the compose file aborts on when unset OR EMPTY.

    The ``${VAR:?msg}`` subset of :func:`compose_required_variables`. A blank
    assignment satisfies a plain ``${VAR}`` (compose reads an empty string) but
    not this form, so the two are reported differently: a plain one is missing
    only when no assignment exists at all, a mandatory one also when the
    assignment is blank.

    Args:
        compose_text: The compose file's text.

    Returns:
        Variable names, first-seen order preserved.
    """
    seen: dict[str, None] = {}
    for match in COMPOSE_VAR_REF.finditer(compose_text):
        if match.group(2) in MANDATORY_NON_EMPTY_SEPARATORS:
            seen.setdefault(match.group(1), None)
    return list(seen)


def assigned_env_values(env_text: str) -> dict[str, str]:
    """Every ``KEY=value`` assignment in an environment file, last one wins.

    A blank assignment is kept as an empty string rather than dropped: ``KEY=``
    does supply a value to compose -- an empty one -- and whether that is
    acceptable depends on the form the compose file references the key in,
    which :func:`unsatisfied_env_variables` decides per variable.

    Args:
        env_text: The environment file's text.

    Returns:
        Assigned keys mapped to their raw values.
    """
    values: dict[str, str] = {}
    for line in env_text.splitlines():
        if "=" not in line or line.lstrip().startswith("#"):
            continue
        key, _, value = line.partition("=")
        values[key.strip()] = value.strip()
    return values


def unsatisfied_env_variables(
    compose_text: str,
    env_text: str,
    process_env: Mapping[str, str],
) -> tuple[list[str], list[str]]:
    """Compute ``required − supplied`` across the compose/environment seam.

    The effective value of a variable is the process environment's when it is
    set there (compose gives it precedence) and the environment file's
    otherwise. A variable is reported in one of two lists, each with a
    different fix:

    - **missing** -- no assignment anywhere. A plain ``${VAR}`` would expand to
      an empty string and the service would start on it; a ``${VAR:?}`` would
      abort interpolation.
    - **blank** -- assigned, but empty, and referenced in the ``${VAR:?}`` form,
      which compose treats exactly like unset. This is the case a copy of a
      template that documents a key by assigning it nothing produces, and it
      used to pass this check because a key-set comparison saw the assignment.

    A variable an environment-sourced compose secret reads
    (:func:`compose_environment_secret_variables`) is required AND
    mandatory-non-empty: compose refuses an unset one at ``up``, and a blank
    one mounts an empty credential the service starts on.

    Args:
        compose_text: The compose file's text.
        env_text: The environment file's text.
        process_env: The process environment compose will read.

    Returns:
        ``(missing, blank)``, each in the compose file's first-seen order --
        interpolated variables first, then secret-sourced ones.
    """
    assigned = assigned_env_values(env_text)
    secret_variables = compose_environment_secret_variables(compose_text)
    mandatory = set(compose_mandatory_variables(compose_text)) | set(secret_variables)
    required: dict[str, None] = {}
    for name in [*compose_required_variables(compose_text), *secret_variables]:
        required.setdefault(name, None)
    missing: list[str] = []
    blank: list[str] = []
    for name in required:
        if name in process_env:
            effective = process_env[name]
        elif name in assigned:
            effective = assigned[name]
        else:
            missing.append(name)
            continue
        if name in mandatory and not effective.strip():
            blank.append(name)
    return missing, blank


#: Manifest ``backend_identifier`` values realized as a file compose mounts at
#: ``/run/secrets/<handle>``. Every other backend (a managed vault, the compose
#: environment) is delivered another way and is not this seam's to check.
FILE_SECRET_BACKENDS = ("docker-secret", "file")

#: Manifest ``preflight_action`` values whose file the OPERATOR (or, on a local
#: profile, the generator's seed from the handle's ``localDefault``) supplies.
#: The deployment never writes one of these: an absent file is a refusal, never
#: a generated stand-in, because the value behind it is a real credential this
#: script does not hold.
OPERATOR_SUPPLIED_ACTIONS = (
    "check-operator-secret",
    "check-local-secret-file",
    "report-optional-operator-secret",
)

#: The manifest ``preflight_action`` of a CruftFree-owned key pair: two files the
#: deployment generates, on the machine that runs the stack, when both are absent.
KEYPAIR_ACTION = "generate-owned-keypair-if-missing"

#: Manifest ``preflight_action`` values CruftFree owns. The generator writes the
#: file of a generated secret beside every other artifact generated against the
#: same value (a database password also lands in the environment file), so an
#: absent one is a regeneration, reported by name. A key pair is the exception:
#: no artifact is generated against its value, so the deployment generates it
#: (:func:`keypair_must_be_generated`) rather than shipping one in every project.
CRUFTFREE_OWNED_ACTIONS = (
    "generate-owned-secret-if-missing",
    "generate-owned-cipher-key-if-missing",
    KEYPAIR_ACTION,
)

#: The manifest ``preflight_action`` of a secret the platform's own provisioning step
#: writes from the resource it creates. The deployment only verifies it: an absent
#: file means that step did not write it, and neither a generated value nor one an
#: operator types in may stand in for the resource's real one.
PLATFORM_WRITTEN_ACTIONS = ("require-platform-written-secret",)

#: Every secret action this script understands.
KNOWN_SECRET_ACTIONS = OPERATOR_SUPPLIED_ACTIONS + CRUFTFREE_OWNED_ACTIONS + PLATFORM_WRITTEN_ACTIONS

#: One top-level compose secret entry name, two-space indented under
#: ``secrets:``, exactly as the emitter serializes it.
_COMPOSE_SECRET_NAME = re.compile(r"^  ([^\s:#][^:]*):\s*$")

#: The ``file:`` source line of a top-level compose secret entry.
_COMPOSE_SECRET_FILE = re.compile(r"^    file:\s*(.+?)\s*$")

#: The ``environment:`` source line of a top-level compose secret entry -- the
#: deploy-host variable compose reads the secret's value from.
_COMPOSE_SECRET_ENVIRONMENT = re.compile(r"^    environment:\s*(.+?)\s*$")

#: One entry of a service's ``secrets:`` mount list, exactly as the emitter
#: serializes it: a ``- source:`` line followed by its ``target:`` line.
_COMPOSE_SECRET_MOUNT_SOURCE = re.compile(r"^\s+- source:\s*(.+?)\s*$")
_COMPOSE_SECRET_MOUNT_TARGET = re.compile(r"^\s+target:\s*(.+?)\s*$")


class SecretFileRequirement(NamedTuple):
    """One mounted secret the stack needs, joined across the seam.

    Attributes:
        handle: The logical handle -- the manifest's ``logical_name`` and the
            ``target`` of every service mount for it.
        action: The manifest's ``preflight_action`` for the handle.
        required: The manifest's ``required`` flag. An optional handle compose
            mounts nowhere is declared-but-unrealized on this deployment (the
            platform runs that dependency without the credential), never a
            defect; a REQUIRED handle compose mounts nowhere is a generation
            defect.
        purpose: The handle's declared purpose, for the operator-facing report.
        mounted: Whether any service mounts this handle at all -- from a host
            file or from the deploy host's environment.
        paths: Every project-relative host file the compose file mounts as
            this handle; empty for a handle mounted from the environment
            (nothing on disk to check) and for one mounted nowhere.
    """

    handle: str
    action: str
    required: bool
    purpose: str
    mounted: bool
    paths: tuple[str, ...]


def _compose_top_level_secret_sources(
    compose_text: str, source_line: re.Pattern[str]
) -> dict[str, str]:
    """Top-level compose secrets whose source line matches *source_line*.

    Walks the ``secrets:`` block the emitter serializes as one two-space
    indented entry per secret, each carrying one four-space indented source
    line (``file:`` or ``environment:``). Entries whose source line is of the
    other kind are not returned.

    Returns:
        Top-level secret names mapped to the matched source value, in
        document order.
    """
    sources: dict[str, str] = {}
    in_block = False
    current: str | None = None
    for line in compose_text.splitlines():
        if not in_block:
            in_block = line.rstrip() == "secrets:"
            continue
        if line.strip() and not line[0].isspace():
            break
        name_match = _COMPOSE_SECRET_NAME.match(line)
        if name_match is not None:
            current = name_match.group(1).strip("'\"")
            continue
        source_match = source_line.match(line)
        if source_match is not None and current is not None:
            sources[current] = source_match.group(1).strip("'\"")
    return sources


def compose_file_secret_sources(compose_text: str) -> dict[str, str]:
    """Every file-sourced top-level compose secret, name to host path.

    Reads the CONSUMER side of the secret-file seam from the compose file
    itself. An entry sourced from the environment carries no ``file:`` line
    and is not returned (see :func:`compose_environment_secret_variables`). An
    entry whose file is a ``${VAR:?...}`` reference (an external server's CA
    certificate, whose path the operator sets in the project ``.env``) has no
    project-relative path to check: its variable is required and non-empty by
    the ``:?`` form (:func:`compose_mandatory_variables`), and compose refuses
    a file that does not exist at ``up``, so it is not returned.

    Args:
        compose_text: The compose file's text.

    Returns:
        Top-level secret names mapped to the project-relative path each is
        read from, in document order.
    """
    return {
        name: path
        for name, path in _compose_top_level_secret_sources(
            compose_text, _COMPOSE_SECRET_FILE
        ).items()
        if "${" not in path
    }


def compose_environment_secret_variables(compose_text: str) -> list[str]:
    """Every deploy-host variable an environment-sourced compose secret reads.

    A top-level secret carrying ``environment: VAR`` is the delivery path for
    a credential the deploy host owns (an external datasource's password, an
    external object store's keys): compose reads ``VAR`` from the process
    environment or the project ``.env`` at ``up`` and mounts the value at
    ``/run/secrets/<handle>``. The variable never appears as a ``${VAR}``
    interpolation, so :func:`compose_required_variables` cannot see it -- and
    an unset one is a compose refusal at start-up, a blank one an empty
    credential the service starts on. Both are this seam's to report.

    Args:
        compose_text: The compose file's text.

    Returns:
        Variable names in document order, de-duplicated (several secrets may
        read one variable).
    """
    seen: dict[str, None] = {}
    for variable in _compose_top_level_secret_sources(
        compose_text, _COMPOSE_SECRET_ENVIRONMENT
    ).values():
        seen.setdefault(variable, None)
    return list(seen)


def compose_service_secret_mounts(compose_text: str) -> dict[str, tuple[str, ...]]:
    """Every handle some service mounts, with the top-level secrets mounted as it.

    Reads each service's ``secrets:`` list -- one ``- source: <name>`` /
    ``target: <handle>`` pair per mount, as the emitter serializes it. A handle
    in the result reaches a container at ``/run/secrets/<handle>`` whether its
    top-level source is a host ``file:`` or the deploy host's ``environment:``;
    one absent from it reaches no container at all. The file a handle is read
    from is the file of the source mounted as it, which need not be named like
    the handle: a database login's password is mounted under the login's own
    name from the file the service keeps its block password in.

    Args:
        compose_text: The compose file's text.

    Returns:
        Mount target names mapped to the top-level secret names mounted as each,
        in document order, de-duplicated.
    """
    mounts: dict[str, dict[str, None]] = {}
    pending_source: str | None = None
    for line in compose_text.splitlines():
        if pending_source is not None:
            target_match = _COMPOSE_SECRET_MOUNT_TARGET.match(line)
            if target_match is not None:
                target = target_match.group(1).strip("'\"")
                mounts.setdefault(target, {})[pending_source] = None
        source_match = _COMPOSE_SECRET_MOUNT_SOURCE.match(line)
        pending_source = source_match.group(1).strip("'\"") if source_match is not None else None
    return {target: tuple(sources) for target, sources in mounts.items()}


def secret_file_requirements(
    manifest: Mapping[str, object],
    secret_sources: Mapping[str, str],
    mounts: Mapping[str, tuple[str, ...]],
) -> list[SecretFileRequirement]:
    """Join the manifest's mounted-file secret handles to compose's mounts.

    The manifest (``.cruftfree/runtime-requirements.json``) DECLARES which handles
    the stack needs and how each is provisioned; the compose file DECIDES which
    services mount each and from which host file. This joins the two by the
    handle name, which is the ``target`` of every service mount, and follows
    each mount to the top-level secret mounted as the handle and so to the host
    file it reads: the file's leaf name is not the join key, because a handle
    may be mounted from a file named for another one.

    Args:
        manifest: The parsed manifest document.
        secret_sources: :func:`compose_file_secret_sources` of the compose file.
        mounts: :func:`compose_service_secret_mounts` of the compose file.

    Returns:
        One requirement per manifest secret handle on a file backend, in
        manifest order, each carrying whether any service mounts it and every
        host path compose mounts for it.

    Raises:
        ValueError: A file-backed handle whose preflight action is neither
            operator-supplied nor generator-owned -- no provisioner is known,
            so the absent-file report could only guess at the fix.
    """
    items = manifest.get("items")
    if not isinstance(items, list):
        return []
    requirements: list[SecretFileRequirement] = []
    for item in items:
        if not isinstance(item, dict) or item.get("kind") != "secret-handle":
            continue
        if item.get("backend_identifier") not in FILE_SECRET_BACKENDS:
            continue
        handle = str(item["logical_name"])
        action = str(item["preflight_action"])
        if action not in KNOWN_SECRET_ACTIONS:
            raise ValueError(
                f"Secret handle {handle!r} carries preflight action {action!r}, "
                "which names no known provisioner. Known operator-supplied "
                f"actions: {list(OPERATOR_SUPPLIED_ACTIONS)}; generator-owned "
                f"actions: {list(CRUFTFREE_OWNED_ACTIONS)}; platform-written "
                f"actions: {list(PLATFORM_WRITTEN_ACTIONS)}. Fix: regenerate the "
                "project with the generator that wrote this manifest."
            )
        paths = tuple(
            dict.fromkeys(
                secret_sources[source] for source in mounts.get(handle, ()) if source in secret_sources
            )
        )
        purpose = item.get("purpose")
        requirements.append(
            SecretFileRequirement(
                handle=handle,
                action=action,
                required=bool(item["required"]),
                purpose=str(purpose) if purpose is not None else "",
                mounted=handle in mounts,
                paths=paths,
            )
        )
    return requirements


def unmounted_required_secret_handles(
    requirements: list[SecretFileRequirement],
) -> list[SecretFileRequirement]:
    """Every REQUIRED requirement that no service mounts -- a generation defect.

    The manifest and the compose file are generated together, so a required
    handle compose mounts nowhere means the two disagree about what the stack
    needs; nothing an operator provisions can close that. An OPTIONAL handle
    compose mounts nowhere is the shared model's way of saying the platform
    realizes that dependency without the credential (a cache without AUTH, a
    broker without SASL) and is not reported. A key-pair half is likewise never
    reported: the pair is provisioned whole, and a half no service reads (the
    private one) is mounted by none.

    Args:
        requirements: :func:`secret_file_requirements` of the project.

    Returns:
        The required, unmounted requirements, in manifest order.
    """
    return [
        requirement
        for requirement in requirements
        if requirement.required
        and not requirement.mounted
        and requirement.action != KEYPAIR_ACTION
    ]


class KeypairFiles(NamedTuple):
    """The two host files of one CruftFree-owned key pair.

    Attributes:
        group: The key pair's name (both halves share it).
        public_path: Project-relative host path of the public half.
        private_path: Project-relative host path of the private half.
    """

    group: str
    public_path: str
    private_path: str


def owned_keypair_files(
    manifest: Mapping[str, object],
    application_secrets_dir: str,
    halves: Mapping[str, tuple[str, str]],
) -> list[KeypairFiles]:
    """Pair the manifest's key-pair handles into their two host files.

    A key pair is two manifest items (one per half) that must be generated
    together, so each half is named by *halves* -- handle to ``(group, half)`` --
    never inferred from the handle's spelling. A half's file is
    ``<application_secrets_dir>/<its rendered name>`` whether or not a service
    mounts it: the private half is mounted by none.

    Args:
        manifest: The parsed manifest document.
        application_secrets_dir: Project-relative directory of the application-owned
            secret files.
        halves: The key-pair halves the generator knows, handle to
            ``(group, "public" | "private")``.

    Returns:
        One entry per key pair, in manifest order.

    Raises:
        ValueError: A key-pair handle that is no known half, a half named twice, or a
            pair missing a half.
    """
    items = manifest.get("items")
    if not isinstance(items, list):
        return []
    parts_by_group: dict[str, dict[str, str]] = {}
    for item in items:
        if not isinstance(item, dict) or item.get("kind") != "secret-handle":
            continue
        if item.get("preflight_action") != KEYPAIR_ACTION:
            continue
        if item.get("backend_identifier") not in FILE_SECRET_BACKENDS:
            continue
        handle = str(item["logical_name"])
        if handle not in halves:
            raise ValueError(
                f"Secret handle {handle!r} carries the key-pair action but is no known "
                f"key-pair half. Known halves: {sorted(halves)}. Fix: regenerate the "
                "project with the generator that wrote this manifest."
            )
        group, half = halves[handle]
        parts = parts_by_group.setdefault(group, {})
        if half in parts:
            raise ValueError(
                f"Key pair {group!r} names its {half} half twice. Fix: regenerate the project."
            )
        parts[half] = f"{application_secrets_dir}/{item['platform_name']}"
    keypairs: list[KeypairFiles] = []
    for group, parts in parts_by_group.items():
        if set(parts) != {"public", "private"}:
            raise ValueError(
                f"Key pair {group!r} has only its {sorted(parts)} half in the manifest; "
                "both halves are always declared together. Fix: regenerate the project."
            )
        keypairs.append(KeypairFiles(group, parts["public"], parts["private"]))
    return keypairs


def keypair_library_install_command(
    interpreter: str, interpreter_prefix: str, project_venv: str
) -> list[str] | None:
    """The command that installs the key generator's library, or ``None`` when it is not ours to run.

    The entrypoint scripts create the project's virtual environment only to run the
    deployment, so a first deploy fills it without being asked. Any other interpreter
    belongs to the operator and is never changed.

    Args:
        interpreter: The running interpreter's executable.
        interpreter_prefix: The running interpreter's resolved environment directory.
        project_venv: The project's resolved virtual environment directory.

    Returns:
        The argument list to run, or ``None`` outside the project's environment.
    """
    if interpreter_prefix != project_venv:
        return None
    return [interpreter, "-m", "pip", "install", "--quiet", "cryptography"]


def keypair_must_be_generated(
    keypair: KeypairFiles, is_file: Callable[[str], bool]
) -> bool:
    """Whether the deployment generates *keypair* now.

    Both files present: the pair is kept untouched (never overwritten). Both absent:
    generate. Exactly one present is refused, because generating the other half would
    produce a pair that does not match the one on disk, and replacing the present half
    would destroy a key the operator may still use.

    Args:
        keypair: The pair's two host files.
        is_file: Whether a project-relative path is an existing file.

    Returns:
        ``True`` when both files are absent, ``False`` when both exist.

    Raises:
        ValueError: Exactly one half exists.
    """
    public_present = is_file(keypair.public_path)
    private_present = is_file(keypair.private_path)
    if public_present == private_present:
        return not public_present
    present, absent = (
        (keypair.public_path, keypair.private_path)
        if public_present
        else (keypair.private_path, keypair.public_path)
    )
    raise ValueError(
        f"Key pair {keypair.group!r} is half present: '{present}' exists but '{absent}' "
        "does not. A generated half would not match the one on disk and removing the "
        "existing one would destroy a key. Fix: restore the missing file, or delete the "
        "remaining one to have the deployment generate a fresh pair."
    )


def unsatisfied_secret_files(
    requirements: list[SecretFileRequirement],
    is_file: Callable[[str], bool],
) -> list[SecretFileRequirement]:
    """Every requirement with at least one mounted host file that does not exist.

    Args:
        requirements: :func:`secret_file_requirements` of the project.
        is_file: Whether a project-relative path is an existing file.

    Returns:
        The unsatisfied requirements, each narrowed to its ABSENT paths only,
        in manifest order.
    """
    unsatisfied: list[SecretFileRequirement] = []
    for requirement in requirements:
        absent = tuple(path for path in requirement.paths if not is_file(path))
        if absent:
            unsatisfied.append(requirement._replace(paths=absent))
    return unsatisfied



def compose_file_list() -> str:
    """The compose files this tree ships, quoted, for a message."""
    return ", ".join(f"'{name}'" for name in COMPOSE_FILES) or "no compose file"


def read_compose_file(name: str) -> str:
    """The text of the shipped compose file *name*.

    Raises:
        DeployError: If the file is not in the tree.
    """
    compose_path = PROJECT_ROOT / name
    if not compose_path.is_file():
        raise DeployError(
            f"'{name}' not found in '{PROJECT_ROOT}' -- this tree was generated with "
            f"it and cannot be deployed without it. Fix: regenerate the project."
        )
    return compose_path.read_text(encoding="utf-8")


def _compose_file_required_variables(name: str, compose_text: str) -> list[str]:
    """Every variable the compose file *name* needs a value for.

    Raises:
        DeployError: If it holds an interpolation the parser cannot read.
    """
    unreadable = compose_unreadable_references(compose_text)
    if unreadable:
        raise DeployError(
            f"'{name}' interpolates {unreadable!r}, which the variable parser "
            f"cannot read -- so this check would pass without verifying that "
            f"reference. Its format has changed and this check must be updated "
            f"to match it."
        )
    interpolated = compose_required_variables(compose_text)
    # A top-level secret sourced from ``environment: VAR`` reads the host
    # variable without a ``${VAR}`` anywhere; it needs a value just the same.
    return [*interpolated, *compose_environment_secret_variables(compose_text)]


def require_env_keys() -> None:
    """Fail loud when a variable compose needs has no value anywhere.

    THE SEAM THIS CLOSES: every compose file of ``COMPOSE_FILES`` CONSUMES
    variables, ``.env`` (plus the process environment) PRODUCES them, and nothing
    compared the two on the machine that runs compose.

    Both failure modes were live. A plain ``${VAR}`` expands to an empty string
    and only warns -- a service starts with a blank credential and looks
    healthy. A ``${VAR:?}`` aborts, but at interpolation time: after the
    archive shipped, after images built, tens of minutes into a release,
    naming one variable. ``.env`` deliberately survives redeployment so an
    operator's values are never overwritten, which also means a variable
    introduced by a later regeneration is simply absent until someone adds it.

    This runs before any of that and names every unsatisfied variable at once,
    in two lists with two fixes: variables with NO assignment anywhere, and
    variables assigned a BLANK value where compose references them in the
    ``${VAR:?}`` form -- which compose treats exactly like unset. The second
    list is what a copy of a template that documents a key by assigning it
    nothing produces, and a key-set comparison saw the assignment and passed.

    Raises:
        DeployError: If a compose file cannot be read, if no variable
            reference can be parsed out of one that interpolates (the check
            would otherwise verify nothing), or if any required variable is
            missing or blank-mandatory.
    """
    required: list[str] = []
    missing: list[str] = []
    blank: list[str] = []
    env_text: str | None = None
    for name in COMPOSE_FILES:
        compose_text = read_compose_file(name)
        file_required = _compose_file_required_variables(name, compose_text)
        if not file_required:
            continue
        if env_text is None:
            env_text = (PROJECT_ROOT / ENV_FILE).read_text(encoding="utf-8")
        file_missing, file_blank = unsatisfied_env_variables(compose_text, env_text, os.environ)
        required.extend(variable for variable in file_required if variable not in required)
        missing.extend(variable for variable in file_missing if variable not in missing)
        blank.extend(variable for variable in file_blank if variable not in blank)
    if not missing and not blank:
        return
    files = compose_file_list()
    sections: list[str] = []
    if missing:
        listing = "\n".join(f"  {name}=" for name in missing)
        sections.append(
            f"{len(missing)} of the {len(required)} variable(s) "
            f"{files} require have no value in '{ENV_FILE}' or the "
            f"process environment:\n{listing}"
        )
    if blank:
        listing = "\n".join(f"  {name}=" for name in blank)
        sections.append(
            f"{len(blank)} variable(s) {files} require in the "
            "mandatory '${VAR:?}' form or as a secret's 'environment:' source "
            f"are assigned but BLANK, which compose treats exactly like unset "
            f"(or mounts as an empty credential):\n{listing}"
        )
    raise DeployError(
        "\n\n".join(sections)
        + "\n\n"
        f"These are deployment-owned: '{ENV_TEMPLATE}' names them and "
        f"deliberately assigns no value, and '{ENV_FILE}' is never refreshed "
        f"from it. Fix: give each line above a real value. Left unset or blank, "
        f"a variable either aborts compose at interpolation or -- worse -- "
        f"expands to an empty string and the service starts with a blank "
        f"credential."
    )


def _secret_file_fix(requirement: SecretFileRequirement) -> str:
    """The operator-facing fix for one absent secret file, by provisioning action."""
    mounted_at = f"{CONTAINER_SECRETS_DIR}/{requirement.handle}"
    if requirement.action == KEYPAIR_ACTION:
        return (
            f"a key pair is generated by 'deploy' when both of its files are "
            f"absent; run it again, or restore the missing file (mounted at "
            f"{mounted_at})"
        )
    if requirement.action in CRUFTFREE_OWNED_ACTIONS:
        return (
            f"regenerate the project: the generator writes this file with the "
            f"value the rest of the stack was generated against, and a value "
            f"minted here instead would not match it (mounted at {mounted_at})"
        )
    if requirement.action in PLATFORM_WRITTEN_ACTIONS:
        return (
            f"the platform's provisioning step writes this file from the resource "
            f"it creates; re-run that step -- never write a value by hand, it "
            f"would not be the resource's own (mounted at {mounted_at})"
        )
    if requirement.action == "check-local-secret-file":
        return (
            f"the handle declares a 'localDefault' the generator seeds on a local "
            f"profile only; on this profile write the real value to the path "
            f"above (mounted at {mounted_at})"
        )
    if requirement.action == "report-optional-operator-secret":
        return (
            f"the handle is declared optional, but compose mounts file secrets "
            f"unconditionally and refuses a missing source -- write the value "
            f"to the path above (mounted at {mounted_at}), or remove the "
            f"handle from the service's 'secrets' config section if it is unused"
        )
    return (
        f"write the value the operator holds to the path above, mode 0600 "
        f"(mounted at {mounted_at}; 'secrets/*/' is never committed)"
    )


def _write_new_secret_file(path: Path, content: bytes, mode: int) -> None:
    """Create *path* with *mode*, refusing to overwrite an existing file.

    Raises:
        DeployError: If the file already exists or cannot be written.
    """
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, mode)
    except FileExistsError as exc:
        raise DeployError(
            f"'{path}' already exists and is never overwritten. Fix: remove it "
            f"deliberately if you want a new key pair generated."
        ) from exc
    except OSError as exc:
        raise DeployError(f"Cannot create '{path}': {exc}") from exc
    with os.fdopen(descriptor, "wb") as handle:
        handle.write(content)


def _install_keypair_library_if_absent(pending: int) -> None:
    """Make the ``cryptography`` package importable, or refuse with the command that does.

    Args:
        pending: How many key pairs wait on it, for the refusal's message.

    Raises:
        DeployError: The package is absent and this interpreter is not the project's
            own environment, or installing it there failed.
    """
    try:
        import cryptography  # noqa: F401
    except ImportError:
        command = keypair_library_install_command(
            sys.executable,
            str(Path(sys.prefix).resolve()),
            str((PROJECT_ROOT / ".venv").resolve()),
        )
        if command is None:
            raise DeployError(
                f"{pending} key pair(s) must be generated but the 'cryptography' "
                f"package is not installed in this Python environment. Fix: "
                f"'{sys.executable} -m pip install cryptography', then deploy again."
            ) from None
        step("Installing 'cryptography' into the project environment, to generate key pairs")
        if subprocess.run(command, check=False).returncode != 0:
            raise DeployError(
                f"Could not install 'cryptography' into the project environment. Fix: run "
                f"'{' '.join(command)}' and read its error, then deploy again."
            ) from None


def provision_owned_keypairs() -> None:
    """Generate every CruftFree-owned key pair whose two files are both absent.

    THE KEY PAIR IS NEVER SHIPPED. ``.cruftfree/runtime-requirements.json`` declares the
    pair (two ``generate-owned-keypair-if-missing`` items), compose mounts the
    public half where it is read, and the files are written here, on the machine
    that runs the stack, so no two deployments share a signing key and no key is
    ever committed. An existing pair is kept as it is: the files are created
    exclusively, never overwritten. Exactly one half present is refused, since
    generating the other would not match it.

    Key generation needs the ``cryptography`` package, imported only when a pair
    has to be generated; every other deployment step uses the standard library.

    Raises:
        DeployError: If the manifest or compose file cannot be read or disagree
            about the pair, if one half exists without the other, if
            ``cryptography`` is not installed, or if a file cannot be written.
    """
    manifest_path = PROJECT_ROOT / MANIFEST_FILE
    if not manifest_path.is_file():
        raise DeployError(
            f"'{MANIFEST_FILE}' not found in '{PROJECT_ROOT}' -- the key pairs "
            f"this stack needs cannot be determined. Fix: regenerate the project."
        )
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    is_file = lambda path: (PROJECT_ROOT / path).is_file()  # noqa: E731
    try:
        keypairs = owned_keypair_files(manifest, APPLICATION_SECRETS_DIR, KEYPAIR_HALVES)
        pending = [
            keypair for keypair in keypairs if keypair_must_be_generated(keypair, is_file)
        ]
    except ValueError as exc:
        raise DeployError(str(exc)) from exc
    if not pending:
        return
    _install_keypair_library_if_absent(len(pending))
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric import rsa

    for keypair in pending:
        step(f"Generating key pair '{keypair.group}' (RSA {KEYPAIR_BITS})")
        private_key = rsa.generate_private_key(
            public_exponent=KEYPAIR_PUBLIC_EXPONENT, key_size=KEYPAIR_BITS
        )
        private_pem = private_key.private_bytes(
            serialization.Encoding.PEM,
            serialization.PrivateFormat.PKCS8,
            serialization.NoEncryption(),
        )
        public_pem = private_key.public_key().public_bytes(
            serialization.Encoding.PEM,
            serialization.PublicFormat.SubjectPublicKeyInfo,
        )
        _write_new_secret_file(
            PROJECT_ROOT / keypair.private_path, private_pem, KEYPAIR_PRIVATE_MODE
        )
        _write_new_secret_file(
            PROJECT_ROOT / keypair.public_path, public_pem, KEYPAIR_PUBLIC_MODE
        )


def require_secret_files() -> None:
    """Fail loud when a secret file compose will mount does not exist.

    THE SEAM THIS CLOSES: ``.cruftfree/runtime-requirements.json`` DECLARES every secret
    handle the stack needs and who provisions it, the compose files mount
    one host file per handle under ``secrets/<service>/``, and the
    machine that runs compose is where the file must exist. An operator-
    provisioned value (a vendor API key, a model credential, a webhook signing
    key) is written by the operator, never generated: an absent one is
    reported by name with its path and purpose, and nothing is put in its
    place -- a stand-in would start the service with a credential the vendor
    has never seen. A CruftFree-owned value is written by the generator, beside
    the artifacts generated against it, so an absent one is a regeneration,
    never something minted here that the rest of the stack would not match.

    Compose itself would refuse a missing source, but at interpolation time,
    after every image is built, naming one file. This runs first and names
    every absent file at once.

    An OPTIONAL handle the manifest declares but no service mounts is not a
    defect: the shared model declares a credential handle for every cache and
    broker block and leaves it to the platform whether the dependency is
    realized with authentication, so an unmounted optional handle is one this
    deployment runs without. A REQUIRED handle no service mounts is the two
    generated-together artifacts disagreeing, which no provisioning can fix.

    Raises:
        DeployError: If the manifest or compose file cannot be read, if no
            service mounts a REQUIRED handle the manifest declares (a
            generation defect), or if any mounted secret file is absent.
    """
    manifest_path = PROJECT_ROOT / MANIFEST_FILE
    if not manifest_path.is_file():
        raise DeployError(
            f"'{MANIFEST_FILE}' not found in '{PROJECT_ROOT}' -- the secret "
            f"files compose mounts cannot be checked. Fix: regenerate the project."
        )
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    # A placed secret a schema-read client reads is consumed though no service
    # mounts it: the client is handed it from the owner login's variable, which
    # compose requires, so it has no file to check here.
    mounts: dict[str, tuple[str, ...]] = {handle: () for handle in SCHEMA_READ_SECRET_HANDLES}
    sources: dict[str, str] = {}
    for name in COMPOSE_FILES:
        compose_text = read_compose_file(name)
        for handle, secrets in compose_service_secret_mounts(compose_text).items():
            mounts[handle] = (*mounts.get(handle, ()), *secrets)
        sources.update(compose_file_secret_sources(compose_text))
    requirements = secret_file_requirements(manifest, sources, mounts)
    unmounted = unmounted_required_secret_handles(requirements)
    if unmounted:
        listing = "\n".join(f"  {requirement.handle}" for requirement in unmounted)
        raise DeployError(
            f"'{MANIFEST_FILE}' declares {len(unmounted)} REQUIRED secret "
            f"handle(s) on a mounted-file backend that no service in "
            f"{compose_file_list()} mounts:\n"
            f"{listing}\n\nThe two are generated together, so this is a "
            f"generation defect, not something to provision. Fix: regenerate "
            f"the project."
        )
    absent = unsatisfied_secret_files(
        requirements, lambda path: (PROJECT_ROOT / path).is_file()
    )
    if not absent:
        return
    sections: list[str] = []
    for requirement in absent:
        paths = "\n".join(f"    {path}" for path in requirement.paths)
        purpose = f" -- {requirement.purpose}" if requirement.purpose else ""
        sections.append(
            f"  secret '{requirement.handle}'{purpose}\n"
            f"   expected file(s):\n{paths}\n"
            f"   fix: {_secret_file_fix(requirement)}"
        )
    raise DeployError(
        f"{len(absent)} secret file(s) {compose_file_list()} mount do not exist on "
        f"this machine, so the stack would abort at interpolation:\n\n"
        + "\n\n".join(sections)
        + "\n\nNo value was generated in their place: each is a credential this "
        "deployment does not hold."
    )


def build_base_images() -> None:
    """Build each shared base image the local daemon does not have.

    Every service Dockerfile of a language is ``FROM`` that language's tag, and
    compose never builds a ``FROM`` image -- so each base must exist locally
    BEFORE the services build. Each tag is a content hash of its dependency
    union, so an image is rebuilt only when that union changes, which makes
    this idempotent.

    ``--load`` lands the image in the engine's store on every builder: one that
    runs in a container otherwise keeps its result in its own cache and still
    reports success, so the store is read back after each build.

    Raises:
        DeployError: If a build failed, or left the image out of the store.
    """
    for tag, directory in BASE_IMAGES:
        if docker("image", "inspect", tag).succeeded:
            continue
        step(f"Building shared base image {tag}")
        result = docker("buildx", "build", "--load", "-t", tag, f"./{directory}", capture=False)
        if not result.succeeded:
            raise DeployError(
                f"Building the shared base image '{tag}' failed (docker exited "
                f"{result.returncode}). Every service image of its language is "
                f"FROM this tag, so the deployment cannot proceed."
            )
        if not docker("image", "inspect", tag).succeeded:
            raise DeployError(
                f"The shared base image '{tag}' built, but the engine's image store "
                f"does not hold it, so every service image FROM it would fail on a "
                f"registry pull. Fix: run 'docker buildx ls', select the builder "
                f"whose driver is '{ENGINE_BUILDER_DRIVER}' ('docker buildx use "
                f"<name>'), unset {BUILDX_BUILDER_VARIABLE}, and deploy again."
            )
    if BASE_IMAGES:
        keep_compose_on_engine_builder()


def keep_compose_on_engine_builder() -> None:
    """Build the service images on the builder that reads the engine's image store.

    A service's ``FROM`` names a base image only that store holds, and a builder
    running in a container resolves it against a registry, failing on a pull of
    an image that was never published. The selected builder is left alone when
    it is already the engine's. Runs after the base images are built, because
    the name compose takes here is one ``docker build`` refuses.

    Raises:
        DeployError: If docker cannot describe the selected builder.
    """
    inspected = docker("buildx", "inspect")
    if not inspected.succeeded:
        raise DeployError(f"'docker buildx inspect' failed (exit {inspected.returncode}): {inspected.output}")
    try:
        driver = selected_builder_driver(inspected.stdout)
    except ValueError as error:
        raise DeployError(f"{error} Nothing was started.") from error
    if driver != ENGINE_BUILDER_DRIVER:
        step(f"Building service images on the engine's builder, not the selected {driver} one")
        os.environ[BUILDX_BUILDER_VARIABLE] = COMPOSE_ENGINE_BUILDER


#: Lines of container log to print for each failed container. Enough to carry a
#: stack trace and the statement that produced it, without burying the report.
_FAILED_CONTAINER_LOG_LINES = "200"


def _failed_service_names(states: list[dict[str, object]]) -> list[str]:
    """Return the compose services whose container exited non-zero.

    Args:
        states: Compose's account of each container, as ``_service_states`` reads it.

    Returns:
        Service names, in the order compose reports them; empty when none failed.
    """
    names: list[str] = []
    for entry in states:
        exit_code = entry.get("ExitCode")
        name = entry.get("Service") or entry.get("Name")
        if isinstance(exit_code, int) and exit_code != 0 and name:
            names.append(str(name))
    return names


def _report_failed_container_logs() -> list[str] | None:
    """Print the logs of every container that exited non-zero.

    ``docker compose up`` reports a one-shot container's failure as nothing but
    ``didn't complete successfully: exit 1``. The reason it failed -- the
    seed error, the connection refusal, the traceback -- is in that
    container's own log, which compose does not print. Without this, a failed
    deployment reports which container died and says nothing about why, and the
    cause takes another round trip to the host to read.

    It runs only once ``up`` has already failed, so a container state it cannot
    read is printed and reported to the caller, never raised over the failure
    being reported.

    Returns:
        The names of the failed services, so the caller can name them; None when
        compose's account of the containers could not be read.
    """
    result = docker("compose", *COMPOSE_FILE_ARGS, "ps", "--all", "--format", "json")
    if not result.succeeded:
        print(
            f"'docker compose ps' failed (exit {result.returncode}): "
            f"{result.output or 'no output'}. The failed containers cannot be named."
        )
        return None
    try:
        states = _service_states(result)
    except DeployError as error:
        print(f"{error} The failed containers cannot be named.")
        return None
    failed = _failed_service_names(states)
    for name in failed:
        step(f"Logs for failed container '{name}'")
        docker(
            "compose", *COMPOSE_FILE_ARGS, "logs", "--no-color", "--tail", _FAILED_CONTAINER_LOG_LINES,
            name, capture=False,
        )
    return failed


def compose_up_databases() -> None:
    """Start what every RDBMS block's data lives in, returning once each block can be read.

    Each database container is started and waited for until its healthcheck
    passes; then each one-shot creating a block's logins -- the owner login the
    schema client connects as -- runs to its exit, a non-zero exit failing the
    deploy. Nothing else starts: the release waits until every block's schema
    is ready for it.

    Raises:
        DeployError: If a database did not become healthy or a login job failed.
    """
    if not DATABASE_CONTAINERS and not DATABASE_JOBS:
        print("No database runs in this compose project: there is nothing to start first.")
        return
    if DATABASE_CONTAINERS:
        step("Starting the databases")
        result = docker(
            "compose", *COMPOSE_FILE_ARGS, "up", "-d", "--wait", *DATABASE_CONTAINERS,
            capture=False,
        )
        if not result.succeeded:
            raise DeployError(
                f"'docker compose up --wait' did not bring the database(s) "
                f"{', '.join(DATABASE_CONTAINERS)} to a passing healthcheck (exit "
                f"{result.returncode}). Nothing of the release was started; review the "
                f"output above, or the database's own log: {COMPOSE_COMMAND} logs <service>."
            )
    for job in DATABASE_JOBS:
        step(f"Creating the database logins ('{job}')")
        result = docker(
            "compose", *COMPOSE_FILE_ARGS, "run", "--rm", "--no-TTY", job, capture=False
        )
        if not result.succeeded:
            raise DeployError(
                f"The login job '{job}' failed (exit {result.returncode}); its output is "
                f"above. Nothing of the release was started."
            )


