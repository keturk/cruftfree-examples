class SchemaToolRun(NamedTuple):
    """What one command of the schema tool left: its exit status and its two output streams."""

    exit_status: int
    stdout: bytes
    stderr: bytes


class SchemaRun(NamedTuple):
    """One run of a block's read, as the channel sees it.

    Attributes:
        block: The block key the read is of.
        run_id: The run's id (:func:`require_run_id`): names the run's run-store prefix, its
            workload and its tag.
        directory: The run's private directory, holding ``in`` and receiving ``out``, ``err``
            and ``exit``.
        client_arguments: The arguments the client takes after its own (the places binding),
            from ``read-batch --places``.
    """

    block: str
    run_id: str
    directory: Path
    client_arguments: tuple[str, ...]

    @property
    def input_file(self) -> Path:
        """The client's input, to be delivered on the client's standard input."""
        return self.directory / SCHEMA_RUN_INPUT_FILE

    @property
    def output_file(self) -> Path:
        """Where the channel leaves the client's standard output."""
        return self.directory / SCHEMA_RUN_OUTPUT_FILE

    @property
    def error_file(self) -> Path:
        """Where the channel leaves the client's standard error."""
        return self.directory / SCHEMA_RUN_ERROR_FILE

    @property
    def exit_file(self) -> Path:
        """Where the channel leaves the client's exit status."""
        return self.directory / SCHEMA_RUN_EXIT_FILE

    def record_exit_status(self, status: int) -> None:
        """Write *status*, the client's exit status, as the run's ``exit`` file.

        For a channel that runs the client from the deploy's own process; a workload writes
        the file itself.
        """
        _write_new_file(self.exit_file, f"{status}{_LINE_BREAK}".encode("ascii"))


#: Runs one schema-tool command with the given arguments and returns what it left.
SchemaTool = Callable[[Sequence[str]], SchemaToolRun]

#: A platform's channel: runs the client of :class:`SchemaRun` on the database's network and
#: leaves its ``out``, ``err`` and ``exit`` in the run's directory, raising the host's error when
#: the run could not be carried out.
SchemaChannel = Callable[[SchemaRun], None]

#: How many runs a platform's channel carries side by side: asked once, before the first run of a
#: plan or a converge with a block, and at least one. A channel that carries several runs at once
#: is called from that many threads.
ConcurrentRuns = Callable[[], int]

_Result = TypeVar("_Result")


def schema_client_command(client_argv: Sequence[str], arguments: Sequence[str] = ()) -> tuple[str, ...]:
    """The command line a run's client runs as: *client_argv* and *arguments* under ``timeout``.

    ``timeout`` stops the client after :data:`SCHEMA_CLIENT_TIMEOUT_SECONDS` and kills it
    :data:`SCHEMA_CLIENT_KILL_AFTER_SECONDS` later, so every run ends by itself. Both GNU
    coreutils and BusyBox ``timeout`` take this spelling.

    Args:
        client_argv: The engine's client program and options (``CatalogClient.argv``).
        arguments: The arguments a run appends (:attr:`SchemaRun.client_arguments`); empty
            where the workload declares the command and a run appends them itself.

    Raises:
        ValueError: *client_argv* is empty.
    """
    if not client_argv:
        raise ValueError(
            "A schema read was given no client program. Pass the engine's catalog client "
            "argv (CatalogClient.argv), the program first."
        )
    return (
        _TIMEOUT_PROGRAM,
        _TIMEOUT_KILL_OPTION,
        str(SCHEMA_CLIENT_KILL_AFTER_SECONDS),
        str(SCHEMA_CLIENT_TIMEOUT_SECONDS),
        *client_argv,
        *arguments,
    )


def require_run_id(run_id: str) -> str:
    """Return *run_id* when it is a run id: a :data:`RUN_STORE_NAME_PART`.

    Raises:
        ValueError: *run_id* is empty, starts with ``.`` or holds a character outside
            ``[A-Za-z0-9._-]``.
    """
    if RUN_STORE_NAME_PART.fullmatch(run_id) is None:
        raise ValueError(
            f"{run_id!r} is not a run id. A run id names the run's run-store keys and its "
            "workload, so it holds only letters, digits, '.', '_' and '-', and does not start "
            "with '.'."
        )
    return run_id


def new_run_id() -> str:
    """A new run id: the UTC time and 16 random hex digits, ``20261027T081143Z-<hex>``."""
    stamp = time.strftime(_RUN_ID_TIME_FORMAT, time.gmtime())
    return require_run_id(f"{stamp}-{secrets.token_hex(_RUN_ID_RANDOM_BYTES)}")


def host_client_operands(block: str, run_id: str, client_arguments: Sequence[str]) -> tuple[str, ...]:
    """The operands of :data:`SCHEMA_HOST_CLIENT_COMMAND` for one run of *block*'s client.

    The command is started inside the run's directory on the host, which holds ``in``, so no
    operand names a path: ``<block> <run id> [client argument ...]``.

    Raises:
        ValueError: *run_id* is not a run id.
    """
    return (block, require_run_id(run_id), *client_arguments)


def host_client_run(
    arguments: Sequence[str],
    directory: Path,
    blocks: Sequence[str],
    failure: Callable[[str], Exception],
) -> SchemaRun:
    """The run :data:`SCHEMA_HOST_CLIENT_COMMAND` was given: *arguments* as
    :func:`host_client_operands` built them, started in the run's *directory*.

    Args:
        arguments: The command's operands.
        directory: The directory the command was started in: the run's.
        blocks: The blocks whose client the host runs.
        failure: The host's error type, built from a message naming the cause.

    Raises:
        Exception: *failure*'s, when an operand is missing, the block has no client here, the run
            id breaks the run-store name rule, or *directory* holds no ``in``.
    """
    if len(arguments) < 2:
        raise failure(
            f"'{SCHEMA_HOST_CLIENT_COMMAND}' takes a block and a run id, then the client's "
            f"arguments; got {list(arguments)}."
        )
    block, run_id, *client_arguments = arguments
    if block not in blocks:
        raise failure(
            f"'{SCHEMA_HOST_CLIENT_COMMAND}' has no client for block '{block}'; the blocks this "
            f"host reaches are {sorted(blocks)}."
        )
    if RUN_STORE_NAME_PART.fullmatch(run_id) is None:
        raise failure(
            f"'{SCHEMA_HOST_CLIENT_COMMAND}' was given {run_id!r}, which is not a run id: letters, "
            "digits, '.', '_' and '-', not starting with '.'."
        )
    run = SchemaRun(block, run_id, directory.resolve(), tuple(client_arguments))
    if not run.input_file.is_file():
        raise failure(
            f"'{SCHEMA_HOST_CLIENT_COMMAND}' runs inside the run's directory, which holds the "
            f"client's input '{SCHEMA_RUN_INPUT_FILE}'; {run.directory} holds none."
        )
    return run


def run_schema_tool(script: Path, arguments: Sequence[str]) -> SchemaToolRun:
    """Run the schema tool *script* with *arguments* under this interpreter, its output as bytes.

    The tool needs only the standard library, so the deploy's own interpreter runs it. Its
    output is kept as the bytes it wrote, never decoded or translated here.
    """
    completed = subprocess.run(
        [sys.executable, str(script), *arguments],
        stdin=subprocess.DEVNULL,
        capture_output=True,
        check=False,
    )
    return SchemaToolRun(completed.returncode, completed.stdout, completed.stderr)


def _write_new_file(path: Path, content: bytes) -> None:
    """Create *path* (it must not exist) holding exactly *content*."""
    with path.open("xb") as handle:
        handle.write(content)


def _say(message: str) -> None:
    """Write *message* and a line break on standard error as one write, so lines of runs carried
    out side by side never run into each other."""
    sys.stderr.write(f"{message}{_LINE_BREAK}")


def serial_schema_runs() -> int:
    """The :data:`ConcurrentRuns` of a channel that carries one run at a time: one."""
    return 1


def _concurrency(concurrent_runs: ConcurrentRuns, failure: Callable[[str], Exception]) -> int:
    """How many runs the channel carries at once, as *concurrent_runs* says; the host's error unless at least one."""
    count = concurrent_runs()
    if count < 1:
        raise failure(
            f"The schema channel says it carries {count!r} run(s) at once, where a number of at "
            "least one is expected. This is a generator defect -- regenerate the project."
        )
    return count


class _NotStarted(Exception):
    """A block's step that never started, because the step of a block before it failed."""


def _each_block(
    blocks: Sequence[str], step: Callable[[str], _Result], concurrent: int
) -> Iterator[tuple[str, _Result]]:
    """*step* of each block of *blocks*, at most *concurrent* at once: each block and its result, in block order.

    The steps start in the blocks' order. Once a block's step raises, no step of a block after
    it starts; the steps already running finish, and the error is raised when the iteration
    reaches that block, every block before it having been yielded. A step that never started
    is never reached, since a block before it failed. Leaving the iteration early starts no
    further step and waits for the running ones. With *concurrent* one, every step runs on the
    calling thread, each once the block before it was yielded, so a channel carrying one run at
    a time is never called from another thread.
    """
    if concurrent == 1:
        for block in blocks:
            yield block, step(block)
        return
    failed: list[int] = []
    lock = threading.Lock()

    def guarded(index: int, block: str) -> _Result:
        with lock:
            if any(earlier < index for earlier in failed):
                raise _NotStarted(block)
        try:
            return step(block)
        except BaseException:
            with lock:
                failed.append(index)
            raise

    pool = ThreadPoolExecutor(max_workers=concurrent)
    try:
        futures = [pool.submit(guarded, index, block) for index, block in enumerate(blocks)]
        for block, future in zip(blocks, futures, strict=True):
            yield block, future.result()
    finally:
        with lock:
            failed.append(-1)
        pool.shutdown(wait=True, cancel_futures=True)


def _exit_cause(result: SchemaToolRun) -> str:
    """What a schema-tool command that did not succeed printed on its standard error."""
    return result.stderr.decode(_TEXT_ENCODING, errors="replace").strip() or "it printed no error"


def _tool_output(
    schema_tool: SchemaTool,
    arguments: Sequence[str],
    failed: str,
    failure: Callable[[str], Exception],
) -> bytes:
    """The standard output of the schema-tool command *arguments*; the host's error opening with *failed* otherwise.

    *failed* is the sentence naming the block and what did not happen to it.
    """
    result = schema_tool(arguments)
    if result.exit_status != 0:
        raise failure(
            f"{failed}: 'schema.py {' '.join(arguments)}' exited {result.exit_status}: "
            f"{_exit_cause(result)}"
        )
    return result.stdout


def _decoded_lines(output: bytes, what: str, failed: str, failure: Callable[[str], Exception]) -> list[str]:
    """*output*, UTF-8 text ended by a line break, as its lines; the host's error opening with *failed* otherwise."""
    try:
        text = output.decode(_TEXT_ENCODING)
    except UnicodeDecodeError as error:
        raise failure(f"{failed}: the schema tool's {what} is not UTF-8 ({error}).") from error
    if not text.endswith(_LINE_BREAK):
        raise failure(
            f"{failed}: the schema tool's {what} does not end with a line break, so it may have "
            "been cut."
        )
    return text[: -len(_LINE_BREAK)].split(_LINE_BREAK)


def _client_arguments(
    schema_tool: SchemaTool, block: str, failed: str, failure: Callable[[str], Exception]
) -> tuple[str, ...]:
    """The client arguments ``read-batch <block> --places`` printed, one per line."""
    places = (SCHEMA_READ_BATCH_COMMAND, block, SCHEMA_READ_PLACES_OPTION)
    output = _tool_output(schema_tool, places, failed, failure)
    arguments = _decoded_lines(output, "client arguments", failed, failure)
    if not all(arguments):
        raise failure(
            f"{failed}: 'schema.py {' '.join(places)}' printed an empty line where each line is "
            "one client argument."
        )
    return tuple(arguments)


def _run_file_options(run: SchemaRun) -> list[str]:
    """The options naming the files *run* brought back, as ``read-verify`` and ``apply-verify`` take them."""
    return [
        part
        for option, name in SCHEMA_RUN_FILE_OPTIONS
        for part in (option, str(run.directory / name))
    ]


def _private_directory(prefix: str, failed: str, failure: Callable[[str], Exception]) -> Path:
    """A new temporary directory private to one step, named from *prefix*; the host's error opening with *failed* otherwise."""
    try:
        return Path(tempfile.mkdtemp(prefix=prefix))
    except OSError as error:
        raise failure(f"{failed}: its private directory could not be created ({error}).") from error


def _write_stdout(content: bytes) -> None:
    """Write *content* to standard output as these bytes, whatever the console's encoding or line ending."""
    sys.stdout.flush()
    sys.stdout.buffer.write(content)
    sys.stdout.buffer.flush()


def _remove_private_directory(
    directory: Path, block: str, holding: str, failure: Callable[[str], Exception]
) -> None:
    """Remove *directory*, private to one step on *block*, or raise the host's error naming it."""
    try:
        shutil.rmtree(directory)
    except OSError as error:
        raise failure(
            f"The files of block '{block}' could not be removed from {directory}: {error}. "
            f"They hold {holding}: remove the directory."
        ) from error


def read_live_catalog(
    block: str,
    *,
    schema_tool: SchemaTool,
    channel: SchemaChannel,
    failure: Callable[[str], Exception],
) -> str:
    """Read *block*'s live catalog through *channel* and return the verified document.

    Args:
        block: The block key (``schema_tool_block_key``).
        schema_tool: Runs a schema-tool command (:func:`run_schema_tool` bound to the project's
            ``schema.py``).
        channel: The platform's channel to the block's client.
        failure: The host's error type, built from a message naming the cause.

    Raises:
        Exception: *failure*'s, when the tool refuses the block, the channel's files are not a
            verified read, or the run's directory cannot be removed; and whatever *channel*
            raises.
    """
    failed = f"The live catalog of block '{block}' was not read"
    input_text = _tool_output(schema_tool, (SCHEMA_READ_BATCH_COMMAND, block), failed, failure)
    client_arguments = _client_arguments(schema_tool, block, failed, failure)
    run_id = new_run_id()
    directory = _private_directory(f"{_RUN_DIRECTORY_PREFIX}{run_id}-", failed, failure)
    try:
        run = SchemaRun(block, run_id, directory, client_arguments)
        _write_new_file(run.input_file, input_text)
        _say(f"Reading the live catalog of block '{block}' (run {run_id}).")
        channel(run)
        verified = _tool_output(
            schema_tool, [SCHEMA_READ_VERIFY_COMMAND, block, *_run_file_options(run)], failed, failure
        )
    finally:
        _remove_private_directory(directory, block, "the read's input and the client's output", failure)
    return _LINE_BREAK.join(_decoded_lines(verified, "verified document", failed, failure))


def schema_read(
    block: str,
    *,
    schema_tool: SchemaTool,
    channel: SchemaChannel,
    failure: Callable[[str], Exception],
) -> None:
    """``schema-read <block>``: print *block*'s verified live catalog on standard output, alone.

    The document is written as UTF-8 bytes ended by one line break, whatever the console's
    encoding or line ending, so what a consumer reads is what the server sent. Progress goes to
    standard error. Arguments and errors as :func:`read_live_catalog`.
    """
    document = read_live_catalog(block, schema_tool=schema_tool, channel=channel, failure=failure)
    _write_stdout(f"{document}{_LINE_BREAK}".encode(_TEXT_ENCODING))


def _plan_file_bytes(path: Path, failed: str, failure: Callable[[str], Exception]) -> bytes:
    """The bytes of the SQL file *path*; the host's error opening with *failed* when it cannot be read."""
    try:
        return path.read_bytes()
    except OSError as error:
        raise failure(
            f"{failed}: the file could not be read ({error}). Give a SQL file "
            f"'schema.py {SCHEMA_PLAN_COMMAND}' wrote for the block."
        ) from error


def _apply_plan_file(
    block: str,
    path: Path,
    *,
    schema_tool: SchemaTool,
    channel: SchemaChannel,
    failure: Callable[[str], Exception],
) -> str | None:
    """Apply *path*, one of *block*'s plan files, through *channel*: the verified document of the
    catalog it left, or ``None``.

    ``None`` is an empty file, which applies nothing: that is said on standard error and no client
    runs. The steps and the errors are :func:`schema_apply`'s.
    """
    failed = f"The SQL file {path} was not applied to block '{block}'"
    if not _plan_file_bytes(path, failed, failure):
        _say(f"The SQL file {path} of block '{block}' is empty: nothing applies.")
        return None
    sql_option = (SCHEMA_APPLY_SQL_OPTION, str(path))
    input_text = _tool_output(schema_tool, (SCHEMA_APPLY_BATCH_COMMAND, block, *sql_option), failed, failure)
    if not input_text:
        raise failure(
            f"{failed}: 'schema.py {SCHEMA_APPLY_BATCH_COMMAND}' printed no input, so the file was "
            "emptied after it was read."
        )
    client_arguments = _client_arguments(schema_tool, block, failed, failure)
    run_id = new_run_id()
    directory = _private_directory(f"{_APPLY_DIRECTORY_PREFIX}{run_id}-", failed, failure)
    unverified = f"The apply of {path} to block '{block}' was not verified"
    try:
        run = SchemaRun(block, run_id, directory, client_arguments)
        _write_new_file(run.input_file, input_text)
        _say(f"Applying {path} to block '{block}' (run {run_id}).")
        channel(run)
        verified = _tool_output(
            schema_tool,
            [SCHEMA_APPLY_VERIFY_COMMAND, block, *sql_option, *_run_file_options(run)],
            unverified,
            failure,
        )
    finally:
        _remove_private_directory(directory, block, "the apply's input and the client's output", failure)
    document = _LINE_BREAK.join(_decoded_lines(verified, "verified document", unverified, failure))
    if not document:
        raise failure(
            f"{unverified}: 'schema.py {SCHEMA_APPLY_VERIFY_COMMAND}' printed an empty line where "
            "it prints the document of the catalog the apply left."
        )
    return document


def schema_apply(
    block: str,
    sql_file: str,
    *,
    schema_tool: SchemaTool,
    channel: SchemaChannel,
    failure: Callable[[str], Exception],
) -> None:
    """``schema-apply <block> <sql-file>``: apply *sql_file*, one of *block*'s plan files, through *channel*.

    ``schema.py apply-batch`` prints the client's input, refusing a file that is not one of
    *block*'s plan files (so no DDL runs unguarded), and ``read-batch --places`` the client
    arguments, as for a read. The input is written to ``in`` in a directory private to this run,
    never passed as an argument; *channel* runs the client as the block's owner login, and
    ``schema.py apply-verify`` checks the files it left. The directory is removed whatever
    happened. The verified document of the catalog the apply left goes to standard output as
    UTF-8 bytes ended by one line break, nothing else, as :func:`schema_read` prints a read's;
    progress goes to standard error. An empty file applies nothing: that is said on standard
    error and no client runs.

    Args:
        block: The block key (``schema_tool_block_key``).
        sql_file: The SQL file, as ``schema.py plan`` wrote it beside its statement map.
        schema_tool: Runs a schema-tool command (:func:`run_schema_tool` bound to the project's
            ``schema.py``).
        channel: The platform's channel to the block's client: the one ``schema-read`` uses.
        failure: The host's error type, built from a message naming the cause.

    Raises:
        Exception: *failure*'s, naming *block* and the cause, when the file cannot be read, the
            tool refuses the file or the block, the run is not a verified apply (``apply-verify``'s
            message names the statement and change a failed apply stopped at and what it left of
            the schema), or the run's directory cannot be removed; and whatever *channel* raises.
    """
    document = _apply_plan_file(
        block, Path(sql_file).resolve(), schema_tool=schema_tool, channel=channel, failure=failure
    )
    if document is not None:
        _write_stdout(f"{document}{_LINE_BREAK}".encode(_TEXT_ENCODING))


def schema_plan_arguments(
    block: str, catalog: Path, expand: Path, contract: Path, approved: bool
) -> list[str]:
    """``schema.py plan``'s arguments for *block*: :data:`SCHEMA_PLAN_APPROVED_OPTION` exactly when *approved*."""
    arguments = [
        SCHEMA_PLAN_COMMAND,
        block,
        SCHEMA_PLAN_CATALOG_OPTION,
        str(catalog),
        SCHEMA_PLAN_EXPAND_OPTION,
        str(expand),
        SCHEMA_PLAN_CONTRACT_OPTION,
        str(contract),
    ]
    if approved:
        arguments.append(SCHEMA_PLAN_APPROVED_OPTION)
    return arguments


def _printed_plan(result: SchemaToolRun, block: str) -> bool:
    """Whether *result*'s standard output is a plan of *block*: it opens with :data:`SCHEMA_PLAN_HEADER`."""
    return result.stdout.startswith(SCHEMA_PLAN_HEADER.format(block=block).encode(_TEXT_ENCODING))


class _PlanFiles(NamedTuple):
    """The files one ``plan`` of a block reads and writes: the live catalog's document and each phase's SQL.

    ``plan`` writes each phase's statement map beside its SQL file.
    """

    catalog: Path
    expand: Path
    contract: Path


def _plan_files(directory: Path) -> _PlanFiles:
    """The files of one ``plan`` in *directory*, a directory private to it."""
    return _PlanFiles(
        directory / _PLAN_CATALOG_FILE, directory / _PLAN_EXPAND_FILE, directory / _PLAN_CONTRACT_FILE
    )


def _write_catalog(catalog: Path, document: str, failed: str, failure: Callable[[str], Exception]) -> None:
    """Write *document*, a verified catalog document, to *catalog* as a verified read prints it.

    A document that cannot be written raises the host's error opening with *failed*.
    """
    try:
        _write_new_file(catalog, f"{document}{_LINE_BREAK}".encode(_TEXT_ENCODING))
    except OSError as error:
        raise failure(f"{failed}: its catalog could not be written to {catalog} ({error}).") from error


def _run_plan(
    block: str,
    approved: bool,
    files: _PlanFiles,
    failed: str,
    *,
    schema_tool: SchemaTool,
    failure: Callable[[str], Exception],
) -> SchemaToolRun:
    """Run ``schema.py plan`` over *files*' catalog document, writing its SQL there.

    ``plan`` gets :data:`SCHEMA_PLAN_APPROVED_OPTION` exactly when *approved*.

    Returns:
        ``plan``'s run, which printed a plan of *block*: exit 0 applies every change, exit
        :data:`SCHEMA_PLAN_REFUSED_EXIT` refuses one.

    Raises:
        Exception: *failure*'s, opening with *failed*, when ``plan`` exits with any other status
            or prints no plan of *block*.
    """
    result = schema_tool(
        schema_plan_arguments(block, files.catalog, files.expand, files.contract, approved)
    )
    planned = result.exit_status in (0, SCHEMA_PLAN_REFUSED_EXIT) and _printed_plan(result, block)
    if not planned:
        raise failure(
            f"{failed}: 'schema.py {SCHEMA_PLAN_COMMAND} {block}' exited {result.exit_status} "
            f"without printing a plan of the block: {_exit_cause(result)}"
        )
    return result


def _read_and_plan(
    block: str,
    approved: bool,
    files: _PlanFiles,
    *,
    schema_tool: SchemaTool,
    channel: SchemaChannel,
    failure: Callable[[str], Exception],
) -> SchemaToolRun:
    """Read *block*'s live catalog into *files* and run ``schema.py plan`` over it (:func:`_run_plan`).

    Raises:
        Exception: *failure*'s, naming *block* and the cause, when the read fails, the document
            cannot be written, or ``plan`` fails; and whatever *channel* raises.
    """
    failed = f"The plan of block '{block}' was not made"
    document = read_live_catalog(block, schema_tool=schema_tool, channel=channel, failure=failure)
    _write_catalog(files.catalog, document, failed, failure)
    return _run_plan(block, approved, files, failed, schema_tool=schema_tool, failure=failure)


def _refused_plans(refused: Sequence[str], outcome: str) -> str:
    """The message naming each refused block (*refused*: ``<block>: <cause>``) and *outcome*."""
    listed = "\n  - ".join(refused)
    return (
        f"The plan refuses changes in {len(refused)} block(s), and {outcome}:\n"
        f"  - {listed}\nA change that needs approval is planned only when the deploy runs "
        f"with {SCHEMA_PLAN_APPROVED_OPTION}; a change never applied needs the fix its plan "
        "names."
    )


def _plan_block(
    block: str,
    approved: bool,
    *,
    schema_tool: SchemaTool,
    channel: SchemaChannel,
    failure: Callable[[str], Exception],
) -> SchemaToolRun:
    """What a deploy would do to *block*, changing nothing: the run of ``schema.py plan`` that printed it.

    *block*'s live catalog is read (:func:`read_live_catalog`), its document written to a
    directory private to this plan, and ``schema.py plan`` run over it with ``--approved`` exactly
    when *approved*, writing its expand and contract SQL, each with its statement map, into that
    directory. The directory, holding the document and every file the plan wrote, is removed
    whatever happened.

    Raises:
        Exception: *failure*'s, naming *block* and the cause, when the read fails, when ``plan``
            exits with a status other than 0 and :data:`SCHEMA_PLAN_REFUSED_EXIT` or prints no
            plan of *block*, or when the directory cannot be removed; and whatever *channel*
            raises.
    """
    directory = _private_directory(
        _PLAN_DIRECTORY_PREFIX, f"The plan of block '{block}' was not made", failure
    )
    try:
        return _read_and_plan(
            block,
            approved,
            _plan_files(directory),
            schema_tool=schema_tool,
            channel=channel,
            failure=failure,
        )
    finally:
        _remove_private_directory(
            directory, block, "its live catalog and the plan's SQL files", failure
        )


def plan_schema_blocks(
    blocks: Sequence[str],
    approved: bool,
    *,
    concurrent_runs: ConcurrentRuns,
    schema_tool: SchemaTool,
    channel: SchemaChannel,
    failure: Callable[[str], Exception],
) -> None:
    """``deploy --plan``: print what a deploy would do to every block of *blocks*, changing nothing.

    The blocks are planned side by side (:func:`_plan_block`), as many at once as the channel
    carries, and each plan goes to standard output as its bytes, in the blocks' order. A plan that
    refuses a change is printed and the other blocks planned, so one run shows every refusal.

    Args:
        blocks: The block keys whose schema convergence is enabled, in the order to plan them.
        approved: Whether the operator gave ``deploy --approved``; the one source of approval.
        concurrent_runs: How many runs *channel* carries at once, asked once when there is a block.
        schema_tool: Runs a schema-tool command (:func:`run_schema_tool` bound to the project's
            ``schema.py``).
        channel: The platform's channel to a block's client.
        failure: The host's error type, built from a message naming the cause.

    Raises:
        Exception: *failure*'s, naming each block whose plan refuses a change once every block
            is planned; or, for the first block in order that cannot be read or planned, naming
            it and the cause, once the plans already running have finished (no block after it
            starts).
    """
    if not blocks:
        print("No RDBMS block has schema convergence enabled: there is nothing to plan.")
        return

    def plan_block(block: str) -> SchemaToolRun:
        return _plan_block(block, approved, schema_tool=schema_tool, channel=channel, failure=failure)

    refused: list[str] = []
    for block, result in _each_block(blocks, plan_block, _concurrency(concurrent_runs, failure)):
        _write_stdout(result.stdout)
        if result.exit_status != 0:
            refused.append(f"{block}: {_exit_cause(result)}")
    if refused:
        raise failure(_refused_plans(refused, "nothing was changed"))


def _step_files(
    directory: Path, step: str, block: str, failure: Callable[[str], Exception]
) -> _PlanFiles:
    """The files of one converge *step* on *block*, in its own new subdirectory of *directory*."""
    step_directory = directory / step
    try:
        step_directory.mkdir()
    except OSError as error:
        raise failure(
            f"Block '{block}' was not converged: the directory {step_directory} could not be "
            f"created ({error})."
        ) from error
    return _plan_files(step_directory)


class _Converging(NamedTuple):
    """Where one block's converge stands once its expand is applied.

    Attributes:
        expanded: Whether its expand applied a change.
        contract: The contract SQL it applies once the release is healthy: the re-plan's when
            its expand applied a change, the first plan's otherwise.
        catalog: The document of the catalog it was last seen with: the one its expand left, or
            the first read's.
    """

    expanded: bool
    contract: Path
    catalog: Path


def _plan_before_release(
    blocks: Sequence[str],
    approved: bool,
    directories: dict[str, Path],
    concurrent: int,
    *,
    schema_tool: SchemaTool,
    channel: SchemaChannel,
    failure: Callable[[str], Exception],
) -> dict[str, _PlanFiles]:
    """Read and plan every block of *blocks* in its converge directory, printing each plan; the files of each block's plan.

    The blocks are planned side by side, *concurrent* at once, and each plan printed in the
    blocks' order. A plan refusing a change is printed and the other blocks planned; once every
    block is planned, the host's error names each refused block, before anything is applied.
    """

    def plan_block(block: str) -> tuple[_PlanFiles, SchemaToolRun]:
        files = _step_files(directories[block], _CONVERGE_PLAN_STEP, block, failure)
        return files, _read_and_plan(
            block, approved, files, schema_tool=schema_tool, channel=channel, failure=failure
        )

    planned: dict[str, _PlanFiles] = {}
    refused: list[str] = []
    for block, (files, result) in _each_block(blocks, plan_block, concurrent):
        _write_stdout(result.stdout)
        if result.exit_status != 0:
            refused.append(f"{block}: {_exit_cause(result)}")
        planned[block] = files
    if refused:
        raise failure(
            _refused_plans(refused, "nothing was applied and the new release was not started")
        )
    return planned


def _apply_phase(
    block: str,
    phase: str,
    sql: Path,
    step: tuple[Path, str],
    *,
    schema_tool: SchemaTool,
    channel: SchemaChannel,
    failure: Callable[[str], Exception],
) -> _PlanFiles | None:
    """Apply *sql*, *block*'s *phase* SQL (:func:`_apply_plan_file`), keeping the catalog it left.

    *step* is the block's converge directory and the step whose new subdirectory receives the
    verified document of the catalog the apply left, as its catalog file.

    Returns:
        The step's files, or ``None`` when *sql* is empty: it applies nothing and no client runs.
    """
    document = _apply_plan_file(
        block, sql.resolve(), schema_tool=schema_tool, channel=channel, failure=failure
    )
    if document is None:
        return None
    directory, name = step
    files = _step_files(directory, name, block, failure)
    kept = f"The {phase} of block '{block}' is applied, but the catalog it left was not kept"
    _write_catalog(files.catalog, document, kept, failure)
    return files


def _replan_after_expand(
    block: str,
    approved: bool,
    replanned: _PlanFiles,
    planned: _PlanFiles,
    *,
    schema_tool: SchemaTool,
    failure: Callable[[str], Exception],
) -> None:
    """Plan *block* again from the catalog its expand left (*replanned*'s catalog), into *replanned*.

    The re-plan runs with the arguments of the first and must hold exactly *planned*'s contract
    changes (``schema.py plan-compare``): no expand change, no contract change more or less. The
    catalog is the one the apply itself read under the block's lock once its changes were
    committed, so what anything else changed beside the expand is in it.

    Raises:
        Exception: *failure*'s, naming *block*, when the re-plan fails, refuses a change or
            differs from *planned*'s contract (``plan-compare``'s message names each extra and
            each missing change).
    """
    failed = (
        f"The re-plan of block '{block}' after its expand is not exactly its planned contract, "
        "so the new release was not started"
    )
    result = _run_plan(block, approved, replanned, failed, schema_tool=schema_tool, failure=failure)
    if result.exit_status != 0:
        raise failure(f"{failed}: it refuses a change: {_exit_cause(result)}")
    comparison = (
        SCHEMA_PLAN_COMPARE_COMMAND,
        block,
        SCHEMA_PLAN_COMPARE_PLANNED_OPTION,
        str(planned.contract),
        SCHEMA_PLAN_EXPAND_OPTION,
        str(replanned.expand),
        SCHEMA_PLAN_CONTRACT_OPTION,
        str(replanned.contract),
    )
    _tool_output(schema_tool, comparison, failed, failure)


def _expand_and_replan(
    blocks: Sequence[str],
    approved: bool,
    directories: dict[str, Path],
    planned: dict[str, _PlanFiles],
    concurrent: int,
    *,
    schema_tool: SchemaTool,
    channel: SchemaChannel,
    failure: Callable[[str], Exception],
) -> dict[str, _Converging]:
    """Apply each block's expand and re-plan each block it changed (:func:`_replan_after_expand`); where each block stands.

    The blocks are carried side by side, *concurrent* at once. A block whose expand is empty
    applies nothing and keeps its first plan: no change ran, so its contract still carries the
    fingerprint of the catalog it applies to.
    """

    def expand(block: str) -> _Converging:
        files = planned[block]
        replanned = _apply_phase(
            block,
            "expand",
            files.expand,
            (directories[block], _CONVERGE_REPLAN_STEP),
            schema_tool=schema_tool,
            channel=channel,
            failure=failure,
        )
        if replanned is None:
            return _Converging(False, files.contract, files.catalog)
        _replan_after_expand(block, approved, replanned, files, schema_tool=schema_tool, failure=failure)
        return _Converging(True, replanned.contract, replanned.catalog)

    standing: dict[str, _Converging] = {}
    for block, converging in _each_block(blocks, expand, concurrent):
        if converging.expanded:
            print(f"Applied the expand of block '{block}'; its re-plan holds exactly its planned contract.")
        standing[block] = converging
    return standing


def _verdict(result: SchemaToolRun, block: str) -> str:
    """Why ``schema.py verify``'s run *result* says *block* differs from its declared schema."""
    verdict = result.stdout.decode(_TEXT_ENCODING, errors="replace").strip()
    return (
        f"'schema.py {SCHEMA_VERIFY_COMMAND} {block}' exited {result.exit_status}: "
        f"{verdict or 'it printed no verdict'} ({_exit_cause(result)})"
    )


def _contract_and_verify(
    blocks: Sequence[str],
    directories: dict[str, Path],
    standing: dict[str, _Converging],
    concurrent: int,
    *,
    schema_tool: SchemaTool,
    channel: SchemaChannel,
    failure: Callable[[str], Exception],
) -> None:
    """Apply each block's contract, then have ``schema.py verify`` check the catalog the block was left with.

    The blocks are carried side by side, *concurrent* at once, and each verdict printed in the
    blocks' order. The catalog verified is the one the contract's apply left, or, when the
    contract is empty, the one the block was last seen with (:class:`_Converging`).

    Raises:
        Exception: *failure*'s, naming each block whose catalog differs from its declared schema,
            once every block is verified; and as :func:`_apply_phase`.
    """

    def contract(block: str) -> tuple[bool, SchemaToolRun]:
        converging = standing[block]
        applied = _apply_phase(
            block,
            "contract",
            converging.contract,
            (directories[block], _CONVERGE_VERIFY_STEP),
            schema_tool=schema_tool,
            channel=channel,
            failure=failure,
        )
        catalog = converging.catalog if applied is None else applied.catalog
        return applied is not None, schema_tool(
            (SCHEMA_VERIFY_COMMAND, block, SCHEMA_PLAN_CATALOG_OPTION, str(catalog))
        )

    differing: list[str] = []
    for block, (contracted, result) in _each_block(blocks, contract, concurrent):
        if contracted:
            print(f"Applied the contract of block '{block}'.")
        _write_stdout(result.stdout)
        if result.exit_status != 0:
            differing.append(f"{block}: {_verdict(result, block)}")
    if differing:
        listed = "\n  - ".join(differing)
        raise failure(
            f"{len(differing)} block(s) do not hold their declared schema after the deploy:\n"
            f"  - {listed}\nThe new release runs against the schema the deploy left; read the "
            "block's catalog for what changed, then deploy again: it plans the remaining changes "
            "anew."
        )


def _remove_converge_directories(
    directories: dict[str, Path], failure: Callable[[str], Exception]
) -> None:
    """Remove every block's converge directory of *directories*, naming each that cannot be removed."""
    left: list[str] = []
    for block, directory in directories.items():
        try:
            shutil.rmtree(directory)
        except OSError as error:
            left.append(f"block '{block}': {directory} ({error})")
    if left:
        listed = "\n  - ".join(left)
        raise failure(
            f"The converge files of {len(left)} block(s) could not be removed:\n  - {listed}\n"
            "They hold the blocks' live catalogs and plan SQL: remove the directories."
        )


def _expand_and_start(
    blocks: Sequence[str],
    approved: bool,
    directories: dict[str, Path],
    concurrent: int,
    *,
    start_release: Callable[[], None],
    schema_tool: SchemaTool,
    channel: SchemaChannel,
    failure: Callable[[str], Exception],
) -> dict[str, _Converging]:
    """Plan every block, apply each expand, re-plan each against its planned contract, then start the release.

    Each block gets a directory private to its converge, recorded in *directories* as soon as it
    exists so the caller removes it whatever happens. The blocks are carried side by side,
    *concurrent* at once.

    Returns:
        Where each block stands (:class:`_Converging`): the contract SQL it applies once the
        release is healthy and the catalog it was last seen with.
    """
    for block in blocks:
        directories[block] = _private_directory(
            _CONVERGE_DIRECTORY_PREFIX, f"Block '{block}' was not converged", failure
        )
    planned = _plan_before_release(
        blocks, approved, directories, concurrent, schema_tool=schema_tool, channel=channel, failure=failure
    )
    standing = _expand_and_replan(
        blocks,
        approved,
        directories,
        planned,
        concurrent,
        schema_tool=schema_tool,
        channel=channel,
        failure=failure,
    )
    print(
        f"The expand of {len(blocks)} block(s) is applied and each re-plan holds exactly its "
        "planned contract: starting the new release."
    )
    start_release()
    return standing


def _converge(
    blocks: Sequence[str],
    approved: bool,
    directories: dict[str, Path],
    concurrent: int,
    *,
    start_release: Callable[[], None],
    verify_release: Callable[[], None],
    schema_tool: SchemaTool,
    channel: SchemaChannel,
    failure: Callable[[str], Exception],
) -> None:
    """The steps of :func:`converge_schema_blocks` once the databases are up, in their order."""
    standing = _expand_and_start(
        blocks,
        approved,
        directories,
        concurrent,
        start_release=start_release,
        schema_tool=schema_tool,
        channel=channel,
        failure=failure,
    )
    print("Verifying the new release: no block's contract is applied unless it is healthy.")
    verify_release()
    _contract_and_verify(
        blocks, directories, standing, concurrent, schema_tool=schema_tool, channel=channel, failure=failure
    )


def converge_schema_blocks(
    blocks: Sequence[str],
    approved: bool,
    *,
    bring_up_data: Callable[[], None],
    start_release: Callable[[], None],
    verify_release: Callable[[], None],
    concurrent_runs: ConcurrentRuns,
    schema_tool: SchemaTool,
    channel: SchemaChannel,
    failure: Callable[[str], Exception],
) -> None:
    """``deploy``'s ``converge`` step: bring every block of *blocks* to its declared schema around the release.

    In this order, each step only once the one before succeeded for every block:

    1. *bring_up_data* starts the databases, and every block is read and planned
       (``schema.py plan``, ``--approved`` exactly when *approved*), its plan printed. A plan
       refusing a change stops the deploy, naming every refused block, before anything applies.
    2. Each block's expand SQL is applied (:func:`schema_apply`'s path; an empty file applies
       nothing and runs no client). A block whose expand applied a change is planned again with
       the same arguments from the verified catalog that apply left, and ``schema.py
       plan-compare`` requires the re-plan to hold exactly the first plan's contract changes; a
       block whose expand is empty keeps its first plan's contract.
    3. *start_release* starts the new release and *verify_release* proves it healthy.
    4. Each block's contract SQL is applied: it carries the fingerprint of the catalog the block
       was last seen with. ``schema.py verify`` then checks the catalog the block was left with
       -- the one its contract's apply left, else its expand's, else its first read -- and prints
       its verdict; a block that differs from its declared schema fails the deploy once every
       block is verified.

    A block's client runs once for its read and once for each phase file holding a change: an
    apply reads the catalog it left under the block's lock, so no step reads the catalog again.
    Each step is carried out for the blocks side by side, as many at once as *concurrent_runs*
    says, and what it prints comes out in the blocks' order; a block that fails stops every block
    after it from starting that step, the ones already running finish, and the failure is raised
    for the first failed block in order.

    Every plan's files stay in a directory private to the block's converge until the end, and
    every such directory is removed whatever happened. With no block (the profile's migrations
    disabled) the three callbacks run in their order, no block is converged and *concurrent_runs*
    is not asked.

    Args:
        blocks: The block keys whose schema convergence is enabled, each once (a shared block under its
            one key), in the order to converge them.
        approved: Whether the operator gave ``deploy --approved``; the one source of approval.
        bring_up_data: Starts the databases the blocks live in, returning once they accept
            connections.
        start_release: Starts the new release.
        verify_release: The deploy's health verification of the new release.
        concurrent_runs: How many runs *channel* carries at once, asked once *bring_up_data*
            returned, since a channel may read it from what that step deploys (Azure App
            Service's run store is part of its foundation stage).
        schema_tool: Runs a schema-tool command (:func:`run_schema_tool` bound to the project's
            ``schema.py``).
        channel: The platform's channel to a block's client: the one ``schema-read`` uses.
        failure: The host's error type, built from a message naming the cause.

    Raises:
        Exception: *failure*'s, naming the block and the cause, when a block is given twice, the
            channel's concurrency is not at least one, a plan refuses a change, an apply fails, a
            re-plan differs, a block differs from its declared schema at the end, or a directory
            cannot be removed; and whatever a callback or *channel* raises, which stops the steps
            after it.
    """
    _require_distinct_blocks(blocks, failure)
    if not blocks:
        print("No RDBMS block has schema convergence enabled: no block is converged.")
        bring_up_data()
        start_release()
        verify_release()
        return
    bring_up_data()
    # Asked once the data is up: a channel may read its count from what bring_up_data deploys.
    concurrent = _concurrency(concurrent_runs, failure)
    directories: dict[str, Path] = {}
    try:
        _converge(
            blocks,
            approved,
            directories,
            concurrent,
            start_release=start_release,
            verify_release=verify_release,
            schema_tool=schema_tool,
            channel=channel,
            failure=failure,
        )
    finally:
        _remove_converge_directories(directories, failure)


def _require_distinct_blocks(blocks: Sequence[str], failure: Callable[[str], Exception]) -> None:
    """Raise the host's error naming every block *blocks* gives more than once."""
    repeated = sorted({block for block in blocks if blocks.count(block) > 1})
    if repeated:
        raise failure(
            f"The blocks to converge name {', '.join(repeated)} more than once; a block is "
            "planned once per run, under its one schema-tool key. Regenerate the project."
        )


def expand_schema_blocks(
    blocks: Sequence[str],
    approved: bool,
    *,
    bring_up_data: Callable[[], None],
    start_release: Callable[[], None],
    concurrent_runs: ConcurrentRuns,
    schema_tool: SchemaTool,
    channel: SchemaChannel,
    failure: Callable[[str], Exception],
) -> None:
    """The expand half of the ``converge`` step, around a release a later ``deploy`` completes.

    Steps 1 to 3 of :func:`converge_schema_blocks`, then *start_release*: the databases come up,
    every block is read and planned (a plan refusing a change stops the run, naming every refused
    block, before anything applies), each expand is applied, and each re-plan must hold exactly
    the first plan's contract changes before the release starts. No contract is applied and no
    block verified: the expanded schema still holds everything the release before it reads, and
    the next ``deploy``'s converge applies the contract once its own release is healthy.

    Args:
        blocks: The block keys whose schema convergence is enabled, each once, in the order to
            expand them.
        approved: Whether the plans run with ``--approved``; a command without that switch of its
            own passes ``False``.
        bring_up_data: Starts the databases the blocks live in, returning once they accept
            connections.
        start_release: Starts the release.
        concurrent_runs: As :func:`converge_schema_blocks` takes it, asked once the data is up.
        schema_tool: Runs a schema-tool command.
        channel: The platform's channel to a block's client.
        failure: The host's error type, built from a message naming the cause.

    Raises:
        Exception: *failure*'s, naming the block and the cause, when a block is given twice, the
            concurrency is below one, a plan refuses a change, an apply fails, a re-plan differs or
            a directory cannot be removed; and whatever a callback or *channel* raises.
    """
    _require_distinct_blocks(blocks, failure)
    if not blocks:
        print("No RDBMS block has schema convergence enabled: no block is expanded.")
        bring_up_data()
        start_release()
        return
    bring_up_data()
    concurrent = _concurrency(concurrent_runs, failure)
    directories: dict[str, Path] = {}
    try:
        _expand_and_start(
            blocks,
            approved,
            directories,
            concurrent,
            start_release=start_release,
            schema_tool=schema_tool,
            channel=channel,
            failure=failure,
        )
    finally:
        _remove_converge_directories(directories, failure)
    print(
        f"The contract of {len(blocks)} block(s) is not applied: the next deploy applies it once "
        "its release is healthy."
    )


def start_on_converged_schema(
    blocks: Sequence[str],
    *,
    start_release: Callable[[], None],
    concurrent_runs: ConcurrentRuns,
    schema_tool: SchemaTool,
    channel: SchemaChannel,
    failure: Callable[[str], Exception],
) -> None:
    """Start *start_release* only when every block of *blocks* already holds its declared schema.

    For a command that delivers a release without converging: each block is read and ``schema.py
    verify`` prints its verdict; once every block is verified, a block that differs from its
    declared schema stops the run, naming each differing block, before the release starts. A
    ``deploy`` converges them. The blocks are carried side by side as :func:`converge_schema_blocks`
    carries them, and each verdict is printed in the blocks' order.

    Args:
        blocks: The block keys whose schema convergence is enabled, each once.
        start_release: Starts the release.
        concurrent_runs: How many runs *channel* carries at once, asked once when there is a block.
        schema_tool: Runs a schema-tool command.
        channel: The platform's channel to a block's client.
        failure: The host's error type, built from a message naming the cause.

    Raises:
        Exception: *failure*'s, naming each block that differs from its declared schema, or the
            first block that cannot be read or verified, a directory that cannot be removed or a
            concurrency below one; and whatever *start_release* or *channel* raises.
    """
    _require_distinct_blocks(blocks, failure)
    if not blocks:
        print("No RDBMS block has schema convergence enabled: no block is verified.")
        start_release()
        return
    concurrent = _concurrency(concurrent_runs, failure)
    directories: dict[str, Path] = {}
    differing: list[str] = []

    def verify(block: str) -> SchemaToolRun:
        files = _step_files(directories[block], _CONVERGE_VERIFY_STEP, block, failure)
        document = read_live_catalog(block, schema_tool=schema_tool, channel=channel, failure=failure)
        _write_catalog(files.catalog, document, f"Block '{block}' was not verified", failure)
        return schema_tool((SCHEMA_VERIFY_COMMAND, block, SCHEMA_PLAN_CATALOG_OPTION, str(files.catalog)))

    try:
        for block in blocks:
            directories[block] = _private_directory(
                _CONVERGE_DIRECTORY_PREFIX, f"Block '{block}' was not verified", failure
            )
        for block, result in _each_block(blocks, verify, concurrent):
            _write_stdout(result.stdout)
            if result.exit_status != 0:
                differing.append(f"{block}: {_verdict(result, block)}")
    finally:
        _remove_converge_directories(directories, failure)
    if differing:
        listed = "\n  - ".join(differing)
        raise failure(
            f"{len(differing)} block(s) do not hold their declared schema, so the release was not "
            f"started:\n  - {listed}\nThe release reads the schema it declares; run deploy, which "
            "converges every block around its release."
        )
    print(f"Every one of {len(blocks)} block(s) holds its declared schema: starting the release.")
    start_release()



