class DeployError(RuntimeError):
    """A fatal, operator-actionable deployment failure."""


class CommandResult(NamedTuple):
    """Outcome of one external command.

    The two streams stay apart: docker writes the document a ``--format`` or
    ``--quiet`` command asks for to stdout, and its warnings and notices to
    stderr, so a caller that reads what a command printed reads ``stdout``.
    ``output`` joins both, for a message that quotes the command.
    """

    returncode: int
    stdout: str
    stderr: str

    @property
    def succeeded(self) -> bool:
        """True when the command exited zero."""
        return self.returncode == 0

    @property
    def output(self) -> str:
        """Combined stdout and stderr, for error reporting."""
        return "\n".join(part for part in (self.stdout, self.stderr) if part)


