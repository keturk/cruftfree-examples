class EngineEndpoint(NamedTuple):
    """The engine docker drives, and how it is reached.

    Attributes:
        host: The endpoint, as docker names it (``unix:///var/run/docker.sock``).
        tls_verified: Whether docker verifies the engine's TLS certificate on it.
        origin: Where the endpoint was read, for the operator.
    """

    host: str
    tls_verified: bool
    origin: str


def environment_engine_endpoint(environment: Mapping[str, str]) -> EngineEndpoint | None:
    """The endpoint ``DOCKER_HOST`` names in *environment*, or ``None`` when it names none.

    docker verifies TLS on it when ``DOCKER_TLS_VERIFY`` holds any non-empty value.
    """
    host = environment.get(DOCKER_HOST_VARIABLE, "").strip()
    if not host:
        return None
    return EngineEndpoint(
        host=host,
        tls_verified=bool(environment.get(DOCKER_TLS_VERIFY_VARIABLE, "")),
        origin=f"the {DOCKER_HOST_VARIABLE} variable",
    )


def context_engine_endpoint(document: str) -> EngineEndpoint:
    """The endpoint of the context ``docker context inspect`` printed as *document*.

    TLS is verified only when the context holds TLS material for its docker
    endpoint and does not skip verification; a context with no material reaches
    a TCP engine in plain text.

    Raises:
        ValueError: *document* is not one context with a docker endpoint host.
    """
    try:
        parsed = json.loads(document)
    except ValueError as error:
        raise ValueError(
            f"'docker context inspect' printed what is not JSON ({error}). Expected a list "
            f"holding the current context."
        ) from error
    if not isinstance(parsed, list) or len(parsed) != 1 or not isinstance(parsed[0], dict):
        raise ValueError(
            "'docker context inspect' did not print exactly one context. Expected a list "
            "holding the current context."
        )
    context = parsed[0]
    endpoints = context.get("Endpoints")
    docker_endpoint = endpoints.get("docker") if isinstance(endpoints, dict) else None
    host = docker_endpoint.get("Host") if isinstance(docker_endpoint, dict) else None
    if not isinstance(host, str) or not host.strip():
        raise ValueError(
            f"Docker context {context.get('Name')!r} names no docker endpoint host. Expected "
            f"'Endpoints.docker.Host' in 'docker context inspect'."
        )
    material = context.get("TLSMaterial")
    holds_material = isinstance(material, dict) and bool(material.get("docker"))
    skips = docker_endpoint.get("SkipTLSVerify") if isinstance(docker_endpoint, dict) else None
    return EngineEndpoint(
        host=host.strip(),
        tls_verified=holds_material and skips is False,
        origin=f"docker context {context.get('Name')!r}",
    )


def _endpoint_scheme(endpoint: EngineEndpoint) -> str:
    """The lower-cased scheme of *endpoint*'s host, or ``""`` when it names none."""
    scheme, separator, _ = endpoint.host.partition("://")
    return scheme.lower() if separator else ""


def project_mount_refusal(
    endpoint: EngineEndpoint, mount_count: int, mount_example: str
) -> str | None:
    """Why *endpoint* cannot run a stack mounting project files, or ``None`` when it can.

    Args:
        endpoint: The engine docker reaches.
        mount_count: How many distinct project paths the compose file mounts.
        mount_example: One of them, for the operator.

    Returns:
        ``None`` when the stack mounts no project path or the engine is reached
        on a local socket or named pipe; otherwise the refusal.
    """
    if mount_count == 0 or _endpoint_scheme(endpoint) in LOCAL_SCHEMES:
        return None
    return (
        f"Docker reaches its engine at '{endpoint.host}' ({endpoint.origin}), which is not "
        f"on this machine, but the compose file mounts {mount_count} project path(s) into "
        f"its containers ('{mount_example}' among them). A bind mount's source is resolved "
        f"on the engine's machine, so that engine would start the containers without these "
        f"secrets and configuration files, or fail to create them. Nothing was run. Copy "
        f"this project to the engine's host and run this script there against its local "
        f"engine (a unix:// socket or npipe:// named pipe)."
    )


def engine_image_store(document: str) -> str:
    """The image store of the engine ``docker info --format json`` printed *document* for.

    Raises:
        ValueError: *document* is not JSON.
        TypeError: *document* is JSON, but not an object.
    """
    try:
        parsed = json.loads(document)
    except ValueError as error:
        raise ValueError(
            f"'docker info' printed what is not JSON ({error}). Expected the engine's description."
        ) from error
    if not isinstance(parsed, dict):
        raise TypeError("'docker info' did not print a JSON object. Expected the engine's description.")
    status = parsed.get("DriverStatus")
    rows = status if isinstance(status, list) else []
    snapshotter = any(
        isinstance(row, list) and tuple(row[:2]) == CONTAINERD_SNAPSHOTTER_STATUS for row in rows
    )
    return CONTAINERD_IMAGE_STORE if snapshotter else CLASSIC_IMAGE_STORE


def image_store_refusal(generated_for: str, engine_store: str) -> str | None:
    """Why an engine on *engine_store* cannot run a stack generated for *generated_for*.

    cAdvisor's mounts follow the image store the stack was generated for: the
    classic store's layer database, or containerd's socket. On the other store it
    names no container, and every alert over container series stays silent.

    Returns:
        ``None`` when the two stores agree; otherwise the refusal.
    """
    if generated_for == engine_store:
        return None
    features = json.dumps({"containerd-snapshotter": generated_for == CONTAINERD_IMAGE_STORE})
    return (
        f"The engine keeps images on its {engine_store} image store, but this stack was "
        f"generated for the {generated_for} store (platforms.docker.infra.imageStore), and "
        f"its cAdvisor names containers only on that one. Nothing was run. Either move the "
        f"engine to the {generated_for} store (set \"features\": {features} in its "
        f"daemon.json and restart it), or declare imageStore = \"{engine_store}\" and generate again -- the "
        f"containerd store is refused on a platform that hands its services secrets of "
        f"their own, because cAdvisor then holds containerd's unfiltered socket."
    )


def selected_builder_driver(inspection: str) -> str:
    """The driver of the builder ``docker buildx inspect`` printed *inspection* for.

    Raises:
        ValueError: *inspection* has no ``Driver:`` line.
    """
    for line in inspection.splitlines():
        label, _, value = line.partition(":")
        if label.strip() == "Driver" and value.strip():
            return value.strip()
    raise ValueError("'docker buildx inspect' printed no 'Driver:' line. Expected the selected builder's description.")


def engine_endpoint_refusal(endpoint: EngineEndpoint) -> str | None:
    """Why *endpoint* may not be driven, or ``None`` when its transport is authenticated.

    A local socket, a named pipe and SSH are accepted; TCP only with TLS
    verification; any other scheme is refused.
    """
    scheme = _endpoint_scheme(endpoint)
    if scheme in AUTHENTICATED_SCHEMES:
        return None
    if scheme == TLS_SCHEME and endpoint.tls_verified:
        return None
    fix = (
        "Reach a remote engine over SSH (a docker context created with "
        "--docker host=ssh://user@host, or DOCKER_HOST=ssh://user@host), or over TCP "
        f"with TLS verification ({DOCKER_TLS_VERIFY_VARIABLE}=1 with the certificates in "
        "DOCKER_CERT_PATH, or a context holding its ca, cert and key without "
        "skip-tls-verify). A local engine is reached on its unix socket or named pipe."
    )
    if scheme == TLS_SCHEME:
        return (
            f"Docker reaches its engine at '{endpoint.host}' ({endpoint.origin}) over TCP "
            f"without TLS verification: anyone who can reach that port drives the engine "
            f"and reads what this script sends it, the database owner's password included. "
            f"Nothing was run. {fix}"
        )
    return (
        f"Docker reaches its engine at '{endpoint.host}' ({endpoint.origin}), a transport "
        f"this script cannot tell is authenticated; it drives an engine only over "
        f"{', '.join(f'{name}://' for name in AUTHENTICATED_SCHEMES)} or {TLS_SCHEME}:// "
        f"with TLS verification. Nothing was run. {fix}"
    )



def require_drivable_engine(docker_path: str) -> None:
    """Refuse an engine reached without authentication, or not on this machine.

    The endpoint is ``DOCKER_HOST``'s when set, else the current docker
    context's (``docker context inspect``, which reads ``DOCKER_CONTEXT``).
    While the compose file mounts project paths (``PROJECT_MOUNT_COUNT``),
    only a local socket or pipe reaches an engine that can resolve them.

    Raises:
        DeployError: If the context cannot be read, the endpoint is neither
            a local socket or pipe, SSH, nor TCP with TLS verification, or it
            is not local while the stack mounts project paths.
    """
    endpoint = environment_engine_endpoint(os.environ)
    if endpoint is None:
        inspected = subprocess.run(
            [docker_path, "context", "inspect"],
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            cwd=PROJECT_ROOT,
            check=False,
        )
        if inspected.returncode != 0:
            raise DeployError(
                f"'docker context inspect' failed (exit {inspected.returncode}): "
                f"{inspected.stderr.strip() or 'no output'}. This script reads which "
                f"engine docker reaches before driving it, and runs nothing when it "
                f"cannot. Select a context ('docker context use <name>') or set "
                f"{DOCKER_HOST_VARIABLE}."
            )
        try:
            endpoint = context_engine_endpoint(inspected.stdout)
        except ValueError as error:
            raise DeployError(f"{error} Nothing was run.") from error
    refusal = engine_endpoint_refusal(endpoint) or project_mount_refusal(
        endpoint, PROJECT_MOUNT_COUNT, PROJECT_MOUNT_EXAMPLE
    )
    if refusal is not None:
        raise DeployError(refusal)


@functools.cache
def resolve_docker() -> str:
    """Return the absolute path of the docker executable, its engine checked.

    Every command resolves docker before its first docker call, and the first
    resolution refuses an engine reached without authentication, or one this
    stack's project mounts cannot reach (``require_drivable_engine``), so no
    command drives one.

    Raises:
        DeployError: If docker is not on PATH, or its engine is refused.
    """
    resolved = shutil.which("docker")
    if resolved is None:
        raise DeployError("'docker' not found. Install Docker.")
    require_drivable_engine(resolved)
    return resolved


def require_engine_image_store() -> None:
    """Refuse an engine on another image store than the one cAdvisor was generated for.

    Raises:
        DeployError: If ``docker info`` fails or prints no engine description, or
            the engine's store is not ``OBSERVED_IMAGE_STORE``.
    """
    if OBSERVED_IMAGE_STORE is None:
        return
    result = docker("info", "--format", "json")
    if not result.succeeded:
        raise DeployError(f"'docker info' failed (exit {result.returncode}): {result.output}")
    try:
        engine_store = engine_image_store(result.stdout)
    except (TypeError, ValueError) as error:
        raise DeployError(f"{error} Nothing was run.") from error
    refusal = image_store_refusal(OBSERVED_IMAGE_STORE, engine_store)
    if refusal is not None:
        raise DeployError(refusal)


def docker(*args: str, capture: bool = True) -> CommandResult:
    """Run one ``docker`` invocation from the project root."""
    completed = subprocess.run(
        [resolve_docker(), *args],
        capture_output=capture,
        text=True,
        encoding="utf-8",
        errors="replace",
        cwd=PROJECT_ROOT,
    )
    return CommandResult(
        returncode=completed.returncode,
        stdout=(completed.stdout or "").strip() if capture else "",
        stderr=(completed.stderr or "").strip() if capture else "",
    )


