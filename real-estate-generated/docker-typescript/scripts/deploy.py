def _schema_read_network() -> str:
    """The name docker gave this project's SCHEMA_READ_NETWORK.

    Raises:
        DeployError: If the networks could not be listed, or the project has
            no such network (the stack is not deployed) or more than one.
    """
    project = compose_project_name()
    listed = docker(
        "network", "ls",
        "--filter", f"label={COMPOSE_PROJECT_LABEL}={project}",
        "--filter", f"label={COMPOSE_NETWORK_LABEL}={SCHEMA_READ_NETWORK}",
        "--format", "json",
    )
    if not listed.succeeded:
        raise DeployError(
            f"Listing the networks of compose project '{project}' failed (docker "
            f"exited {listed.returncode}): {listed.output or 'no output'}."
        )
    names: list[str] = []
    for line in listed.stdout.splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            names.append(str(json.loads(line)["Name"]))
        except (ValueError, KeyError, TypeError) as error:
            raise DeployError(
                f"'docker network ls --format json' printed a line this script "
                f"cannot read ({error}): {line!r}. Expected one JSON object per "
                f"network with 'Name'."
            ) from error
    if len(names) != 1:
        raise DeployError(
            f"Compose project '{project}' has {len(names)} '{SCHEMA_READ_NETWORK}' "
            f"network(s) {names}, and the catalog client joins exactly one. The "
            f"network exists while the stack is deployed: run '{SCRIPT_NAME} "
            f"{VERB_DEPLOY}' first."
        )
    return names[0]


def _deploy_variable(name: str, block: str, what: str) -> str:
    """The value compose reads for *name*: the process environment's, else ENV_FILE's.

    *what* is what the value is to block *block*, for the message.

    Raises:
        DeployError: If *name* has no value, or an empty one.
    """
    if name in os.environ:
        value = os.environ[name]
    else:
        require_env_file()
        env_text = (PROJECT_ROOT / ENV_FILE).read_text(encoding="utf-8")
        value = assigned_env_values(env_text).get(name, "")
    if not value.strip():
        raise DeployError(
            f"{what} of block '{block}' is read from '{name}', which has no "
            f"value in the environment or in '{ENV_FILE}'. Set it to the value "
            f"compose provisions and connects with, then read block '{block}' again."
        )
    return value


def _owner_credential_line(password: str, block: str) -> bytes:
    """The first line of the client's standard input: *block*'s owner *password*.

    Raises:
        DeployError: If the password holds a line break, which would end the
            line early and hand the rest of the password to the client as input.
    """
    if "\n" in password or "\r" in password:
        raise DeployError(
            f"The owner login's password of block '{block}' holds a line break, "
            f"and the catalog client reads it as one line of its input. Set a "
            f"password without one, then read block '{block}' again."
        )
    return f"{password}\n".encode("utf-8")


def _run_schema_client(
    run: SchemaRun,
    container: str,
    command: list[str],
    environment: dict[str, str],
    credential_line: bytes,
) -> None:
    """Run *command*, the client's container, over the run's files; record its status.

    The container's standard input is *credential_line*, which the client's
    credential wrapper reads, then the run's input, which the client reads.

    Raises:
        DeployError: If the container outlived the wait (it is removed).
    """
    client_input = credential_line + run.input_file.read_bytes()
    with (
        run.output_file.open("xb") as client_output,
        run.error_file.open("xb") as client_error,
    ):
        try:
            completed = subprocess.run(
                command,
                input=client_input,
                stdout=client_output,
                stderr=client_error,
                cwd=PROJECT_ROOT,
                env={**os.environ, **environment},
                check=False,
                timeout=SCHEMA_RUN_WAIT_SECONDS,
            )
        except subprocess.TimeoutExpired as error:
            removed = docker("rm", "--force", container)
            outcome = (
                "was removed"
                if removed.succeeded
                else f"could not be removed ({removed.output or 'no output'}): "
                f"remove it with 'docker rm --force {container}'"
            )
            raise DeployError(
                f"The catalog client of block '{run.block}' was still running "
                f"after {SCHEMA_RUN_WAIT_SECONDS} seconds; its container "
                f"'{container}' {outcome}."
            ) from error
    run.record_exit_status(completed.returncode)


def compose_schema_channel(workload: str) -> SchemaChannel:
    """The channel running a run's catalog client once, in a container on SCHEMA_READ_NETWORK.

    *workload* names what the runs are for -- the schema verb this script
    carries out, or SCHEMA_HOST_CLIENT_COMMAND for a provider's front door --
    and, with each run's id, the run's container.

    The input reaches the client on its standard input; its standard output and
    standard error are written to the run's files as they come, untouched, and
    its exit status is recorded. The container is removed when it exits, has a
    read-only root and no capabilities, and gets its connection variables by
    name from this process's environment, so no value travels as an argument.
    The client stops itself under ``timeout``; a container still running when
    this wait expires is removed.

    The block's owner password, read as compose reads the owner login's
    variable, is the first line of the container's standard input, ahead of
    the run's input: the client's credential wrapper reads that one line into
    the client's credential file on the in-memory SCHEMA_CREDENTIAL_TMPFS, and
    the client reads the rest. Neither an argument, a container variable nor a
    file on any host carries it, so it reaches a remote engine only over the
    authenticated transport ``require_drivable_engine`` holds docker to.
    """

    def run_client(run: SchemaRun) -> None:
        """Run *run*'s catalog client once and record what it left.

        Raises:
            DeployError: If a connection value or the owner password is missing,
                the password holds a line break, the network cannot be found, or
                the container outlived the wait.
        """
        client = SCHEMA_READ_CLIENTS[run.block]
        environment = dict(client.environment)
        for variable, name in client.deploy_environment.items():
            environment[variable] = _deploy_variable(name, run.block, "The server")
        owner_line = _owner_credential_line(
            _deploy_variable(
                client.credential_variable, run.block, "The owner login's password"
            ),
            run.block,
        )
        network = _schema_read_network()
        container = f"{workload}-{run.run_id}"
        command = [
            resolve_docker(), "run", "--rm", "--interactive",
            "--name", container,
            "--network", network,
            "--read-only", "--cap-drop", "ALL", "--security-opt", "no-new-privileges",
            "--tmpfs", SCHEMA_CREDENTIAL_TMPFS,
            *(f"--add-host={host}" for host in client.extra_hosts),
            *(part for variable in sorted(environment) for part in ("--env", variable)),
            client.image,
            *client.command,
            *run.client_arguments,
        ]
        _run_schema_client(run, container, command, environment, owner_line)

    return run_client


