class ClientRequest(NamedTuple):
    """What the command line asked of ``deploy``'s clients."""

    #: The value of the scope flag, or ``None`` to run both scopes.
    scope: str | None
    #: The value of the contract flag, or ``None`` when absent.
    contract: str | None
    #: The build number of a native target, or ``None`` when absent.
    build_number: str | None


def client_request(parsed: argparse.Namespace) -> ClientRequest:
    """What *parsed* asks of ``deploy``'s clients."""
    return ClientRequest(
        parsed.scope,
        parsed.client_contract,
        None,
    )


def client_contract_file(clients: ClientRequest) -> Path:
    """The contract this deploy reads, refusing a bad command before anything runs.

    Raises:
        DeployError: The command names a contract this deploy does not read.
    """
    try:
        return client_contract_source(
            PROJECT_ROOT / CLIENT_CONTRACT_PATH,
            clients.contract,
            clients.scope,
            has_backend_scope=True,
        )
    except ClientDeployStepError as exc:
        raise DeployError(str(exc)) from exc


# ---------------------------------------------------------------------------
# Post-deploy cleanup
# ---------------------------------------------------------------------------
# Every deploy rebuilds the service images on this host. Each rebuild moves the
# service's tag to the new image and leaves the previous one behind untagged; a
# changed dependency union leaves the previous shared base image behind under
# its old tag; and every build adds to the build cache. None of it is used
# again, and nothing else on the host removes it, so a long-lived host ends at
# a full disk. The deploy that superseded it removes it.

#: Label Compose puts on every image it builds, carrying the project name. It
#: scopes the image prune to THIS project's leftovers, so the deploy never
#: removes an image another project on the same host owns.
COMPOSE_PROJECT_LABEL = "com.docker.compose.project"

#: Build cache no build has used within this window is removed. The layers the
#: deploy that just finished used are fresh, so the next rebuild stays cached;
#: what superseded builds left behind ages out.
BUILD_CACHE_RETENTION = "24h"


def _require_cleanup_step(result: CommandResult, what: str) -> None:
    """Fail loud when one cleanup command did not succeed.

    Raises:
        DeployError: If the command exited non-zero, naming what it was
            removing. The services are already running at this point; only
            the cleanup failed, and a cleanup that silently stops working is
            how the disk fills again.
    """
    if result.succeeded:
        return
    raise DeployError(
        f"Removing {what} failed (docker exited {result.returncode}): "
        f"{result.output or 'no output'}. The services are up; only the "
        f"post-deploy cleanup failed. Fix the cause and re-run '{SCRIPT_NAME} "
        f"{VERB_DEPLOY}' (it rebuilds nothing that is unchanged), or the host "
        f"keeps accumulating superseded images."
    )


def _superseded_base_images() -> list[str]:
    """Return every tag of each shared base image's repository but its current one.

    Returns:
        ``repository:tag`` references, empty when the system has no shared
        base image.

    Raises:
        DeployError: If an image list could not be read.
    """
    references: list[str] = []
    for tag, _directory in BASE_IMAGES:
        references.extend(_superseded_tags(tag))
    return references


def _superseded_tags(current: str) -> list[str]:
    """Return every tag of *current*'s repository but *current* itself.

    Raises:
        DeployError: If the image list could not be read.
    """
    repository = current.rpartition(":")[0]
    listed = docker("image", "ls", repository, "--format", "json")
    _require_cleanup_step(listed, f"superseded tags of '{repository}' (listing them)")
    references: list[str] = []
    for line in listed.stdout.splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            entry = json.loads(line)
            listed_repository, listed_tag = entry["Repository"], entry["Tag"]
        except (ValueError, KeyError, TypeError) as error:
            raise DeployError(
                f"'docker image ls --format json' printed a line this script "
                f"cannot read ({error}): {line!r}. Expected one JSON object per "
                f"image with 'Repository' and 'Tag'."
            ) from error
        # An untagged image is the image prune's to remove, not this step's.
        if listed_repository != repository or listed_tag == "<none>":
            continue
        reference = f"{repository}:{listed_tag}"
        if reference != current:
            references.append(reference)
    return references


def prune_superseded_build_state() -> None:
    """Remove what this deploy's rebuild superseded on this host.

    In order: this project's untagged images (the previous build of each
    service, which no container references any more), every older tag of the
    shared base image of each language that no container uses, and build cache unused for
    ``BUILD_CACHE_RETENTION``. An image a container still runs from is never
    removed: the prune skips it, and the base-image step checks first.

    Raises:
        DeployError: If any removal failed.
    """
    step("Removing superseded images and stale build cache")
    project = compose_project_name()
    _require_cleanup_step(
        docker(
            "image", "prune", "--force",
            "--filter", f"label={COMPOSE_PROJECT_LABEL}={project}",
        ),
        f"the superseded images of compose project '{project}'",
    )
    for reference in _superseded_base_images():
        in_use = docker("ps", "--all", "--quiet", "--filter", f"ancestor={reference}")
        _require_cleanup_step(in_use, f"'{reference}' (checking whether a container uses it)")
        if in_use.stdout:
            continue
        _require_cleanup_step(docker("image", "rm", reference), f"'{reference}'")
    _require_cleanup_step(
        docker(
            "builder", "prune", "--force",
            "--filter", f"until={BUILD_CACHE_RETENTION}",
        ),
        f"build cache unused for {BUILD_CACHE_RETENTION}",
    )


