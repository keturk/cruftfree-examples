def parse_arguments(argv: Sequence[str] | None) -> argparse.Namespace:
    """The command line, or exit naming what is missing."""
    parser = argparse.ArgumentParser(
        description="Check the client contract and compose every runtime config under config/resolved/."
    )
    parser.add_argument(
        CLIENT_CONTRACT_FLAG,
        dest="client_contract",
        metavar="PATH",
        required=True,
        help="the client contract the backend's deploy published",
    )
    parser.add_argument(
        "--profile",
        required=True,
        help="the profile to prepare; it must be the one this tree was generated for",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="run every check and composition, and leave the tree as it was",
    )
    return parser.parse_args(argv)


def main(argv: Sequence[str] | None = None) -> int:
    """Prepare the clients; the exit code is 1 when a check or a composition fails."""
    args = parse_arguments(argv)
    if args.profile != TREE_PROFILE:
        print(
            f"This tree was generated for profile '{TREE_PROFILE}', not '{args.profile}'. "
            f"Nothing was composed. Generate the tree with --profile {args.profile}.",
            file=sys.stderr,
        )
        return 1
    tree_root = (Path(__file__).resolve().parent / PROJECT_ROOT_FROM_SCRIPT_DIR).resolve()
    try:
        prepare_client_configs(
            CLIENT_STEP_PLAN,
            tree_root,
            Path(args.client_contract),
            ClientStepRuntime(
                read_contract=read_client_contract,
                compose=compose_client_runtime_config,
                verify_release=verify_client_release,
                log=print,
            ),
            check_only=args.check,
        )
    except (ClientDeployStepError, ClientRuntimeResolutionError) as exc:
        print(exc, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
