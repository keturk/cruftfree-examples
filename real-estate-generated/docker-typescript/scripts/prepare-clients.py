r"""Prepare this tree's clients from the contract their backend published.

Generated by CruftFree -- do not edit manually. Run it through
'scripts/prepare-clients.sh' or '.\scripts\prepare-clients.ps1', or directly with
Python 3.11+ from the project root:

    python scripts/prepare-clients.py --client-contract <path> --profile <name> [--check]

For a workspace or a tree with no platform to release its clients. In two steps:

1. check the client contract: its system.version must equal the version this tree
   was built for, each native app's links host must be the host of its
   registration's web origin, the gateway must answer at backend.apiBaseUrl, and
   for every app that signs users in, the identity provider at its registration's
   authority must publish an OpenID configuration whose issuer is the contract's;
2. compose every (app, client target) runtime config from the contract, writing
   the deployed copies under config/resolved/.

Nothing is composed until step 1 has passed. --check runs both steps and removes
what it composed, so the tree is left as it was. The script publishes nothing and
builds nothing: the consumer's build places each composed file and hosts the bundle.

Standard library only: no CruftFree package. It reads the contract and the generated
runtime configs. Its network reads are credential-free GETs that follow no
redirect, over verified https or to a loopback host: the gateway's liveness route,
and each signing-in registration's {authority}/.well-known/openid-configuration.
"""

