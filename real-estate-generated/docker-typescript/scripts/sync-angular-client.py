@dataclass(frozen=True)
class SyncPlan:
    """The verified source content and the destination's recorded state."""

    synced: dict[str, bytes]
    digests: dict[str, str]
    recorded: dict[str, str]

    def added(self) -> list[str]:
        return sorted(set(self.digests) - set(self.recorded))

    def removed(self) -> list[str]:
        return sorted(set(self.recorded) - set(self.digests))

    def changed(self) -> list[str]:
        return sorted(path for path in set(self.digests) & set(self.recorded) if self.digests[path] != self.recorded[path])


def normalize_switches(argv: Sequence[str], option_names: Sequence[str]) -> list[str]:
    """Translate PowerShell-style switches (``-Destination``) onto this script's flags.

    The PowerShell wrapper forwards its arguments verbatim, so an operator
    there types ``-Destination x -Check``. Only a whole argument matching a
    declared option name case-insensitively is translated; anything else -- a
    path, a value -- passes through untouched.
    """
    aliases = {f"-{name}": f"--{name}" for name in option_names}
    return [aliases.get(token.lower(), token) for token in argv]


def _digest(content: bytes) -> str:
    return hashlib.sha256(content).hexdigest()


def _path_problems(relative: object) -> list[str]:
    """Why *relative* cannot name a file inside a tree; empty when it can."""
    if not isinstance(relative, str) or not relative:
        return [f"{relative!r} is not a non-empty path"]
    windows = PureWindowsPath(relative)
    if "\\" in relative or windows.drive or windows.root or PurePosixPath(relative).is_absolute():
        return [f"{relative!r} is absolute or not a POSIX path"]
    if {".", ".."} & set(relative.split("/")) or relative.endswith("/"):
        return [f"{relative!r} carries a '.' or '..' component"]
    return []


def contained_path(root: Path, relative: object, label: str) -> Path:
    """The path *relative* names under *root*, proven to stay inside it.

    Raises:
        SyncRefused: *relative* is not a relative POSIX path, carries a
            ``.``/``..`` component, or resolves (symlinks followed) outside *root*.
    """
    problems = _path_problems(relative)
    if problems:
        raise SyncRefused([f"{label}: {problem}" for problem in problems])
    candidate = root / str(relative)
    if not candidate.resolve().is_relative_to(root.resolve()):
        raise SyncRefused([f"{label}: {relative!r} resolves outside {root}"])
    return candidate


def read_manifest(manifest_path: Path, root: Path) -> dict[str, str]:
    """The path -> sha256 mapping a manifest records, every path contained in *root*.

    Raises:
        SyncRefused: The manifest is unreadable, not of the
            ``{"files": {path: sha256}}`` shape, or records a path outside *root*.
    """
    try:
        recorded = json.loads(manifest_path.read_text(encoding="utf-8"))[MANIFEST_FILES_KEY]
    except (OSError, ValueError, KeyError, TypeError) as error:
        raise SyncRefused([f"{manifest_path}: unreadable manifest ({error!r}); expected {{\"files\": {{path: sha256}}}}"]) from error
    if not isinstance(recorded, dict):
        raise SyncRefused([f"{manifest_path}: '{MANIFEST_FILES_KEY}' is not a mapping of path to sha256"])
    problems = [
        f"{manifest_path}: {path!r} records {digest!r}, not a sha256 hex digest"
        for path, digest in recorded.items()
        if not isinstance(digest, str) or len(digest) != _SHA256_HEX_LENGTH or not set(digest) <= _HEX_DIGITS
    ]
    for path in recorded:
        try:
            contained_path(root, path, str(manifest_path))
        except SyncRefused as refused:
            problems.extend(refused.problems)
    if problems:
        raise SyncRefused(problems)
    return dict(recorded)


def _is_synced(path: str, target: SyncTarget) -> bool:
    return path in target.synced_files or any(path.startswith(f"{root}/") for root in target.synced_roots)


def _lies_under(path: str, roots: Sequence[str]) -> bool:
    return any(path == root or path.startswith(f"{root}/") for root in roots)


def _is_app_path(path: str, target: SyncTarget) -> bool:
    return _lies_under(path, target.app_paths)


def _is_selected(path: str, target: SyncTarget) -> bool:
    return _lies_under(path, target.selected_paths)


def _destination(relative: str, target: SyncTarget) -> str | None:
    """The path the source file *relative* is copied to; ``None`` when a consumer does not receive it."""
    for source, destination in target.library_files:
        if relative == source:
            return destination
        if relative == destination:
            return None
    if _is_selected(relative, target):
        return relative
    if _is_app_path(relative, target):
        return None
    return relative if _is_synced(relative, target) else None


def _synced_file_source(name: str, target: SyncTarget) -> str:
    """The tree file the synced file *name* is copied from."""
    return next((source for source, destination in target.library_files if destination == name), name)


def _tree_path(path: Path, target: SyncTarget) -> str:
    return path.relative_to(target.source_root).as_posix()


def _entries_outside_tool_paths(base: Path, target: SyncTarget) -> list[str]:
    """Every file and link under *base*, as a tree path; a tool path is matched whole and never entered."""
    entries: list[str] = []
    for directory, dirnames, filenames in os.walk(base, followlinks=False):
        folder = Path(directory)
        dirnames[:] = [name for name in dirnames if _tree_path(folder / name, target) not in target.tool_paths]
        linked_dirs = [name for name in dirnames if (folder / name).is_symlink()]
        found = (_tree_path(folder / name, target) for name in (*filenames, *linked_dirs))
        entries += [relative for relative in found if relative not in target.tool_paths]
    return entries


def _unlisted_files(target: SyncTarget, listed: Mapping[str, str]) -> list[str]:
    """Every entry under a synced root, outside the unselected app paths and the tool paths, the manifest does not list."""
    problems: list[str] = []
    for root in target.synced_roots:
        base = target.source_root / root
        if not base.is_dir() or base.is_symlink():
            problems.append(f"source: the tree has no '{root}' folder the target declares as a synced root")
            continue
        problems += [
            f"source: '{relative}' is not listed in {SOURCE_MANIFEST_NAME}"
            for relative in _entries_outside_tool_paths(base, target)
            if relative not in listed and (_is_selected(relative, target) or not _is_app_path(relative, target))
        ]
    return problems


def _matches_template(parts: Sequence[str], pattern: Sequence[str]) -> bool:
    """Whether the path *parts* lies at or under *pattern*, whose ``{app}`` segment matches any name."""
    return len(parts) >= len(pattern) and all(
        segment in (part, _APP_PLACEHOLDER) for part, segment in zip(parts, pattern, strict=False)
    )


def _tree_apps(target: SyncTarget, listed: Mapping[str, str]) -> list[str]:
    """Every app key the ``app_paths_template`` entries match among the manifest's paths, sorted."""
    apps: set[str] = set()
    for template in target.app_paths_template:
        pattern = template.split("/")
        position = pattern.index(_APP_PLACEHOLDER)
        paths = (path.split("/") for path in listed)
        apps.update(parts[position] for parts in paths if _matches_template(parts, pattern))
    return sorted(apps)


def _selected_app_files(target: SyncTarget, apps: Sequence[str]) -> tuple[tuple[str, str], ...]:
    """The ``app_files`` pairs a run of *apps* copies: a ``{app}`` pair once per app, any other pair once."""
    return tuple(
        dict.fromkeys(
            (source.replace(_APP_PLACEHOLDER, app), destination.replace(_APP_PLACEHOLDER, app))
            for source, destination in target.app_files
            for app in apps
        )
    )


def select_apps(target: SyncTarget, apps: Sequence[str]) -> SyncTarget:
    """*target* widened to the selected *apps*: what a run then copies and verifies.

    The tree's apps are read from its manifest and *apps* are only compared with
    them, so a key the tree does not hold never builds a path. Each selected app
    then gets its own ``app_files`` pairs, which :func:`verify_source` holds to
    the manifest like any other synced file, and its own tool paths.

    Raises:
        SyncRefused: Naming every key the tree does not hold, with the tree's
            apps, and every selected path the manifest lists nothing at.
    """
    listed = read_manifest(target.source_root / SOURCE_MANIFEST_NAME, target.source_root)
    known = _tree_apps(target, listed)
    choices = ", ".join(known) or "none"
    unknown = [app for app in apps if app not in known]
    if unknown:
        raise SyncRefused([f"--{_APP_OPTION}: '{app}' is not an app of this tree; its apps: {choices}" for app in unknown])
    selected = (
        *target.app_runtime_paths,
        *(template.replace(_APP_PLACEHOLDER, app) for app in apps for template in target.app_paths_template),
    )
    absent = [path for path in selected if not any(_lies_under(name, (path,)) for name in listed)]
    if absent:
        raise SyncRefused([f"source: {SOURCE_MANIFEST_NAME} lists nothing at '{path}', which a selected app needs" for path in absent])
    app_files = _selected_app_files(target, apps)
    app_destinations = tuple(destination for _, destination in app_files)
    return replace(
        target,
        synced_roots=(
            *target.synced_roots,
            *(path for path in selected if path not in listed and not _is_synced(path, target)),
        ),
        synced_files=(*target.synced_files, *(name for name in app_destinations if name not in target.synced_files)),
        library_files=(
            *(pair for pair in target.library_files if pair[1] not in app_destinations),
            *app_files,
        ),
        selected_paths=selected,
        tool_paths=tuple(
            template.replace(_APP_PLACEHOLDER, app) for app in apps for template in target.app_tool_paths_template
        ),
    )


def verify_source(target: SyncTarget) -> tuple[dict[str, bytes], dict[str, str], list[str]]:
    """Step 1: the synced files' bytes and digests, and every file verified, the source proven intact.

    Raises:
        SyncRefused: Naming every listed file that is missing or changed,
            every unlisted file under a synced root, every declared synced
            file the manifest does not list, and every listed file under a
            tool path.
    """
    listed = read_manifest(target.source_root / SOURCE_MANIFEST_NAME, target.source_root)
    problems = _unlisted_files(target, listed)
    problems += [
        f"source: '{_synced_file_source(name, target)}' is declared as a synced file but "
        f"{SOURCE_MANIFEST_NAME} does not list it"
        for name in target.synced_files
        if _synced_file_source(name, target) not in listed
    ]
    problems += [
        f"source: '{path}' lies under a tool path, which {SOURCE_MANIFEST_NAME} must not list"
        for path in sorted(listed)
        if _lies_under(path, target.tool_paths)
    ]
    synced: dict[str, bytes] = {}
    for relative, recorded_digest in sorted(listed.items()):
        path = target.source_root / relative
        if not path.is_file():
            problems.append(f"source: '{relative}' is listed in {SOURCE_MANIFEST_NAME} but missing")
            continue
        content = path.read_bytes()
        destination = _destination(relative, target)
        if _digest(content) != recorded_digest:
            problems.append(f"source: '{relative}' no longer matches its {SOURCE_MANIFEST_NAME} sha256 (edited by hand?)")
        elif destination is not None:
            synced[destination] = content
    if problems:
        raise SyncRefused(problems)
    return synced, {relative: _digest(content) for relative, content in synced.items()}, sorted(listed)


def _recorded_file_problems(destination: Path, recorded: Mapping[str, str]) -> list[str]:
    """Every recorded destination file that no longer matches what was written."""
    problems: list[str] = []
    for relative, recorded_digest in sorted(recorded.items()):
        path = destination / relative
        if path.is_symlink() or (os.path.lexists(path) and not path.is_file()):
            problems.append(f"destination: '{relative}' was replaced by a link or folder (hand edit)")
        elif not path.exists():
            problems.append(f"destination: '{relative}' was deleted by hand")
        elif _digest(path.read_bytes()) != recorded_digest:
            problems.append(f"destination: '{relative}' was edited by hand")
    return problems


def _unrecorded_conflicts(destination: Path, planned: Sequence[str], recorded: Mapping[str, str]) -> list[str]:
    """Every planned path (or a folder on its way) the destination holds but no manifest records.

    A folder on the way must be a real folder inside the destination; a link
    or junction there is a conflict, named once however many planned paths
    pass through it.
    """
    problems: dict[str, None] = {}
    resolved_destination = destination.resolve()
    for relative in planned:
        parts = PurePosixPath(relative).parts
        for depth in range(1, len(parts) + 1):
            prefix = "/".join(parts[:depth])
            path = destination / prefix
            is_folder_on_the_way = (
                depth < len(parts)
                and path.is_dir()
                and not path.is_symlink()
                and path.resolve().is_relative_to(resolved_destination)
            )
            if os.path.lexists(path) and prefix not in recorded and not is_folder_on_the_way:
                problems[f"destination: '{prefix}' exists but no earlier sync recorded writing it"] = None
                break
    return list(problems)


def check_destination(target: SyncTarget, destination: Path, digests: Mapping[str, str]) -> dict[str, str]:
    """Step 3: the destination's recorded files, proven untouched since the last sync.

    Raises:
        SyncRefused: Naming every hand-edited recorded file and every planned
            path the destination holds without a record of writing it.
    """
    manifest_path = destination / target.destination_manifest_name
    recorded: dict[str, str] = {}
    if manifest_path.is_symlink():
        raise SyncRefused([f"destination: '{target.destination_manifest_name}' is a link, not a file this script wrote"])
    if manifest_path.exists():
        recorded = read_manifest(manifest_path, destination)
    problems = _recorded_file_problems(destination, recorded)
    problems += _unrecorded_conflicts(destination, sorted(digests), recorded)
    if problems:
        raise SyncRefused(problems)
    return recorded


def _prune_empty_folders(destination: Path, relative: str) -> None:
    """Remove the folders above *relative* that its deletion left empty, up to *destination*."""
    parent = PurePosixPath(relative).parent
    while parent.parts:
        folder = destination / parent.as_posix()
        if folder.is_symlink() or not folder.is_dir() or any(folder.iterdir()):
            return
        folder.rmdir()
        parent = parent.parent


def _walk_real_folders(destination: Path, resolved_destination: Path, relative: str, *, create: bool) -> None:
    """Prove every folder above *relative* is a real folder inside *destination*.

    Walked one level at a time, so a folder replaced by a link (or a junction)
    after the plan was made is refused before anything is deleted or written
    through it. With *create*, a missing folder is made at that level -- never
    by a ``mkdir`` that would follow a link it did not check.

    Raises:
        SyncRefused: A folder on the way is a link, a file, or resolves
            outside the destination.
    """
    folder = destination
    for part in PurePosixPath(relative).parent.parts:
        folder = folder / part
        if create and not os.path.lexists(folder):
            folder.mkdir()
            continue
        if folder.is_symlink() or not folder.is_dir() or not folder.resolve().is_relative_to(resolved_destination):
            raise SyncRefused(
                [f"destination: '{relative}' lies under '{folder}', which is not a folder inside {destination}"]
            )


def _write_new_file(path: Path, content: bytes) -> None:
    """Create *path* exclusively -- never following or overwriting an existing entry."""
    descriptor = os.open(path, _EXCLUSIVE_CREATE_FLAGS, _NEW_FILE_MODE)
    with os.fdopen(descriptor, "wb") as handle:
        handle.write(content)


def _replace_destination_manifest(target: SyncTarget, destination: Path, files: Mapping[str, str]) -> None:
    manifest_path = destination / target.destination_manifest_name
    if os.path.lexists(manifest_path):
        os.unlink(manifest_path)
    manifest = json.dumps({MANIFEST_FILES_KEY: dict(files)}, indent=2, sort_keys=True) + "\n"
    _write_new_file(manifest_path, manifest.encode("utf-8"))


def apply_sync(target: SyncTarget, destination: Path, plan: SyncPlan) -> None:
    """Steps 4-5: delete the recorded files, copy the synced ones, record them.

    The destination manifest is rewritten even when a step fails part-way, to
    record exactly the files this sync left in place -- so the next run sees a
    consistent destination rather than "hand edits" it caused itself.

    Raises:
        OSError: A file could not be deleted or written.
        SyncRefused: A folder on a recorded or planned path is no longer a
            real folder inside the destination.
    """
    present = dict(plan.recorded)
    resolved_destination = destination.resolve()
    try:
        for relative in sorted(plan.recorded):
            _walk_real_folders(destination, resolved_destination, relative, create=False)
            os.unlink(destination / relative)
            del present[relative]
            _prune_empty_folders(destination, relative)
        for relative, content in sorted(plan.synced.items()):
            _walk_real_folders(destination, resolved_destination, relative, create=True)
            _write_new_file(destination / relative, content)
            present[relative] = plan.digests[relative]
    finally:
        _replace_destination_manifest(target, destination, present)


def _parser(target: SyncTarget) -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog=f"sync-{target.target}-client",
        allow_abbrev=False,
        description=(
            f"Copy the generated {target.target} client libraries into a consuming repository, "
            f"after verifying the source tree and the consumer's mappings."
        ),
        epilog=(
            f"Exit status: {EXIT_IN_SYNC} in sync, {EXIT_DRIFT} --check found a difference, "
            f"{EXIT_REFUSED} refused (nothing written)."
        ),
    )
    parser.add_argument(f"--{_DESTINATION_OPTION}", required=True, metavar="DIR", help="The consuming repository's library folder.")
    for option in target.consumer_options:
        parser.add_argument(f"--{option.name}", required=True, metavar=option.metavar, help=option.help)
    if target.app_paths_template:
        parser.add_argument(
            f"--{_APP_OPTION}",
            action="append",
            metavar="KEY",
            help="Also copy this app of the tree and the runtime apps share; repeatable.",
        )
    for option in target.app_consumer_options:
        parser.add_argument(
            f"--{option.name}",
            action="append",
            metavar=option.metavar,
            help=f"{option.help} Required with --{_APP_OPTION}: once for every app, or once per --{_APP_OPTION} in order.",
        )
    parser.add_argument(f"--{_CHECK_OPTION}", action="store_true", help="Report every difference and write nothing.")
    return parser


def _consumer_arguments(target: SyncTarget, parsed: argparse.Namespace) -> dict[str, str]:
    """The consumer options, keyed by declared name, each proven to name a file."""
    arguments = {option.name: str(getattr(parsed, option.name.replace("-", "_"))) for option in target.consumer_options}
    missing = [f"--{name}: '{value}' is not a file" for name, value in arguments.items() if not Path(value).is_file()]
    if missing:
        raise SyncRefused(missing)
    return arguments


def _repeated_option(parsed: argparse.Namespace, name: str) -> list[str]:
    """Every value a repeatable option was given, in command-line order."""
    return list(getattr(parsed, name.replace("-", "_")) or ())


def _app_option_values(target: SyncTarget, parsed: argparse.Namespace, apps: Sequence[str]) -> dict[str, list[str]]:
    """The app consumer options, keyed by declared name, each proven to serve the selected *apps*.

    Raises:
        SyncRefused: An option given with no ``--app``, so it would check nothing;
            given neither once nor once per app; or naming no file.
    """
    values = {option.name: _repeated_option(parsed, option.name) for option in target.app_consumer_options}
    problems: list[str] = []
    for name, given in values.items():
        if given and not apps:
            problems.append(f"--{name}: an app check reads it, so it needs --{_APP_OPTION}")
        elif apps and len(given) not in (1, len(apps)):
            problems.append(
                f"--{name}: given {len(given)} time(s) for {len(apps)} app(s); give it once for every app, "
                f"or once per --{_APP_OPTION} in order"
            )
        problems += [f"--{name}: '{value}' is not a file" for value in given if not Path(value).is_file()]
    if problems:
        raise SyncRefused(problems)
    return values


def _selection(
    target: SyncTarget, parsed: argparse.Namespace, destination: Path, arguments: Mapping[str, str]
) -> tuple[SyncTarget, dict[str, dict[str, str]]]:
    """The target a run's ``--app`` options select, and each selected app's check arguments.

    An app check reads the consumer options, its own app options and the
    destination the app is copied under.

    Raises:
        SyncRefused: An app is named twice, or :func:`select_apps` or the app
            options refuse the selection.
    """
    if not target.app_paths_template:
        return target, {}
    apps = _repeated_option(parsed, _APP_OPTION)
    values = _app_option_values(target, parsed, apps)
    if not apps:
        return target, {}
    repeated = sorted({app for app in apps if apps.count(app) > 1})
    if repeated:
        raise SyncRefused([f"--{_APP_OPTION}: '{app}' is given twice; name each app once" for app in repeated])
    app_arguments = {
        app: {
            **arguments,
            **{name: given[index % len(given)] for name, given in values.items()},
            _DESTINATION_OPTION: str(destination),
        }
        for index, app in enumerate(apps)
    }
    return select_apps(target, apps), app_arguments


def _require_destination(target: SyncTarget, destination: Path) -> None:
    if not destination.is_dir():
        raise SyncRefused([f"--destination: '{destination}' is not an existing folder; create it first"])
    resolved, source = destination.resolve(), target.source_root.resolve()
    if resolved.is_relative_to(source) or source.is_relative_to(resolved):
        raise SyncRefused([f"--destination: '{destination}' overlaps the generated tree '{target.source_root}'"])


def _app_consumer_problems(
    target: SyncTarget, files: Sequence[str], app_arguments: Mapping[str, Mapping[str, str]]
) -> list[str]:
    """Every entry a selected app needs that the consumer's files do not carry."""
    if target.app_entries is None or target.check_app_consumer is None:
        return []
    return [
        problem
        for app, arguments in app_arguments.items()
        for problem in target.check_app_consumer(arguments, app, target.app_entries(target.source_root, files, app))
    ]


def plan_sync(
    target: SyncTarget,
    destination: Path,
    arguments: Mapping[str, str],
    app_arguments: Mapping[str, Mapping[str, str]],
) -> SyncPlan:
    """Steps 1-3: verify the source, check the consumer, check the destination.

    A consumer check (or library listing, or app check) that raises ``OSError``
    or ``ValueError`` -- an unreadable or malformed consumer file -- refuses the
    run with its message. *app_arguments* holds each selected app's check
    arguments, and is empty for a library sync.

    Raises:
        SyncRefused: Naming every problem of the first step that found one.
    """
    _require_destination(target, destination)
    synced, digests, verified = verify_source(target)
    try:
        consumer_problems = target.check_consumer(arguments, target.library_names(target.source_root, sorted(synced)))
        consumer_problems += _app_consumer_problems(target, verified, app_arguments)
    except (OSError, ValueError) as error:
        raise SyncRefused([f"consumer: {error}"]) from error
    if consumer_problems:
        raise SyncRefused([f"consumer: {problem}" for problem in consumer_problems])
    recorded = check_destination(target, destination, digests)
    return SyncPlan(synced=synced, digests=digests, recorded=recorded)


def _report_drift(plan: SyncPlan, out: TextIO) -> int:
    differences = [
        *(f"would add: {path}" for path in plan.added()),
        *(f"would remove: {path}" for path in plan.removed()),
        *(f"would change: {path}" for path in plan.changed()),
    ]
    for line in differences:
        print(line, file=out)
    if differences:
        return EXIT_DRIFT
    print(f"in sync: {len(plan.digests)} file(s)", file=out)
    return EXIT_IN_SYNC


def run_client_sync(argv: Sequence[str], target: SyncTarget, out: TextIO, err: TextIO) -> int:
    """Run one sync (or ``--check``) for *target* with the command line *argv*.

    Returns:
        :data:`EXIT_IN_SYNC`, :data:`EXIT_DRIFT` (``--check`` found a
        difference) or :data:`EXIT_REFUSED` (nothing was written).
    """
    app_options = (_APP_OPTION, *(option.name for option in target.app_consumer_options)) if target.app_paths_template else ()
    option_names = (_DESTINATION_OPTION, _CHECK_OPTION, *(option.name for option in target.consumer_options), *app_options)
    parsed = _parser(target).parse_args(normalize_switches(argv, option_names))
    destination = Path(getattr(parsed, _DESTINATION_OPTION))
    try:
        arguments = _consumer_arguments(target, parsed)
        selected, app_arguments = _selection(target, parsed, destination, arguments)
        plan = plan_sync(selected, destination, arguments, app_arguments)
    except SyncRefused as refused:
        for problem in refused.problems:
            print(f"error: {problem}", file=err)
        print(f"refused: nothing was written to {destination}", file=err)
        return EXIT_REFUSED
    if getattr(parsed, _CHECK_OPTION):
        return _report_drift(plan, out)
    try:
        apply_sync(selected, destination, plan)
    except (OSError, SyncRefused) as error:
        print(
            f"error: the sync stopped part-way ({error}); {target.destination_manifest_name} in "
            f"{destination} records exactly the files left in place -- fix the cause and re-run",
            file=err,
        )
        return EXIT_REFUSED
    print(
        f"synced {len(plan.digests)} file(s) into {destination} "
        f"({len(plan.added())} added, {len(plan.removed())} removed, {len(plan.changed())} changed)",
        file=out,
    )
    return EXIT_IN_SYNC


