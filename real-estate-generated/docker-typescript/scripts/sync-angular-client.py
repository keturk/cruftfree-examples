def library_names(source_root: Path, files: Sequence[str]) -> list[str]:
    """Every package entry the synced Angular libraries publish, sorted.

    A library is a folder ``libs/<name>/`` holding a ``package.json``; its
    entry is that manifest's ``name``, plus ``<name>/testing`` when the
    library carries ``src/testing/index.ts``.

    Raises:
        ValueError: A library's ``package.json`` declares no string ``name``.
    """
    present = set(files)
    names: list[str] = []
    for path in sorted(present):
        parts = PurePosixPath(path).parts
        if len(parts) != _LIBRARY_ROOT_DEPTH + 1 or parts[0] != ANGULAR_LIBS_DIR or parts[2] != ANGULAR_PACKAGE_JSON:
            continue
        manifest = json.loads((source_root / path).read_text(encoding="utf-8"))
        name = manifest.get("name") if isinstance(manifest, dict) else None
        if not isinstance(name, str) or not name:
            raise ValueError(f"{path} declares no package name; regenerate the client tree")
        names.append(name)
        if f"{parts[0]}/{parts[1]}/{ANGULAR_TESTING_INDEX}" in present:
            names.append(f"{name}/{ANGULAR_TESTING_ENTRY}")
    return sorted(names)


def _skip_json_string(text: str, start: int) -> int:
    """The index just past the JSON string literal opening at *start*."""
    index = start + 1
    while index < len(text):
        if text[index] == _ESCAPE:
            index += 2
            continue
        if text[index] == _STRING_QUOTE:
            return index + 1
        index += 1
    raise ValueError("unterminated string")


def _skip_comment(text: str, start: int) -> int:
    """The index just past the comment opening at *start*."""
    if text.startswith(_LINE_COMMENT, start):
        end = text.find("\n", start)
        return len(text) if end < 0 else end
    end = text.find(_BLOCK_COMMENT_CLOSE, start + len(_BLOCK_COMMENT_OPEN))
    if end < 0:
        raise ValueError("unterminated /* comment")
    return end + len(_BLOCK_COMMENT_CLOSE)


def _without_comments(text: str) -> str:
    """*text* with every ``//`` and ``/* */`` comment outside a string replaced by a space."""
    pieces: list[str] = []
    index = 0
    while index < len(text):
        if text[index] == _STRING_QUOTE:
            end = _skip_json_string(text, index)
            pieces.append(text[index:end])
        elif text.startswith((_LINE_COMMENT, _BLOCK_COMMENT_OPEN), index):
            end = _skip_comment(text, index)
            pieces.append(" ")
        else:
            end = index + 1
            pieces.append(text[index])
        index = end
    return "".join(pieces)


def _without_trailing_commas(text: str) -> str:
    """*text* (comments already removed) with every comma before a ``}`` or ``]`` dropped."""
    pieces: list[str] = []
    index = 0
    while index < len(text):
        if text[index] == _STRING_QUOTE:
            end = _skip_json_string(text, index)
            pieces.append(text[index:end])
            index = end
            continue
        if not (text[index] == "," and _next_significant(text, index + 1) in _CLOSERS):
            pieces.append(text[index])
        index += 1
    return "".join(pieces)


def _next_significant(text: str, start: int) -> str:
    """The first non-whitespace character at or after *start*; empty at the end."""
    index = start
    while index < len(text) and text[index].isspace():
        index += 1
    return text[index : index + 1]


def _read_commented_json(path: Path, label: str) -> object:
    """The parsed file at *path* (JSON with comments and trailing commas), *label* naming it in an error.

    Raises:
        ValueError: The file is not JSON once comments and trailing commas are removed.
    """
    text = path.read_text(encoding="utf-8-sig")
    try:
        return json.loads(_without_trailing_commas(_without_comments(text)))
    except ValueError as error:
        raise ValueError(f"{path} is not a valid {label}: {error}") from error


def read_tsconfig(path: Path) -> object:
    """The parsed tsconfig at *path* (JSON with comments and trailing commas).

    Raises:
        ValueError: The file is not JSON once comments and trailing commas are removed.
    """
    return _read_commented_json(path, "tsconfig")


def check_consumer(arguments: Mapping[str, str], library_names: Sequence[str]) -> list[str]:
    """One problem per package entry the consumer's tsconfig does not map.

    Args:
        arguments: The consumer options; reads ``arguments["tsconfig"]``.
        library_names: Every package entry the synced libraries publish.

    Returns:
        A problem per unmapped entry; empty when ``compilerOptions.paths`` maps all.

    Raises:
        ValueError: The tsconfig cannot be parsed.
    """
    tsconfig = Path(arguments[TSCONFIG_ARGUMENT])
    parsed = read_tsconfig(tsconfig)
    options = parsed.get("compilerOptions") if isinstance(parsed, dict) else None
    paths = options.get("paths") if isinstance(options, dict) else None
    mapped = paths if isinstance(paths, dict) else {}
    return [
        f"{tsconfig}: compilerOptions.paths maps no '{name}'; add it, pointing at the synced library's entry"
        for name in library_names
        if name not in mapped
    ]


def _project_of(parsed: object, app: str) -> Mapping[str, object] | None:
    """The project *app* of a parsed project file: ``projects[app]`` in a workspace, else the file itself."""
    if not isinstance(parsed, dict):
        return None
    projects = parsed.get(_PROJECTS_KEY)
    project = projects.get(app) if isinstance(projects, dict) else parsed
    return project if isinstance(project, dict) else None


def _build_options(project: Mapping[str, object]) -> Mapping[str, object]:
    """The options of *project*'s build target; empty when it declares none."""
    for key in _TARGET_KEYS:
        targets = project.get(key)
        build = targets.get(_BUILD_TARGET) if isinstance(targets, dict) else None
        options = build.get(_OPTIONS_KEY) if isinstance(build, dict) else None
        if isinstance(options, dict):
            return options
    return {}


def _option_items(options: Mapping[str, object], kind: str) -> list[object]:
    """The items of the build option *kind*; empty when it is not a list."""
    items = options.get(kind)
    return items if isinstance(items, list) else []


def _item_path(item: object) -> str | None:
    """The path a ``styles`` or ``assets`` item names, the item itself or an object's ``input``.

    A path is normalized, so ``./libs/a.css`` and ``libs/a.css`` are one entry;
    ``None`` when the item names no path.
    """
    raw = item.get(_INPUT_KEY) if isinstance(item, dict) else item
    return PurePosixPath(raw).as_posix() if isinstance(raw, str) else None


def _entry(kind: str, item: object, path: str) -> str:
    """*item* as a ``<kind>:<value>`` entry naming *path*.

    A style's value is its path. An asset's is canonical JSON, because its glob
    and output decide what the build copies, so they compare too.
    """
    if kind == _STYLES_KEY:
        return f"{kind}{_ENTRY_SEPARATOR}{path}"
    value = {**item, _INPUT_KEY: path} if isinstance(item, dict) else path
    return f"{kind}{_ENTRY_SEPARATOR}{json.dumps(value, sort_keys=True, separators=(',', ':'))}"


def _option_entries(options: Mapping[str, object]) -> list[str]:
    """One entry per ``styles`` and ``assets`` item of *options* that names a path."""
    return [
        _entry(kind, item, path)
        for kind in (_STYLES_KEY, _ASSETS_KEY)
        for item in _option_items(options, kind)
        if (path := _item_path(item)) is not None
    ]


def app_entries(source_root: Path, files: Sequence[str], app: str) -> list[str]:
    """Every ``styles`` and ``assets`` entry the generated workspace builds *app* with, sorted.

    Args:
        source_root: The verified client tree.
        files: The tree-relative paths of its verified files.
        app: The app key, the app's project name in ``angular.json``.

    Returns:
        ``styles:<path>`` and ``assets:<canonical JSON>`` strings.

    Raises:
        ValueError: The tree has no verified ``angular.json``, or it holds no
            project *app*, or a build item names no path.
    """
    if ANGULAR_WORKSPACE_FILE not in files:
        raise ValueError(f"the client tree lists no {ANGULAR_WORKSPACE_FILE}; regenerate the client tree")
    parsed = _read_commented_json(source_root / ANGULAR_WORKSPACE_FILE, "workspace file")
    project = _project_of(parsed, app)
    if project is None:
        raise ValueError(f"{ANGULAR_WORKSPACE_FILE} holds no project '{app}'; regenerate the client tree")
    options = _build_options(project)
    pathless = [
        item
        for kind in (_STYLES_KEY, _ASSETS_KEY)
        for item in _option_items(options, kind)
        if _item_path(item) is None
    ]
    if pathless:
        raise ValueError(f"{ANGULAR_WORKSPACE_FILE}: project '{app}' has build items naming no path: {pathless}; regenerate the client tree")
    return sorted(_option_entries(options))


def _destination_prefix(arguments: Mapping[str, str]) -> PurePosixPath:
    """``--destination`` relative to the consumer workspace root, the folder of the ``--tsconfig`` file.

    Raises:
        ValueError: The destination lies outside that folder, so no entry can be
            rebased onto it.
    """
    workspace = Path(arguments[TSCONFIG_ARGUMENT]).resolve().parent
    destination = Path(arguments[_DESTINATION_ARGUMENT]).resolve()
    if not destination.is_relative_to(workspace):
        raise ValueError(
            f"--{_DESTINATION_ARGUMENT} {destination} lies outside the consumer workspace {workspace}, the folder "
            f"of --{TSCONFIG_ARGUMENT}, so no build entry can be rebased onto it; pass the tsconfig at the "
            f"workspace root, or a destination inside it"
        )
    return PurePosixPath(destination.relative_to(workspace).as_posix())


def _rebased_path(path: str, app: str, prefix: PurePosixPath) -> str:
    """The spelling of the generated *path* in the consumer's build.

    Raises:
        ValueError: *path* lies neither under ``node_modules/`` nor under a root
            the sync copies for *app*, so no consumer spelling of it exists.
    """
    parts = PurePosixPath(path).parts
    if parts[:1] == (ANGULAR_NODE_MODULES,):
        return path
    if parts[:1] == (ANGULAR_LIBS_DIR,) or parts[:2] == (ANGULAR_APPS_DIR, app):
        return (prefix / path).as_posix()
    raise ValueError(
        f"build entry '{path}' of app '{app}' lies under neither {ANGULAR_NODE_MODULES}/, {ANGULAR_LIBS_DIR}/ "
        f"nor {ANGULAR_APPS_DIR}/{app}/; regenerate the client tree"
    )


def _rebased_entry(entry: str, app: str, prefix: PurePosixPath) -> str:
    """The generated *entry* as the consumer's build spells it.

    Raises:
        ValueError: *entry* names no path, or :func:`_rebased_path` refuses it.
    """
    kind, _, value = entry.partition(_ENTRY_SEPARATOR)
    item = value if kind == _STYLES_KEY else json.loads(value)
    path = _item_path(item)
    if path is None:
        raise ValueError(f"build entry '{entry}' of app '{app}' names no path; regenerate the client tree")
    return _entry(kind, item, _rebased_path(path, app, prefix))


def check_app_consumer(arguments: Mapping[str, str], app: str, entries: Sequence[str]) -> list[str]:
    """One problem per generated build entry the consumer's project file does not carry for *app*.

    Args:
        arguments: The consumer options, keyed by declared name, with the sync's
            ``destination``; reads ``project-file``, ``tsconfig`` and ``destination``.
        app: The app key, its project name in a file holding several projects.
        entries: What :func:`app_entries` returned for *app*.

    Returns:
        A problem per missing entry, or one when the file holds no project
        *app*; empty when the build options carry every entry. The file is
        read, never written.

    Raises:
        ValueError: The project file cannot be parsed, the destination lies
            outside the consumer workspace, or an entry has no consumer spelling.
    """
    project_file = Path(arguments[PROJECT_FILE_ARGUMENT])
    prefix = _destination_prefix(arguments)
    project = _project_of(_read_commented_json(project_file, "project file"), app)
    if project is None:
        return [f"{project_file}: holds no project '{app}'; pass the project file that builds this app"]
    carried = set(_option_entries(_build_options(project)))
    expected = sorted({_rebased_entry(entry, app, prefix) for entry in entries})
    return [
        f"{project_file}: the build options of project '{app}' carry no '{entry}'; add it"
        for entry in expected
        if entry not in carried
    ]


