/**
 * The Host-header check every request and every WebSocket upgrade passes.
 *
 * A request whose Host matches no allowed pattern is refused `400 Invalid host header`
 * before any route, guard or CORS answer runs -- a host-header attack reaches nothing.
 * The allow-list is baked at generation time from httpSecurity.allowedHosts, the
 * platform's front-door host patterns and this service's own in-network name (the
 * host peers dial); no environment variable is read.
 *
 * A pattern is `*` (any host), an exact host name, or `*.` followed by a domain
 * (any host ending in `.` plus that domain). The port is not part of the match. A
 * host refused only because its `www.` form is allowed is redirected there.
 *
 * Auto-generated by cruftfree-codegen-typescript. Do not edit manually.
 */
import type { NextFunction, Request, Response } from 'express';

const ALLOWED_HOSTS: readonly string[] = ["realestate-email-mock", "localhost"];
const ANY_HOST = '*';
const WWW_PREFIX = 'www.';
const REDIRECT_STATUS = 307;
const REFUSED_STATUS = 400;
const REFUSED_BODY = 'Invalid host header';

/** What the check decides for one Host header. */
export type HostVerdict =
  | { readonly kind: 'allowed' }
  | { readonly kind: 'redirect'; readonly host: string }
  | { readonly kind: 'refused' };

/** The verdict for the Host header *header* (`undefined` when the request sent none). */
export function hostVerdict(header: string | undefined): HostVerdict {
  if (ALLOWED_HOSTS.includes(ANY_HOST)) {
    return { kind: 'allowed' };
  }
  const host = (header ?? '').split(':')[0];
  let wwwAllowed = false;
  for (const pattern of ALLOWED_HOSTS) {
    if (host === pattern || (pattern.startsWith('*') && host.endsWith(pattern.slice(1)))) {
      return { kind: 'allowed' };
    }
    if (`${WWW_PREFIX}${host}` === pattern) {
      wwwAllowed = true;
    }
  }
  return wwwAllowed ? { kind: 'redirect', host: `${WWW_PREFIX}${header ?? ''}` } : { kind: 'refused' };
}

/** Express middleware: pass an allowed Host on, refuse or redirect any other. */
export function hostCheckMiddleware(req: Request, res: Response, next: NextFunction): void {
  const verdict = hostVerdict(req.headers.host);
  if (verdict.kind === 'allowed') {
    next();
    return;
  }
  if (verdict.kind === 'redirect') {
    res.redirect(REDIRECT_STATUS, `${req.protocol}://${verdict.host}${req.originalUrl}`);
    return;
  }
  res.status(REFUSED_STATUS).type('text/plain').send(REFUSED_BODY);
}

/**
 * The status and headers a refused WebSocket upgrade is answered with, or `undefined` when allowed.
 * A redirect keeps the scheme the upgrade arrived on (`wss` over TLS), so it never downgrades.
 */
export function upgradeHostRefusal(
  header: string | undefined,
  url: string | undefined,
  secure: boolean,
): { readonly status: number; readonly headers: Readonly<Record<string, string>> } | undefined {
  const verdict = hostVerdict(header);
  if (verdict.kind === 'allowed') {
    return undefined;
  }
  if (verdict.kind === 'redirect') {
    const scheme = secure ? 'wss' : 'ws';
    return { status: REDIRECT_STATUS, headers: { Location: `${scheme}://${verdict.host}${url ?? '/'}` } };
  }
  return { status: REFUSED_STATUS, headers: {} };
}
