import { ArgumentMetadata, PipeTransform } from '@nestjs/common';
import { paramFailure } from '../common/request-validation';
import type { FieldErrorLocation } from '../errors/problem-details.dto';

/**
 * Coerces a query string to a TypeScript string-backed enum member value.
 *
 * Accepts the enum's wire values only -- the member's declared ``value(...)``,
 * else its DSL member name -- exactly as the other targets do. A missing
 * required value, and a value outside the wire set, are refused as the
 * registered ``request-validation`` problem; its entry names the parameter and
 * never carries the received value.
 *
 * Auto-generated by cruftfree-codegen-typescript. Do not edit manually.
 */
export class CoerceStringEnumPipe<
  T extends Record<string, unknown>,
> implements PipeTransform<string | undefined, T[keyof T] | undefined> {
  constructor(
    private readonly enumObject: T,
    private readonly optional: boolean,
    private readonly location: FieldErrorLocation,
    private readonly field: string,
  ) {}

  transform(
    value: string | undefined,
    _metadata: ArgumentMetadata,
  ): T[keyof T] | undefined {
    if (value === undefined || value === '') {
      if (this.optional) {
        return undefined;
      }
      throw paramFailure(this.location, this.field, "required");
    }

    const values = Object.values(this.enumObject) as string[];
    if (values.includes(value)) {
      return value as T[keyof T];
    }

    throw paramFailure(this.location, this.field, "invalid");
  }
}
