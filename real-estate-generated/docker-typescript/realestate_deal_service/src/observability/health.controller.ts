/**
 * Health, readiness, and liveness endpoints.
 *
 * Three distinct contracts:
 *
 * - `/live`   -- process liveness; 200 whenever the process is up. No checks.
 * - `/ready`  -- readiness; 503 when any readiness-blocking dependency (a
 *                  required one, or a degraded one declared `readyOnDegraded = false`)
 *                  is down, or an in-process event consumer is stopped.
 * - `/health` -- detailed per-dependency report (status / required / health),
 *                  keyed by dependency identity (`<kind>.<block>`); 503 only when a
 *                  required dependency is down.
 *
 * The routes are unauthenticated, so a failed probe's error is logged here and
 * never returned: its text routinely names a dependency's internal host and port.
 *
 * Auto-generated by cruftfree-codegen-typescript. Do not edit manually.
 */
import { Controller, Get, HttpStatus, Logger, Res } from '@nestjs/common';
import type { Response } from 'express';
import { DatabaseHealthService as DealDbRdbmsHealth } from '../deal-db/database.health';

const STATUS_UP = 'up';
const STATUS_DOWN = 'down';
const STATUS_DEGRADED = 'degraded';
const STORE_HEALTHY = 'healthy';

type DependencyStatus = typeof STATUS_UP | typeof STATUS_DOWN;

interface DependencyCheck {
  status: DependencyStatus;
  required: boolean;
  health?: string;
}

interface DependencyProbe {
  key: string;
  required: boolean;
  /** Whether this dependency being down must fail readiness. */
  blocksReadiness: boolean;
  /** The resolved health severity, when the dependency's policy declares one. */
  health?: string;
  run: () => Promise<boolean>;
}

interface LivenessReport {
  status: typeof STATUS_UP;
  service: string;
}

interface ReadinessReport {
  status: DependencyStatus;
  service: string;
  blockers: Record<string, string>;
}

interface HealthReport {
  status: DependencyStatus | typeof STATUS_DEGRADED;
  service: string;
  checks: Record<string, DependencyCheck>;
}

@Controller()
export class HealthController {
  private readonly logger = new Logger(HealthController.name);

  constructor(
    private readonly dealDbRdbmsHealth: DealDbRdbmsHealth,
  ) {}

  /** Every dependency this service probes, with the readiness facts of its declared policy. */
  private dependencyProbes(): DependencyProbe[] {
    return [
      {
        key: 'rdbms.dealDb',
        required: true,
        blocksReadiness: true,
        health: 'ready',
        run: async () => (await this.dealDbRdbmsHealth.checkHealth()).status === STORE_HEALTHY,
      },
    ];
  }

  /** Run one probe; a throwing probe is recorded as down and logged, never propagated. */
  private async runProbe(probe: DependencyProbe): Promise<DependencyCheck> {
    let up = false;
    try {
      up = await probe.run();
    } catch (err) {
      this.logger.error(
        `health_probe_failed dependency=${probe.key} error=${err instanceof Error ? err.message : String(err)}`,
      );
    }
    if (!up) {
      this.logger.warn(`health_probe_down dependency=${probe.key}`);
    }
    const check: DependencyCheck = { status: up ? STATUS_UP : STATUS_DOWN, required: probe.required };
    if (probe.health !== undefined) {
      check.health = probe.health;
    }
    return check;
  }

  /**
   * Process liveness. Returns 200 whenever the process is serving requests.
   *
   * Performs no dependency checks -- a live process that cannot reach its
   * dependencies is still live (use `/ready` to gate traffic).
   */
  @Get('/live')
  live(): LivenessReport {
    return { status: STATUS_UP, service: 'realestate.DealService' };
  }

  /**
   * Readiness gate. Responds 503 when any readiness-blocking dependency is down.
   *
   * A `required` dependency, or a `degraded` dependency declared
   * `readyOnDegraded = false`, blocks readiness when its probe is down. An
   * `optional` dependency never blocks readiness. A stopped event consumer hosted
   * in this process also blocks readiness: a service whose receive loop died must
   * not keep reporting ready while its backlog grows.
   */
  @Get('/ready')
  async ready(@Res({ passthrough: true }) res: Response): Promise<ReadinessReport> {
    const blockers: Record<string, string> = {};
    for (const probe of this.dependencyProbes()) {
      if (!probe.blocksReadiness) {
        continue;
      }
      const check = await this.runProbe(probe);
      if (check.status !== STATUS_UP) {
        blockers[probe.key] = check.status;
      }
    }
    if (Object.keys(blockers).length > 0) {
      res.status(HttpStatus.SERVICE_UNAVAILABLE);
      this.logger.warn(`readiness_not_ready service=realestate.DealService blockers=${JSON.stringify(blockers)}`);
      return { status: STATUS_DOWN, service: 'realestate.DealService', blockers };
    }
    return { status: STATUS_UP, service: 'realestate.DealService', blockers: {} };
  }

  /**
   * Detailed health report with a per-dependency `checks` map.
   *
   * Overall status is `down` when a required dependency is down, `degraded`
   * when a non-required dependency is down, else `up`. Responds 503 only when a
   * required dependency is down.
   */
  @Get('/health')
  async check(@Res({ passthrough: true }) res: Response): Promise<HealthReport> {
    const checks: Record<string, DependencyCheck> = {};
    let requiredDown = false;
    let degraded = false;
    for (const probe of this.dependencyProbes()) {
      const check = await this.runProbe(probe);
      checks[probe.key] = check;
      if (check.status === STATUS_UP) {
        continue;
      }
      if (probe.required) {
        requiredDown = true;
      } else {
        degraded = true;
      }
    }

    let overall: HealthReport['status'] = STATUS_UP;
    if (requiredDown) {
      overall = STATUS_DOWN;
      res.status(HttpStatus.SERVICE_UNAVAILABLE);
    } else if (degraded) {
      overall = STATUS_DEGRADED;
    }

    return {
      status: overall,
      service: 'realestate.DealService',
      checks,
    };
  }
}
