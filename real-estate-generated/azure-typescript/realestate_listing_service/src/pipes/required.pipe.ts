import { Injectable, PipeTransform } from '@nestjs/common';
import { paramFailure } from '../common/request-validation';
import type { FieldErrorLocation } from '../errors/problem-details.dto';

/**
 * Refuses an ``undefined`` / ``null`` parameter value as the registered
 * ``request-validation`` problem, code ``required``, naming where the
 * parameter is read and its name.
 *
 * Apply to required ``@Query()`` parameters that have no default value.
 * NestJS does not enforce required-ness of individual query parameters
 * by default; this pipe provides the same behaviour as FastAPI's required
 * query parameter validation.
 *
 * Auto-generated by cruftfree-codegen-typescript. Do not edit manually.
 */
@Injectable()
export class RequiredPipe implements PipeTransform {
  constructor(
    private readonly location: FieldErrorLocation,
    private readonly field: string,
  ) {}

  transform(value: unknown): unknown {
    if (value === undefined || value === null) {
      throw paramFailure(this.location, this.field, "required");
    }
    return value;
  }
}
