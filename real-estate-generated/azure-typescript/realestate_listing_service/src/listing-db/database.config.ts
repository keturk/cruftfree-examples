import type { MikroOrmModuleOptions } from '@mikro-orm/nestjs';
import { PostgreSqlDriver } from '@mikro-orm/postgresql';
import type { AppSettings } from '../config/settings';
import { optionalSetting } from '../config/settings';
import { SecretsService } from '../realestate_listing_service/secrets/secrets.service';
import { azureCredential } from "../config/credentials";

/** Entra access-token scope for Azure Database for PostgreSQL (passwordless auth). */
const PG_ENTRA_SCOPE = 'https://ossrdbms-aad.database.windows.net/.default';
const pgCredential = azureCredential();

/**
 * A fresh Entra access token per connection -- the server runs with password auth
 * disabled, so the connection password is a short-lived token from this service's
 * managed identity. Never cached beyond the credential's own cache, never logged.
 */
async function entraAccessToken(): Promise<string> {
  const token = await pgCredential.getToken(PG_ENTRA_SCOPE);
  if (!token) {
    throw new Error('Managed identity returned no access token for Azure Database for PostgreSQL.');
  }
  return token.token;
}

/** The function app sets CRUFTFREE_DB_USERNAME to its own role; the web app does not. */
function databaseUser(): string {
  return optionalSetting("CRUFTFREE_DB_USERNAME") ?? 'realestate-listing-service';
}


export async function getDatabaseConfig(
  settings: AppSettings,
  secrets: SecretsService = new SecretsService(),
): Promise<MikroOrmModuleOptions> {
  const host = settings.connections.listing_db_host;
  const port = settings.connections.listing_db_port;
  const database = settings.connections.listing_db_database;
  const user = databaseUser();

  return {
    driver: PostgreSqlDriver,
    entities: [
      __dirname + '/../realestate_listing_service/entities/listing_db/**/*.entity{.ts,.js}',
    ],
    allowGlobalContext: true,
    debug: false,
    driverOptions: { connection: { ssl: true } },
    pool: {
      max: 20,
    },
    host,
    port,
    user,
    password: entraAccessToken,
    dbName: database,
  };
}
