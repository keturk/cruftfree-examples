/**
 * Reading a message another service produced.
 *
 * Every consumer of a peer-produced message -- a pub/sub event, a subscription
 * handler, a queued message -- validates it here before any handler code runs:
 * the decoded JSON becomes an instance of the message's payload class (nested
 * structs become their classes, dates become Date values) and is validated by
 * that class's class-validator decorators, the ones a request DTO carries. A
 * missing declared field, a wrong type or a malformed nested struct fails the
 * delivery. A field the class does not declare -- a newer peer's addition
 * during a rolling deploy -- is stripped, never rejected.
 *
 * Auto-generated by cruftfree-codegen-typescript. Do not edit manually.
 */
import { plainToInstance } from 'class-transformer';
import { ValidationError, validate } from 'class-validator';

/** A peer's message that does not satisfy its payload class. Names the failing fields, never their values. */
export class PeerPayloadError extends Error {
  readonly payloadClass: string;
  readonly fields: readonly string[];

  constructor(payloadClass: string, fields: readonly string[]) {
    super(
      `${payloadClass} payload is invalid at ${fields.join(', ')}; expected every declared field ` +
        'with its declared type. Fix the producer, or redeliver once it sends a valid payload.',
    );
    this.name = 'PeerPayloadError';
    this.payloadClass = payloadClass;
    this.fields = fields;
  }
}

/** The property paths of a class-validator tree that failed a constraint: `a.b`, `items.0.sku`. */
function failedPaths(errors: readonly ValidationError[], parentPath: string): string[] {
  const paths: string[] = [];
  for (const error of errors) {
    const path = parentPath === '' ? error.property : `${parentPath}.${error.property}`;
    if (error.constraints !== undefined && Object.keys(error.constraints).length > 0) {
      paths.push(path);
    }
    if (error.children !== undefined && error.children.length > 0) {
      paths.push(...failedPaths(error.children, path));
    }
  }
  return paths;
}

/** The peer-produced *raw* message, validated into an instance of *payloadClass*. */
export async function readPeerPayload<T extends object>(
  payloadClass: new () => T,
  raw: unknown,
): Promise<T> {
  if (typeof raw !== 'object' || raw === null || Array.isArray(raw)) {
    throw new PeerPayloadError(payloadClass.name, ['(payload)']);
  }
  const instance = plainToInstance(payloadClass, raw);
  const errors = await validate(instance, { whitelist: true, forbidNonWhitelisted: false });
  if (errors.length > 0) {
    throw new PeerPayloadError(payloadClass.name, failedPaths(errors, ''));
  }
  return instance;
}
