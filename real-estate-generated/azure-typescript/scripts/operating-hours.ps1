# Install (default) or uninstall an operating-hours scheduler for realestate.System.
#
# The scheduler keeps the application's compute running only during a daily time
# window and shuts it down outside that window to cut cost without losing data.
# It provisions two Consumption Logic Apps (in their own resource group) on
# weekly Recurrence schedules: a "start" app at the window's start hour and a
# "stop" app at the end hour. Each enumerates the App Service / Function App sites, PostgreSQL Flexible Servers
# in the watched resource group and starts
# or stops them via Azure Resource Manager. The Logic Apps authenticate with a
# user-assigned managed identity granted Contributor on the watched group only.
#
# Databases, storage and Key Vault are never touched -- only compute is started
# and stopped, so no data is lost.
#
# Usage:
#   .\scripts\operating-hours.ps1                          install 08:00-20:00 Mon-Fri UTC (default)
#   .\scripts\operating-hours.ps1 -StartHour 7 -StopHour 19  custom window (24h clock)
#   .\scripts\operating-hours.ps1 -TimeZone "Eastern Standard Time"  custom time zone
#   .\scripts\operating-hours.ps1 -WeekDays Monday,Wednesday,Friday  custom days
#   .\scripts\operating-hours.ps1 -Uninstall               remove the scheduler
#
# Generated by CruftFree -- do not edit manually. See DEPLOYMENT.md for details.
param(
    # Remove the scheduler instead of installing it.
    [switch]$Uninstall,
    # Resource group whose compute is started/stopped (override via $env:RESOURCE_GROUP).
    [string]$ResourceGroup = "realestate-system-dev-rg",
    # Region for the scheduler resource group and Logic Apps (override via $env:LOCATION).
    [string]$Location = "eastus",
    # Resource group that holds the scheduler Logic Apps; must differ from $ResourceGroup.
    [string]$SchedulerResourceGroup = "operating-hours-rg",
    # Hour (0-23) compute is started each scheduled day.
    [ValidateRange(0, 23)][int]$StartHour = 8,
    # Hour (0-23) compute is stopped each scheduled day.
    [ValidateRange(0, 23)][int]$StopHour = 20,
    # Windows time-zone id the schedule is evaluated in (e.g. "UTC", "Eastern Standard Time").
    [string]$TimeZone = "UTC",
    # Days the start/stop schedule fires on.
    [string[]]$WeekDays = @("Monday", "Tuesday", "Wednesday", "Thursday", "Friday")
)
$ErrorActionPreference = "Stop"

# Explicit parameters win over environment, which wins over the generated default.
if (-not $PSBoundParameters.ContainsKey('ResourceGroup') -and $env:RESOURCE_GROUP) { $ResourceGroup = $env:RESOURCE_GROUP }
if (-not $PSBoundParameters.ContainsKey('Location') -and $env:LOCATION) { $Location = $env:LOCATION }

# ---- Output helpers ----
$script:Watch = [System.Diagnostics.Stopwatch]::StartNew()
$script:StepColor = "Cyan"
function Show-Elapsed { "{0}m{1:00}s" -f [int]$script:Watch.Elapsed.TotalMinutes, $script:Watch.Elapsed.Seconds }
function Write-Step($msg) { Write-Host "`n==> $msg" -ForegroundColor $script:StepColor }
function Write-Ok($msg)   { Write-Host "    $msg" -ForegroundColor Green }
function Write-Note($msg) { Write-Host "    $msg" -ForegroundColor Yellow }

# ---- Embedded Bicep (written to a temp dir at install time) ----
# Subscription-scoped: creates the scheduler resource group, a user-assigned
# managed identity + the two scheduled Logic Apps (in the scheduler group), and a
# Contributor role assignment on the watched group. Authored as Bicep so the
# cross-scope wiring stays declarative.
$script:MainBicep = @'
targetScope = 'subscription'

param targetResourceGroupName string

param location string

param schedulerResourceGroupName string = 'operating-hours-rg'

@minValue(0)
@maxValue(23)
param startHour int = 8

@minValue(0)
@maxValue(23)
param stopHour int = 20

param timeZone string = 'UTC'

param weekDays array = [
  'Monday'
  'Tuesday'
  'Wednesday'
  'Thursday'
  'Friday'
]

resource schedulerRg 'Microsoft.Resources/resourceGroups@2024-11-01' = {
  name: schedulerResourceGroupName
  location: location
}

module scheduler 'scheduler.bicep' = {
  name: 'operating-hours-scheduler'
  scope: schedulerRg
  params: {
    location: location
    targetResourceGroupName: targetResourceGroupName
    startHour: startHour
    stopHour: stopHour
    timeZone: timeZone
    weekDays: weekDays
  }
}

module role 'role.bicep' = {
  name: 'operating-hours-role'
  scope: resourceGroup(targetResourceGroupName)
  params: {
    principalId: scheduler.outputs.principalId
  }
}
'@

$script:SchedulerBicep = @'
param location string

param targetResourceGroupName string

@minValue(0)
@maxValue(23)
param startHour int

@minValue(0)
@maxValue(23)
param stopHour int

param timeZone string

param weekDays array

// environment().resourceManager ends with '/'. A resource id begins with '/',
// so the leading slash is stripped from the id at runtime (substring(id, 1))
// before concatenation to avoid a double slash.
var armBase = environment().resourceManager
var subId = subscription().subscriptionId
var sitesListUri = '${armBase}subscriptions/${subId}/resourceGroups/${targetResourceGroupName}/providers/Microsoft.Web/sites?api-version=2023-12-01'
var databasesListUri = '${armBase}subscriptions/${subId}/resourceGroups/${targetResourceGroupName}/providers/Microsoft.DBforPostgreSQL/flexibleServers?api-version=2024-08-01'

// One Logic App per edge of the window. 'start' brings compute back at the start
// hour; 'stop' pauses it at the stop hour. Both share the managed identity.
// vmAction differs from action on the stop edge: a VM's cost-saving stop verb
// is 'deallocate' (releases the compute allocation), not the plain 'stop' a
// Web site or Flexible Server accepts ('stop' on a VM only powers it off
// without releasing the allocation, so it keeps billing for compute).
var jobs = [
  {
    suffix: 'start'
    action: 'start'
    vmAction: 'start'
    hour: startHour
  }
  {
    suffix: 'stop'
    action: 'stop'
    vmAction: 'deallocate'
    hour: stopHour
  }
]

resource identity 'Microsoft.ManagedIdentity/userAssignedIdentities@2023-01-31' = {
  name: 'operating-hours-mi'
  location: location
}

resource workflows 'Microsoft.Logic/workflows@2019-05-01' = [for job in jobs: {
  name: 'operating-hours-${job.suffix}'
  location: location
  identity: {
    type: 'UserAssigned'
    userAssignedIdentities: {
      '${identity.id}': {}
    }
  }
  properties: {
    state: 'Enabled'
    definition: {
      '$schema': 'https://schema.management.azure.com/providers/Microsoft.Logic/schemas/2016-06-01/workflowdefinition.json#'
      contentVersion: '1.0.0.0'
      parameters: {}
      triggers: {
        Recurrence: {
          type: 'Recurrence'
          recurrence: {
            frequency: 'Week'
            interval: 1
            timeZone: timeZone
            schedule: {
              hours: [
                job.hour
              ]
              minutes: [
                0
              ]
              weekDays: weekDays
            }
          }
        }
      }
      actions: {
        List_sites: {
          type: 'Http'
          runAfter: {}
          inputs: {
            method: 'GET'
            uri: sitesListUri
            authentication: {
              type: 'ManagedServiceIdentity'
              identity: identity.id
              audience: armBase
            }
          }
        }
        For_each_site: {
          type: 'Foreach'
          foreach: '@body(\'List_sites\')?[\'value\']'
          runAfter: {
            List_sites: [
              'Succeeded'
            ]
          }
          actions: {
            Manage_site: {
              type: 'Http'
              runAfter: {}
              inputs: {
                method: 'POST'
                uri: '@{concat(\'${armBase}\', substring(items(\'For_each_site\')?[\'id\'], 1), \'/${job.action}?api-version=2023-12-01\')}'
                authentication: {
                  type: 'ManagedServiceIdentity'
                  identity: identity.id
                  audience: armBase
                }
              }
            }
          }
        }
        List_databases: {
          type: 'Http'
          runAfter: {
            For_each_site: [
              'Succeeded'
            ]
          }
          inputs: {
            method: 'GET'
            uri: databasesListUri
            authentication: {
              type: 'ManagedServiceIdentity'
              identity: identity.id
              audience: armBase
            }
          }
        }
        For_each_database: {
          type: 'Foreach'
          foreach: '@body(\'List_databases\')?[\'value\']'
          runAfter: {
            List_databases: [
              'Succeeded'
            ]
          }
          actions: {
            Manage_database: {
              type: 'Http'
              runAfter: {}
              inputs: {
                method: 'POST'
                uri: '@{concat(\'${armBase}\', substring(items(\'For_each_database\')?[\'id\'], 1), \'/${job.action}?api-version=2024-08-01\')}'
                authentication: {
                  type: 'ManagedServiceIdentity'
                  identity: identity.id
                  audience: armBase
                }
              }
            }
          }
        }
      }
    }
    parameters: {}
  }
}]

output principalId string = identity.properties.principalId
'@

$script:RoleBicep = @'
param principalId string

// Contributor (b24988ac-...) on the watched resource group only -- enough to
// start and stop the compute resources inside it, nothing more.
var contributorRoleDefinitionId = subscriptionResourceId('Microsoft.Authorization/roleDefinitions', 'b24988ac-6180-42a0-ab88-20f7382dd24c')

resource contributorAssignment 'Microsoft.Authorization/roleAssignments@2022-04-01' = {
  name: guid(resourceGroup().id, principalId, contributorRoleDefinitionId)
  properties: {
    roleDefinitionId: contributorRoleDefinitionId
    principalId: principalId
    principalType: 'ServicePrincipal'
  }
}
'@

function Test-Preflight {
    if (-not (Get-Command az -ErrorAction SilentlyContinue)) { Write-Error "'az' CLI not found. Install the Azure CLI."; exit 1 }
    az account show *> $null
    if ($LASTEXITCODE -ne 0) { Write-Error "Not logged in to Azure. Run 'az login'."; exit 1 }
    if ($SchedulerResourceGroup -eq $ResourceGroup) {
        Write-Error "SchedulerResourceGroup must differ from ResourceGroup ('$ResourceGroup'), otherwise the scheduler would stop itself."
        exit 1
    }
    if ($StartHour -eq $StopHour) {
        Write-Error "StartHour and StopHour must differ (got $StartHour for both); there would be no running window."
        exit 1
    }
}

function Invoke-SchedulerInstall {
    $subName = az account show --query name -o tsv
    $windowLabel = "{0:00}:00-{1:00}:00 {2}" -f $StartHour, $StopHour, $TimeZone

    Write-Host "============================================================" -ForegroundColor Cyan
    Write-Host " Install operating-hours scheduler for realestate.System" -ForegroundColor Cyan
    Write-Host "   subscription   : $subName" -ForegroundColor Cyan
    Write-Host "   watched rg     : '$ResourceGroup' (compute started/stopped)" -ForegroundColor Cyan
    Write-Host "   scheduler in   : '$SchedulerResourceGroup' (separate, not stopped)" -ForegroundColor Cyan
    Write-Host "   running window : $windowLabel" -ForegroundColor Cyan
    Write-Host "   on days        : $($WeekDays -join ', ')" -ForegroundColor Cyan
    Write-Host "============================================================" -ForegroundColor Cyan
    Write-Note "App Service / Function App sites and PostgreSQL Flexible Servers in"
    Write-Note "'$ResourceGroup' are STARTED at $($StartHour):00 and STOPPED at $($StopHour):00 on the listed days."
    Write-Note "Databases, storage and Key Vault are retained -- only compute is paused."
    Write-Note "Note: a stopped App Service site still bills its App Service Plan; the main"
    Write-Note "saving is paused PostgreSQL compute. Use 'deploy.ps1 destroy' to stop all charges."

    $work = Join-Path ([System.IO.Path]::GetTempPath()) ("cruftfree-operating-hours-" + [guid]::NewGuid().ToString("N"))
    New-Item -ItemType Directory -Path $work -Force | Out-Null
    try {
        Set-Content -LiteralPath (Join-Path $work "main.bicep")      -Value $script:MainBicep      -Encoding utf8
        Set-Content -LiteralPath (Join-Path $work "scheduler.bicep") -Value $script:SchedulerBicep -Encoding utf8
        Set-Content -LiteralPath (Join-Path $work "role.bicep")      -Value $script:RoleBicep      -Encoding utf8

        # Bicep parameters are delivered as an ARM parameters FILE, never as inline
        # `key=value` arguments. On Windows `az` is `az.cmd`, so PowerShell routes
        # every native argument through cmd.exe, which strips the double quotes a
        # JSON value carries: `weekDays=["Monday",...]` arrives as `[Monday,...]`
        # and the CLI rejects it client-side before any ARM call. A parameters file
        # has no shell-quoting surface on any shell, and it carries real JSON types,
        # which the int-typed startHour/stopHour params require.
        $paramFile = Join-Path $work "main.parameters.json"
        $paramDoc = [ordered]@{
            '$schema'      = 'https://schema.management.azure.com/schemas/2019-04-01/deploymentParameters.json#'
            contentVersion = '1.0.0.0'
            parameters     = [ordered]@{
                targetResourceGroupName    = @{ value = $ResourceGroup }
                location                   = @{ value = $Location }
                schedulerResourceGroupName = @{ value = $SchedulerResourceGroup }
                startHour                  = @{ value = [int]$StartHour }
                stopHour                   = @{ value = [int]$StopHour }
                timeZone                   = @{ value = $TimeZone }
                # @(...) is load-bearing: a single -WeekDays Monday would otherwise
                # serialize as a bare string and Bicep would reject the array param.
                weekDays                   = @{ value = @($WeekDays) }
            }
        }
        Set-Content -LiteralPath $paramFile -Value ($paramDoc | ConvertTo-Json -Depth 6) -Encoding utf8

        Write-Step "Deploying operating-hours scheduler (provisions the Logic Apps; stops nothing now)"
        Write-Note "Azure is provisioning resources -- this can take a minute with no output."
        az deployment sub create `
            --name ("operating-hours-" + (Get-Date -Format "yyyyMMddHHmmss")) `
            --location $Location `
            --template-file (Join-Path $work "main.bicep") `
            --parameters "@$paramFile" `
            -o none
        if ($LASTEXITCODE -ne 0) { Write-Error "Operating-hours scheduler deployment failed."; exit 1 }
    }
    finally {
        Remove-Item -LiteralPath $work -Recurse -Force -ErrorAction SilentlyContinue
    }

    Write-Step "Done"
    Write-Ok ("Operating-hours scheduler installed in {0}." -f (Show-Elapsed))
    Write-Note "Compute is not started or stopped until the next scheduled $($StartHour):00 / $($StopHour):00."
    Write-Host ""
    Write-Host "Uninstall with:  .\scripts\operating-hours.ps1 -Uninstall"
}

function Invoke-SchedulerUninstall {
    $script:StepColor = "Yellow"
    $subId = az account show --query id -o tsv

    Write-Host "============================================================" -ForegroundColor Yellow
    Write-Host " Uninstall operating-hours scheduler for realestate.System" -ForegroundColor Yellow
    Write-Host "   scheduler group : $SchedulerResourceGroup (will be deleted)" -ForegroundColor Yellow
    Write-Host "   watched rg      : $ResourceGroup (left untouched)" -ForegroundColor Yellow
    Write-Host "============================================================" -ForegroundColor Yellow
    Write-Note "This removes the scheduler only. Compute in '$ResourceGroup' is left in its current state."
    Write-Note "If anything is currently stopped, bring it back with '.\scripts\deploy.ps1'."

    # Resolve the managed identity before deleting its resource group.
    $principalId = az identity show --resource-group $SchedulerResourceGroup --name "operating-hours-mi" --query principalId -o tsv --only-show-errors

    if ($principalId) {
        Write-Step "Removing Contributor role assignment on '$ResourceGroup'"
        $out = az role assignment delete --assignee $principalId --role "Contributor" --scope "/subscriptions/$subId/resourceGroups/$ResourceGroup" --only-show-errors 2>&1
        if ($LASTEXITCODE -ne 0) { Write-Note "Role assignment removal did not succeed: $out" } else { Write-Ok "Role assignment removed." }
    } else {
        Write-Note "Managed identity not found in '$SchedulerResourceGroup' -- skipping role assignment removal."
    }

    Write-Step "Deleting scheduler resource group '$SchedulerResourceGroup'"
    $exists = az group exists --name $SchedulerResourceGroup
    if ($exists -eq "true") {
        az group delete --name $SchedulerResourceGroup --yes -o none
        Write-Ok "Scheduler resource group deleted."
    } else {
        Write-Note "Scheduler resource group '$SchedulerResourceGroup' does not exist -- nothing to delete."
    }

    Write-Step "Done"
    Write-Ok ("Operating-hours scheduler uninstalled in {0}." -f (Show-Elapsed))
}

Test-Preflight

if ($Uninstall) { Invoke-SchedulerUninstall } else { Invoke-SchedulerInstall }
