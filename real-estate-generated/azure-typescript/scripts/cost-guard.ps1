# Install (default) or uninstall a cost guard for realestate.System.
#
# The cost guard STOPS every App Service / Function App site and PostgreSQL
# Flexible Server in the watched resource group when the subscription's
# ACTUAL monthly spend reaches a budget cap -- non-destructive by default. It
# does this with a Consumption Logic App (in its own resource group, so it is
# never stopped by itself) wired to a budget alert via an action group, plus
# an 80%-actual early-warning email alongside the 100%-actual breach action.
# Deleting the watched resource group is an explicit opt-in last resort: only
# when installed with -AllowDelete does the Logic App additionally gain a
# DELETE action, run only after every stop action succeeds. The Logic App
# authenticates to ARM with a managed identity granted Contributor (not
# Owner) on the watched resource group only -- stopping and (opt-in)
# deleting are both within Contributor; Owner's role-administration rights
# were never needed.
#
# Usage:
#   .\scripts\cost-guard.ps1                       install: STOP on breach, $900/month cap (default)
#   .\scripts\cost-guard.ps1 -MonthlyBudgetUsd 500 install with a custom cap
#   .\scripts\cost-guard.ps1 -AllowDelete          install: STOP, then DELETE the resource group (last resort)
#   .\scripts\cost-guard.ps1 -Uninstall            remove the cost guard
#
# Generated by CruftFree -- do not edit manually. See DEPLOYMENT.md for details.
param(
    # Remove the cost guard instead of installing it.
    [switch]$Uninstall,
    # Also grant the Logic App a DELETE action on the watched resource group,
    # run only after every stop action succeeds. Opt-in last resort -- the
    # default guard only ever stops compute; it never deletes.
    [switch]$AllowDelete,
    # Monthly budget in USD; when actual spend reaches this, the guard fires.
    [int]$MonthlyBudgetUsd = 900,
    # Resource group to watch (override via $env:RESOURCE_GROUP).
    [string]$ResourceGroup = "realestate-system-dev-rg",
    # Region for the guard resource group and Logic App (override via $env:LOCATION).
    [string]$Location = "eastus",
    # Resource group that holds the guard Logic App; must differ from $ResourceGroup.
    [string]$GuardResourceGroup = "cost-guard-rg",
    # Email also notified when the guard fires; defaults to the signed-in account.
    [string]$NotificationEmail = ""
)
$ErrorActionPreference = "Stop"

# Explicit parameters win over environment, which wins over the generated default.
if (-not $PSBoundParameters.ContainsKey('ResourceGroup') -and $env:RESOURCE_GROUP) { $ResourceGroup = $env:RESOURCE_GROUP }
if (-not $PSBoundParameters.ContainsKey('Location') -and $env:LOCATION) { $Location = $env:LOCATION }

