function Test-Preflight {
    if (-not (Get-Command az -ErrorAction SilentlyContinue)) { Write-Error "'az' CLI not found. Install the Azure CLI."; exit 1 }
    az account show *> $null
    if ($LASTEXITCODE -ne 0) { Write-Error "Not logged in to Azure. Run 'az login'."; exit 1 }
    if ($GuardResourceGroup -eq $ResourceGroup) {
        Write-Error "GuardResourceGroup must differ from ResourceGroup ('$ResourceGroup'), otherwise the guard would stop/delete itself."
        exit 1
    }
}

function Invoke-CostGuardInstall {
    if (-not $NotificationEmail) { $NotificationEmail = az account show --query user.name -o tsv }
    if (-not $NotificationEmail) {
        Write-Error "Could not determine a notification email. Pass -NotificationEmail <you@example.com>."
        exit 1
    }

    $subName = az account show --query name -o tsv
    $breachAction = if ($AllowDelete) {
        "STOP every App Service / Function App site + PostgreSQL server, then DELETE resource group '$ResourceGroup' (last resort)"
    } else {
        "STOP every App Service / Function App site + PostgreSQL server in '$ResourceGroup'"
    }

    Write-Host "============================================================" -ForegroundColor Cyan
    Write-Host " Install cost guard for realestate.System" -ForegroundColor Cyan
    Write-Host "   subscription   : $subName" -ForegroundColor Cyan
    Write-Host "   budget cap     : $MonthlyBudgetUsd USD / month (actual spend)" -ForegroundColor Cyan
    Write-Host "   on breach      : $breachAction" -ForegroundColor Cyan
    Write-Host "   guard lives in : '$GuardResourceGroup' (separate, never stopped/deleted)" -ForegroundColor Cyan
    Write-Host "   alert email    : $NotificationEmail (also warned at 80% of budget)" -ForegroundColor Cyan
    Write-Host "============================================================" -ForegroundColor Cyan
    if ($AllowDelete) {
        Write-Note "When monthly ACTUAL spend reaches $MonthlyBudgetUsd USD, every App Service / Function App site"
        Write-Note "and PostgreSQL server in '$ResourceGroup' is stopped, then"
        Write-Note "'$ResourceGroup' itself (and everything left in it) is PERMANENTLY DELETED."
    } else {
        Write-Note "When monthly ACTUAL spend reaches $MonthlyBudgetUsd USD, every App Service / Function App site"
        Write-Note "and PostgreSQL server in '$ResourceGroup' is STOPPED."
        Write-Note "No data is deleted. Re-run with -AllowDelete to also delete the resource group as a last resort."
    }
    Write-Note "Azure cost data lags 8-24h, so this caps overage; it is not a real-time hard cap."

    # Pick the already-rendered variant that matches -AllowDelete; the deployed
    # Logic App is whichever ONE of these two complete bodies gets written below.
    $guardBicepBody = if ($AllowDelete) { $script:GuardBicepAllowDelete } else { $script:GuardBicep }

    $work = Join-Path ([System.IO.Path]::GetTempPath()) ("cruftfree-cost-guard-" + [guid]::NewGuid().ToString("N"))
    New-Item -ItemType Directory -Path $work -Force | Out-Null
    try {
        Set-Content -LiteralPath (Join-Path $work "main.bicep")  -Value $script:MainBicep  -Encoding utf8
        Set-Content -LiteralPath (Join-Path $work "guard.bicep") -Value $guardBicepBody    -Encoding utf8
        Set-Content -LiteralPath (Join-Path $work "role.bicep")  -Value $script:RoleBicep  -Encoding utf8

        # Bicep parameters are delivered as an ARM parameters FILE, never as inline
        # `key=value` arguments. On Windows `az` is `az.cmd`, so PowerShell routes
        # every native argument through cmd.exe, which strips any quote character
        # the value itself carries -- a corruption no caller can escape around. A
        # parameters file has no shell-quoting surface on any shell, and it carries
        # real JSON types, which the int-typed monthlyBudgetUsd param requires.
        $paramFile = Join-Path $work "main.parameters.json"
        $paramDoc = [ordered]@{
            '$schema'      = 'https://schema.management.azure.com/schemas/2019-04-01/deploymentParameters.json#'
            contentVersion = '1.0.0.0'
            parameters     = [ordered]@{
                monthlyBudgetUsd        = @{ value = [int]$MonthlyBudgetUsd }
                targetResourceGroupName = @{ value = $ResourceGroup }
                location                = @{ value = $Location }
                guardResourceGroupName  = @{ value = $GuardResourceGroup }
                notificationEmail       = @{ value = $NotificationEmail }
            }
        }
        Set-Content -LiteralPath $paramFile -Value ($paramDoc | ConvertTo-Json -Depth 6) -Encoding utf8

        Write-Step "Deploying cost guard (provisions the budget + Logic App; stops/deletes nothing now)"
        Write-Note "Azure is provisioning resources -- this can take a minute with no output."
        az deployment sub create `
            --name ("cost-guard-" + (Get-Date -Format "yyyyMMddHHmmss")) `
            --location $Location `
            --template-file (Join-Path $work "main.bicep") `
            --parameters "@$paramFile" `
            -o none
        if ($LASTEXITCODE -ne 0) { Write-Error "Cost guard deployment failed."; exit 1 }
    }
    finally {
        Remove-Item -LiteralPath $work -Recurse -Force -ErrorAction SilentlyContinue
    }

    Write-Step "Done"
    Write-Ok ("Cost guard installed in {0}. You will be emailed at 80% of budget and when it fires." -f (Show-Elapsed))
    Write-Host ""
    Write-Host "Uninstall with:  .\scripts\cost-guard.ps1 -Uninstall"
}

function Invoke-CostGuardUninstall {
    $script:StepColor = "Yellow"
    $subId = az account show --query id -o tsv

    Write-Host "============================================================" -ForegroundColor Yellow
    Write-Host " Uninstall cost guard for realestate.System" -ForegroundColor Yellow
    Write-Host "   guard group : $GuardResourceGroup (will be deleted)" -ForegroundColor Yellow
    Write-Host "   watched rg  : $ResourceGroup (left untouched)" -ForegroundColor Yellow
    Write-Host "============================================================" -ForegroundColor Yellow
    Write-Note "This removes the cost guard only. '$ResourceGroup' is NOT deleted."

    # Resolve the Logic App identity before deleting its resource group.
    $principalId = az resource show --resource-group $GuardResourceGroup --name "cost-guard-workflow" --resource-type "Microsoft.Logic/workflows" --query identity.principalId -o tsv --only-show-errors

    Write-Step "Removing budget 'cost-guard-budget'"
    $out = az consumption budget delete --budget-name "cost-guard-budget" --only-show-errors 2>&1
    if ($LASTEXITCODE -ne 0) { Write-Note "Budget removal did not succeed: $out" } else { Write-Ok "Budget removed (if it existed)." }

    if ($principalId) {
        Write-Step "Removing Contributor role assignment on '$ResourceGroup'"
        $out = az role assignment delete --assignee $principalId --role "Contributor" --scope "/subscriptions/$subId/resourceGroups/$ResourceGroup" --only-show-errors 2>&1
        if ($LASTEXITCODE -ne 0) { Write-Note "Role assignment removal did not succeed: $out" } else { Write-Ok "Role assignment removed." }
    } else {
        Write-Note "Logic App not found in '$GuardResourceGroup' -- skipping role assignment removal."
    }

    Write-Step "Deleting guard resource group '$GuardResourceGroup'"
    $exists = az group exists --name $GuardResourceGroup
    if ($exists -eq "true") {
        az group delete --name $GuardResourceGroup --yes -o none
        Write-Ok "Guard resource group deleted."
    } else {
        Write-Note "Guard resource group '$GuardResourceGroup' does not exist -- nothing to delete."
    }

    Write-Step "Done"
    Write-Ok ("Cost guard uninstalled in {0}." -f (Show-Elapsed))
}

Test-Preflight

if ($Uninstall) { Invoke-CostGuardUninstall } else { Invoke-CostGuardInstall }
