/**
 * API-key verification for the API-key providers this service stores.
 *
 * verifyApiKeyHash is the one verification path of this service: the handler
 * of each provider's internal verify route calls it (through
 * answerApiKeyVerifyRequest), and so does this service's own in-process key
 * resolution -- the lookup, the decision order and the per-key rate-limit
 * counter exist nowhere else.
 *
 * Decision order, over one equality lookup on the unique hash column that is
 * never tenant-scoped (the tenant is an output of the lookup, not an input):
 *   1. no row                          -> invalid
 *   2. the key is not active           -> invalid
 *   3. the key expired (at or before now) -> invalid
 *   4. the per-key rate limit exceeded -> rateLimited, with retryAfterSeconds
 *   5. otherwise                       -> ok
 * An invalid outcome never says which check failed. Neither the key nor its
 * hash is ever logged.
 *
 * Auto-generated by cruftfree-codegen-typescript. Do not edit manually.
 */
