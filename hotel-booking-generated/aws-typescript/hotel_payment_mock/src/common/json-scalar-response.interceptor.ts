/**
 * Global interceptor that answers a scalar REST value (a string, number or
 * boolean) as the JSON document it is, with `Content-Type: application/json`.
 *
 * Nest's Express adapter replies `res.json(value)` to an object and
 * `res.send(String(value))` to anything else, so a scalar handler return would
 * reach the wire as raw text labelled `text/html` -- disagreeing with the
 * route's OpenAPI document, with the REST route of every other language, and
 * with the serverless realization of the same declaration. The value is encoded
 * once here, for every scalar return shape of every controller.
 *
 * A route that already chose its own `Content-Type`, or already wrote its reply
 * (a binary route answering through the response object), is left untouched.
 *
 * Auto-generated by cruftfree-codegen-typescript. Do not edit manually.
 */
import {
  CallHandler,
  ExecutionContext,
  Injectable,
  NestInterceptor,
} from '@nestjs/common';
import type { Response } from 'express';
import { Observable } from 'rxjs';
import { map } from 'rxjs/operators';

const JSON_CONTENT_TYPE = 'application/json';

/** Whether *value* is a scalar Express would send as `String(value)`. */
function isScalar(value: unknown): value is string | number | boolean {
  return (
    typeof value === 'string' ||
    typeof value === 'number' ||
    typeof value === 'boolean'
  );
}

@Injectable()
export class JsonScalarResponseInterceptor implements NestInterceptor {
  intercept(context: ExecutionContext, next: CallHandler): Observable<unknown> {
    if (context.getType() !== 'http') {
      return next.handle();
    }
    return next.handle().pipe(
      map((value: unknown) => {
        if (!isScalar(value)) {
          return value;
        }
        const response = context.switchToHttp().getResponse<Response>();
        if (response.headersSent || response.getHeader('Content-Type') !== undefined) {
          return value;
        }
        response.type(JSON_CONTENT_TYPE);
        return JSON.stringify(value);
      }),
    );
  }
}
