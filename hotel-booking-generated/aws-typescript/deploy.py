LAMBDA_PIP_PLATFORM = "manylinux2014_x86_64"

#: Files and directories never included in a content hash: byte-compiled output
#: is a build artifact of the source already covered.
HASH_EXCLUDED_DIR = "__pycache__"
HASH_EXCLUDED_SUFFIX = ".pyc"

#: What an S3 lookup returns for a key that does not exist yet. Any OTHER
#: failure (an authentication error, for instance) fails loud.
OBJECT_NOT_FOUND_MARKERS = ("Not Found", "404")

#: How long a package file's download may take before the deploy fails.
FETCH_TIMEOUT_SECONDS = 60

#: A package's zip entries carry this timestamp and these permissions, so the
#: same files always zip to the same bytes -- and so to the same upload key.
ZIP_ENTRY_TIMESTAMP = (1980, 1, 1, 0, 0, 0)
ZIP_ENTRY_ATTRIBUTES = 0o644 << 16


