def upload_assets(bucket: str, region: str) -> dict[str, str]:
    """Package and upload every function package, returning each key parameter's value.

    Each package is uploaded under a key named by the digest of its zip, so an
    unchanged package is found and not uploaded again, and a changed one never
    replaces what a running function reads.

    Raises:
        DeployError: If a package could not be built or uploaded.
    """
    keys: dict[str, str] = {}
    for asset in ASSETS:
        step(f"Packaging function: {asset.name}")
        archive, digest = package_asset(asset)
        key = f"assets/{asset.name}/{digest}.zip"
        if object_exists(bucket, key, region):
            detail(f"{asset.name} unchanged ({key} is already uploaded) -- skipping upload")
        else:
            with tempfile.TemporaryDirectory() as scratch:
                local = Path(scratch) / f"{digest}.zip"
                local.write_bytes(archive)
                upload = aws(
                    "s3", "cp", str(local), f"s3://{bucket}/{key}",
                    "--sse", "aws:kms", "--region", region,
                )
            if not upload.succeeded:
                raise DeployError(
                    f"Uploading the '{asset.name}' function package to "
                    f"'s3://{bucket}/{key}' failed: {upload.output}"
                )
        keys[asset.code_key_parameter] = key
    return keys


