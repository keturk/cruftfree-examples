def build_base_image(base: BaseImageSpec, registry: str, region: str) -> None:
    """Build and push one shared base image, unless the registry already has it.

    Built with TWO tags: the bare tag every per-service Dockerfile's ``FROM``
    line already references -- loaded into the local daemon so those builds
    resolve it without a registry round-trip -- plus the registry-qualified tag,
    pushed separately so the skip check above has something to find next run.

    Local availability is part of this function's contract on BOTH paths: the
    bare ``FROM`` reference resolves against the local daemon and then the
    public hub, never against this registry, so when the registry already holds
    the tag the image is pulled and tagged bare -- otherwise a fresh deploy host
    building a changed service fails resolving its ``FROM``.

    Raises:
        DeployError: If the build, the push, the pull or the tag failed.
    """
    step(f"Building shared base image ({base.repo})")
    bare = f"{base.repo}:{base.content_hash}"
    remote = f"{registry}/{bare}"
    if ecr_tag_exists(base.repo, base.content_hash, region):
        detail(
            f"base image unchanged (tag {base.content_hash} is already in the registry) "
            f"-- skipping build and push, pulling it for the service builds"
        )
        # The explicit platform is mandatory: the base exists only for
        # CONTAINER_PLATFORM, so a host-default pull on another architecture
        # fails resolving the manifest.
        pull = docker("pull", "--platform", CONTAINER_PLATFORM, remote, capture=False)
        if not pull.succeeded:
            raise DeployError(
                f"Pulling the shared base image '{remote}' failed (docker exited "
                f"{pull.returncode}). Every service image is FROM '{bare}'."
            )
        tagged = docker("tag", remote, bare)
        if not tagged.succeeded:
            raise DeployError(
                f"Tagging the shared base image as '{bare}' failed -- every service "
                f"Dockerfile's FROM line resolves exactly that reference. docker "
                f"exited {tagged.returncode}."
            )
        return
    build = docker(
        "buildx", "build", "--platform", CONTAINER_PLATFORM,
        "-t", bare,
        "-t", remote,
        "-f", base.dockerfile_path, base.build_context, "--load",
        capture=False,
    )
    if not build.succeeded:
        raise DeployError(
            f"Building the shared base image '{bare}' failed "
            f"(docker exited {build.returncode}). Review the build output above."
        )
    push = docker("push", remote, capture=False)
    if not push.succeeded:
        raise DeployError(
            f"Pushing the shared base image '{bare}' failed "
            f"(docker exited {push.returncode})."
        )


def base_image_contexts(registry: str) -> list[str]:
    """The ``--build-context`` arguments that resolve each service ``FROM`` from the registry.

    A service Dockerfile's ``FROM`` names the bare base tag. A builder that runs
    in a container never reads the engine's image store, so it would resolve that
    name against a public registry and fail on a pull of an image that was never
    published. Each bare tag is therefore bound to the pushed, registry-qualified
    image, which every builder driver resolves the same way. A base the
    Dockerfile does not name is ignored by the build.
    """
    contexts: list[str] = []
    for base in BASE_IMAGES:
        bare = f"{base.repo}:{base.content_hash}"
        contexts.extend(["--build-context", f"{bare}=docker-image://{registry}/{bare}"])
    return contexts


def build_image(image: ImageSpec, registry: str, region: str) -> str:
    """Build and push one image, skipping when the registry already holds its tag.

    Returns:
        The image's resolved content-hash tag.

    Raises:
        DeployError: If the build failed.
    """
    kind = "Lambda image" if image.single_manifest else "service image"
    step(f"Building {kind}: {image.name}")
    tag = deploy_content_hash(image.hash_inputs)
    if ecr_tag_exists(image.repo, tag, region):
        detail(
            f"{image.name} unchanged (tag {tag} is already in the registry) -- "
            f"skipping build and push"
        )
        return tag
    argv = ["buildx", "build", "--platform", CONTAINER_PLATFORM, *base_image_contexts(registry)]
    if image.single_manifest:
        argv.append("--provenance=false")
    argv.extend([
        "-t", f"{registry}/{image.repo}:{tag}",
        "-f", image.dockerfile_path,
        image.build_context,
        "--push",
    ])
    build = docker(*argv, capture=False)
    if not build.succeeded:
        raise DeployError(
            f"Building the image for '{image.name}' failed (docker exited "
            f"{build.returncode}). Review the build output above."
        )
    return tag


def supply_images(registry: str, region: str) -> dict[str, str]:
    """Build and push every image, returning each stack parameter's resolved tag.

    The base image is built once, before any image that depends on it. Each
    resolved tag is passed to the stacks as a parameter override -- every
    compute surface reads its image's tag back from there, never a mutable
    default.
    """
    build_base_images(registry, region)
    return {
        image.context_key: build_image(image, registry, region)
        for image in (*SERVICE_IMAGES, *LAMBDA_IMAGES)
    }


