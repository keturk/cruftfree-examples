class CommandResult(NamedTuple):
    """Outcome of one external command."""

    returncode: int
    stdout: str
    stderr: str

    @property
    def succeeded(self) -> bool:
        """True when the command exited zero."""
        return self.returncode == 0

    @property
    def output(self) -> str:
        """Combined stdout and stderr, for error reporting."""
        return "\n".join(part for part in (self.stdout, self.stderr) if part).strip()


def resolve_executable(name: str, install_hint: str) -> str:
    """Return the absolute path of an external command, or fail loud.

    The absolute path matters on Windows, where several of these tools are
    ``.cmd`` shims: a bare name is resolved through PATHEXT only by a shell,
    which this script deliberately does not use.

    Raises:
        DeployError: If the command is not on PATH.
    """
    resolved = shutil.which(name)
    if resolved is None:
        raise DeployError(f"'{name}' not found. {install_hint}")
    return resolved


def run(argv: Sequence[str], *, capture: bool = True) -> CommandResult:
    """Run an external command. Never raises on a nonzero exit.

    Args:
        argv: Full argument vector, executable path first.
        capture: When False the command's output goes straight to the console,
            which is what a long build or deployment needs.
    """
    completed = subprocess.run(
        list(argv),
        capture_output=capture,
        text=True,
        encoding="utf-8",
        errors="replace",
        cwd=PROJECT_ROOT,
    )
    return CommandResult(
        returncode=completed.returncode,
        stdout=(completed.stdout or "").strip() if capture else "",
        stderr=(completed.stderr or "").strip() if capture else "",
    )


def aws(*args: str, capture: bool = True) -> CommandResult:
    """Run one ``aws`` invocation."""
