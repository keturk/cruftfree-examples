def _target_health_states(target_group_arn: str) -> list[str] | None:
    """The ``TargetHealth.State`` of every target registered in one target group.

    Returns:
        The state list (possibly empty while no target is registered yet), or
        ``None`` when the describe call itself failed or returned something
        other than a JSON list of strings.
    """
    result = aws(
        "elbv2", "describe-target-health",
        "--target-group-arn", target_group_arn,
        "--query", "TargetHealthDescriptions[].TargetHealth.State",
        "--output", "json",
    )
    if not result.succeeded:
        return None
    try:
        states = json.loads(result.stdout or "[]")
    except json.JSONDecodeError:
        return None
    if not isinstance(states, list) or not all(isinstance(state, str) for state in states):
        return None
    return states


def poll_target_group_health(target_group_arn: str, timeout_seconds: int) -> tuple[bool, str]:
    """Poll one load-balancer target group until every target is healthy.

    A target group with no registered target is not healthy: the ECS service
    has not placed a task behind the load balancer yet, so nothing can serve
    traffic. A target group whose every target reports ``healthy`` has passed
    the load balancer's own health check -- the readiness route the service's
    language declares -- which is exactly the condition under which the load
    balancer routes requests to it.

    Args:
        target_group_arn: The target group to describe.
        timeout_seconds: Total budget to keep retrying.

    Returns:
        ``(True, "healthy (<n> target(s))")`` once every target is healthy
        within budget; otherwise ``(False, "<last observed states>")``.
    """
    deadline = time.monotonic() + timeout_seconds
    last_detail = "target group not yet describable"
    while True:
        states = _target_health_states(target_group_arn)
        if states is None:
            last_detail = "describe-target-health failed"
        elif not states:
            last_detail = "no target registered"
        elif all(state == "healthy" for state in states):
            return True, f"healthy ({len(states)} target(s))"
        else:
            last_detail = "target states: " + ", ".join(sorted(states))
        if time.monotonic() >= deadline:
            return False, last_detail
        time.sleep(VERIFY_POLL_INTERVAL_SECONDS)


def _resolve_target_group_arn(spec: VerifySpec) -> str | None:
    """Read the target-group ARN ``CfnOutput`` off *spec*'s stack."""
    return _resolve_stack_output(spec.stack_name, spec.output_key)


def verify_deployment() -> None:
    """Prove every load-balanced service is actually healthy behind its
    target group after the stack deployments report success.

    A CloudFormation ``UPDATE_COMPLETE`` proves the infrastructure converged,
    not that the application inside it is live. Fails loud with a nonzero
    process exit (via ``DeployError``) naming every service whose target
    group never reported every target healthy within budget.

    Raises:
        DeployError: If any service is not healthy within
            DEFAULT_VERIFY_APP_TIMEOUT_SECONDS, naming every failing service
            with its last observed status.
    """
    if not VERIFY_SPECS:
        return
    step("Verifying deployment health")
    failures: list[str] = []
    for spec in VERIFY_SPECS:
        target_group_arn = _resolve_target_group_arn(spec)
        if target_group_arn is None:
            failures.append(f"{spec.service_name}: could not resolve target-group ARN from stack outputs")
            detail(f"{spec.service_name}: FAILED -- no resolvable output")
            continue
        healthy, status_detail = poll_target_group_health(
            target_group_arn, DEFAULT_VERIFY_APP_TIMEOUT_SECONDS
        )
        if healthy:
            detail(f"{spec.service_name}: {status_detail}")
        else:
            failures.append(f"{spec.service_name}: {status_detail}")
            detail(f"{spec.service_name}: FAILED -- {status_detail}")
    if failures:
        raise DeployError(
            f"Post-deploy verification FAILED for {len(failures)} service(s):\n  "
            + "\n  ".join(failures)
        )
    step("Done")


