def _schema_stack_output(stack_name: str, output_key: str, region: str, block: str) -> str:
    """One output of a deployed stack that a read of *block* needs.

    Raises:
        DeployError: If the stack is not deployed or has no such output.
    """
    value = _resolve_stack_output(stack_name, output_key, region=region)
    if value is None:
        raise DeployError(
            f"Block '{block}' cannot be read: stack '{stack_name}' has no output "
            f"'{output_key}' in region {region}. The output exists once the stack "
            f"is deployed: run '{VERB_DEPLOY}' first."
        )
    return value


def _ecs_json(argv: Sequence[str], what: str, block: str) -> dict[str, object]:
    """The JSON object one ``aws ecs`` call printed.

    Raises:
        DeployError: If the call failed or printed something other than an object.
    """
    result = aws(*argv, "--output", "json")
    if not result.succeeded:
        raise DeployError(
            f"{what} of block '{block}' failed (aws exited {result.returncode}): "
            f"{result.output or 'no output'}"
        )
    try:
        parsed = json.loads(result.stdout)
    except ValueError as error:
        raise DeployError(
            f"{what} of block '{block}' printed output this script cannot read ({error})."
        ) from error
    if not isinstance(parsed, dict):
        raise DeployError(f"{what} of block '{block}' printed {parsed!r}, not a JSON object.")
    return parsed


def _copy_run_file(source: str, destination: str, region: str, block: str) -> None:
    """Copy one file of a run between this machine and the run store, as bytes.

    Raises:
        DeployError: If the copy failed.
    """
    copied = aws("s3", "cp", source, destination, "--only-show-errors", "--region", region)
    if not copied.succeeded:
        raise DeployError(
            f"Copying '{source}' to '{destination}' for block '{block}' failed (aws "
            f"exited {copied.returncode}): {copied.output or 'no output'}"
        )


def _start_schema_task(
    task: SchemaTaskRun, schema_run: SchemaRun, region: str, workload: str
) -> str:
    """Start one run of *task* for *workload* and return the started task's ARN.

    The copy containers get the run id and the client the run's arguments as
    container overrides; the task runs in its own security group on the
    stack's private subnets, with no public address, started by
    ``<workload>-<run id>`` so ECS names what each run was for.

    Raises:
        DeployError: If an output is missing or ECS did not start the task.
    """
    block = schema_run.block
    task_definition = _schema_stack_output(
        task.stack_name, task.task_definition_output, region, block
    )
    security_group = _schema_stack_output(
        task.stack_name, task.security_group_output, region, block
    )
    subnets = _schema_stack_output(task.stack_name, SCHEMA_TASK_SUBNETS_OUTPUT, region, block)
    run_id = [{"name": SCHEMA_RUN_ID_VARIABLE, "value": schema_run.run_id}]
    overrides = {
        "containerOverrides": [
            {"name": SCHEMA_TASK_COPY_IN_CONTAINER, "environment": run_id},
            {
                "name": SCHEMA_TASK_CLIENT_CONTAINER,
                "command": [*task.client_command, *schema_run.client_arguments],
            },
            {"name": SCHEMA_TASK_COPY_OUT_CONTAINER, "environment": run_id},
        ]
    }
    network = {
        "awsvpcConfiguration": {
            "subnets": [subnet for subnet in subnets.split(",") if subnet],
            "securityGroups": [security_group],
            "assignPublicIp": "DISABLED",
        }
    }
    started = _ecs_json(
        (
            "ecs", "run-task",
            "--cluster", SCHEMA_TASK_CLUSTER,
            "--task-definition", task_definition,
            "--launch-type", "FARGATE",
            "--count", "1",
            "--started-by", f"{workload}-{schema_run.run_id}",
            "--network-configuration", json.dumps(network),
            "--overrides", json.dumps(overrides),
            "--region", region,
        ),
        "Starting the schema task",
        block,
    )
    tasks = started.get("tasks")
    if (
        started.get("failures")
        or not isinstance(tasks, list)
        or len(tasks) != 1
        or not isinstance(tasks[0], dict)
        or not isinstance(tasks[0].get("taskArn"), str)
    ):
        raise DeployError(
            f"ECS did not start the schema task of block '{block}': "
            f"{started.get('failures') or started}."
        )
    return str(tasks[0]["taskArn"])


def _stop_schema_task(task_arn: str, region: str, block: str, workload: str) -> str:
    """Stop a schema task the deploy no longer waits for; what happened, for a message."""
    stopped = aws(
        "ecs", "stop-task",
        "--cluster", SCHEMA_TASK_CLUSTER,
        "--task", task_arn,
        "--reason", f"{workload} of block {block} stopped waiting for it",
        "--region", region,
    )
    if stopped.succeeded:
        return "was stopped"
    return (
        f"could not be stopped ({stopped.output or 'no output'}): stop it with "
        f"'aws ecs stop-task --cluster {SCHEMA_TASK_CLUSTER} --task {task_arn}'"
    )


def _await_schema_task(task_arn: str, region: str, block: str) -> bool:
    """Wait for the task to stop, at most SCHEMA_RUN_WAIT_SECONDS.

    ``aws ecs wait tasks-stopped`` polls for a bounded number of attempts; it is
    run again while the deploy's own wait has time left.

    Returns:
        Whether the task stopped within the wait.

    Raises:
        DeployError: If the waiter failed for any reason but running out of attempts.
    """
    deadline = time.monotonic() + SCHEMA_RUN_WAIT_SECONDS
    argv = [
        resolve_executable("aws", "Install the AWS CLI."),
        "ecs", "wait", "tasks-stopped",
        "--cluster", SCHEMA_TASK_CLUSTER,
        "--tasks", task_arn,
        "--region", region,
    ]
    while (remaining := deadline - time.monotonic()) > 0:
        try:
            waited = subprocess.run(
                argv,
                capture_output=True,
                text=True,
                encoding="utf-8",
                errors="replace",
                cwd=PROJECT_ROOT,
                check=False,
                timeout=remaining,
            )
        except subprocess.TimeoutExpired:
            return False
        if waited.returncode == 0:
            return True
        if WAITER_EXHAUSTED_MARKER not in waited.stderr:
            raise DeployError(
                f"Waiting for the schema task of block '{block}' failed (aws exited "
                f"{waited.returncode}): {(waited.stderr or waited.stdout).strip() or 'no output'}"
            )
    return False


def _require_files_copied_out(task_arn: str, region: str, block: str) -> None:
    """Fail unless the stopped task's copy-out container uploaded the client's files.

    Raises:
        DeployError: Naming why the task stopped and each container's exit.
    """
    described = _ecs_json(
        (
            "ecs", "describe-tasks",
            "--cluster", SCHEMA_TASK_CLUSTER,
            "--tasks", task_arn,
            "--region", region,
        ),
        "Reading the outcome of the schema task",
        block,
    )
    tasks = described.get("tasks")
    if not isinstance(tasks, list) or len(tasks) != 1 or not isinstance(tasks[0], dict):
        raise DeployError(
            f"ECS did not describe the schema task '{task_arn}' of block '{block}': "
            f"{described.get('failures') or described}."
        )
    listed = tasks[0].get("containers")
    containers = {
        str(container.get("name")): container
        for container in (listed if isinstance(listed, list) else [])
        if isinstance(container, dict)
    }
    if containers.get(SCHEMA_TASK_COPY_OUT_CONTAINER, {}).get("exitCode") == 0:
        return
    exits = "; ".join(
        f"{name} exited {container.get('exitCode')} {container.get('reason') or ''}".rstrip()
        for name, container in sorted(containers.items())
    )
    raise DeployError(
        f"The schema task of block '{block}' did not bring the client's files back: "
        f"{tasks[0].get('stoppedReason') or 'ECS gave no reason'} ({exits or 'no containers'}). "
        f"Its containers' logs are in the task's log group."
    )


def _run_schema_task(
    task: SchemaTaskRun, schema_run: SchemaRun, region: str, workload: str
) -> None:
    """Start *task* for *schema_run*, wait for it, and stop it if the wait ends first.

    Raises:
        DeployError: If the task did not start, outlived the wait, or did not
            upload the client's files.
    """
    block = schema_run.block
    task_arn = _start_schema_task(task, schema_run, region, workload)
    print(f"Started schema task {task_arn}.", file=sys.stderr)
    try:
        stopped = _await_schema_task(task_arn, region, block)
    except BaseException:
        outcome = _stop_schema_task(task_arn, region, block, workload)
        print(f"The schema task '{task_arn}' of block '{block}' {outcome}.", file=sys.stderr)
        raise
    if not stopped:
        outcome = _stop_schema_task(task_arn, region, block, workload)
        raise DeployError(
            f"The schema task of block '{block}' was still running after "
            f"{SCHEMA_RUN_WAIT_SECONDS} seconds; task '{task_arn}' {outcome}."
        )
    _require_files_copied_out(task_arn, region, block)


def _delete_run_files(
    bucket: str, prefix: str, run_files: Sequence[str], region: str
) -> list[str]:
    """Delete every file a run may have left under *prefix*; the keys that remain.

    Each key is deleted by name: the deploy holds no right to list the run store.
    """
    left: list[str] = []
    for name in (*run_files, *SCHEMA_RUN_RESULT_FILES):
        key = f"{prefix}{name}"
        deleted = aws(
            "s3api", "delete-object", "--bucket", bucket, "--key", key, "--region", region
        )
        if not deleted.succeeded:
            left.append(key)
    return left


def ecs_schema_channel(workload: str) -> SchemaChannel:
    """The channel running a run's catalog client once, as its block's schema task.

    *workload* names what the runs are for -- the schema verb this script
    carries out -- and, with each run's id, who ECS records as starting the
    task and why a task the deploy stopped waiting for was stopped. The run
    store prefix is the block's, whatever the verb.

    The task's run files (the input, and the CA bundle of a database AWS
    provisions) are uploaded under the run's prefix of the run store, the task
    copies them in, runs the client under its credential wrapper and ``timeout`` and
    copies its standard output, standard error and exit status back, and the
    deploy downloads those three files as they are. No file's content travels
    as an argument, and every file of the run is deleted from the run store,
    whatever happened.

    The AWS CLI's credentials are checked first, on every run, so a read that
    'deploy --plan' starts fails on them exactly as 'schema-read' does.
    """

    def run_task(schema_run: SchemaRun) -> None:
        """Run *schema_run*'s catalog client once and bring back what it left.

        Raises:
            DeployError: If the AWS CLI has no usable credentials, the run could
                not be carried out, or its files could not be deleted after a run
                that was.
        """
        require_credentials()
        task = SCHEMA_TASK_RUNS[schema_run.block]
        region = resolve_region()
        bucket = _schema_stack_output(
            RUN_STORE_STACK, RUN_STORE_BUCKET_OUTPUT, region, schema_run.block
        )
        prefix = f"{task.run_store_prefix}{schema_run.run_id}/"
        location = f"s3://{bucket}/{prefix}"
        if SCHEMA_CA_BUNDLE_FILE in task.run_files:
            fetch_package_file(SCHEMA_CA_BUNDLE_URL, schema_run.directory / SCHEMA_CA_BUNDLE_FILE)
        carried_out = False
        try:
            for name in task.run_files:
                _copy_run_file(
                    str(schema_run.directory / name), f"{location}{name}", region, schema_run.block
                )
            _run_schema_task(task, schema_run, region, workload)
            for name in SCHEMA_RUN_RESULT_FILES:
                _copy_run_file(
                    f"{location}{name}", str(schema_run.directory / name), region, schema_run.block
                )
            carried_out = True
        finally:
            left = _delete_run_files(bucket, prefix, task.run_files, region)
            if left:
                message = (
                    f"The run store '{bucket}' still holds {left} of the {workload} run "
                    f"of block '{schema_run.block}': delete them, they hold the run's "
                    f"input and the client's output."
                )
                if carried_out:
                    raise DeployError(message)
                print(f"ERROR: {message}", file=sys.stderr)

    return run_task


