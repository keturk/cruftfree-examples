ClientSiteStage = Callable[[str, str], None]

#: A platform's publish stage for one web target: called with the app key, the target,
#: and the deploy-supplied build inputs its build takes (`ClientStepRow.build_inputs`).
ClientSitePublish = Callable[[str, str, Mapping[str, str]], None]


class ClientDeployStepError(RuntimeError):
    """The clients step refused to go on; the message names what failed and how to clear it."""


class ClientStepCompose(TypedDict):
    """One deployed runtime config to compose; paths are relative to the tree's root.

    Attributes:
        name: ``<app key>-<target>``, for log lines.
        generated: The generated runtime config.
        resolved: The deployed copy.
        registration: The registration the app composes from.
        kind: The client kind the target runs as.
        identity: Whether the deployed copy carries the kind's client record.
        web_origin: Whether the deployed copy carries the registration's web origin.
    """

    name: str
    generated: str
    resolved: str
    registration: str
    kind: str
    identity: bool
    web_origin: bool


class ClientStepNativeBuild(TypedDict):
    """How one (app, native target) is built: names and public identifiers only.

    Attributes:
        script: The target's build script, relative to the tree's root.
        runtime_config_parameter: The script's parameter naming the deployed runtime config.
        build_number_parameter: The script's parameter carrying the store build number.
        platform_parameter: The script's parameter naming what it builds.
        platforms: The mobile platforms the app declares signing for.
        android_signing: ``(variable the build reads, variable the operator sets)`` pairs.
        ios_team_variable: The variable the iOS development team reaches the build in.
        ios_team: The iOS development team, a public identifier, or ``None``.
        links_host_variable: The variable the links host reaches the build in.
        links_host: The host the app's links verify against, or ``None``.
    """

    script: str
    runtime_config_parameter: str
    build_number_parameter: str
    platform_parameter: str
    platforms: tuple[str, ...]
    android_signing: tuple[tuple[str, str], ...]
    ios_team_variable: str
    ios_team: str | None
    links_host_variable: str
    links_host: str | None


class ClientStepRow(TypedDict):
    """What releasing one (own app, client target) does.

    Attributes:
        app_key: The app's key.
        target: The client target.
        web: Whether the target publishes a web bundle.
        compose: The runtime config to compose, or ``None`` for a prerendered app.
        native_build: The native build, or ``None`` when the row has none to run.
        api_document: The API document the app's client calls, relative to the tree's
            root, or ``None`` for a prerendered app.
        build_inputs: The deploy-supplied build inputs the row's build takes, by name
            (`API_ORIGIN_INPUT`, `BUILD_COMMIT_INPUT`); empty when it takes none.
    """

    app_key: str
    target: str
    web: bool
    compose: ClientStepCompose | None
    native_build: ClientStepNativeBuild | None
    api_document: str | None
    build_inputs: tuple[str, ...]


class ClientStepPlan(TypedDict):
    """Every row of a tree's client release, and the version the tree was built for.

    Attributes:
        tree_version: The version a client contract must carry.
        rows: One per (own app, client target), in declaration order.
    """

    tree_version: str
    rows: tuple[ClientStepRow, ...]


class ClientStepRuntime(NamedTuple):
    """What the host gives the step, which it cannot import.

    Attributes:
        read_contract: `client_runtime_resolution.read_client_contract`.
        compose: `client_runtime_resolution.compose_client_runtime_config`.
        verify_release: `client_api_verification.verify_client_release`: every way the
            services the contract names differ from what the release's clients call,
            given the contract, each (app key, registration, kind) that signs in, and
            each app's consumed API document by app key.
        log: Where a progress line goes. It never receives a signing value.
    """

    read_contract: Callable[[Path], ClientStepContract]
    compose: Callable[..., None]
    verify_release: Callable[
        [ClientStepContract, Sequence[tuple[str, str, str]], Mapping[str, object]], tuple[str, ...]
    ]
    log: Callable[[str], None]


class _RefuseRedirect(urllib.request.HTTPRedirectHandler):
    """Treat a redirect as a failure: its target is an origin the contract never named."""

    def redirect_request(
        self,
        req: urllib.request.Request,
        fp: IO[bytes],
        code: int,
        msg: str,
        headers: http.client.HTTPMessage,
        newurl: str,
    ) -> None:
        """Follow nothing, so urllib raises the 3xx as an ``HTTPError``."""


def client_contract_source(
    own_contract: Path, given: str | None, scope: str | None, *, has_backend_scope: bool
) -> Path:
    """Where this deploy reads its client contract from, or refuse the command.

    A front door with a backend scope reads the contract its own deploy wrote; one
    without reads the file the operator names. Touches no file, so a front door
    calls it before any scope runs and a bad command stops before anything happens.

    Args:
        own_contract: The tree's own contract (``client_runtime_paths.client_contract_path``).
        given: The value of ``--client-contract``, or ``None`` when absent.
        scope: The value of ``--scope``, or ``None`` when absent.
        has_backend_scope: Whether this front door deploys a backend.

    Returns:
        The contract's path.

    Raises:
        ClientDeployStepError: The flag is given where the tree has its own contract,
            is missing or empty where it has none, or the backend scope is asked of
            a tree with no backend.
    """
    if has_backend_scope:
        if given is not None:
            raise ClientDeployStepError(
                f"{CLIENT_CONTRACT_FLAG} is refused here: this deploy reads the contract its "
                f"own backend scope wrote at '{own_contract}'. Remove the flag."
            )
        return own_contract
    if scope == BACKEND_SCOPE:
        raise ClientDeployStepError(
            f"The '{BACKEND_SCOPE}' scope is refused here: this tree deploys clients only and "
            "has no backend to run. Deploy the backend from its own tree."
        )
    if not given:
        raise ClientDeployStepError(
            f"{CLIENT_CONTRACT_FLAG} PATH is required: this tree has no backend, so its clients "
            "compose from the contract the backend's deploy published. Pass that file's path."
        )
    return Path(given)


def _contract_section(parent: Mapping[str, object], key: str) -> dict[str, object]:
    """*parent*'s *key* as a JSON object, or fail naming it."""
    section = parent[key]
    if not isinstance(section, dict):
        raise ClientDeployStepError(
            f"Client contract member '{key}' is not a JSON object. Use the file the backend's "
            "deploy published, unchanged."
        )
    return section


def _require_tree_version(
    plan: ClientStepPlan, contract: ClientStepContract, contract_path: Path
) -> None:
    """Fail unless the contract is for the backend version this tree was built for."""
    system = _contract_section(contract, CONTRACT_SYSTEM_KEY)
    published = system[CONTRACT_SYSTEM_VERSION_KEY]
    if published != plan["tree_version"]:
        raise ClientDeployStepError(
            f"Client contract '{contract_path}' states {CONTRACT_SYSTEM_KEY}."
            f"{CONTRACT_SYSTEM_VERSION_KEY} '{published}' for system "
            f"'{system[CONTRACT_SYSTEM_NAME_KEY]}', but this tree was built for version "
            f"'{plan['tree_version']}'. No client was composed or published. Deploy the backend "
            "version this tree was built for, or regenerate the tree against the deployed one."
        )


def _registration_web_origin(contract: ClientStepContract, registration: str) -> str | None:
    """The web origin the contract states for *registration*, or ``None`` when it states none."""
    registrations = _contract_section(contract, CONTRACT_REGISTRATIONS_KEY)
    if registration not in registrations:
        return None
    entry = _contract_section(registrations, registration)
    if CONTRACT_WEB_ORIGIN_KEY not in entry:
        return None
    return str(entry[CONTRACT_WEB_ORIGIN_KEY])


def _require_links_host(row: ClientStepRow, contract: ClientStepContract) -> None:
    """Fail unless *row*'s native links verify against its registration's web origin."""
    build, compose = row["native_build"], row["compose"]
    if build is None or compose is None or build["links_host"] is None:
        return
    origin = _registration_web_origin(contract, compose["registration"])
    if origin is None or urlsplit(origin).hostname != build["links_host"]:
        raise ClientDeployStepError(
            f"App '{row['app_key']}' ({row['target']}) verifies its links against host "
            f"'{build['links_host']}', but registration '{compose['registration']}' states "
            f"{CONTRACT_WEB_ORIGIN_KEY} '{origin}' in the client contract. No client was composed "
            "or published. Declare the same web origin on the app and on the backend's "
            "registration, then redeploy the backend."
        )


def _dead_gateway(api_base_url: str, reason: object) -> ClientDeployStepError:
    """The refusal of a gateway that did not answer."""
    return ClientDeployStepError(
        f"The backend at {CONTRACT_API_BASE_URL_KEY} '{api_base_url}' did not answer its gateway "
        f"liveness route '{GATEWAY_LIVENESS_PATH}': {reason}. No client was composed or "
        "published. Deploy the backend first, or check the contract is the one it published."
    )


def _require_live_gateway(contract: ClientStepContract) -> None:
    """Fail unless the gateway answers its liveness route itself, with no redirect."""
    backend = _contract_section(contract, CONTRACT_BACKEND_KEY)
    api_base_url = str(backend[CONTRACT_API_BASE_URL_KEY])
    opener = urllib.request.build_opener(_RefuseRedirect)
    try:
        with opener.open(
            f"{api_base_url}{GATEWAY_LIVENESS_PATH}", timeout=_LIVENESS_TIMEOUT_SECONDS
        ) as response:
            response.read()
    except urllib.error.HTTPError as exc:
        exc.close()
        raise _dead_gateway(api_base_url, exc) from exc
    except (OSError, http.client.HTTPException) as exc:
        raise _dead_gateway(api_base_url, exc) from exc


def short_build_commit(raw: str | None) -> str:
    """The value of `BUILD_COMMIT_INPUT` for the commit *raw* names: 7 to 40 hexadecimal digits,
    in either case, lowered and cut to `BUILD_COMMIT_SHORT_LENGTH`.

    Raises:
        ValueError: *raw* is missing, empty, or anything but 7 to 40 hexadecimal digits.
    """
    if raw is None or raw == "":
        raise ValueError(
            f"{BUILD_COMMIT_INPUT} is required to build an app that reads Build.commit and is not set. "
            "Fix: deploy from the checkout the tree was generated in (git rev-parse HEAD)."
        )
    lowered = raw.lower()
    if BUILD_COMMIT_PATTERN.fullmatch(lowered) is None:
        raise ValueError(
            f"{BUILD_COMMIT_INPUT} must be {BUILD_COMMIT_SHORT_LENGTH} to {BUILD_COMMIT_MAX_LENGTH} "
            f"hexadecimal digits; got {raw!r}."
        )
    return lowered[:BUILD_COMMIT_SHORT_LENGTH]


def deploying_commit(tree_root: Path) -> str:
    """The commit the checkout holding *tree_root* is at, as `BUILD_COMMIT_INPUT` carries it.

    Raises:
        ClientDeployStepError: `git` is not on PATH, *tree_root* is in no checkout, or what
            it reports is not a commit.
    """
    if shutil.which(GIT_HEAD_COMMAND[0]) is None:
        raise ClientDeployStepError(
            f"An app of this tree reads Build.commit, and reading the commit needs "
            f"'{GIT_HEAD_COMMAND[0]}', which is not on PATH. Nothing was composed or published. "
            "Install it, then rerun."
        )
    result = subprocess.run(
        list(GIT_HEAD_COMMAND), cwd=tree_root, capture_output=True, text=True, check=False
    )
    if result.returncode != 0:
        raise ClientDeployStepError(
            f"An app of this tree reads Build.commit, but '{' '.join(GIT_HEAD_COMMAND)}' failed "
            f"(exit {result.returncode}) in '{tree_root}': {result.stderr.strip()}. Nothing was "
            "composed or published. Deploy from the checkout the tree is in."
        )
    try:
        return short_build_commit(result.stdout.strip())
    except ValueError as exc:
        raise ClientDeployStepError(f"{exc} Nothing was composed or published.") from exc


def _required_commit(plan: ClientStepPlan, tree_root: Path) -> str | None:
    """The deploying commit when a row of *plan* takes it, else ``None``."""
    if not any(BUILD_COMMIT_INPUT in row["build_inputs"] for row in plan["rows"]):
        return None
    return deploying_commit(tree_root)


def supplied_build_inputs(
    plan: ClientStepPlan, contract: ClientStepContract, commit: str | None
) -> dict[tuple[str, str], dict[str, str]]:
    """The deploy-supplied build inputs of each row of *plan*, by (app key, target).

    Args:
        plan: The tree's client release.
        contract: The checked contract; `API_ORIGIN_INPUT` is its `backend.apiBaseUrl`.
        commit: The deploying commit (:func:`deploying_commit`), or ``None`` when no row
            takes it.

    Returns:
        Exactly the inputs each row names, and nothing else.

    Raises:
        ClientDeployStepError: A row names an input the step does not supply, or takes the
            commit while none was read.
    """
    backend = _contract_section(contract, CONTRACT_BACKEND_KEY)
    known: dict[str, str | None] = {
        API_ORIGIN_INPUT: str(backend[CONTRACT_API_BASE_URL_KEY]),
        BUILD_COMMIT_INPUT: commit,
    }
    supplied: dict[tuple[str, str], dict[str, str]] = {}
    for row in plan["rows"]:
        inputs: dict[str, str] = {}
        for name in row["build_inputs"]:
            value = known.get(name)
            if value is None:
                raise ClientDeployStepError(
                    f"App '{row['app_key']}' ({row['target']}) builds with input '{name}', which "
                    f"this step does not supply (it supplies {sorted(known)}). Regenerate the tree."
                )
            inputs[name] = value
        supplied[(row["app_key"], row["target"])] = inputs
    return supplied


def _signing_in_clients(plan: ClientStepPlan) -> tuple[tuple[str, str, str], ...]:
    """Each (app key, registration, kind) of *plan* whose deployed copy signs users in."""
    uses = (
        (row["app_key"], compose["registration"], compose["kind"])
        for row in plan["rows"]
        if (compose := row["compose"]) is not None and compose["identity"]
    )
    return tuple(dict.fromkeys(uses))


def _consumed_api_documents(plan: ClientStepPlan, tree_root: Path) -> dict[str, object]:
    """Each app's consumed API document under *tree_root*, by app key, as parsed JSON.

    Raises:
        ClientDeployStepError: Two rows of one app name different documents, or a
            document is absent or not JSON, naming it.
    """
    paths: dict[str, str] = {}
    for row in plan["rows"]:
        relative = row["api_document"]
        if relative is None:
            continue
        known = paths.setdefault(row["app_key"], relative)
        if known != relative:
            raise ClientDeployStepError(
                f"App '{row['app_key']}' has release rows naming two API documents, '{known}' and "
                f"'{relative}'. No client was composed or published. Regenerate the tree."
            )
    documents: dict[str, object] = {}
    for app_key, relative in paths.items():
        path = tree_root / relative
        try:
            documents[app_key] = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            raise ClientDeployStepError(
                f"The API document of app '{app_key}' at '{path}' could not be read: {exc}. No "
                "client was composed or published. Regenerate the tree."
            ) from exc
    return documents


def _require_release_matches(
    plan: ClientStepPlan, tree_root: Path, contract: ClientStepContract, runtime: ClientStepRuntime
) -> None:
    """Fail unless the release verifier finds no difference, naming every one it finds."""
    differences = runtime.verify_release(
        contract, _signing_in_clients(plan), _consumed_api_documents(plan, tree_root)
    )
    if differences:
        listed = "".join(f"\n  - {difference}" for difference in differences)
        raise ClientDeployStepError(
            f"The services the client contract names differ from what this release's clients "
            f"call:{listed}\nNo client was composed or published."
        )


def verify_client_contract(
    plan: ClientStepPlan, tree_root: Path, contract_path: Path, runtime: ClientStepRuntime
) -> ClientStepContract:
    """Read the contract at *contract_path* and prove the backend it names is this tree's.

    Args:
        plan: The tree's client release.
        tree_root: The generated project's root, which holds each app's API document.
        contract_path: The contract (:func:`client_contract_source`).
        runtime: The host's reader, release verifier and log.

    Returns:
        The contract, checked.

    Raises:
        ClientDeployStepError: The version differs, a native app's links host is not its
            registration's web origin, the gateway does not answer, an app's API document
            is unreadable, or the release verifier found a difference.
        ClientRuntimeResolutionError: The file is absent or is not a well-formed contract.
    """
    contract = runtime.read_contract(contract_path)
    _require_tree_version(plan, contract, contract_path)
    for row in plan["rows"]:
        _require_links_host(row, contract)
    _require_live_gateway(contract)
    _require_release_matches(plan, tree_root, contract, runtime)
    runtime.log(
        f"client contract '{contract_path}' matches this tree; the gateway answers, every "
        "identity provider states the contract's issuer, and the served API holds every "
        "operation the apps call"
    )
    return contract


def _compose_rows(
    plan: ClientStepPlan,
    tree_root: Path,
    contract: ClientStepContract,
    runtime: ClientStepRuntime,
    output_root: Path,
) -> None:
    """Compose every row's deployed runtime config under *output_root*."""
    for row in plan["rows"]:
        compose = row["compose"]
        if compose is None:
            continue
        runtime.compose(
            tree_root / compose["generated"],
            contract,
            compose["registration"],
            compose["kind"],
            output_root / compose["resolved"],
            identity=compose["identity"],
            web_origin=compose["web_origin"],
        )
        runtime.log(f"{compose['name']}: {compose['resolved']}")


def prepare_client_configs(
    plan: ClientStepPlan,
    tree_root: Path,
    contract_path: Path,
    runtime: ClientStepRuntime,
    *,
    check_only: bool,
) -> ClientStepContract:
    """Verify the contract, then compose every row's deployed runtime config.

    Args:
        plan: The tree's client release.
        tree_root: The generated project's root.
        contract_path: The contract (:func:`client_contract_source`).
        runtime: The host's reader, composer, release verifier and log.
        check_only: Compose into a scratch directory that is then removed, so every
            check and every composition runs and the tree is left as it was.

    Returns:
        The contract, checked.

    Raises:
        ClientDeployStepError: A check failed (:func:`verify_client_contract`).
        ClientRuntimeResolutionError: The contract is unreadable, or lacks what a
            deployed copy needs.
    """
    contract = verify_client_contract(plan, tree_root, contract_path, runtime)
    if not check_only:
        _compose_rows(plan, tree_root, contract, runtime, tree_root)
        return contract
    with tempfile.TemporaryDirectory() as scratch:
        _compose_rows(plan, tree_root, contract, runtime, Path(scratch))
    return contract


def _require_build_number(build_number: str | None) -> None:
    """Fail unless *build_number* is one a native build script accepts."""
    shaped = build_number is not None and _BUILD_NUMBER_SHAPE.fullmatch(build_number) is not None
    if not shaped or int(str(build_number)) > MAX_BUILD_NUMBER:
        raise ClientDeployStepError(
            f"{BUILD_NUMBER_FLAG} is required to build a native client and must be a whole "
            f"number from 1 to {MAX_BUILD_NUMBER}; got {build_number!r}. Nothing was composed "
            "or published. Pass the store build number."
        )


def _require_native_row_inputs(row: ClientStepRow, build: ClientStepNativeBuild, tree_root: Path) -> None:
    """Fail unless *build*'s script and every signing variable it needs are present."""
    if not (tree_root / build["script"]).is_file():
        raise ClientDeployStepError(
            f"App '{row['app_key']}' ({row['target']}) builds with '{build['script']}', which "
            "does not exist in this tree. Nothing was composed or published. Regenerate the tree."
        )
    missing = [operator for _, operator in build["android_signing"] if not os.environ.get(operator)]
    if missing:
        raise ClientDeployStepError(
            f"App '{row['app_key']}' ({row['target']}) signs its Android build with {missing}, "
            "which the environment does not set. Nothing was composed or published. Set each "
            "variable, then rerun."
        )


def _require_native_inputs(
    plan: ClientStepPlan, tree_root: Path, build_number: str | None, launcher: Sequence[str]
) -> None:
    """Fail unless every native row of *plan* can build."""
    rows = [(row, row["native_build"]) for row in plan["rows"]]
    builds = [(row, build) for row, build in rows if build is not None]
    if not builds:
        return
    _require_build_number(build_number)
    if shutil.which(launcher[0]) is None:
        raise ClientDeployStepError(
            f"Building a native client needs '{launcher[0]}', which is not on PATH. Nothing was "
            "composed or published. Install it, then rerun."
        )
    for row, build in builds:
        _require_native_row_inputs(row, build, tree_root)


def native_build_environment(
    build: ClientStepNativeBuild, environment: Mapping[str, str], inputs: Mapping[str, str]
) -> dict[str, str]:
    """The environment of *build*'s process: *environment* plus what the build reads.

    A team, links host or deploy-supplied build input the build must not use is removed,
    so a value left in the operator's shell cannot reach an artifact.

    Args:
        build: The native build.
        environment: The deploy's own environment, left unchanged.
        inputs: The deploy-supplied build inputs the row's build takes
            (:func:`supplied_build_inputs`).

    Returns:
        A new mapping; each signing value stands under the name the build reads.
    """
    child = dict(environment)
    for native_name, operator_name in build["android_signing"]:
        child[native_name] = environment[operator_name]
    stated = (
        (build["ios_team_variable"], build["ios_team"]),
        (build["links_host_variable"], build["links_host"]),
        (API_ORIGIN_INPUT, inputs.get(API_ORIGIN_INPUT)),
        (BUILD_COMMIT_INPUT, inputs.get(BUILD_COMMIT_INPUT)),
    )
    for variable, value in stated:
        child.pop(variable, None)
        if value is not None:
            child[variable] = value
    return child


def native_build_commands(
    build: ClientStepNativeBuild,
    tree_root: Path,
    runtime_config: Path,
    build_number: str,
    launcher: Sequence[str],
) -> tuple[tuple[str, ...], ...]:
    """The command of each platform of *build*, one each.

    One per platform because a script started with ``-File`` receives each argument
    as text, so a list of platforms never reaches its array parameter as a list.

    Args:
        build: The native build.
        tree_root: The generated project's root.
        runtime_config: The composed deployed runtime config.
        build_number: The store build number, already checked.
        launcher: How the script is run.

    Returns:
        One argument vector per platform; no signing value is in any of them.
    """
    return tuple(
        (
            *launcher,
            str(tree_root / build["script"]),
            f"-{build['runtime_config_parameter']}",
            str(runtime_config),
            f"-{build['build_number_parameter']}",
            build_number,
            f"-{build['platform_parameter']}",
            platform,
        )
        for platform in build["platforms"]
    )


def _build_native_row(
    row: ClientStepRow,
    build: ClientStepNativeBuild,
    tree_root: Path,
    build_number: str,
    launcher: Sequence[str],
    log: Callable[[str], None],
    inputs: Mapping[str, str],
) -> None:
    """Run *build*'s script for each platform, or fail naming the app and the exit code."""
    compose = row["compose"]
    if compose is None:
        raise ClientDeployStepError(
            f"App '{row['app_key']}' ({row['target']}) has a native build but no runtime config "
            "to embed. Regenerate the tree."
        )
    environment = native_build_environment(build, os.environ, inputs)
    commands = native_build_commands(
        build, tree_root, tree_root / compose["resolved"], build_number, launcher
    )
    for platform, command in zip(build["platforms"], commands, strict=True):
        log(f"building {row['app_key']} ({row['target']}) for {platform}")
        result = subprocess.run(command, cwd=tree_root, env=environment, check=False)
        if result.returncode != 0:
            raise ClientDeployStepError(
                f"Building app '{row['app_key']}' ({row['target']}) for {platform} failed (exit "
                f"{result.returncode}) in '{build['script']}'. Review its output above."
            )


def run_client_step(
    plan: ClientStepPlan,
    tree_root: Path,
    contract_path: Path,
    runtime: ClientStepRuntime,
    *,
    publish: ClientSitePublish,
    host: ClientSiteStage,
    build_number: str | None,
    launcher: Sequence[str] = NATIVE_BUILD_LAUNCHER,
) -> None:
    """Release every client of *plan*, in plan order, once its backend is proved.

    Args:
        plan: The tree's client release.
        tree_root: The generated project's root.
        contract_path: The contract (:func:`client_contract_source`).
        runtime: The host's reader, composer, release verifier and log.
        publish: The platform's publish stage for a web target, given the deploy-supplied
            build inputs the row's build takes.
        host: The platform's stage binding a web target's custom-domain surface.
        build_number: The value of ``--build-number``, or ``None`` when absent.
        launcher: How a native build script is run.

    Raises:
        ClientDeployStepError: A native build's input or the deploying commit is missing,
            a check failed, or a build failed.
        ClientRuntimeResolutionError: The contract is unreadable, or lacks what a
            deployed copy needs.
    """
    _require_native_inputs(plan, tree_root, build_number, launcher)
    commit = _required_commit(plan, tree_root)
