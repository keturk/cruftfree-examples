def _normalize_argv(argv: list[str], switch_aliases: dict[str, str]) -> list[str]:
    """Translate PowerShell-style switches into this script's own flags.

    Only whole arguments are translated, and only when they match a declared
    alias case-insensitively: a value that merely looks like a switch (a path,
    a negative number, an argument to another flag) passes through untouched.

    Args:
        argv: The arguments as the shell handed them over.
        switch_aliases: PowerShell switch spelling -> this script's own flag.

    Returns:
        The same arguments with every recognized PowerShell switch replaced by
        this script's own flag spelling.
    """
    return [switch_aliases.get(token.lower(), token) for token in argv]


def _help_block(heading: str, entries: dict[str, str]) -> list[str]:
    """Render one aligned ``name  description`` block for the --help epilog.

    Args:
        heading: The block's heading line.
        entries: Name -> description, in the order they should be listed.

    Returns:
        The block's lines, or an empty list when there is nothing to list.
    """
    if not entries:
        return []
    width = max(len(name) for name in entries)
    return ["", heading] + [
        f"  {name.ljust(width)}  {text}" for name, text in entries.items()
    ]


def _schema_usage(verb: str, operands: tuple[str, ...]) -> str:
    """Spell a schema verb's command line: the verb, ``<block>``, then its operands.

    Args:
        verb: The schema verb.
        operands: The operands it takes after its block, by attribute name.

    Returns:
        The usage, e.g. ``schema-apply <block> <sql-file>``.
    """
    names = ("block", *operands)
    return " ".join([verb, *(f"<{name.replace('_', '-')}>" for name in names)])


def _lifecycle_epilog(
    verb_help: dict[str, str],
    unrealized_verbs: dict[str, str],
    schema_help: dict[str, str],
    schema_blocks: tuple[str, ...],
    extra_commands: dict[str, str] | None = None,
    *,
    schema_operands: dict[str, tuple[str, ...]],
    deploy_verb: str,
    deploy_step_help: dict[str, str],
    client_step_help: dict[str, str],
    unrealized_client_members: dict[str, str],
) -> str:
    """Return the --help epilog: what this profile does, and what it does not.

    The unrealized half is the part that matters. The vocabulary is shared
    across every CruftFree target, so an operator arriving from another profile
    will type verbs this one does not implement; telling them WHY, and what to
    use instead, is the difference between a usable CLI and a dead end.

    Args:
        verb_help: One help line per realized lifecycle verb.
        unrealized_verbs: Vocabulary verb -> why this profile lacks it.
        schema_help: One help line per schema verb this profile implements.
        schema_blocks: The block keys a schema verb accepts.
        extra_commands: Platform-specific commands this CLI also accepts, which
            are NOT lifecycle verbs -- a read-only check, a partial rollout, an
            escape hatch. Listed separately so the shared vocabulary stays
            recognizable next to them.
        schema_operands: The operands each schema verb of *schema_help* takes
            after its block, by attribute name.
        deploy_verb: The verb the schema steps belong to.
        deploy_step_help: One help line per schema step every *deploy_verb*
            runs. A step is no command and no flag: it is listed under the
            deploy verb so the operator knows what a deploy does.
        client_step_help: One help line per client step *deploy_verb* runs,
            listed after the schema steps, which is the order a deploy runs them.
        unrealized_client_members: Client member -> why this profile lacks it,
            listed with the unrealized verbs.

    Returns:
        The epilog text.
    """
    lines = _help_block("lifecycle commands:", dict(verb_help))[1:]
    lines += _help_block(
        f"steps of '{deploy_verb}':", {**deploy_step_help, **client_step_help}
    )
    lines += _help_block(
        "schema commands:",
        {
            _schema_usage(verb, schema_operands[verb]): text
            for verb, text in schema_help.items()
        },
    )
    if schema_help:
        lines += ["", "blocks:"] + [f"  {key}" for key in schema_blocks]
    lines += _help_block("platform-specific commands:", extra_commands or {})
    lines += _help_block(
        "not implemented on this deployment profile:",
        {**unrealized_verbs, **unrealized_client_members},
    )
    return "\n".join(lines)


def _verbs_phrase(verbs: tuple[str, ...]) -> str:
    """Name *verbs* for a message: ``'deploy'``, ``'deploy' or 'down'``."""
    quoted = [f"'{verb}'" for verb in verbs]
    if len(quoted) == 1:
        return quoted[0]
    return f"{', '.join(quoted[:-1])} or {quoted[-1]}"


def _flag_help(verbs: tuple[str, ...], help_line: str) -> str:
    """The --help text of a flag: the verbs it is accepted with, then *help_line*.

    A ``%`` in the profile's line reaches --help verbatim, never as a format error.
    """
    return f"(with {_verbs_phrase(verbs)}) {help_line}".replace("%", "%%")


class _LifecycleArgumentParser(argparse.ArgumentParser):
    """The lifecycle parser: argparse, plus the operands and flags each command takes.

    One optional command positional cannot say "a schema verb takes its block
    and its own operands, a lifecycle verb takes nothing", so every operand is
    collected into ``args`` and checked here once argparse is done. A schema verb
    gets its block as ``block``, one of the keys this deployment's blocks have,
    and each further operand it declares (``schema-apply``'s ``sql_file``) under
    that operand's name, exactly as many as it declares; every other command
    gets ``block = None`` and ``None`` for every schema operand and, unless the
    platform asked for operands of its own, a stray operand is rejected exactly
    as argparse would reject it.

    A schema flag (:meth:`add_deploy_flag`) is accepted with the deploy verb
    alone, a client flag (:meth:`add_value_flag`) with the verbs it declares:
    given with any other command it is rejected by name, never quietly ignored.
    """

    def __init__(
        self,
        program_name: str,
        description: str,
        epilog: str,
        schema_verbs: tuple[str, ...],
        schema_blocks: tuple[str, ...],
        schema_operands: dict[str, tuple[str, ...]],
        takes_platform_operands: bool,
        deploy_verb: str,
    ) -> None:
        super().__init__(
            prog=program_name,
            description=description,
            epilog=epilog,
            formatter_class=argparse.RawDescriptionHelpFormatter,
        )
        self._schema_verbs = schema_verbs
        self._schema_blocks = schema_blocks
        self._schema_operands = schema_operands
        self._takes_platform_operands = takes_platform_operands
        self._deploy_verb = deploy_verb
        self._flag_verbs: dict[str, tuple[tuple[str, ...], str]] = {}

    def add_deploy_flag(self, flag: str, help_line: str) -> None:
        """Add *flag* as a switch the deploy verb alone accepts.

        Args:
            flag: The flag's spelling, e.g. ``--plan``.
            help_line: The profile's help line for it, shown by --help after the
                verb it is accepted with.
        """
        verbs = (self._deploy_verb,)
        action = self.add_argument(
            flag, action="store_true", help=_flag_help(verbs, help_line)
        )
        self._flag_verbs[flag] = (verbs, action.dest)

    def add_value_flag(
        self,
        flag: str,
        help_line: str,
        values: tuple[str, ...],
        verbs: tuple[str, ...],
    ) -> None:
        """Add *flag* as an option taking one value, accepted with *verbs* alone.

        Args:
            flag: The flag's spelling, e.g. ``--scope``.
            help_line: The profile's help line for it, shown by --help after the
                verbs it is accepted with.
            values: The values it accepts, any other being rejected by name;
                empty when it takes any value.
            verbs: The commands it is accepted with; never empty.
        """
        if not verbs:
            raise ValueError(f"{flag}: a flag needs at least one verb to be accepted with")
        action = self.add_argument(
            flag, choices=values or None, help=_flag_help(verbs, help_line)
        )
        self._flag_verbs[flag] = (verbs, action.dest)

    def _refuse_misplaced_flags(self, parsed: argparse.Namespace) -> None:
        """Reject, by name, every given flag the chosen command does not accept."""
        refused: dict[tuple[str, ...], list[str]] = {}
        for flag, (verbs, dest) in self._flag_verbs.items():
            if getattr(parsed, dest) in (None, False) or parsed.command in verbs:
                continue
            refused.setdefault(verbs, []).append(flag)
        if refused:
            reasons = "; ".join(
                f"{' '.join(flags)}: accepted with {_verbs_phrase(verbs)} alone"
                for verbs, flags in refused.items()
            )
            self.error(f"{reasons}, not with '{parsed.command}'")

    def parse_known_args(  # type: ignore[override]
        self,
        args: list[str] | None = None,
        namespace: argparse.Namespace | None = None,
    ) -> tuple[argparse.Namespace, list[str]]:
        """Parse *args*, then check the operands and flags the chosen command takes."""
        parsed, extras = super().parse_known_args(args, namespace)
        self._refuse_misplaced_flags(parsed)
        operands = list(getattr(parsed, "args", None) or [])
        for names in self._schema_operands.values():
            for name in names:
                setattr(parsed, name, None)
        if parsed.command in self._schema_verbs:
            names = self._schema_operands[parsed.command]
            if len(operands) != 1 + len(names) or operands[0] not in self._schema_blocks:
                self.error(
                    f"'{parsed.command}' takes exactly "
                    f"'{_schema_usage(parsed.command, names)}', the block one of: "
                    f"{', '.join(self._schema_blocks)} (got: {' '.join(operands) or 'none'})"
                )
            parsed.block = operands[0]
            for name, value in zip(names, operands[1:], strict=True):
                setattr(parsed, name, value)
            return parsed, extras
        if operands and not self._takes_platform_operands:
            self.error(f"unrecognized arguments: {' '.join(operands)}")
        parsed.block = None
        return parsed, extras


