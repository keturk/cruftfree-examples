class _UnreadDocument(Exception):
    """A document could not be read; the message says why."""


def _connection(parts: SplitResult) -> http.client.HTTPConnection:
    """A connection to *parts*' host: verified TLS, or plain http to a loopback host only."""
    if parts.username is not None or parts.password is not None:
        raise _UnreadDocument("the URL carries credentials")
    if parts.query or parts.fragment:
        raise _UnreadDocument("the URL carries a query or fragment")
    host = parts.hostname
    if not host:
        raise _UnreadDocument("the URL names no host")
    if parts.scheme == "https":
        return http.client.HTTPSConnection(
            host, parts.port, timeout=_FETCH_TIMEOUT_SECONDS, context=ssl.create_default_context()
        )
    if parts.scheme == "http" and host in _LOOPBACK_HOSTS:
        return http.client.HTTPConnection(host, parts.port, timeout=_FETCH_TIMEOUT_SECONDS)
    raise _UnreadDocument("it is neither https nor plain http to a loopback host")


def _read_body(response: http.client.HTTPResponse) -> bytes:
    """*response*'s body, or fail unless it answered 200 with a bounded body."""
    if 300 <= response.status < 400:
        target = response.getheader("Location")
        raise _UnreadDocument(
            f"it answered HTTP {response.status} redirecting to {target!r}; a redirect is not followed"
        )
    if response.status != 200:
        raise _UnreadDocument(f"it answered HTTP {response.status}")
    body = response.read(_MAX_DOCUMENT_BYTES + 1)
    if len(body) > _MAX_DOCUMENT_BYTES:
        raise _UnreadDocument(f"its body is larger than {_MAX_DOCUMENT_BYTES} bytes")
    return body


def _fetch_json_document(url: str) -> dict[str, object]:
    """The JSON object served at *url*, read with one GET that carries no credential.

    Raises:
        _UnreadDocument: The URL is not one the verifier may reach, or the server did
            not answer 200, redirected, sent too much, or sent no JSON object.
    """
    try:
        parts = urlsplit(url)
        connection = _connection(parts)
        try:
            connection.request("GET", parts.path or "/", headers={"Accept": "application/json"})
            document = json.loads(_read_body(connection.getresponse()))
        finally:
            connection.close()
    except (OSError, http.client.HTTPException, ValueError) as exc:
        raise _UnreadDocument(str(exc) or type(exc).__name__) from exc
    if not isinstance(document, dict):
        raise _UnreadDocument("it is not a JSON object")
    return document


def openid_configuration_url(authority: str) -> str:
    """Where the provider at *authority* publishes its OpenID configuration."""
    return f"{authority.rstrip('/')}{OPENID_CONFIGURATION_PATH}"


def _served_issuer(url: str, served: dict[str, str | _UnreadDocument]) -> str:
    """The issuer the configuration at *url* states, fetched once per *url*."""
    if url not in served:
        try:
            issuer = _fetch_json_document(url).get(VERIFY_ISSUER_KEY)
            if not isinstance(issuer, str) or not issuer:
                raise _UnreadDocument(f"it states no '{VERIFY_ISSUER_KEY}'")
            served[url] = issuer
        except _UnreadDocument as exc:
            served[url] = exc
    answer = served[url]
    if isinstance(answer, _UnreadDocument):
        raise answer
    return answer


def _client_record(
    contract: Mapping[str, object], registration: str, kind: str
) -> Mapping[str, object] | None:
    """The contract's *kind* client record of *registration*, or ``None`` when it holds none."""
    registrations = contract.get(VERIFY_REGISTRATIONS_KEY)
    entry = registrations.get(registration) if isinstance(registrations, dict) else None
    clients = entry.get(VERIFY_CLIENTS_KEY) if isinstance(entry, dict) else None
    record = clients.get(kind) if isinstance(clients, dict) else None
    return record if isinstance(record, dict) else None


def _identity_difference(
    use: ClientIdentityUse,
    contract: Mapping[str, object],
    served: dict[str, str | _UnreadDocument],
) -> str | None:
    """How *use*'s identity provider differs from the contract, or ``None`` when it matches."""
    app, registration, kind = use
    subject = f"App '{app}' ({kind} client of registration '{registration}')"
    record = _client_record(contract, registration, kind)
    authority = None if record is None else record.get(VERIFY_AUTHORITY_KEY)
    stated = None if record is None else record.get(VERIFY_ISSUER_KEY)
    if not isinstance(authority, str) or not isinstance(stated, str):
        return (
            f"{subject} signs users in, but the client contract holds no '{kind}' client record "
            f"with an '{VERIFY_AUTHORITY_KEY}' and an '{VERIFY_ISSUER_KEY}' for it. Declare a "
            "login provider for the registration, then redeploy the backend."
        )
    url = openid_configuration_url(authority)
    try:
        issuer = _served_issuer(url, served)
    except _UnreadDocument as exc:
        return (
            f"{subject}: the OpenID configuration at '{url}' could not be read: {exc}. Deploy the "
            "identity provider the contract names, or check its authority."
        )
    if issuer != stated:
        return (
            f"{subject}: the identity provider at '{authority}' states issuer '{issuer}', but the "
            f"client contract states issuer '{stated}'. Configure the provider's issuer to the one "
            "the backend declares, or redeploy the backend against the provider's issuer."
        )
    return None


def _api_object(value: object, what: str) -> Mapping[str, object]:
    """*value* as a JSON object, or fail naming *what*."""
    if not isinstance(value, dict):
        raise _UnreadDocument(f"{what} is not a JSON object")
    return value


def _api_list(value: object, what: str) -> list[object]:
    """*value* as a JSON array, or fail naming *what*."""
    if not isinstance(value, list):
        raise _UnreadDocument(f"{what} is not a JSON array")
    return value


def _api_text(entry: Mapping[str, object], key: str, what: str) -> str:
    """*entry*'s *key* as a non-empty string, or fail naming *what*."""
    value = entry.get(key)
    if not isinstance(value, str) or not value:
        raise _UnreadDocument(f"{what} states no '{key}'")
    return value


def _api_routes(service: Mapping[str, object], what: str) -> dict[ApiOperation, Mapping[str, object]]:
    """Each route of *service*, keyed by its (method, path)."""
    routes: dict[ApiOperation, Mapping[str, object]] = {}
    for item in _api_list(service.get(API_DOC_ROUTES_KEY), f"'{API_DOC_ROUTES_KEY}' of {what}"):
        route = _api_object(item, f"a route of {what}")
        operation = (
            _api_text(route, API_DOC_METHOD_KEY, f"a route of {what}"),
            _api_text(route, API_DOC_PATH_KEY, f"a route of {what}"),
        )
        if operation in routes:
            raise _UnreadDocument(f"{what} holds {operation[0]} {operation[1]} twice")
        routes[operation] = route
    return routes


def _api_services(document: object, what: str) -> dict[str, dict[ApiOperation, Mapping[str, object]]]:
    """Every service of the API *document*, by qualified name, with its routes.

    Raises:
        _UnreadDocument: A member is absent or of the wrong shape, naming it.
    """
    entries = _api_list(
        _api_object(document, what).get(VERIFY_API_SERVICES_KEY), f"'{VERIFY_API_SERVICES_KEY}' of {what}"
    )
    services: dict[str, dict[ApiOperation, Mapping[str, object]]] = {}
    for entry in entries:
        service = _api_object(entry, f"a service of {what}")
        name = _api_text(service, API_DOC_SERVICE_KEY, f"a service of {what}")
        if name in services:
            raise _UnreadDocument(f"{what} holds service '{name}' twice")
        services[name] = _api_routes(service, f"service '{name}' of {what}")
    return services


def _api_members(route: Mapping[str, object], key: str, what: str) -> dict[str, Mapping[str, object]]:
    """The named entries under *route*'s *key* (parameters or body fields), by name."""
    members: dict[str, Mapping[str, object]] = {}
    for item in _api_list(route.get(key), f"'{key}' of {what}"):
        member = _api_object(item, f"an entry of '{key}' of {what}")
        members[_api_text(member, API_DOC_NAME_KEY, f"an entry of '{key}' of {what}")] = member
    return members


def _api_type(member: Mapping[str, object]) -> str:
    """*member*'s type, written so two equal types read the same."""
    return json.dumps(member.get(API_DOC_TYPE_KEY), sort_keys=True)


def _member_differences(
    subject: str,
    label: str,
    consumed: Mapping[str, Mapping[str, object]],
    served: Mapping[str, Mapping[str, object]],
) -> list[str]:
    """How the *label* members the client sends differ from the ones the API serves.

    Every member the client sends must be served with the same type, and every one
    the served API requires must be one the client always sends.
    """
    differences: list[str] = []
    for name in sorted(consumed):
        if name not in served:
            differences.append(
                f"{subject}: the client sends {label} '{name}', which the served API does not take. "
                f"{_API_FIX}"
            )
        elif _api_type(consumed[name]) != _api_type(served[name]):
            differences.append(
                f"{subject}: {label} '{name}' is {_api_type(consumed[name])} in the client, but "
                f"{_api_type(served[name])} in the served API. {_API_FIX}"
            )
    for name in sorted(served):
        always_sent = name in consumed and consumed[name].get(API_DOC_REQUIRED_KEY) is True
        if served[name].get(API_DOC_REQUIRED_KEY) is True and not always_sent:
            differences.append(
                f"{subject}: the served API requires {label} '{name}', which the client does not "
                f"always send. {_API_FIX}"
            )
    return differences


def _body_differences(subject: str, consumed: object, served: object, what: str) -> list[str]:
    """How the request body the client sends differs from the one the API takes."""
    if consumed is None and served is None:
        return []
    if consumed is None:
        return [f"{subject}: the served API takes a request body, which the client does not send. {_API_FIX}"]
    if served is None:
        return [f"{subject}: the client sends a request body, but the served API takes none. {_API_FIX}"]
    sent = _api_object(consumed, f"the client's body of {what}")
    taken = _api_object(served, f"the served body of {what}")
    differences: list[str] = []
    sent_encoding = _api_text(sent, API_DOC_ENCODING_KEY, f"the client's body of {what}")
    taken_encoding = _api_text(taken, API_DOC_ENCODING_KEY, f"the served body of {what}")
    if sent_encoding != taken_encoding:
        differences.append(
            f"{subject}: the client sends a '{sent_encoding}' body, but the served API takes "
            f"'{taken_encoding}'. {_API_FIX}"
        )
    if _api_type(sent) != _api_type(taken):
        differences.append(
            f"{subject}: the request body is {_api_type(sent)} in the client, but "
            f"{_api_type(taken)} in the served API. {_API_FIX}"
        )
    differences.extend(
        _member_differences(
            subject,
            "body field",
            _api_members(sent, API_DOC_FIELDS_KEY, f"the client's body of {what}"),
            _api_members(taken, API_DOC_FIELDS_KEY, f"the served body of {what}"),
        )
    )
    return differences


def _api_reads(route: Mapping[str, object], what: str) -> set[tuple[str, ...]]:
    """The response field paths of *route*, each a tuple of wire names."""
    reads: set[tuple[str, ...]] = set()
    for item in _api_list(route.get(API_DOC_READS_KEY), f"'{API_DOC_READS_KEY}' of {what}"):
        segments = _api_list(item, f"a read of {what}")
        if not segments or not all(isinstance(segment, str) for segment in segments):
            raise _UnreadDocument(f"a read of {what} is not a list of field names")
        reads.add(tuple(str(segment) for segment in segments))
    return reads


def _api_credential(auth: str) -> str:
    """What a caller of an operation of auth mode *auth* presents."""
    if auth in _BEARER_AUTH_MODES:
        return "a bearer token"
    if auth == _PUBLIC_AUTH_MODE:
        return "no credential"
    return f"a '{auth}' caller's credential"


def _route_differences(
    subject: str, consumed: Mapping[str, object], served: Mapping[str, object]
) -> list[str]:
    """Every way one route the client calls differs from the served operation.

    Raises:
        _UnreadDocument: A member of either route is absent or of the wrong shape.
    """
    what = subject
    differences: list[str] = []
    sent_auth = _api_text(consumed, API_DOC_AUTH_KEY, f"the client's route of {what}")
    taken_auth = _api_text(served, API_DOC_AUTH_KEY, f"the served route of {what}")
    if _api_credential(sent_auth) != _api_credential(taken_auth):
        differences.append(
            f"{subject}: the client calls it with auth '{sent_auth}' ({_api_credential(sent_auth)}), "
            f"but the served API's operation is '{taken_auth}' ({_api_credential(taken_auth)}). "
            f"{_API_FIX}"
        )
    for key, label in ((API_DOC_PATH_PARAMS_KEY, "path parameter"), (API_DOC_QUERY_PARAMS_KEY, "query parameter")):
        differences.extend(
            _member_differences(
                subject,
                label,
                _api_members(consumed, key, f"the client's route of {what}"),
                _api_members(served, key, f"the served route of {what}"),
            )
        )
    differences.extend(
        _body_differences(subject, consumed.get(API_DOC_BODY_KEY), served.get(API_DOC_BODY_KEY), what)
    )
    served_reads = _api_reads(served, f"the served route of {what}")
    differences.extend(
        f"{subject}: the client reads response field '{'.'.join(path)}', which the served API's "
        f"response does not have. {_API_FIX}"
        for path in sorted(_api_reads(consumed, f"the client's route of {what}") - served_reads)
    )
    return differences


def _app_api_differences(
    app: str, document: object, served: Mapping[str, Mapping[ApiOperation, Mapping[str, object]]]
) -> list[str]:
    """Every way the API *app* calls differs from the *served* one."""
    try:
        services = _api_services(document, f"the API document of app '{app}'")
    except _UnreadDocument as exc:
        return [f"App '{app}': its API document could not be read: {exc}. Regenerate the tree."]
    differences: list[str] = []
    for name in sorted(services):
        if name not in served:
            listed = ", ".join(f"'{service}'" for service in sorted(served)) or "none"
            differences.append(
                f"App '{app}' calls service '{name}', which the served API does not hold; it "
                f"serves {listed}. {_API_FIX}"
            )
            continue
        for operation in sorted(services[name]):
            subject = f"App '{app}' calls {name} {operation[0]} {operation[1]}"
            taken = served[name].get(operation)
            if taken is None:
                differences.append(f"{subject}, which the served API does not hold. {_API_FIX}")
                continue
            try:
                differences.extend(_route_differences(subject, services[name][operation], taken))
            except _UnreadDocument as exc:
                differences.append(f"{subject}: a route could not be read: {exc}. Regenerate the tree.")
    return differences


def _api_differences(contract: Mapping[str, object], consumed: Mapping[str, object]) -> list[str]:
    """Every way the API each app calls differs from the API the contract states is served."""
    if not consumed:
        return []
    where = f"'{VERIFY_BACKEND_KEY}.{VERIFY_API_KEY}'"
    try:
        backend = _api_object(contract.get(VERIFY_BACKEND_KEY), f"'{VERIFY_BACKEND_KEY}'")
        served = _api_services(backend.get(VERIFY_API_KEY), f"the served API document {where}")
    except _UnreadDocument as exc:
        reason = (
            f"The client contract's served API {where} could not be read: {exc}. Use the contract "
            "the backend's deploy published, unchanged."
        )
        return [reason]
    differences: list[str] = []
    for app in sorted(consumed):
        differences.extend(_app_api_differences(app, consumed[app], served))
    return differences


def verify_client_release(
    contract: Mapping[str, object],
    clients: Sequence[ClientIdentityUse],
    consumed: Mapping[str, object],
) -> tuple[str, ...]:
    """Every way the services *contract* names differ from what the release's clients call.

    Args:
        contract: The client contract, as `client_runtime_resolution.read_client_contract`
            returned it.
        clients: Each (app key, registration, kind) the release signs users in with.
        consumed: Each app's consumed API document, by app key, as parsed JSON.

    Returns:
        One line per difference, naming the app, the kind or the operation and member,
        and both values; empty when every provider matches and every operation an app
        calls is served as it calls it.
    """
    served: dict[str, str | _UnreadDocument] = {}
    identity = (_identity_difference(use, contract, served) for use in dict.fromkeys(clients))
    return (
        *(difference for difference in identity if difference is not None),
        *_api_differences(contract, consumed),
    )


