def _sha256_file(path: Path) -> str:
    """Return the lowercase hex SHA-256 of a file's bytes."""
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def deploy_content_hash(roots: Sequence[str | Path]) -> str:
    """Return a deterministic hash of the given files and directory trees.

    Each root contributes ``<root index>:<relative path>|<file sha256>`` lines
    (a directory contributes one line per file, in relative-path order); the
    joined manifest is hashed. The root index is part of every line, so moving a
    file between roots changes the hash even when the file set does not. Missing
    roots contribute nothing. Byte-compiled output is excluded, so a tree that
    has been imported hashes the same as one that has not.
    """
    lines: list[str] = []
    for index, raw_root in enumerate(roots):
        root = PROJECT_ROOT / raw_root
        if root.is_dir():
            entries: list[tuple[str, Path]] = []
            for path in root.rglob("*"):
                if not path.is_file():
                    continue
                if (
                    HASH_EXCLUDED_DIR in path.parts
                    or path.suffix == HASH_EXCLUDED_SUFFIX
                ):
                    continue
                entries.append((path.relative_to(root).as_posix(), path))
            for relative, path in sorted(entries, key=lambda pair: pair[0]):
                lines.append(f"{index}:{relative}|{_sha256_file(path)}")
        elif root.is_file():
            lines.append(f"{index}:{root.name}|{_sha256_file(root)}")
    manifest = "".join(f"{line}\n" for line in lines)
    return hashlib.sha256(manifest.encode("utf-8")).hexdigest()


