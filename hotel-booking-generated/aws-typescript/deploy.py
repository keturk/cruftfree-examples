def destroy_stacks(region: str) -> None:
    """Delete every stack of the deployment, the last-deployed first.

    The bootstrap stack goes last: it holds the deployment bucket and the
    container repositories the other stacks' packages and images came from,
    and the run store the schema workloads read and write. Its
    buckets and repositories are retained when it is deleted.

    Args:
        region: The operator's region.

    Raises:
        DeployError: If a stack could not be deleted; the stacks before it in
            the deploy order are left standing.
    """
    delete_stacks((*reversed(STACKS), *reversed(DATA_STACKS), BOOTSTRAP_STACK), region)


def command_deploy(forced: bool, approved: bool, clients: ClientRequest) -> None:
    """Deploy the bootstrap stack, supply packages and images, then converge every block around the release.

    The ``converge`` step: the data stacks deploy first, every block is read,
    planned and expanded, the release stacks deploy and are verified healthy
    (``verify_deployment``), and only then is each block's contract applied
    and its schema verified.

    Args:
        forced: Unused -- ``deploy`` removes nothing and needs no confirmation.
            Accepted so every command shares one signature.
        approved: Whether the command line gave ``--approved``: the one source
            of approval for a change that needs it.
        clients: What the command line asked of the clients.
    """
    del forced
    contract = client_contract_file(clients)
    # Fail on missing tooling before anything is built, pushed or deployed.
    resolve_executable("aws", "Install the AWS CLI.")
    if clients.scope == SCOPE_CLIENTS:
        require_credentials()
        # Read the contract off the deployed stacks again, so the clients are released against
        # the backend as it is deployed, also from a clean checkout (a scheduled site refresh).
        client_contract()
        run_clients_step(contract, clients.build_number)
        print(f"Clients of {APP_NAME} released.")
        return
    region = resolve_region()
    resolve_executable("docker", "Docker builds and pushes the container images.")
    require_credentials()
    deploy_stack(BOOTSTRAP_STACK, {}, region, None)
    bucket = deployment_bucket(region)
    parameters = upload_assets(bucket, region)
    registry = registry_login(region)
    parameters.update(supply_images(registry, region))
    parameters[RUN_ID_PARAMETER] = str(uuid.uuid4())
    parameters[SITE_ENABLED_PARAMETER] = "true"
    converge_schema_blocks(
        PLAN_BLOCKS,
        approved,
        bring_up_data=functools.partial(deploy_data_stacks, parameters, bucket, region),
        start_release=functools.partial(deploy_release_stacks, parameters, bucket, region),
        verify_release=verify_deployment,
        concurrent_runs=serial_schema_runs,
        schema_tool=run_project_schema_tool,
        channel=ecs_schema_channel(STEP_CONVERGE),
        failure=DeployError,
    )
    client_contract()
    if clients.scope == SCOPE_BACKEND:
        print(f"Backend of {APP_NAME} deployed. Run '{VERB_DEPLOY} {FLAG_SCOPE} {SCOPE_CLIENTS}' to release its clients.")
        return
    run_clients_step(contract, clients.build_number)
    print(f"Deployment of {APP_NAME} complete.")


#: Why this deployment's backend has no ``down``: the same reason a deployment hosting no
#: client gives for refusing the verb.
BACKEND_DOWN_REASON = "stopping compute would change resources outside the templates that declare them, and the next \u0027deploy\u0027 would silently restore them. Use \u0027destroy\u0027 when the environment is no longer needed."


def command_down(forced: bool, scope: str | None) -> None:
    """Stop serving every deployed site, losing nothing: the clients scope of ``down``.

    The backend has no ``down`` (BACKEND_DOWN_REASON), so the backend scope, and ``down``
    with no scope, which would stop both, are refused before anything runs.

    Args:
        forced: Unused -- ``down`` removes nothing and needs no confirmation.
            Accepted so every command shares one signature.
        scope: The scope flag's value, or ``None`` for both scopes.

    Raises:
        DeployError: If the scope is not the clients scope, a stack failed to deploy, or
            a distribution still reads enabled.
    """
    del forced
    if scope != SCOPE_CLIENTS:
        asked = f"'{VERB_DOWN} {FLAG_SCOPE} {scope}'" if scope else f"'{VERB_DOWN}' of both scopes"
        raise DeployError(
            f"{asked} is refused: the backend of {APP_NAME} has no '{VERB_DOWN}' -- "
            f"{BACKEND_DOWN_REASON} Run '{VERB_DOWN} {FLAG_SCOPE} {SCOPE_CLIENTS}' to stop "
            f"its clients alone."
        )
    region = resolve_region()
    resolve_executable("aws", "Install the AWS CLI.")
    require_credentials()
    stop_web_static_sites(region, lambda: deployment_bucket(region))
    print(f"Clients of {APP_NAME} stopped. Run '{VERB_DEPLOY}' to serve them again.")


def command_destroy(forced: bool) -> None:
    """Delete every stack of the deployment.

    Args:
        forced: Whether the operator waived the confirmation prompt.

    Raises:
        DeployError: If the operator declined, or the deletion failed.
    """
    region = resolve_region()
    resolve_executable("aws", "Install the AWS CLI.")
    require_credentials()
    lost = (
        f"Every stack of {APP_NAME} in region {region} is deleted, and with it "
        f"every resource the stacks created -- databases, queues, buckets and "
        f"everything they hold. The bootstrap stack's buckets (the deployment "
        f"bucket and the run store, which empties itself a day after its last "
        f"write) and container repositories are retained."
    )
    if not confirm_destructive(VERB_DESTROY, lost, APP_NAME, forced):
        raise DeployError(
            f"'{VERB_DESTROY}' was not confirmed. Nothing has been changed."
        )
    destroy_stacks(region)
    print(f"Destroy of {APP_NAME} complete.")


