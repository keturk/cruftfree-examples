def ecr_tag_exists(repo: str, tag: str, region: str) -> bool:
    """Return True when the registry already holds ``repo:tag``.

    Distinguishes "tag not found" (a build is needed) from any other failure,
    such as an authentication error, which fails loud rather than being
    silently treated as a skip.

    Raises:
        DeployError: If the registry could not be queried at all.
    """
    result = aws(
        "ecr", "describe-images",
        "--repository-name", repo,
        "--image-ids", f"imageTag={tag}",
        "--region", region,
    )
    if result.succeeded:
        return True
    if IMAGE_NOT_FOUND_MARKER in result.output:
        return False
    raise DeployError(
        f"Could not query the container registry for repository '{repo}' tag "
        f"'{tag}': {result.output}"
    )


def registry_login(region: str) -> str:
    """Authenticate the local docker daemon against the account's registry.

    Returns:
        The registry host every image is pushed to.

    Raises:
        DeployError: If the account id or the login itself could not be
            resolved.
    """
    step("Logging in to the container registry")
    identity = aws(
        "sts", "get-caller-identity", "--query", "Account", "--output", "text"
    )
    if not identity.succeeded or not identity.stdout:
        raise DeployError(
            f"Could not resolve the AWS account id. aws reported: "
            f"{identity.output}"
        )
    registry = f"{identity.stdout}.dkr.ecr.{region}.amazonaws.com"
    password = aws("ecr", "get-login-password", "--region", region)
    if not password.succeeded or not password.stdout:
        raise DeployError(
            f"Could not obtain a registry login password. aws reported: "
            f"{password.output}"
        )
    login = subprocess.run(
        [
            resolve_executable("docker", "Install Docker."),
            "login", "--username", "AWS", "--password-stdin", registry,
        ],
        input=password.stdout,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        cwd=PROJECT_ROOT,
    )
    if login.returncode != 0:
        raise DeployError(
            f"Registry login failed for '{registry}': "
            f"{(login.stderr or login.stdout or '').strip()}"
        )
    return registry


