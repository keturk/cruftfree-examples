#!/usr/bin/env python3
r"""Sync the generated flutter client libraries into a consuming repository.

Generated by CruftFree -- do not edit manually. Run it through
'scripts/sync-flutter-client.sh' or '.\scripts\sync-flutter-client.ps1', or directly with
Python 3.11+ from the project root:

    python scripts/sync-flutter-client.py --destination <dir> --pubspec <FILE> [--app <key> ...] [--check]

It copies the libraries of clients/flutter/ into <dir>, in five steps:

1. verify clients/flutter/ against its MANIFEST.json (every listed file matches its
   sha256, and no unlisted file sits under a synced folder);
2. check the consumer files given on the command line map every library,
   and refuse before writing anything when one is missing;
3. verify every file the destination manifest (cruftfree-flutter-manifest.json in <dir>)
   records is unchanged since the last sync -- a hand edit is reported, never overwritten;
4. delete exactly the recorded files, and the folders they leave empty;
5. copy the libraries and record them in the destination manifest.

--check runs steps 1-3 and lists every file that would be added, removed or
changed, writing nothing; it exits 1 on any difference.

--app <key>, repeatable, also copies that app, the runtime the apps share and the
app form of each file, and every step covers them. An unknown key is refused,
listing the tree's apps. A run replaces what the last run recorded, so name every
app <dir> keeps; a run without --app is the library sync and removes them.

Standard library only: no CruftFree package, no network access, no subprocess.
Consumer files are read, never written.
"""

