def _strip_comment(line: str) -> str:
    """*line* without a trailing ``#`` comment (one starting the line or after a space, outside quotes)."""
    quote = ""
    for index, char in enumerate(line):
        if quote:
            quote = "" if char == quote else quote
        elif char in _QUOTES:
            quote = char
        elif char == _COMMENT and (index == 0 or line[index - 1].isspace()):
            return line[:index].rstrip()
    return line.rstrip()


def _unquote(value: str) -> str:
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in _QUOTES:
        return value[1:-1]
    return value


def _significant_lines(text: str, source: Path) -> list[tuple[int, str]]:
    """Every non-blank, comment-stripped line as ``(indent, content)``.

    Raises:
        ValueError: A line is indented with a tab, which YAML forbids.
    """
    lines: list[tuple[int, str]] = []
    for number, raw in enumerate(text.splitlines(), 1):
        stripped = _strip_comment(raw)
        if not stripped.strip():
            continue
        indent = len(stripped) - len(stripped.lstrip(" "))
        if stripped[indent:indent + 1] == "\t":
            raise ValueError(f"{source}:{number}: tab indentation is not YAML")
        lines.append((indent, stripped.strip()))
    return lines


def _key_value(content: str) -> tuple[str, str]:
    """``key: value`` split into the unquoted key and the raw value (empty for a block)."""
    key, separator, value = content.partition(":")
    if not separator:
        return "", ""
    return _unquote(key), value.strip()


def _top_level_value(lines: Sequence[tuple[int, str]], key: str) -> str:
    """The inline value of top-level *key*, or an empty string when absent or a block."""
    for indent, content in lines:
        found, value = _key_value(content)
        if indent == 0 and found == key:
            return value
    return ""


def _block(lines: Sequence[tuple[int, str]], start: int, parent_indent: int) -> list[tuple[int, str]]:
    """The lines nested under the line at *start* (indented deeper than *parent_indent*)."""
    nested: list[tuple[int, str]] = []
    for indent, content in lines[start + 1 :]:
        if indent <= parent_indent:
            break
        nested.append((indent, content))
    return nested


def _flow_mapping(value: str, source: Path) -> dict[str, str]:
    """A one-line ``{key: value, ...}`` flow mapping of scalars."""
    inner = value.strip()[len(_FLOW_OPEN) : -len(_FLOW_CLOSE)]
    entries: dict[str, str] = {}
    for item in filter(None, (part.strip() for part in inner.split(","))):
        key, separator, scalar = item.partition(":")
        if not separator:
            raise ValueError(f"{source}: cannot read the flow mapping {value!r}; write it in block style")
        entries[_unquote(key)] = _unquote(scalar)
    return entries


def _entry_fields(entry_value: str, nested: Sequence[tuple[int, str]], source: Path) -> dict[str, str]:
    """The scalar fields of one dependency entry (block or flow form); empty for a version constraint."""
    if entry_value.startswith(_FLOW_OPEN) and entry_value.endswith(_FLOW_CLOSE):
        return _flow_mapping(entry_value, source)
    if entry_value or not nested:
        return {}
    field_indent = nested[0][0]
    return {key: _unquote(value) for indent, content in nested if indent == field_indent for key, value in [_key_value(content)]}


def read_dependencies(path: Path) -> dict[str, dict[str, str]]:
    """Every entry of the pubspec's ``dependencies:`` block, with its scalar fields.

    Raises:
        ValueError: The pubspec uses a form this reader refuses (tabs, a
            flow-style ``dependencies:`` mapping, an unreadable flow entry).
    """
    lines = _significant_lines(path.read_text(encoding="utf-8-sig"), path)
    starts = [index for index, (indent, content) in enumerate(lines) if indent == 0 and _key_value(content)[0] == _DEPENDENCIES_KEY]
    if not starts:
        return {}
    inline = _key_value(lines[starts[0]][1])[1]
    if inline and inline != _EMPTY_FLOW:
        raise ValueError(f"{path}: a flow-style '{_DEPENDENCIES_KEY}:' mapping cannot be checked; write it in block style")
    block = _block(lines, starts[0], 0)
    if not block:
        return {}
    entry_indent = block[0][0]
    entries: dict[str, dict[str, str]] = {}
    for index, (indent, content) in enumerate(block):
        if indent != entry_indent:
            continue
        name, value = _key_value(content)
        entries[name] = _entry_fields(value, _block(block, index, entry_indent), path)
    return entries


def library_names(source_root: Path, files: Sequence[str]) -> list[str]:
    """The ``name`` of every pub package among the synced files, sorted.

    A pubspec under ``mobile/`` is left out: it belongs to an app's own project,
    which builds on its own, so the consumer's pubspec never depends on it.

    Raises:
        ValueError: A package's pubspec declares no ``name``.
    """
    names: list[str] = []
    for relative in sorted(files):
        path = PurePosixPath(relative)
        if path.name != FLUTTER_PUBSPEC or path.parts[0] == FLUTTER_MOBILE_ROOT:
            continue
        pubspec = source_root / relative
        name = _unquote(_top_level_value(_significant_lines(pubspec.read_text(encoding="utf-8-sig"), pubspec), _NAME_KEY))
        if not name:
            raise ValueError(f"{relative} declares no package name; regenerate the client tree")
        names.append(name)
    return sorted(names)


def check_consumer(arguments: Mapping[str, str], library_names: Sequence[str]) -> list[str]:
    """One problem per synced package the consumer's pubspec does not path-depend on.

    Args:
        arguments: The consumer options; reads ``arguments["pubspec"]``.
        library_names: Every package the synced tree holds.

    Returns:
        A problem per package that is absent from ``dependencies:`` or listed
        there without a ``path:``; empty when every package is a path dependency.

    Raises:
        ValueError: The pubspec cannot be read unambiguously.
    """
    pubspec = Path(arguments[PUBSPEC_ARGUMENT])
    dependencies = read_dependencies(pubspec)
    problems: list[str] = []
    for name in library_names:
        if name not in dependencies:
            problems.append(f"{pubspec}: '{name}' is not under {_DEPENDENCIES_KEY}:; add it with path: <the sync destination>")
        elif not (_PATH_KEY in dependencies[name] and dependencies[name][_PATH_KEY]):
            problems.append(f"{pubspec}: '{name}' is a dependency but not a path dependency; give it path: <the sync destination>")
    return problems


