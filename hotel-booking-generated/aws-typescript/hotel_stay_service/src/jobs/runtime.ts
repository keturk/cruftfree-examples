/**
 * Jobs runtime: the dependencies the job handlers in ./handlers/ inject.
 *
 * JobsRuntimeModule registers and exports every database, repository and
 * service a job body reaches, so any module importing it -- JobsModule, for
 * the in-process scheduler -- can construct a job from its own injector. A
 * host with no Nest injector of its own (an Azure Functions timer) resolves
 * jobs through jobsRuntimeModuleRef() instead: one application context per
 * process, created on first use, connecting through the same per-block
 * database modules -- and so the same database login -- as the service.
 *
 * Auto-generated by cruftfree-codegen-typescript. Do not edit manually.
 */
import { type DynamicModule, type INestApplicationContext, Module } from '@nestjs/common';
import { ModuleRef, NestFactory } from '@nestjs/core';
import { SettingsModule } from '../config/settings';
import { MikroOrmModule } from '@mikro-orm/nestjs';
import { StayDbDatabaseModule } from '../stay-db/database.module';
import { RoomType } from '../hotel_stay_service/entities/stay_db/room-type.entity';
import { Room } from '../hotel_stay_service/entities/stay_db/room.entity';
import { Stay } from '../hotel_stay_service/entities/stay_db/stay.entity';
import { FunctionsService } from '../functions';

/** One registration per MikroORM context the jobs reach, imported and re-exported. */
const ENTITY_FEATURES: DynamicModule[] = [
  MikroOrmModule.forFeature([RoomType, Room, Stay]),
];

@Module({
  imports: [
    // A standalone application context never inherits AppModule's own SettingsModule: importing
    // it here has Nest assemble the settings before any provider of the context is constructed,
    // so every client the job handlers reach can read them.
    SettingsModule,
    StayDbDatabaseModule,
    ...ENTITY_FEATURES,
  ],
  providers: [
    FunctionsService,
  ],
  exports: [
    ...ENTITY_FEATURES,
    FunctionsService,
  ],
})
export class JobsRuntimeModule {}

/** The root of the Functions host's jobs context. */
@Module({
  imports: [JobsRuntimeModule],
})
class JobsHostModule {}

let hostContext: Promise<INestApplicationContext> | undefined;

/**
 * The standalone jobs context's root injector, created once per process.
 *
 * The promise is memoized, not its resolved value, so two concurrent first
 * invocations await one bootstrap instead of racing to build two.
 */
export async function jobsRuntimeModuleRef(): Promise<ModuleRef> {
  hostContext ??= NestFactory.createApplicationContext(JobsHostModule, { logger: false });
  const context = await hostContext;
  return context.get(ModuleRef, { strict: true });
}
