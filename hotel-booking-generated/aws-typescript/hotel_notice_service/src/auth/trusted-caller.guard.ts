/**
 * Validates the trusted-caller token on the `X-CruftFree-Caller-Token` header.
 *
 * The caller (the managed gateway, or a peer service) presents a JWT it minted
 * with its own platform identity; it is trusted iff it is signed
 * RS256 by a key of the expected issuer (found through the
 * issuer's OpenID discovery document, which must name that same issuer),
 * `iss` == the expected issuer, `aud` == the trusted-caller audience, and its
 * `sub` claim is in the per-service trusted-principal allowlist.
 * Runs BEFORE the identity/JWT guard on every non-probe route.
 *
 * NOT a shared-secret comparison -- validation is JWT/JWKS verification only.
 *
 * The three runtime values (issuer/audience/trusted-principal-ids) are never
 * baked as generation-time context: they are the deploy-time application
 * settings the platform delivers, read through the assembled settings (an
 * unset or blank one aborts startup).
 *
 * Auto-generated by cruftfree-codegen-typescript. Do not edit manually.
 */
import {
  CanActivate,
  ExecutionContext,
  ForbiddenException,
  Injectable,
  Logger,
  UnauthorizedException,
} from '@nestjs/common';
import type { Request } from 'express';
import type { IncomingMessage } from 'node:http';
import { createRemoteJWKSet, jwtVerify } from 'jose';
import { classifyVerificationFailure } from '../_runtime/verification-failure';
import type { VerificationFailureReasonCodes } from '../_runtime/verification-failure';
import { PROBLEM_TYPES } from '../errors/problem-details.dto';
import { deployTimeSetting } from "../config/settings";

// ---------------------------------------------------------------------------
// The one record of requests this guard verified. The client-address resolver reads the
// gateway's asserted header only for a request in this set; a request is added on the
// guard's accept path only. Held weakly, so a finished request is never retained.
// ---------------------------------------------------------------------------

const VERIFIED_REQUESTS = new WeakSet<IncomingMessage>();

/** Record that `req` came through the gateway: its caller token verified. */
export function markTrustedCaller(req: IncomingMessage): void {
  VERIFIED_REQUESTS.add(req);
}

/** Whether `req` was verified by this guard. */
export function isTrustedCaller(req: IncomingMessage): boolean {
  return VERIFIED_REQUESTS.has(req);
}

// ---------------------------------------------------------------------------
// Reason codes (shared vocabulary -- rendered, never re-typed). A failed verification
// is classified by the runtime classifier the identity core uses too
// (`_runtime/verification-failure`); this guard imports nothing from the identity core.
// ---------------------------------------------------------------------------

export const REASON_MALFORMED_TOKEN = "malformed_token";
export const REASON_EXPIRED_TOKEN = "expired_token";
export const REASON_BAD_SIGNATURE = "bad_signature";
export const REASON_ISSUER_MISMATCH = "issuer_mismatch";
export const REASON_AUDIENCE_MISMATCH = "audience_mismatch";
export const REASON_JWKS_REFRESH_FAILED = "jwks_refresh_failed";
const REASONS: VerificationFailureReasonCodes = {
  malformedToken: REASON_MALFORMED_TOKEN,
  expiredToken: REASON_EXPIRED_TOKEN,
  badSignature: REASON_BAD_SIGNATURE,
  issuerMismatch: REASON_ISSUER_MISMATCH,
  audienceMismatch: REASON_AUDIENCE_MISMATCH,
  jwksRefreshFailed: REASON_JWKS_REFRESH_FAILED,
};
export const REASON_MISSING_TOKEN = "missing_token";
export const REASON_UNTRUSTED_CALLER = "untrusted_caller";

const CALLER_TOKEN_HEADER = 'X-CruftFree-Caller-Token';
const CALLER_TOKEN_BEARER_PREFIX = 'Bearer ';
const EXEMPT_PATHS: ReadonlySet<string> = new Set([
  '/live',
  '/ready',
  '/health',
]);

/** The claim naming the calling principal, as the platform's issuer writes it. */
const PRINCIPAL_CLAIM = "sub";
const TOKEN_ALGORITHMS: string[] = ["RS256"];
const DISCOVERY_PATH = "/.well-known/openid-configuration";
const HTTPS_SCHEME = 'https://';
const FETCH_TIMEOUT_MS = 5000;

/**
 * The issuer's key set could not be discovered. Every message starts with `JWKS`,
 * so the shared classifier reports it as a key-set failure, never as a claim mismatch.
 */
export class TrustedCallerDiscoveryError extends Error {
  constructor(cause: string) {
    super(`JWKS discovery failed: ${cause}`);
    this.name = 'TrustedCallerDiscoveryError';
  }
}

/**
 * Resolve the issuer's `jwks_uri` from its OpenID discovery document (fetched over
 * verified TLS, redirects refused). The document must name the expected issuer and an
 * https key set, so no verifier knows a platform's key-set path.
 */
async function discoverJwksUri(issuer: string): Promise<string> {
  if (!issuer.startsWith(HTTPS_SCHEME)) {
    throw new TrustedCallerDiscoveryError('the expected issuer is not an https URL');
  }
  const discoveryUrl = issuer.replace(/\/+$/, '') + DISCOVERY_PATH;
  let response: Response;
  try {
    response = await fetch(discoveryUrl, {
      headers: { Accept: 'application/json' },
      redirect: 'error',
      signal: AbortSignal.timeout(FETCH_TIMEOUT_MS),
    });
  } catch {
    throw new TrustedCallerDiscoveryError('the discovery document is unavailable');
  }
  if (!response.ok) {
    throw new TrustedCallerDiscoveryError('the discovery document is unavailable');
  }
  let document: unknown;
  try {
    document = await response.json();
  } catch {
    throw new TrustedCallerDiscoveryError('the discovery document is not JSON');
  }
  if (typeof document !== 'object' || document === null) {
    throw new TrustedCallerDiscoveryError('the discovery document is not an object');
  }
  const fields = document as Record<string, unknown>;
  if (fields['issuer'] !== issuer) {
    throw new TrustedCallerDiscoveryError('the discovery document names another issuer');
  }
  const jwksUri = fields['jwks_uri'];
  if (typeof jwksUri !== 'string' || !jwksUri.startsWith(HTTPS_SCHEME)) {
    throw new TrustedCallerDiscoveryError('the discovery document names no https key set');
  }
  return jwksUri;
}

/**
 * Log the one refusal event and refuse with an opaque problem.
 *
 * The body is the family title only -- the client never learns which check
 * failed (the reason code goes to the log, never to the response). The log
 * carries the vocabulary reason code and the path: no exception text, no
 * principal id, no token. The exception filter answers the thrown exception
 * through the one problem responder.
 */
function refuse(logger: Logger, path: string, reasonCode: string, forbidden: boolean): never {
  logger.warn(`identity.trusted_caller.rejected reason_code=${reasonCode} path=${path}`);
  if (forbidden) {
    throw new ForbiddenException(PROBLEM_TYPES["forbidden"].title);
  }
  throw new UnauthorizedException(PROBLEM_TYPES["unauthorized"].title);
}

@Injectable()
export class TrustedCallerGuard implements CanActivate {
  private readonly logger = new Logger(TrustedCallerGuard.name);
  private jwks: ReturnType<typeof createRemoteJWKSet> | null = null;

  /**
   * The request whose trusted-caller header this guard verifies. A GraphQL
   * resolver's request lives in the GraphQL context; any other execution
   * context carries no caller token and is refused (fail closed).
   */
  private resolveRequest(context: ExecutionContext): Request {
    const type = context.getType<string>();
    if (type !== 'http') {
      refuse(this.logger, type, REASON_MISSING_TOKEN, false);
    }
    return context.switchToHttp().getRequest<Request>();
  }

  async canActivate(context: ExecutionContext): Promise<boolean> {
    const request = this.resolveRequest(context);

    if (EXEMPT_PATHS.has(request.path)) {
      return true;
    }

    const rawHeader = request.headers[CALLER_TOKEN_HEADER.toLowerCase()];
    const headerValue = Array.isArray(rawHeader) ? rawHeader[0] : rawHeader;
    if (!headerValue) {
      refuse(this.logger, request.path, REASON_MISSING_TOKEN, false);
    }
    // Consumers accept the bare JWT and tolerate an optional "Bearer " prefix
    // as defence in depth -- never require it, never emit it.
    const token = headerValue.startsWith(CALLER_TOKEN_BEARER_PREFIX)
      ? headerValue.slice(CALLER_TOKEN_BEARER_PREFIX.length)
      : headerValue;

    // Deploy-time settings the platform delivers; an unset or blank one aborts startup.
    const issuer = deployTimeSetting("CRUFTFREE_CALLER_EXPECTED_ISSUER");
    const audience = deployTimeSetting("CRUFTFREE_CALLER_AUDIENCE");
    const principalIds = deployTimeSetting("CRUFTFREE_CALLER_TRUSTED_PRINCIPAL_IDS")
      .split(',')
      .map((id) => id.trim())
      .filter(Boolean);

    let principal: unknown;
    try {
      if (this.jwks === null) {
        this.jwks = createRemoteJWKSet(new URL(await discoverJwksUri(issuer)));
      }
      const { payload } = await jwtVerify(token, this.jwks, {
        issuer,
        audience,
        algorithms: TOKEN_ALGORITHMS,
        requiredClaims: ['exp', 'iss', 'aud'],
      });
      principal = payload[PRINCIPAL_CLAIM];
    } catch (err: unknown) {
      return refuse(this.logger, request.path, classifyVerificationFailure(err, REASONS), false);
    }

    if (typeof principal !== 'string' || !principalIds.includes(principal)) {
      refuse(this.logger, request.path, REASON_UNTRUSTED_CALLER, true);
    }

    // Neither the principal nor the token is logged: the path alone identifies the call.
    this.logger.debug(`identity.service_principal.authenticated path=${request.path}`);
    // The one place a request is marked as having come through the verified gateway.
    markTrustedCaller(request);
    return true;
  }
}
