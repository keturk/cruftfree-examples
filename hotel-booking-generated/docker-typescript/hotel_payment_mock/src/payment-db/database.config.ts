/** SQLSTATEs by which a server refuses the login itself (invalid password, invalid authorization). */
const AUTH_FAILURE_SQLSTATES: readonly string[] = ["28P01", "28000"];
/** How many wrapped errors deep the driver's own error is looked for. */
const MAX_CAUSE_DEPTH = 4;

/**
 * True only for a definitive refusal of the login. A timeout, a reset connection or any other
 * database error is not one: the password is not evicted for it.
 */
export function isDefinitiveDatabaseAuthError(error: unknown): boolean {
  let current: unknown = error;
  for (let depth = 0; depth < MAX_CAUSE_DEPTH && current !== null && typeof current === 'object'; depth += 1) {
    const candidate = current as { code?: unknown; sqlState?: unknown; cause?: unknown };
    if (
      (typeof candidate.code === 'string' && AUTH_FAILURE_SQLSTATES.includes(candidate.code)) ||
      (typeof candidate.sqlState === 'string' && AUTH_FAILURE_SQLSTATES.includes(candidate.sqlState))
    ) {
      return true;
    }
    current = candidate.cause;
  }
  return false;
}

/**
 * Evict the cached database password after the server refused it, so the next connection
 * resolves it afresh. Throttled per handle by the secrets service; never loops.
 */
export function invalidateDatabasePassword(): void {
  invalidateSecret('payment_db_password', "db_auth_failed");
}


export async function getDatabaseConfig(
  settings: AppSettings,
  secrets: SecretsService = new SecretsService(),
): Promise<MikroOrmModuleOptions> {
  const host = settings.connections.payment_db_host;
  const port = settings.connections.payment_db_port;
  const database = settings.connections.payment_db_database;
  const user = settings.connections.payment_db_user;

  return {
    driver: PostgreSqlDriver,
    entities: [
      __dirname + '/../hotel_payment_mock/entities/payment_db/**/*.entity{.ts,.js}',
    ],
    allowGlobalContext: true,
    debug: false,
    pool: {
      max: 5,
    },
    host,
    port,
    user,
    // Resolved for every new connection, so a rotated password reaches the pool as its
    // connections are replaced; the secrets service serves its cache until the entry expires.
    password: () => secrets.getSecret('payment_db_password'),
    dbName: database,
  };
}
