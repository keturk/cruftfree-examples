export type BodyKind = 'object' | 'array' | 'string' | 'number' | 'boolean';

/** Refuses a body whose top level is not the declared kind. */
export function requireBodyKind(value: unknown, kind: BodyKind): void {
  let matches: boolean;
  switch (kind) {
    case 'object':
      matches = typeof value === 'object' && value !== null && !Array.isArray(value);
      break;
    case 'array':
      matches = Array.isArray(value);
      break;
    case 'string':
    case 'number':
    case 'boolean':
      matches = typeof value === kind;
      break;
    default:
      throw new Error(`Unknown body kind '${String(kind)}'. Expected object, array, string, number or boolean.`);
  }
  if (!matches) {
    throw new BadBodyException();
  }
}

/**
 * The request body, refused before validation when it is absent or its top
 * level is not the declared kind. A request carries a body exactly when it has
 * a `Content-Length` or a `Transfer-Encoding` header (RFC 9112 section 6.3).
 */
export const RequestBody = createParamDecorator((kind: BodyKind, context: ExecutionContext): unknown => {
  const request = context.switchToHttp().getRequest<Request>();
  if (request.headers['content-length'] === undefined && request.headers['transfer-encoding'] === undefined) {
    throw new BadBodyException();
  }
  requireBodyKind(request.body, kind);
  return request.body;
});

const ARRAY_INDEX = /^\d+$/;

/** The wire path of a class-validator property, relative to the body root: `a.b`, `items[0].sku`. */
function joinPath(parentPath: string, property: string): string {
  if (ARRAY_INDEX.test(property)) {
    return `${parentPath}[${property}]`;
  }
  return parentPath === '' ? property : `${parentPath}.${property}`;
}

export const CODE_PRECEDENCE: readonly FieldErrorCode[] = [
  "required",
  "unknown_field",
  "repeated",
  "invalid",
];

/** The registered code of one property's failed constraints, by constraint name. */
export function codeFor(constraints: Record<string, string>): FieldErrorCode {
  const names = Object.keys(constraints);
  if (names.includes('isDefined')) {
    return "required";
  }
  if (names.includes('whitelistValidation')) {
    return "unknown_field";
  }
  return "invalid";
}

/**
 * Walks a class-validator tree into ``path -> code``: one entry per property
 * path, the code by precedence (required, unknown field, invalid).
 */
export function collect(
  errors: readonly ValidationError[],
  parentPath: string,
  into: Map<string, FieldErrorCode>,
): void {
  for (const error of errors) {
    const path = joinPath(parentPath, error.property);
    if (error.constraints !== undefined && Object.keys(error.constraints).length > 0) {
      const code = codeFor(error.constraints);
      const held = into.get(path);
      if (held === undefined || CODE_PRECEDENCE.indexOf(code) < CODE_PRECEDENCE.indexOf(held)) {
        into.set(path, code);
      }
    }
    if (error.children !== undefined && error.children.length > 0) {
      collect(error.children, path, into);
    }
  }
}

/**
 * The field errors of a class-validator tree: one entry per property path, the
 * code by precedence (required, unknown field, invalid). The framework's own
 * messages are never read -- they embed fragments of the received value.
 */
export function bodyFieldErrors(errors: readonly ValidationError[], parentPath = ''): FieldError[] {
  const codes = new Map<string, FieldErrorCode>();
  collect(errors, parentPath, codes);
  return [...codes].map(([path, code]) => fieldError("body", path, code));
}

/** The exception the global ValidationPipe throws for a failed body. */
export function bodyValidationException(errors: readonly ValidationError[]): HttpException {
  const fieldErrors = bodyFieldErrors(errors);
  if (fieldErrors.length === 0) {
    // A tree with no constraint names no field: refuse as an unreadable body, never as an empty problem.
    return new BadBodyException();
  }
  return new RequestValidationException(fieldErrors);
}

/**
 * Validates each item of an array body against its DTO class, naming a failing
 * property by its index path (`[0].sku`). The same whitelist rules as the
 * global ValidationPipe apply to every item.
 */
@Injectable()
export class ValidatedArrayPipe implements PipeTransform {
  constructor(private readonly itemType: new () => object) {}

  async transform(value: unknown): Promise<object[]> {
    requireBodyKind(value, 'array');
    const items = value as unknown[];
    const errors: FieldError[] = [];
    const instances: object[] = [];
    for (let index = 0; index < items.length; index += 1) {
      const item = items[index];
      if (typeof item !== 'object' || item === null || Array.isArray(item)) {
        errors.push(fieldError("body", `[${String(index)}]`, "invalid"));
        continue;
      }
      const instance = plainToInstance(this.itemType, item as object);
      const violations = await validate(instance, { whitelist: true, forbidNonWhitelisted: true });
      errors.push(...bodyFieldErrors(violations, `[${String(index)}]`));
      instances.push(instance);
    }
    if (errors.length > 0) {
      throw new RequestValidationException(errors);
    }
    return instances;
  }
}

/** The body-parser error type for a body that is not parseable JSON. */
const BODY_PARSE_FAILED = 'entity.parse.failed';

/**
 * Express error middleware, registered after the routes: a body the body parser
 * could not parse never reaches a route, so the exception filter never sees it.
 * It is answered here as the registered `bad-request` problem; any other error
 * continues to the framework's own handling.
 */
export function bodyParseErrorMiddleware(
  error: unknown,
  request: Request,
  response: Response,
  next: NextFunction,
): void {
  if (
    typeof error !== 'object' ||
    error === null ||
    (error as { type?: unknown }).type !== BODY_PARSE_FAILED
  ) {
    next(error);
    return;
  }
  const problem = problemBody("bad-request", request.path);
  LOGGER.warn(
    `problem_response status=${String(problem.status)} type=${problem.type.slice(PROBLEM_TYPE_URN_PREFIX.length)} path=${problem.instance}`,
  );
  response.status(problem.status).header('Content-Type', 'application/problem+json').json(problem);
}
