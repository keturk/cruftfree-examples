/**
 * Gateway credential verification endpoint.
 *
 * Used by the gateway's nginx `auth_request` to decide whether a request may be
 * forwarded: it answers 200 for a valid bearer JWT, or for a request carrying no
 * `Authorization` header and exactly one admitted API-key header whose value is
 * within the presented-key bounds; 401 otherwise. nginx treats any 2xx as
 * "allow" and 401/403 as "deny". The gateway forwards only the key headers the
 * requested route admits, so a key reaches this check only on such a route. The
 * edge checks a key's presence, never its validity: the service's own credential
 * chain verifies the key on the next hop.
 *
 * A WebSocket upgrade's bearer is read in the order the service's own handshake
 * reads it: the `Authorization` header, else a `cruftfree.bearer.<token>`
 * `Sec-WebSocket-Protocol` offer (the only header a browser can set), else, on the
 * path of a route that opted in with `queryToken(...)`, that query parameter. A
 * present but malformed value, or two bearer offers, is refused, never skipped. No
 * token, offer or query value is ever logged.
 *
 * Delegated verify: a bearer is validated by this service's full auth chain
 * (`authenticateBearer`), the same chain every authenticated route runs, so any
 * check the chain performs (provider plan, audience, revocation) applies here.
 * Only a token of a provider the application declares passes: a provider a platform
 * injects for its own test runs trusts a published key, so it never passes this edge.
 * A presented key is never logged.
 *
 * Auto-generated by cruftfree-codegen-typescript. Do not edit manually.
 */
import {
  Controller,
  ForbiddenException,
  Get,
  HttpCode,
  Logger,
  Req,
  UnauthorizedException,
} from '@nestjs/common';
import { ApiExcludeEndpoint } from '@nestjs/swagger';
import type { Request } from 'express';
import {
  AuthChainError,
  AuthChainRevocationUnavailableError,
  authenticateBearer,
  requireProviders,
} from '../auth/auth-chain';
import { RevocationUnavailableException } from '../errors/business-error';

/** The providers whose bearer tokens this edge admits: the ones the application declares. */
const EDGE_BEARER_PROVIDERS: ReadonlyArray<string> = ["identity", "machine"];
const BEARER_PREFIX = 'Bearer ';

/** Presented-key bounds: 32 to 256 printable ASCII characters (0x21-0x7E). */
const API_KEY_MIN_LENGTH = 32;
const API_KEY_MAX_LENGTH = 256;
const API_KEY_PATTERN = /^[\x21-\x7e]+$/;

/** Every API-key header a credential-checked gateway route admits, lower-cased. */
const API_KEY_HEADERS: readonly string[] = [
  "x-channel-api-key",
  "x-email-api-key",
  "x-payment-api-key",
];

/**
 * The prefix of the token-bearing subprotocol offer a browser WebSocket client sends
 * (it can set no other header). Read here, never echoed.
 */
const BEARER_SUBPROTOCOL_PREFIX = "cruftfree.bearer.";
const SUBPROTOCOL_HEADER = 'sec-websocket-protocol';
const ORIGINAL_URI_HEADER = 'x-original-uri';

/**
 * The header the gateway sets on the verify subrequest of an `auth(optional)` route
 * (lower-cased for lookup), and the value it carries. It is set on the gateway's
 * internal auth location, which forwards no client header, so a client cannot supply it.
 */
const CREDENTIAL_MODE_HEADER = "x-cruftfree-credential-mode";
const CREDENTIAL_MODE_OPTIONAL = "optional";

/**
 * Upgrade path -> the query parameter its block opted into (`queryToken(...)`) for
 * carrying the credential. A query string is read only on a path listed here.
 */
const UPGRADE_QUERY_PARAMETERS: ReadonlyMap<string, string> = new Map<string, string>([
]);

/** A credential source carried a malformed or ambiguous value: the request is refused. */
class CredentialRefusedError extends Error {}

/**
 * The credential a `cruftfree.bearer.<token>` offer carries, or `undefined`
 * when no offer does. Two bearer offers are ambiguous and an empty one is malformed:
 * both refuse, exactly as the service's own handshake reader does. Never logged.
 */
function subprotocolBearer(request: Request): string | undefined {
  const raw = request.headers[SUBPROTOCOL_HEADER];
  const values = raw === undefined ? [] : Array.isArray(raw) ? raw : [raw];
  const bearers = values
    .flatMap((value) => value.split(','))
    .map((offer) => offer.trim())
    .filter((offer) => offer.startsWith(BEARER_SUBPROTOCOL_PREFIX));
  if (bearers.length === 0) {
    return undefined;
  }
  if (bearers.length > 1) {
    throw new CredentialRefusedError();
  }
  const credential = bearers[0].slice(BEARER_SUBPROTOCOL_PREFIX.length);
  if (credential === '') {
    throw new CredentialRefusedError();
  }
  return credential;
}

/**
 * The credential in the declared query parameter of the requested upgrade path, read
 * from the gateway-forwarded original URI and only for a path whose block opted in.
 * A present but empty or repeated value refuses. Never logged.
 */
function queryBearer(request: Request): string | undefined {
  const original = request.headers[ORIGINAL_URI_HEADER];
  if (typeof original !== 'string') {
    return undefined;
  }
  const url = new URL(original, 'http://gateway.invalid');
  const parameter = UPGRADE_QUERY_PARAMETERS.get(url.pathname);
  if (parameter === undefined) {
    return undefined;
  }
  const values = url.searchParams.getAll(parameter);
  if (values.length === 0) {
    return undefined;
  }
  if (values.length > 1 || values[0] === '') {
    throw new CredentialRefusedError();
  }
  return values[0];
}

/** True when *value* is 32-256 printable ASCII characters. Never logs the value. */
function presentedKeyInBounds(value: string): boolean {
  return (
    value.length >= API_KEY_MIN_LENGTH &&
    value.length <= API_KEY_MAX_LENGTH &&
    API_KEY_PATTERN.test(value)
  );
}

/**
 * True when exactly one admitted key header is present, sent once, with an
 * in-bounds value. Two admitted key headers, or one sent twice, are ambiguous
 * and refused, exactly as the service's own credential chain refuses them.
 */
function admittedKeyPresented(request: Request): boolean {
  const presented: string[] = [];
  for (const headerName of API_KEY_HEADERS) {
    const value = request.headers[headerName];
    if (Array.isArray(value)) {
      return false;
    }
    if (value !== undefined && value !== '') {
      presented.push(value);
    }
  }
  if (presented.length !== 1) {
    return false;
  }
  return presentedKeyInBounds(presented[0]);
}

@Controller()
export class GatewayJwtVerifyController {
  private readonly logger = new Logger(GatewayJwtVerifyController.name);

  /**
   * A WebSocket upgrade's credential, in the order a browser can send it: a bearer
   * subprotocol offer, else the declared query parameter of the requested path.
   * `undefined` when neither is present; a malformed or ambiguous value answers 401.
   */
  private upgradeBearer(request: Request): string | undefined {
    try {
      return subprotocolBearer(request) ?? queryBearer(request);
    } catch (err) {
      if (err instanceof CredentialRefusedError) {
        this.logger.debug('gateway_credential_verify_rejected reason_code=malformed_token');
        throw new UnauthorizedException();
      }
      throw err;
    }
  }

  /**
   * Decide one gateway `auth_request`: 200 allows the request, 401 denies it.
   *
   * A request carrying `Authorization` is decided by its bearer token alone --
   * a key header beside it never rescues an invalid or non-bearer
   * `Authorization`. A request without `Authorization` is allowed only when it
   * presents exactly one admitted, in-bounds key header, or, on an `auth(optional)`
   * route (the gateway sets the credential-mode header there), no credential at all.
   * A bearer that verifies but whose principal the auth chain refuses answers 403;
   * any other chain failure answers 401, and a fault that is not a chain denial
   * propagates (500, which nginx also denies).
   */
  @Get("internal/credential-verify")
  @HttpCode(200)
  @ApiExcludeEndpoint()
  async verify(@Req() request: Request): Promise<void> {
    const authHeader = request.headers.authorization;
    let token: string;
    if (authHeader !== undefined) {
      if (!authHeader.startsWith(BEARER_PREFIX)) {
        this.logger.debug('gateway_credential_verify_rejected reason=non_bearer_authorization');
        throw new UnauthorizedException();
      }
      token = authHeader.slice(BEARER_PREFIX.length);
    } else {
      const upgradeToken = this.upgradeBearer(request);
      if (upgradeToken === undefined) {
        if (admittedKeyPresented(request)) {
          return;
        }
        if (request.headers[CREDENTIAL_MODE_HEADER] === CREDENTIAL_MODE_OPTIONAL) {
          // An auth(optional) route serves a request that presents no credential. Reached
          // only when no source carried one: a malformed or invalid credential is refused.
          return;
        }
        this.logger.debug('gateway_credential_verify_rejected reason=no_admitted_credential');
        throw new UnauthorizedException();
      }
      token = upgradeToken;
    }
    try {
      requireProviders(await authenticateBearer(`${BEARER_PREFIX}${token}`), EDGE_BEARER_PROVIDERS);
    } catch (err) {
      if (err instanceof AuthChainError) {
        this.logger.debug(`gateway_credential_verify_rejected reason_code=${err.reasonCode}`);
        // A credential whose revocation status cannot be determined is neither valid nor
        // invalid: the gateway sees the 503, never a 401 that sends the client to re-login.
        if (err instanceof AuthChainRevocationUnavailableError) {
          throw new RevocationUnavailableException(err.retryAfterSeconds);
        }
        if (err.status === 403) {
          throw new ForbiddenException();
        }
        throw new UnauthorizedException();
      }
      throw err;
    }
  }
}
